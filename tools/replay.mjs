/* ---------------------------------------------------------------------------
 * 一、决策点（`--导出决策` 用）：**一律问游戏自己的那一份**（`window.__game.选项`）
 * ---------------------------------------------------------------------------
 * ★ 2026-10-13：这份枚举逻辑**搬进了游戏**（`src/js/8b-决策日志.js`）—— 线上玩的时候也在记
 *   「当时有哪些选项」，两边必须是**同一份代码**，所以工具这边不再自己养一套
 *   （删掉的是原来那份 `决策表` 与它的 6 个辅助函数；**口径一条没变，只是换了出处**）。
 *  · `是决策动作(G, 动作)`：这个动作算不算决策点（19 个族；`tests/录像.js` 第 [6] 段钉着）；
 *  · `选项们(G, 动作, 参数, 附)`：那个动作的**合法可选项**（`动作` / `动作:参数` 短码数组）——
 *    「选择」就是玩家实际按下的那一串，它必须在「可选项」里。
 *  · `附` = `{ 可选项, 步, 上次弹窗 }`：只给 `弹窗:` 用（真弹窗的选项不在局面上，
 *    只能从录像那一步抄下来的、或重放时 `对话框钩子` 刚抓到的那一次拿）。
 *  游戏那边拿不到局面（没有 RUN）时返回空数组，工具照实报出来（**不编一个假的选项**）。
 */
function 选项们(G, 动作, 参数, 附) {
  const 选 = (G && G.选项) || null;
  if (!选 || typeof 选.枚举 !== 'function') return [];
  try { return 选.枚举(G.界面, 动作, 参数, 附) || []; } catch (e) { return []; }
}
/** 这个动作算不算决策点（**唯一真源 = 游戏的 `选项.是决策()`**）。 */
function 是决策动作(G, 动作) {
  const 选 = (G && G.选项) || null;
  if (!选 || typeof 选.是决策 !== 'function') return false;
  try { return !!选.是决策(动作); } catch (e) { return false; }
}

/* ---------------------------------------------------------------------------
 * 二、局面摘要（决策行里的「当时的局面」）
 * ------------------------------------------------------------------------- */
function 局面摘要(G) {
  const R = G.肉鸽.RUN;
  if (!R) return { 局面: '没有进行中的局' };
  const 格 = (() => { try { return G.肉鸽.当前格(); } catch (e) { return null; } })();
  const 出 = {
    层: R.层, 场次: R.场次, 等级: R.等级, 经验: R.经验,
    希望: R.希望, 源碳: R.源碳, 耐久: R.耐久, 推进剂: R.推进剂,
    名册: (R.队伍 || []).map(m => `${m.键} Lv${m.等级}`),
    券: ((R.券 || []).map(c => (c && c.名) || '券')),
    藏品: (R.藏品 || []).slice(),
    零件: ((R.零件 || []).map(p => p && p.k)),
    已走步数: (R.已走过 || []).length,
    当前节点: 格 ? { 格号: 格.k, 类型: 格.类型, 名: (G.节点类型表[格.类型] || {}).名 || 格.类型 } : null,
  };
  const 界面 = G.界面, ctx = 界面 && 界面.ctx;
  if (界面 && 界面.屏 === '战斗' && ctx) {
    出.战斗 = {
      回合: ctx.turn, 阶段: 界面.阶段,
      方针: (() => { try { const p = G.当前方针(ctx); return `${p.类型}${p.目标位 == null ? '' : `（目标位 ${p.目标位}）`}`; } catch (e) { return null; } })(),
      单位开关: (() => {
        const 表 = 界面.单位开关 || {};
        const 键 = Object.keys(表).filter(k => { const v = 表[k] || {}; return v.保留大招 || v.TRANSAM === '手动' || v.本回合开TRANSAM; });
        return 键.length ? 键.map(k => `${k}:${表[k].保留大招 ? '保留大招' : ''}${表[k].TRANSAM === '手动' ? '/手动' : ''}${表[k].本回合开TRANSAM ? '/点开' : ''}`) : [];
      })(),
      我方HP: (ctx.allies || []).map(u => `${u.slot}:${Math.max(0, u.hp)}/${u.maxHp}`),
      敌方HP: (ctx.enemies || []).map(u => `${u.slot}:${Math.max(0, u.hp)}/${u.maxHp}`),
      敌人预览: (() => {
        try {
          return (G.算意图(ctx) || []).map(a => `${a.名称} 用【${a.武器 || '—'}】打 ${a.目标名 || '—'}（约 ${a.期望}${a.被挡 ? '，被挡' : ''}）`);
        } catch (e) { return []; }
      })(),
    };
  }
  return 出;
}

