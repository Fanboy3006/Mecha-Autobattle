#!/usr/bin/env node
/* ============================================================================
 * 对局录像重放工具（作者 2026-10-12 提出、Claude 出规格）
 * ----------------------------------------------------------------------------
 * 用法：
 *   node tools/replay.mjs <录像文件>              # 重放 + 校验（逐字一致 → 退出码 0）
 *   node tools/replay.mjs <录像文件> --导出决策    # 另外打一份 JSONL：每个决策点一行
 *   node tools/replay.mjs <录像文件> --out=决策.jsonl
 *   node tools/replay.mjs <录像文件> --quiet       # 只打结论
 *
 * 干什么：录像里**只有种子 + 游戏版本 + 按顺序的每一个操作**（录操作，不录局面）。
 * 这个工具用 `tests/lib/dom-stub.mjs` 的 `loadPage()` 把 `index.html` 在 Node 的 `vm` 里跑起来，
 * 再**按同一个动作派发入口**（`界面.动作(动作, 参数)`）逐条重放：
 *   ① **逐步校验**：每一步做完，把当前局面压成一条**紧凑串**（`录像.对账(界面)`），
 *      与录像里那一步的 `对账` 比 —— 对不上就报「**第 N 步开始对不上**」+ 当时**期望 / 实际**，**不崩**；
 *   ② **最终校验**：整局重放完，重建 `录像.摘要(RUN)`（规范化投影）与录像的 `最终摘要` **逐字比对**；
 *   ③ **版本不同时先警告，照样尽量重放**（录像里记的是当时的 `__game.version`）；
 *   ③b ★ **架构 2.0 · 跨规则版本重放诊断**（2026-10-13；DEBT-03）：录像多了一个
 *      `规则签名`（`'r1:' + 8 位十六进制`，对 `战斗结构` / `难度调整` / `势力特色` /
 *      `肉鸽数值` / `守军奖励` 五张规则表做稳定序列化后的 FNV-1a）。
 *      **旧录像没有这个字段** → `录像签名 = '未记录'`；而且**更旧的录像**（如 v0.6.6 的
 *      `785164.json`）顶层写的是 `版本: "0.6.6"`，**没有 `游戏版本`** —— 两个都读
 *      （`游戏版本 || 版本(字符串)`），不许因为「读不到版本号」就静默失效
 *      （Guardian 破坏性审查抓出的真漏洞：实跑 785164 时一条诊断都没打）。
 *      **只要满足任一条件**：① `录像签名` 缺失（未记录）、② `录像签名 !== 当前签名`、
 *      ③ `录像版本 !== 当前版本` —— **且**这一次重放真的对不上（逐步对账 / 最终摘要 /
 *      抛异常任一出问题）时，多打一条明确的架构诊断：`[跨规则版本重放] …` —— 说清
 *      「**Seed 只决定随机序列，规则变更会导致跨版本对账差异**」，
 *      不让人误以为「同种子重放对不上」是引擎不决定性。
 *   ③c ★ **战术卡牌开关按录像顶层字段定**（P1.2 §1.1 起；**P1.3 §1.1.2 补了 P1.1 兼容那一条**）：
 *      重放的**主判据**只有一个 —— 录像顶层的 `战术卡牌` 字段（`Boolean(战斗结构.战术卡牌?.开)`）：
 *      是 `true` → 按**开牌**重放；显式写了别的值（`false` / `'true'` / `1`…）→ 按**关牌**。
 *      **没有这个字段**（P1.2 之前的旧录像）时，P1.3 起走一条**明确的兼容判据**：
 *        · `录像.规则签名 === 'r1:1ee3e998'`（P1.1 那个规则宇宙 —— 那时战术卡牌只有「开」一种），或
 *        · **录像自己的 `操作` 流里真的出现 `打战术牌` / `选战术牌` 这两族动作**
 *          （关牌时这两族连按钮都画不出来 → 出现过 = 录的时候一定开着牌）；
 *      任一成立 → 按开牌重放；都不成立 → 关牌（P1 之前的老录像）。
 *      ⚠ 这一条是**任务书 §1.1.2 点名的**（`895903` 就是 P1.1 录的、顶层没有这个字段，
 *        按关牌重放会从第 17 步第一场战斗就开始全错）。它读的是**录像自己的字段**，
 *        不是「猜录像内容」；P1.2 禁的是「没有任何字段依据就去猜」。
 *      实现 = `应用录像战术卡牌开关()`（把 `战斗结构.战术卡牌.开` 钉成这个值）。
 *   ③d ★ **P1.3 §FIX-1 · 弹窗答案的两条落地时机**（2026-10-15）：
 *      真浏览器里 `界面.对话框()` 返回 **Promise**：玩家点按钮那一下**只是 resolve**，
 *      答案的效果（瞭望站 +1 推进剂 / 遗迹扣耐久 / 休整 +2…）是**微任务**里才落地的 ——
 *      所以录像里那一步的 `弹窗` 主步带**真正的答案**（`参数 = '登高'`），
 *      而它**父步**和它**自己**的 `对账` 都是「效果还没落地」的那一份。
 *      同步 `对话框钩子`（测试 / 探针那条路）相反：答案当场返回 → 效果算在**父步之内**，
 *      答案记成父步后面紧挨着的一条 `弹窗` 子步（`参数` 同样是真答案）。
 *      两种形状这里**都要能跑**，做法 = 把弹窗做成一个「延后落地」的 thenable（`造延后()`）：
 *        · 钩子**不**同步返回答案，只把回调排队；
 *        · 真浏览器形状：走到那条 `弹窗` 步时先按**落地之前**的局面记对账（对得上），再把答案落地；
 *        · 同步钩子形状：父步对账会对不上 → **立刻**拿紧接着那条 `弹窗` 子步的参数落地、重算对账。
 *      另：`弹窗` 步的 `参数 === ''`（P1.1 的真实录像就是这么录的，答案没进录像）时，
 *      枚举这一屏摆出来的按钮值，**用「下一步的对账」当判据试算**挑一个（见 `猜弹窗答案()`）；
 *      挑不出就取第一个并打一条明确的警告 —— 绝不静默。
 *   ④ `--导出决策`：每个决策点一行 JSONL，`可选项` **由游戏自己的 `选项.枚举()` 现场枚举**
 *      （`window.__game.选项`，实现在 `src/js/8b-决策日志.js`）—— **线上记的那一份选项与这里导出的
 *      是同一份代码**（口径唯一真源）；这个工具不再自己养一份枚举逻辑。
 *
 * 两个「重放侧」的特殊处理（都写在这里，不改游戏）：
 *   · `编队` 这一步是**录像自己补的一步**（出击名单与站位是拖动出来的，不走动作入口）——
 *     重放时直接写回 `界面.编队.出击` 与 `RUN.出击阵 / 出击`，等价于玩家在编队屏上摆好的那个结果；
 *   · 弹窗（隧道 / 遗迹 / 休整 / 瞭望站 / 侵蚀源）的答案**不经过动作派发入口** ——
 *     两种录像形状（真浏览器 Promise / 同步钩子）按文件头 ③d 那两条时机落地。
 *
 * 本文件**一处 `Math.random` 都没有**；同一条录像重放两遍输出逐字相同。
 * ========================================================================== */

