/** 安全的文字（`null` / 认不出来的东西 → 空串）。 */
const 文字 = v => (v == null ? '' : String(v));

/** **深克隆**（给「试算候选答案」用）：`RUN` 里有 `已走过集` / `已揭开集` 两个 **Set**
 *  （`90-肉鸽-6` 读档时补的界面缓存）—— JSON 往返会把它们变成 `{}`，所以这里认 Set / Map。 */
export function 深克隆(v) {
  const 走 = x => {
    if (x === null || typeof x !== 'object') return x;
    const 类 = Object.prototype.toString.call(x);
    if (类 === '[object Set]') return new Set([...x].map(走));
    if (类 === '[object Map]') return new Map([...x].map(([a, b]) => [走(a), 走(b)]));
    if (Array.isArray(x)) return x.map(走);
    const o = {};
    for (const k of Object.keys(x)) o[k] = 走(x[k]);
    return o;
  };
  try { return 走(v); } catch (e) { return v; }
}

/** **同步排空微任务**（只有 Node 有这条路；别的运行时直接跳过）。
 *  为什么要它：`80-界面-5` 的侵蚀源那条路拿到的是 `Promise.resolve(试)` —— 真 Promise 的
 *  `.then` 回调是**微任务**，而重放是**同步**循环，不排空就永远不落地（等于弹窗没人回答）。 */
export function 排空微任务(最多 = 40) {
  const 冲 = (typeof process !== 'undefined' && process && typeof process._tickCallback === 'function')
    ? process._tickCallback : null;
  if (!冲) return 0;
  let n = 0;
  while (n < 最多) { n++; try { 冲(); } catch (e) { break; } }
  return n;
}

/** 造一个「延后落地」的 thenable：`肉鸽弹窗()` 会 `答案.then(回调)`（`92-肉鸽界面-2`），
 *  回调先排队；等重放走到该落地的时刻（`弹窗` 步 / 父步补判）才把答案喂进去。
 *  `then` 可以被调用多次、`落地` 也可以被调用多次（试算那几个候选时要用）。 */
export function 造延后() {
  const 我 = { 已落地: false, 答案: undefined, 等: [] };
  我.then = (好, 坏) => {
    if (typeof 好 === 'function') {
      if (我.已落地) { try { 好(我.答案); } catch (e) { /* 由调用方那一侧兜 */ } }
      else 我.等.push(好);
    }
    return 我;
  };
  我.catch = () => 我;
  我.finally = () => 我;
  我.落地 = v => {
    我.已落地 = true; 我.答案 = v;
    const 份 = 我.等.slice();                 // **不消费**：试算要能重放同一个答案
    for (const f of 份) f(v);
    return 份.length;
  };
  return 我;
}

