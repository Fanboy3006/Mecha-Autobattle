function 解析参数(argv, 基线) {
  const o = Object.assign({
    quick: false, write: true, out: 默认输出, seed: 主种子默认,
    char: null, lv: null, mode: 'all', quiet: false, help: false,
  }, 基线 || {});
  for (const a of argv) {
    if (a === '--quick') o.quick = true;
    else if (a === '--no-write') o.write = false;
    else if (a === '--quiet') o.quiet = true;
    else if (a === '--help' || a === '-h') o.help = true;
    else if (a.startsWith('--out=')) o.out = resolve(process.cwd(), a.slice(6));
    else if (a.startsWith('--seed=')) o.seed = Number(a.slice(7)) >>> 0;
    else if (a.startsWith('--char=')) { o.char = a.slice(7).toUpperCase(); o.mode = 'one'; }
    else if (a.startsWith('--lv=')) o.lv = Number(a.slice(5));
    else if (a === '--one') o.mode = 'one';
    else if (a === '--solo') o.mode = 'solo';
    else if (a === '--team') o.mode = 'team';
    else throw new 参数错(`不认识的参数：${a}（--help 看用法）`);
  }
  if (o.mode === 'one' && !o.char) o.char = 'B1';
  if (o.mode === 'one' && !o.lv) o.lv = 20;
  return o;
}

