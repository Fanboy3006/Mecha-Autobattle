/* ---- 最强九人：按「Lv30 打标准靶的普通武器平均每回合伤害」选 ---- */
function 最强九人(单挑30) {
  const 键序 = (a, b) => (a < b ? -1 : a > b ? 1 : 0);
  const 榜 = 单挑30.filter(r => r.主动出手 > 0).slice().sort((a, b) =>
    (b.主动每回合 - a.主动每回合) || (b.胜率 - a.胜率) || (a.平均回合 - b.平均回合) || 键序(a.键, b.键));
  const 出 = [], 已用 = new Set();
  /* ① 每个职业先取第 1 名（吃满 `b1 混编作战条例` 的「每个不同职业 +8% 伤害」） */
  for (const 职 of ['近卫', '尖兵', '重装', '狙击', '指挥', '特种']) {
    const r = 榜.find(x => x.职业 === 职 && !已用.has(x.键));
    if (r) { 出.push(r); 已用.add(r.键); }
  }
  /* ② 再从总榜补到 9 台 */
  for (const r of 榜) {
    if (出.length >= 9) break;
    if (!已用.has(r.键)) { 出.push(r); 已用.add(r.键); }
  }
  return 出.map(r => ({ 键: r.键, 名: r.名, 职业: r.职业, 档: r.档, 每回合: r.主动每回合 }));
}

/** 队伍（[{键…}]）→ 出击编成（`台数` 台，全部 Lv30）：**基础 maxHp 从高到低**，前 4 台前排、其余后排。
 *  （基础 maxHp = 开战前的，藏品 `hpPct` 要开战才贴 —— 口径写在任务板里。） */
function 摆位(队伍, 台数) {
  const g = 载入内核();
  const 排 = (队伍 || []).slice(0, Math.max(0, 台数))
    .map(m => ({ 键: m.键, 名: m.名, 职业: m.职业, maxHp: g.makeUnit(m.键, 'ally', 0, 30).maxHp }))
    .sort((a, b) => (b.maxHp - a.maxHp) || (a.键 < b.键 ? -1 : a.键 > b.键 ? 1 : 0));
  const 前排数 = Math.min(4, 排.length);
  return 排.map((m, i) => ({ 键: m.键, 位: i < 前排数 ? i : (4 + (i - 前排数)), 等级: 30 }));
}

/** 第 `行` 排的第一个格子号（前 4 后 5 → 第 0 排从 0 起、第 1 排从 4 起；行列数从 `__game` 取）。 */
function 行首格(行) {
  const g = 载入内核();
  let s = 0;
  for (let i = 0; i < 行; i++) s += g.行列数(i);
  return s;
}

/* ---------------------------------------------------------------------------
 * 「会玩的指令策略」—— 每回合给出一张指令表（`60-战斗.js` 的 `设指令(ctx, 指令表)` 吃的就是它）。
 * 只用**现有指令与机制**（进攻 / 集火 / 守护 / 防御 / 换位 + 大招开关 + TRANS-AM 开关），
 * 一处新规则都不发明、一个数值都不改；全部是决定性的（没有随机数）。
 *  ① **集火威胁最高的敌机**：`算意图()` 会给「每个敌人这一回合打算打谁、期望多少伤害」，
 *     挑期望最高的那台当集火目标（并列取当前 HP 最低的、再取位号小的）——
 *     把最疼的那台提前打掉，它这一回合就出不了手（行动顺序按速度）。
 *     它这一回合打不到人（Boss 蓄力 / 没有可用武器 → 期望 0）时，退成「集火当前 HP 最低的活敌」（收残血）。
 *     打不到的机体不用管：`50-AI.js:125-132` 的「集火」够不到时会自己退回「进攻」。
 *  ② **守护**：`算意图()` 里凡是「**单体**（非范围，`60-战斗.js:370` 的守护只对非范围生效）、
 *     期望伤害 ≥ 该队友当前 HP」的，就是这一回合会被打死的队友；按「**这一回合期望输出最高的先救**」
 *     排队，派**这一回合期望输出最低**的队友去守护它（守护者自己攻击 ×0.7，所以派最闲的那台最划算）。
 *     一名队友只能被一人守护（引擎规则），所以一台守护者只领一个目标；
 *     **没人可派**时那台自己下「防御」（防御值 +50，下回合开始回 5% HP）—— 这是「会玩」的第三步。
 *  ③ **大招**：默认「自动」（不保留）。理由 = 方案 5.1.1 的武器优先级本来就是「大招冷却好了优先放」
 *     （`50-AI.js:62-63`）；保留只会让这一回合退化成普通武器。对照表里的「大招全保留」量了它的代价。
 *  ④ **TRANS-AM（天人）**：每回合给所有机体下 `TRANSAM:'手动'` + `本回合开TRANSAM:true` ——
 *     引擎（`72-势力.js` 的 `手动开天人()`）只在「CD 已到且不在 TRANS-AM 中」时才真的开，
 *     所以效果 = **CD 一到就开**（持续 2 / CD 3 → 第 1、5、9 回合开，覆盖率拉满），
 *     同时把「单位级手动开关」这条路真的走了一遍。
 *  ⑤ **Boss 档换位躲大技能**：这一回合的 `算意图()` 里有 `大技能` 时，用 `areaSlots()` 算出它的落点，
 *     落点里**HP 比例 < 50%** 的队友如果**对位**（`对位(位)[0]`，和 `换位目标()` 挑的是同一格）
 *     站着一位 HP 比例 ≥ 75% 的队友，就让它下「换位」—— 把残血的换出落点、血厚的换进去。
 *     ⚠ 这一条**改变不了总伤害**（蓝肥鱼的 `周身冲击` 是 `area` 默认 `row` = 打一整排，
 *       9 台摆满时两排都有人，总有一排挨打），它换来的是**「这一下别打在快死的那台身上」**。
 *       值不值由对照表里的「不换位躲大技能」一行回答。
 *  ⑥ 其余（守护者、防御者）之外的人一律「进攻」。所有分支都是**纯函数**，不改战斗状态。
 * ------------------------------------------------------------------------- */
function 策略指令(ctx, 配置) {
  const g = 载入内核();
  const 参 = 作弊配置(配置);
  const 我 = g.livingOf('ally', ctx), 敌 = g.livingOf('enemy', ctx);
  const 表 = {};
  for (const u of 我) 表[u.slot] = {
    类型: '进攻', 目标位: null, 保留大招: !!参.大招全保留,
    /* ④ 天人 TRANS-AM：切成手动 + 本回合点开（没有 `transAm` 的机体引擎会自己忽略） */
    TRANSAM: 参.TRANSAM手动 ? '手动' : '自动', 本回合开TRANSAM: !!参.TRANSAM手动,
  };
  if (!我.length || !敌.length || !参.策略) return 表;

  /* 我方每台这一回合的期望输出（用引擎自己的默认 AI 估一次；`aiAction` 是纯函数） */
  const 输出 = new Map(我.map(u => { const a = g.aiAction(u, ctx); return [u, (a && a.expected) || 0]; }));
  const 意图 = g.算意图(ctx);
  const 意图Of = 位 => 意图.find(x => x.单位位 === 位) || null;
  const 武器Of = (攻, 名) => { const e = ((攻 && 攻.weapons) || []).find(x => x.t && x.t.name === 名); return e ? e.t : null; };

  /* ② 守护 / 防御（先做：它决定谁这一回合不出手；① 集火之后只覆盖还想进攻的那些位） */
  if (参.守护) {
    const 危险 = [];
    for (const it of 意图) {
      if (!(it.期望 > 0) || it.目标位 == null) continue;
      const 攻 = 敌.find(x => x.slot === it.单位位);
      const 目标 = 我.find(x => x.slot === it.目标位);
      if (!攻 || !目标) continue;
      const w = 武器Of(攻, it.武器);
      if (w && g.isAreaKind(g.rangeKindOf(w))) continue;      // 范围打不吃守护（60-战斗.js:370 只对非范围改打守护者）
      if (it.期望 >= 目标.hp) 危险.push(目标);
    }
    危险.sort((a, b) => (输出.get(b) - 输出.get(a)) || (b.hp - a.hp) || (a.slot - b.slot));
    const 已用 = new Set();
    for (const 目标 of 危险) {
      if (已用.has(目标.slot) || 表[目标.slot].类型 !== '进攻') continue;   // 它自己已经是别人的守护者 / 已经在做别的
      const 护 = 我.filter(u => u !== 目标 && !已用.has(u.slot) && 表[u.slot].类型 === '进攻')
        .sort((a, b) => (输出.get(a) - 输出.get(b)) || (b.maxHp - a.maxHp) || (a.slot - b.slot))[0];
      if (护) { 表[护.slot] = Object.assign(表[护.slot], { 类型: '守护', 目标位: 目标.slot }); 已用.add(护.slot); }
      else 表[目标.slot] = Object.assign(表[目标.slot], { 类型: '防御', 目标位: null });
    }
  }

  /* ① 集火（只改还想「进攻」的那些位） */
  if (参.集火) {
    const 威胁 = 敌.map(e => { const it = 意图Of(e.slot); return { e, 期望: (it && it.期望) || 0 }; });
    威胁.sort((a, b) => (b.期望 - a.期望) || (a.e.hp - b.e.hp) || (a.e.slot - b.e.slot));
    const 位 = 威胁.length ? 威胁[0].e.slot : null;
    if (位 != null) for (const u of 我) if (表[u.slot].类型 === '进攻') { 表[u.slot].类型 = '集火'; 表[u.slot].目标位 = 位; }
  }

  /* ⑤ Boss 档：换位躲这一回合的大技能落点（只在「落点里有残血 + 对位血厚」时才做） */
  if (参.换位躲大技能) {
    const 已换 = new Set();
    for (const it of 意图) {
      if (!it.大技能 || it.目标位 == null) continue;
      const 攻 = 敌.find(x => x.slot === it.单位位);
      const 中 = 我.find(x => x.slot === it.目标位);
      if (!攻 || !中) continue;
      const w = 武器Of(攻, it.武器);
      if (!w) continue;
      const 落点 = g.areaSlots(w, g.unitRow(中), 中.slot - 行首格(g.unitRow(中)));
      for (const 位 of 落点) {
        const u = 我.find(x => x.slot === 位);
        if (!u || 表[u.slot].类型 !== '进攻' || 已换.has(u.slot)) continue;
        if (u.hp / u.maxHp >= 0.5) continue;                       // 只救残血（<50%）：换位要放弃这一回合的出手
        const 替 = 我.find(x => x.slot === g.对位(位)[0]);          // 换位目标() 优先和「对位」互换
        if (!替 || 替 === u || 已换.has(替.slot)) continue;
        if (替.hp / 替.maxHp < 0.75) continue;                      // 换过去的得是血厚的
        表[u.slot] = Object.assign(表[u.slot], { 类型: '换位', 目标位: null });
        已换.add(u.slot); 已换.add(替.slot);
        break;
      }
    }
  }
  /* 规则触发计数（`配置.计数`；主表会把它写进文档 —— 用来证明这套策略**每一回合真的在做事**，
     不是一个「看起来会玩、其实一条都没触发」的空壳）。 */
  if (参.计数) {
    for (const u of 我) {
      const c = 表[u.slot];
      if (!c) continue;
      参.计数[c.类型] = (参.计数[c.类型] || 0) + 1;
      if (c.类型 === '集火' && c.目标位 != null) 参.计数.集火指派 = (参.计数.集火指派 || 0) + 1;
    }
    try { for (const u of 我) if (g.天人手动可开(u).可以) 参.计数.TRANSAM可开 = (参.计数.TRANSAM可开 || 0) + 1; } catch (e) { /* 没有这条特色就算了 */ }
  }
  return 表;
}

/** 打一场（**一回合一个回合地打**，每回合重下指令 —— 这就是「会玩」和 `simulate` 的区别）。 */
function 打一场策略(我方, 敌方, 种子, 波次, 配置) {
  const g = 载入内核();
  const 参 = 作弊配置(配置);
  /* 开局那一张表只带 TRANS-AM 的开关（`算意图` 要 ctx，所以第一回合的完整指令在 `开局()` 之后补下）：
     天人「手动开」发生在 `势力开局()` 里（`72-势力.js`），所以它必须**在开局时就带上**。 */
  const 起手 = {};
  if (参.策略 && 参.TRANSAM手动) for (const m of 我方) 起手[m.位] = { 类型: '进攻', TRANSAM: '手动', 本回合开TRANSAM: true };
  const ctx = g.开局(我方, 敌方, 种子, (参.策略 && 参.TRANSAM手动) ? 起手 : null, { 波次: 参.波次 ? (波次 || []) : [] });
  let 护栏 = 0;
  while (!ctx.result && 护栏++ < 20) {
    g.设指令(ctx, 参.策略 ? 策略指令(ctx, 参) : null);
    g.打一回合(ctx);
  }
  if (!ctx.result) ctx.result = { 结果: '败', 原因: '超出回合上限' };
  /* 天人那条特色**真的开过几次**（记录里 `势力记录()` 写的字段：`特色 / 结果 / 开启方式`）——
     读记录比在指令阶段猜状态准（`手动开天人()` 是在 `回合开始` 里执行的，指令阶段还没到点）。 */
  if (参.计数) {
    for (const r of ctx.log) {
      if (r.特色 !== 'TRANS-AM') continue;
      if (r.结果 === '启动') { 参.计数.TRANSAM启动 = (参.计数.TRANSAM启动 || 0) + 1; if (r.开启方式 === '手动') 参.计数.TRANSAM手动启动 = (参.计数.TRANSAM手动启动 || 0) + 1; }
      if (r.结果 === '结束') 参.计数.TRANSAM结束 = (参.计数.TRANSAM结束 || 0) + 1;
    }
  }
  return ctx;
}

/** 一场的「结果 + 回合数 + 剩余 HP 比例」（和组队表同一套口径）。 */
function 一场统计(ctx) {
  const 我 = ctx.allies || [];
  const 满 = 我.reduce((a, u) => a + u.maxHp, 0) || 1;
  const 剩 = 我.reduce((a, u) => a + Math.max(0, u.hp), 0);
  return { 胜: ctx.result && ctx.result.结果 === '胜', 回合数: ctx.turn, 血比例: 剩 / 满 };
}

