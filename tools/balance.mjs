/* ============================ main ============================ */
/**
 * 跑一轮，返回 `{md, 单挑, 组队, 汇总, 单点, 写入, 用时}`。
 * **纯函数式**：同参数同一结果；不打印、不退出（打印 / 退出在文件最后的 CLI 块）。
 * 出错了抛异常（`参数错` = 命令行写错；其他 = 内核加载不了）。
 */
function main(argv = [], 基线 = {}) {
  const t0 = Date.now();
  参数 = 解析参数(argv, 基线);
  if (参数.help) return { 帮助: true, md: 帮助, 单挑: [], 组队: [], 汇总: [], 单点: null, 作弊: null, 写入: false, 用时: 0 };
  G = null; 载入内核();
  /* ★ `--cheat` 是**另一个口径**（作弊上限），它有自己的表和自己的输出文件；
     这条路上**不跑**单挑 / 组队那三张表，也**不碰** `docs/平衡表.md`。 */
  if (参数.mode === 'cheat') {
    const 作弊 = 跑作弊();
    const md = 组装作弊(作弊);
    let 写入 = null;
    if (参数.write) { writeFileSync(参数.out, md, 'utf8'); 写入 = 参数.out; }
    return { md, 单挑: [], 组队: [], 汇总: [], 单点: null, 作弊, 写入, 用时: (Date.now() - t0) / 1000, 参数: Object.assign({}, 参数) };
  }
  const 单挑 = (参数.mode === 'team') ? [] : 跑单挑();
  const 组队 = (参数.mode === 'solo' || 参数.mode === 'one') ? [] : 跑组队();
  const 汇总 = 组队.length ? 按档汇总(组队) : [];
  const 单点 = (参数.mode === 'one') ? 跑单点() : null;
  const md = 组装(单挑, 组队, 单点, 汇总);
  let 写入 = null;
  if (参数.write && 参数.mode !== 'one') { writeFileSync(参数.out, md, 'utf8'); 写入 = 参数.out; }
  return { md, 单挑, 组队, 汇总, 单点, 作弊: null, 写入, 用时: (Date.now() - t0) / 1000, 参数: Object.assign({}, 参数) };
}

/* ============================ CLI（只有直接 node 这个文件时才跑） ============================ */
const 直接跑 = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;
if (直接跑) {
  const 传参 = process.argv.slice(2);
  let r;
  try {
    r = main(传参);
  } catch (e) {
    console.error(e instanceof 参数错 ? e.message : (e && e.message ? e.message : String(e)));
    process.exit(e instanceof 参数错 ? 2 : 1);
  }
  if (r.帮助) { console.log(r.md); process.exit(0); }
  if (r.写入) console.error(`已写入 ${r.写入}（${r.md.length} 字符，用时 ${r.用时.toFixed(1)}s）`);
  else if (r.参数.write) console.error('单点查询模式不写 docs/平衡表.md（加 --team / --solo，或去掉 --char 才写）。');
  if (!r.参数.quiet) console.log(r.md);
  else if (r.单点) console.log(r.单点.胜率 + '% / ' + 小数(r.单点.平均回合) + ' 回合 / 每回合 ' + Math.round(r.单点.平均每回合伤害));
  if (r.作弊) {
    const 整体 = (行0) => {
      const 场 = 行0.reduce((a, x) => a + x.总场, 0) || 1;
      return Math.round(行0.reduce((a, x) => a + x.胜率 * x.总场, 0) / 场);
    };
    console.error(`作弊口径：${r.作弊.台数} 台 + ${r.作弊.藏品.length} 件藏品；`
      + `主表 ${r.作弊.主表.length} 行、对照 ${r.作弊.对照.length} 组 × ${r.作弊.主表.length} 行；`
      + `主表整体胜率 ${整体(r.作弊.主表)}%、`
      + `100% 的「层 × 档」${r.作弊.主表.filter(x => x.胜率 >= 100).length}/${r.作弊.主表.length}；用时 ${r.用时.toFixed(1)}s`);
  } else {
    console.error(`行数：单挑 ${r.单挑.length} 行、组队 ${r.组队.length} 行、汇总 ${r.汇总.length} 行；用时 ${r.用时.toFixed(1)}s`);
  }
}

