/* ---- 从逐条战斗记录里统计「一次场次」的战斗量 ----
 * 记录字段出处：`src/js/20-战斗计算.js:306-311` 的 `resolveAttack()` 返回
 * `{文本, 字段:{命中, 伤害, 段数, 命中段数, 暴击, 目标剩余HP, 特种减命中, 详情}}`，
 * `src/js/60-战斗.js:292` 用 `Object.assign(…, rec.字段)` 把它**摊平**进记录，
 * 所以顶层就是 `r.伤害 / r.段数 / r.命中段数 / r.命中`；
 * `单位方 / 单位位 / 目标方 / 目标位 / 回合` 在 `src/js/60-战斗.js:26-32`（`谁()` / `谁目标()`）。
 * `残月余响`（Feena 的**追加攻击**：`src/js/72-势力.js` 的 `残月追加攻击()`，走同一个 `resolveAttack()`）也是同一套字段，
 * 只是 `类型` 是 `残月余响`，所以一起算。★ 作者 2026-10-11 把这条大招从「范围伤害」换成「**队友攻击后追加一发**」之后，
 * 它**只在队友出手之后**才会出现 → 单挑（1 对 1）里一场都不会有，Feena 那三行的伤害是 0（机制使然，不是统计漏了）。 */
const 伤害记录类型 = ['攻击', '残月余响'];
function 战斗统计(记录) {
  let 伤害 = 0, 命中段 = 0, 总段 = 0, 出手 = 0;
  let 主动伤害 = 0, 主动段 = 0, 主动中段 = 0, 主动出手 = 0;
  for (const r of 记录) {
    if (!伤害记录类型.includes(r.类型)) continue;
    if (r.单位方 !== 'ally') continue;        // 只统计我方打出去的（单挑表里就是那名角色自己）
    出手++;
    伤害 += r.伤害 || 0;
    命中段 += r.命中段数 || 0;
    总段 += r.段数 || 1;
    /* 再单独留一份「普通武器（`攻击` 记录）」的账：判「谁强谁弱」用它更公平 ——
       Feena 的「残月的余响」是**队友攻击后追加的那一发**，不是她的普通武器。 */
    if (r.类型 === '攻击') {
      主动出手++; 主动伤害 += r.伤害 || 0;
      主动中段 += r.命中段数 || 0; 主动段 += r.段数 || 1;
    }
  }
  return {
    伤害, 命中段, 总段, 出手,
    主动: { 伤害: 主动伤害, 出手: 主动出手, 命中段: 主动中段, 总段: 主动段 },
  };
}

/** 跑一场：我方编成 vs 敌方编成，返回 {结果, 回合数, ...统计}。 */
function 打一场(我方, 敌方, 种子) {
  const r = 载入内核().simulate(我方, 敌方, null, 种子);
  const 统计 = 战斗统计(r.记录);
  const 我 = r.我方 || [], 敌 = r.敌方 || [];
  const 我活 = 我.filter(u => u.hp > 0).length, 敌活 = 敌.filter(u => u.hp > 0).length;
  const 我血 = 我.reduce((a, u) => a + Math.max(0, u.hp), 0);
  const 我满 = 我.reduce((a, u) => a + u.maxHp, 0) || 1;
  const 敌血 = 敌.reduce((a, u) => a + Math.max(0, u.hp), 0);
  const 敌满 = 敌.reduce((a, u) => a + u.maxHp, 0) || 1;
  return Object.assign({
    结果: r.结果, 原因: r.原因, 回合数: r.回合数,
    我活, 敌活, 我血比例: 我血 / 我满, 敌血比例: 敌血 / 敌满, 记录: r.记录,
  }, 统计);
}

