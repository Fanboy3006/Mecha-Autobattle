/** 把 `index.html` 的内联脚本在 Node 的 vm 里跑起来，取 `window.__game`。跑错就抛。 */
function 载入内核() {
  if (G) return G;
  const page = loadPage(join(ROOT, 'index.html'), { quiet: true });
  if (page.errors.length) {
    throw new Error('index.html 的内联脚本执行报错，平衡工具没法跑：\n  ' + page.errors.join('\n  '));
  }
  const g = page.sandbox.__game;
  if (!g || typeof g.simulate !== 'function' || typeof g.编成到单位 !== 'function') {
    throw new Error('window.__game 里没有 simulate / 编成到单位，加载不完整。');
  }
  G = g;
  return G;
}

