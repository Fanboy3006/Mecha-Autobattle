/* ============================ [1] 单挑表 ============================ */
function 跑单挑() {
  const g = 载入内核();
  const 场次 = 参数.quick ? 5 : 10;
  const 行 = [];
  for (const t of g.ALLY_T) {
    const 键 = t.mech;
    for (const lv of 等级列表) {
      const 我 = [{ 键, 位: 0, 等级: lv }];
      const 敌 = 标准靶(lv);
      let 胜 = 0, 回合 = 0, 伤害 = 0, 命中段 = 0, 总段 = 0, 出手 = 0, 活 = 0;
      let 主动伤害 = 0, 主动出手 = 0;
      for (let i = 0; i < 场次; i++) {
        const r = 打一场(我, 敌, 场种子(1, lv, i, 键.charCodeAt(0) + (键.charCodeAt(1) || 0)));
        if (r.结果 === '胜') 胜++;
        回合 += r.回合数; 伤害 += r.伤害; 命中段 += r.命中段; 总段 += r.总段; 出手 += r.出手;
        主动伤害 += r.主动.伤害; 主动出手 += r.主动.出手;
        活 += r.我活;
      }
      const 回合数 = 回合 / 场次;
      行.push({
        键, 名: t.pilot, 职业: (t.tags || {}).战斗分类 || '—', 档: g.tierOf(键), lv,
        胜率: 百分(胜, 场次), 平均回合: 回合数,
        平均每回合伤害: 回合数 ? 伤害 / 场次 / 回合数 : 0,
        每场伤害: 伤害 / 场次,
        主动每回合: 回合数 ? 主动伤害 / 场次 / 回合数 : 0,
        主动出手: 主动出手 / 场次,
        命中率: 总段 ? 命中段 / 总段 : null,
        出手: 出手 / 场次, 存活率: 百分(活, 场次),
      });
    }
  }
  return 行;
}

const 单挑表 = 行 => {
  const 头 = '| 角色 | 键 | 职业 | 档 | 等级 | 胜率 | 平均回合 | 平均每回合伤害 | 每场总伤害 | 命中率 | 存活 |';
  const 线 = '|---|---|---|---|---|---|---|---|---|---|---|';
  const 体 = 行.map(r => `| ${r.名} | ${r.键} | ${r.职业} | ${r.档} | Lv${r.lv} | ${r.胜率}% | ${小数(r.平均回合)} | `
    + `${Math.round(r.平均每回合伤害)} | ${Math.round(r.每场伤害)} | ${r.命中率 == null ? '—' : 百分(r.命中率, 1) + '%'} | ${r.存活率}% |`);
  return [头, 线, ...体].join('\n');
};

/* ============================ [2] 组队表 ============================ */
/** 默认五人队 × 等级：位次照 `70-编成.js:242-248` 的 前3 后2，只改等级。 */
const 五人队 = lv => 载入内核().默认五人队.map(s => ({ 键: s.键, 位: s.位, 等级: lv }));

function 跑组队() {
  const g = 载入内核();
  const 每档 = 每档场次();
  const 行 = [];
  for (const lv of 等级列表) {
    for (const 层 of [1, 2, 3, 4]) {
      for (const 档 of 档列表) {
        const 候选 = g.选编成(层, 档);
        if (!候选.length) continue;                  // 第 1 层没有侵蚀源、第 4 层没有精英/守军/侵蚀源
        let 胜 = 0, 回合 = 0, 血 = 0, 总场 = 0;
        const 逐条 = [];
        for (let ci = 0; ci < 候选.length; ci++) {
          const 条目 = 候选[ci];
          let 条胜 = 0, 条回合 = 0, 条血 = 0;
          for (let i = 0; i < 每档; i++) {
            const 敌军 = g.编成到单位(条目, 0).map(u => ({ 键: u.key, 位: u.slot, 等级: u.lv }));
            const r = 打一场(五人队(lv), 敌军, 场种子(2, lv, 层 * 100 + ci, i));
            if (r.结果 === '胜') { 胜++; 条胜++; }
            回合 += r.回合数; 条回合 += r.回合数;
            血 += r.我血比例; 条血 += r.我血比例;
            总场++;
          }
          逐条.push({ 编号: ci + 1, 胜率: 百分(条胜, 每档), 平均回合: 条回合 / 每档, 血比例: 条血 / 每档 });
        }
        行.push({
          lv, 层, 档, 条数: 候选.length, 场次: 每档, 总场,
          胜率: 百分(胜, 总场), 平均回合: 回合 / 总场, 血比例: 血 / 总场, 逐条,
          // 给结论段用：这一档的敌人在「一进这一层」时的等级（编成到单位 的 runEnemyLv + 梯队）
          敌等级: g.编成到单位(候选[0], 0).map(u => u.lv),
          考点: 候选.map(e => e.考点),
        });
      }
    }
  }
  return 行;
}

const 组队表 = 行 => {
  const 头 = '| 队伍等级 | 层 | 编成档 | 条数 | 场次 | 胜率 | 平均回合 | 平均剩余 HP 比例 | 敌方等级 |';
  const 线 = '|---|---|---|---|---|---|---|---|---|';
  const 体 = 行.map(r => `| Lv${r.lv} | ${r.层} | ${r.档} | ${r.条数} | ${r.场次}×${r.条数}=${r.总场} | `
    + `**${r.胜率}%** | ${小数(r.平均回合)} | ${百分(r.血比例, 1)}% | ${[...new Set(r.敌等级)].join('/')} |`);
  return [头, 线, ...体].join('\n');
};

/** 组队表的「按档汇总」小表（把同档的 1–4 层合并看）——结论段引用它。 */
function 按档汇总(行) {
  const 出 = [];
  for (const lv of 等级列表) {
    for (const 档 of 档列表) {
      const 有 = 行.filter(r => r.lv === lv && r.档 === 档);
      if (!有.length) continue;
      const 场 = 有.reduce((a, r) => a + r.总场, 0);
      const 胜 = 有.reduce((a, r) => a + r.胜率 * r.总场, 0) / 场;
      const 回 = 有.reduce((a, r) => a + r.平均回合 * r.总场, 0) / 场;
      const 血 = 有.reduce((a, r) => a + r.血比例 * r.总场, 0) / 场;
      出.push({ lv, 档, 层数: 有.length, 总场: 场, 胜率: 胜, 平均回合: 回, 血比例: 血 });
    }
  }
  return 出;
}

/* ============================ [3] 单点查询 ============================ */
function 跑单点() {
  const g = 载入内核();
  const 键 = 参数.char, lv = 参数.lv;
  const t = g.ALLY_T.find(a => a.mech === 键);
  if (!t) {
    throw new 参数错(`没有这个角色键：${键}（可用的是 ALLY_T 里的 34 个键，例如 B1 / CB2 / M1）`);
  }
  const 场 = 参数.quick ? 5 : 10;
  const 我 = [{ 键, 位: 0, 等级: lv }], 敌 = 标准靶(lv);
  let 胜 = 0, 回合 = 0, 伤害 = 0, 命中段 = 0, 总段 = 0;
  let 样例 = null;
  for (let i = 0; i < 场; i++) {
    const r = 打一场(我, 敌, 场种子(1, lv, i, 键.charCodeAt(0) + (键.charCodeAt(1) || 0)));
    if (r.结果 === '胜') 胜++;
    回合 += r.回合数; 伤害 += r.伤害; 命中段 += r.命中段; 总段 += r.总段;
    if (i === 0) 样例 = r;
  }
  return {
    键, 名: t.pilot, 职业: (t.tags || {}).战斗分类, 档: g.tierOf(键), lv, 场次: 场,
    胜率: 百分(胜, 场), 平均回合: 回合 / 场,
    平均每回合伤害: 回合 ? 伤害 / 场 / 回合 : 0,
    命中率: 总段 ? 命中段 / 总段 : null,
    抽样: 样例,
    样例种子: 场种子(1, lv, 0, 键.charCodeAt(0) + (键.charCodeAt(1) || 0)),
  };
}

