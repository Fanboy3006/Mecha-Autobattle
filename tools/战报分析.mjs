/** 渲染跨场对比表。 */
function 渲染对比(各场) {
  const L = [];
  L.push('# 5. 跨场对比');  L.push('');
  if (各场.length < 2) {
    L.push('（只喂了一份记录，没有可对比的第二场 —— 再喂几份 `作战记录-*.txt` 就会出这张表）');
    L.push('');
    return L;
  }
  if (!各场.some(x => x.模型.种类 === '作战记录')) {
    L.push('（这次只有「本局日志」—— 跨场对比表比的是战斗内指标（输出 / 命中 / 大招 / 防御），要作战记录才有）');
    L.push('');
    return L;
  }
  L.push('| 文件 | 结果 | 回合 | 我方输出 | 敌方输出 | 我方占比 | 方针使用分布 | 大招伤害占比(全场) | 防御回合 | 我方命中率 | 暴击 | 阵亡(我/敌) | 条数 |');
  L.push('|---|---|---:|---:|---:|---:|---|---:|---:|---:|---:|---:|---:|');
  for (const x of 各场) {
    const 统 = x.统, 摘 = x.模型.摘要;
    const 方针分布 = (() => {
      const 表 = 摘.方针表 || {};
      const 键 = Object.keys(表).map(Number).sort((a, b) => a - b);
      if (!键.length) return '记录里没有这一项';
      const 计 = new Map();
      for (const k of 键) 计.set(表[k].类型, (计.get(表[k].类型) || 0) + 1);
      return [...计.entries()].sort((a, b) => b[1] - a[1]).map(([k, v]) => `${k} ${v}`).join(' · ');
    })();
    const 双方 = 统.我方.输出 + 统.敌方.输出;
    const 次 = 统.我方.命中次数 + 统.我方.未命中次数;
    const 阵亡 = x.重放 && !x.重放.存疑
      ? `${x.重放.阵亡.filter(d => d.方 === 'ally').reduce((a, d) => a + (d.组 ? d.台数 : 1), 0)}/${x.重放.阵亡.filter(d => d.方 === 'enemy').reduce((a, d) => a + (d.组 ? d.台数 : 1), 0)}`
      : '记录里没有这一项';
    const 大招 = x.规 ? 占比(统.大招.伤害, 双方) : '记录里没有这一项';
    const 防 = (摘.方针表 ? Object.keys(摘.方针表).filter(k => /全军防御|前守后攻/.test(摘.方针表[k].类型)).length : 0);
    L.push(`| ${x.模型.文件} | ${摘.结果 || '—'} | ${统.回合数} | ${数(统.我方.输出)} | ${数(统.敌方.输出)} | ${占比(统.我方.输出, 双方)} | ${方针分布} | ${大招} | ${防} 回合 | ${次 ? `${Math.round((统.我方.命中次数 / 次) * 100)}%` : '—'} | ${统.我方.暴击} | ${阵亡} | ${统.总条数} |`);
  }
  L.push('');
  L.push('> 口径：一行的数字全部来自那一份记录里的逐条行；「记录里没有这一项」= 那份记录缺对应字段（例如 `--no-game` 时的大招 / 阵亡）。');
  L.push('');
  return L;
}

