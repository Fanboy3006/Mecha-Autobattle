/** 记账用的**假 fetch**（只记调用、只 resolve，绝不联网）。 */
function 装假fetch(行为) {
  const 调用 = [];
  const f = (址, 选项) => {
    调用.push({ 址, 选项, 体: 选项 && 选项.body });
    假fetch总数.调用++;
    if (行为 === 'reject') return Promise.reject(new Error('假装网络断了'));
    if (行为 === 'throw') throw new Error('假装 fetch 抛了');
    return Promise.resolve({ type: 'opaque' });
  };
  f.调用 = 调用;
  return f;
}
