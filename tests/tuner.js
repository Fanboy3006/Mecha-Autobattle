    const b = G.simulate(我方, G.敌方规格组(G.编成到单位(e.e, 0)), {}, 20261010 + e.i, { 波次: G.编成波次到单位(e.e, 0), 调参: {} });
    if (JSON.stringify(a.记录) === JSON.stringify(b.记录) && a.结果 === b.结果 && a.回合数 === b.回合数) 同++;
