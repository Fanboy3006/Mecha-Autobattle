  if (前格数 === 4 && 后格数 === 4) ok(`阵型上限：前 ${前格数} 格 / 后 ${后格数} 格（共 ${前格数 + 后格数} 格，正交双排 4×2）`);
  else bad(`阵型上限不对：前 ${前格数} / 后 ${后格数}`);
