  if (!超.length) ok(`${编成表.length} 条编成的站位都放得下（前 ≤ ${前格数}、后 ≤ ${后格数}）`);
  else bad(`有 ${超.length} 条编成的人比格子多：${超.map(e => `${e.层}层${e.类型}`).join('、')}`);
  const 空位 = 编成表.filter(e => !(e.前 || []).length && !(e.后 || []).length);
  if (!空位.length) ok('没有一条编成是空的（每条都有人上阵）');
