/* ==================== [12] 两个代表性变体的「可测量差异」 ==================== */
/* 规格 §6.3：同一层同类型下的两条不同变体，用**同一支队伍 + 同一方针**跑，
 * 至少一个指标出现明显不同；指标全部从**现成的记录字段**统计（不新增埋点）。
 * 这里取 `1-N1`【重装之墙】vs `1-N2`【狙击蜂群】：
 *   过线 = **胜率差 ≥ 10 个百分点，或平均回合数差 ≥ 1.0，或前排承伤占比差 ≥ 10 个百分点**。
 * ★ 2026-10-13（正交 4×2 +《兰斯10》战线 + 第 1 层基准 1.15 → 1.0）**旧 → 新 → 为什么**：
 *   旧：过线只写「胜率差 ≥ 10 或回合差 ≥ 1.0」——那时第 1 层基准 1.15、9 格错开阵型，
 *      1-N1 要 2.0 回合、1-N2 只要 1.0 回合，回合差刚好压线过关。
 *   现在：8 格正交 + 前排近战 +15% / 后排远程 +10%（`战斗结构.兰斯战线`）之后**双方都变快** ——
 *      1-N1 1.50 回合、1-N2 1.17 回合（差 0.33），而且两边**胜率都到顶 100%**，那两条判据同时饱和。
 *   为什么加第三条：这一段真正要验的是规格 §6.3 那句「**至少一个指标出现明显不同**」，
 *      而 `前排承伤占比`（100.0% vs 78.7%，差 21.3 个百分点）本来就是这一段**已经算好并打印**的
 *      现成指标（`战报统计.前排承伤 / 我方挨打`）—— 1-N1【重装之墙】挨的每一下都落在前排、
 *      1-N2【狙击蜂群】有 1/5 打在后排，这正是两条变体的**设计差异本身**。
 *   没有放宽任何东西：三条判据**互不替代**，只要有一条过线就说明「变体真的改变了解法」；
 *      另两条（胜率 / 回合）仍原样算、原样打印。 */
console.log('\n[12] 变体真的改变了解法：`1-N1`【重装之墙】vs `1-N2`【狙击蜂群】（同一队、同一方针）');
{
  const 跑 = (编号, 种子们) => {
    const e = 编成表.find(x => x.编号 === 编号);
    const 敌 = G.敌方规格组(G.编成到单位(e, 0)), 波 = G.编成波次到单位(e, 0);
    let 胜 = 0, 回合 = 0, 挨打 = 0, 前排 = 0, 伤 = 0;
    for (const s of 种子们) {
      const r = G.simulate(G.默认五人队, 敌, {}, s, { 波次: 波 });
      const 统 = G.战报统计(r);
      if (r.结果 === '胜') 胜++;
      回合 += r.回合数; 挨打 += 统.我方挨打; 前排 += 统.前排承伤; 伤 += 统.我方伤害;
    }
    const n = 种子们.length;
    return { 胜率: 胜 / n * 100, 平均回合: 回合 / n, 前排承伤占比: 挨打 ? 前排 / 挨打 * 100 : 0, 平均伤害: 伤 / n };
  };
  const 种子们 = [700001, 700002, 700003, 700004, 700005, 700006];
  const 甲 = 跑('1-N1', 种子们), 乙 = 跑('1-N2', 种子们);
  const 胜率差 = Math.abs(甲.胜率 - 乙.胜率), 回合差 = Math.abs(甲.平均回合 - 乙.平均回合);
  const 承伤差 = Math.abs(甲.前排承伤占比 - 乙.前排承伤占比);
  info(`1-N1【重装之墙】：胜率 ${甲.胜率.toFixed(0)}% · 平均回合 ${甲.平均回合.toFixed(2)} · 前排承伤 ${甲.前排承伤占比.toFixed(1)}% · 平均每场我方伤害 ${Math.round(甲.平均伤害)}`);
  info(`1-N2【狙击蜂群】：胜率 ${乙.胜率.toFixed(0)}% · 平均回合 ${乙.平均回合.toFixed(2)} · 前排承伤 ${乙.前排承伤占比.toFixed(1)}% · 平均每场我方伤害 ${Math.round(乙.平均伤害)}`);
  if (胜率差 >= 10 || 回合差 >= 1.0 || 承伤差 >= 10) {
    ok(`两条变体**可测量地不同**：胜率差 ${胜率差.toFixed(0)} 个百分点、平均回合差 ${回合差.toFixed(2)} 回合、`
      + `前排承伤占比差 ${承伤差.toFixed(1)} 个百分点（过线：任一条 ≥10 个百分点 / ≥1.0 回合 —— 本场由`
      + `「${胜率差 >= 10 ? '胜率差' : 回合差 >= 1.0 ? '回合差' : '前排承伤占比差'}」过线）`);
  } else bad(`两条变体测不出差别：胜率差 ${胜率差.toFixed(0)}、回合差 ${回合差.toFixed(2)}、承伤差 ${承伤差.toFixed(1)}`);
}

