/** 把当前这一场打完（自动战斗是一回合一个回合的，要一直点开打） */
function 打完这一场() {
  let 轮 = 0;
  while (界面.屏 === '战斗' && 轮++ < 30) {
    界面.开打();
    let n = 0;
    while (界面.阶段 === '播放' && n++ < 100000) 播放.tick();
  }
}

/** 开一局（走界面，和玩家一样的路） */
function 开一局(种子) {
  界面.动作('回菜单'); 界面.动作('去分队'); 界面.动作('选分队', '无'); 界面.动作('开新局');
  const R = 肉鸽.RUN;
  if (种子 != null) { R.种子 = 种子; 肉鸽.进层(1); }
  return R;
}

/** 把当前格临时改成某个类型（测节点结算用，不动地图生成） */
function 临时格(R, 类型) {
  const k = Object.keys(R.地图.格).map(Number).find(x => !R.地图.格[x].已过 && x !== R.当前) || R.当前;
  const 格 = R.地图.格[k];
  const 旧类型 = 格.类型, 旧已过 = 格.已过, 旧当前 = R.当前;
  R.当前 = k; 格.类型 = 类型; 格.已过 = false;
  return () => { 格.类型 = 旧类型; 格.已过 = 旧已过; R.当前 = 旧当前; };
}

/** 走完一局（第 [7] 段用）：挑这一格能做的事做完，再走到战斗 / 出口节点；
 *  推进剂用光就打追击战，实在走不动就用「喷气背包 / 小八界」（任意格、不花推进剂）。 */
function 走一局(种子, 记录 = null) {
  const R = 开一局(种子);
  let 步 = 0, 空转 = 0;
  while (肉鸽.进行中 && R.层 <= 4 && 步++ < 600) {
    if (界面.屏 === '肉鸽结算') break;
    if (界面.屏 === '黑市') { 界面.动作('黑市离开'); continue; }
    if (界面.屏 === '招募') { 界面.动作('回大地图'); continue; }
    if (界面.屏 === '奇遇') { 界面.动作('奇遇', '希望'); continue; }
    const 菜单 = 肉鸽.格菜单();
    if (菜单.length) {
      const 动 = 菜单[0].动;
      if (动 === '打这一场') {
        if (记录) 记录.push(`第${R.层}层 打 ${R.地图.格[R.当前].类型}`);
        界面.动作('打这一场');
        if (界面.屏 === '编队') { 界面.编队.出击 = R.队伍.slice(0, 5).map((m, i) => ({ 键: m.键, 位: i })); 界面.动作('开战'); }
        if (界面.屏 === '战斗') 打完这一场();
        continue;
      }
      if (动 === '去黑市') { 界面.动作('去黑市'); continue; }
      if (动 === '去招募') { 界面.动作('去招募'); continue; }
      if (动 === '去奇遇') { 界面.动作('去奇遇'); continue; }
      if (动 === '瞭望') { 界面.动作('瞭望'); continue; }
      if (动 === '穿隧道') { 界面.动作('穿隧道'); continue; }
      if (动 === '探查遗迹') { 界面.动作('探查遗迹'); continue; }
      if (动.startsWith('休整:')) { 界面.动作('休整', '耐久'); continue; }
      if (动 === '前进') { 界面.动作('前进'); continue; }
      if (动 === '跳过') { 界面.动作('跳过节点'); continue; }
      if (动.startsWith('去节点:')) { 界面.去节点(Number(动.slice(4))); continue; }
    }
    let 能去 = 肉鸽.能去的();
    if (!能去.length && R.推进剂 <= 0) {
      const 前层 = R.层;
      if (记录) 记录.push(`第${R.层}层 追击战`);
      界面.追击战();
      if (界面.屏 === '战斗') 打完这一场();
      if (R.层 !== 前层 || !肉鸽.进行中) continue;
    }
    if (!能去.length) {
      const 件 = (R.零件 || []).map((p, i) => i).filter(i => G.零件表[R.零件[i].k].移动 === 'any');
      if (件.length) {
        const i = 件[0], 目标们 = G.零件目标(R.零件[i]);
        const 出口 = 目标们.find(k => R.地图.格[k].类型 === '出口');
        const 战斗 = 目标们.find(k => ['出口守军', '精英', '侵蚀源', '作战'].includes(R.地图.格[k].类型));
        const 落 = 出口 != null ? 出口 : (战斗 != null ? 战斗 : 目标们[0]);
        if (落 != null) {
          if (记录) 记录.push(`第${R.层}层 用零件【${G.零件表[R.零件[i].k].名}】`);
          界面.使用零件(i);
          const 走前 = R.当前;
          界面.去节点(落);
          if (R.当前 === 走前) 界面.使用零件(i);
          continue;
        }
      }
      能去 = 肉鸽.能去的();
      if (!能去.length) break;
    }
    const 排 = t => 能去.find(n => n.类型 === t);
    let 目标 = null;
    if (R.推进剂 <= 1) 目标 = 能去.find(n => n.类型 === '出口');
    if (!目标) 目标 = 排('出口守军') || 排('精英') || 排('侵蚀源') || 排('作战');
    if (!目标) 目标 = 能去.find(n => n.类型 === '出口');
    if (!目标) 目标 = 排('黑市') || 排('遗迹') || 排('休整') || 排('瞭望站') || 排('招募站') || 排('隧道') || 排('事件') || 能去[0];
    const 走前 = R.当前;
    界面.去节点(目标.k);
    if (R.当前 === 走前) { if (++空转 > 6) break; } else 空转 = 0;
  }
  return {
    层: R.层, 希望: R.希望, 源碳: R.源碳, 耐久: R.耐久, 队伍: R.队伍.length,
    等级: R.等级, 经验: R.经验, 出击上限: 肉鸽.出击上限(),
    藏品: R.藏品.length, 零件: (R.零件 || []).length, 场次: R.场次, 步,
    结局: R.结局 || (R.层 >= 4 ? '未结算' : '未结束'), 原因: R.结局原因 || '',
    来源: Object.assign(G.希望来源空(), R.希望来源 || {}),      // 希望来源账（第 [7] 段要拆「升级」那一格）
  };
}

