  R.希望 = 20;
  const 减价前 = G.晋升要多少('B1', 20, R);
  R.下次晋升减价 = true;
  const 减价后 = G.晋升要多少('B1', 20, R);
  if (减价前 === 3 && 减价后 === 2) ok(`休整的「下次晋升 −1 希望」真的减价（30:60 / 22:446）：B1 的 Lv10→20 ${减价前} → ${减价后} 希望`);
  else bad(`减价不对：${减价前} → ${减价后}（预期 3 → 2）`);
  /* 减价最小 0（照抄 Math.max(0, …)） */
  R.下次晋升减价 = true;
  if (G.晋升要多少('M5', 20, R) === 0) ok('减价之后不会变负数（照抄 22:446 的 Math.max(0, …)）：B 档 1 − 1 = 0');
