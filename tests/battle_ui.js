#!/usr/bin/env node
/* ============================================================================
 * 机甲指挥 · 界面测试（方案第 9 节 M2 的验收）
 * ----------------------------------------------------------------------------
 * 方案 M2：「作者能从菜单进一场固定的测试战斗并打完」；另外方案 8.1 要求
 * 「二倍速 / 跳过动画只影响播放，不影响结果」，所以这里重点验：
 *   1. 菜单 → 编队（选人 / 放位 / 取回 / 默认五人队 / 上限 6）→ 开战；
 *   2. 战斗屏画出双方 2×3 格子、单位卡、战斗记录；
 *   3. **同一种子：跳过动画 vs 手动一步步播，结果和回合数完全一样**；
 *   4. 播放结束自动进结算屏，结算屏显示胜负与种子。
 *
 * 不依赖 Playwright：用 tests/lib/dom-stub.mjs 把 index.html 的内联脚本跑起来。
 * 页面里的动画（setTimeout）在替身里不会自己跑，所以用 `播放.手动 = true` + `播放.tick()`
 * 一步步推进——这正是「播放只是播放」的证据：推进方式不影响结果。
 *
 * 用法：node tests/battle_ui.js
 * ========================================================================== */
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';
import { loadPage } from './lib/dom-stub.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '..');

let fails = 0;
const errs = [];
const ok = m => console.log('  ✓ ' + m);
const bad = m => { fails++; errs.push(m); console.log('  ✗ ' + m); };
const info = m => console.log('    · ' + m);

const page = loadPage(join(ROOT, 'index.html'), { quiet: true });
if (page.errors.length) {
  page.errors.forEach(e => bad('内联脚本执行报错：' + e));
  console.log(`\nERRS [${errs.join(' | ')}]`);
  process.exit(1);
}
const G = page.sandbox.__game;
const 界面 = G.界面, 播放 = G.播放;
界面.手动播放 = true;          // 替身里没有真计时器：播放靠测试自己 tick（见文件头说明）
const 屏文字 = () => String(page.byId.get('screen') && page.byId.get('screen').innerHTML || '');
const 日志文字 = () => String(page.byId.get('log') && page.byId.get('log').innerHTML || '');
console.log(`界面测试：机甲指挥 ${G.version} · ${G.milestone}\n`);

/* ============================ [1] 菜单 → 编队 ============================ */
console.log('[1] 菜单 → 编队');
if (界面.屏 === '菜单') ok('打开页面先到菜单屏');
else bad(`打开页面停在「${界面.屏}」屏`);
if (屏文字().includes('开始编队')) ok('菜单屏有「开始编队」入口');
else bad('菜单屏没有入口按钮');
界面.动作('去编队');
if (界面.屏 === '编队') ok('进了编队屏');
else bad(`没进编队屏（当前 ${界面.屏}）`);
const 编队HTML = 屏文字();
for (const 关键词 of ['机师', '出击编队', '敌方编成', '空位']) {
  if (编队HTML.includes(关键词)) ok(`编队屏有「${关键词}」`);
  else bad(`编队屏缺少「${关键词}」`);
}
if (编队HTML.includes('速 ')) ok('机师列表里显示了速度（方案 8.1 要求显示速度和大招）');
else bad('机师列表里没有速度');

/* ============================ [2] 编队操作 ============================ */
console.log('\n[2] 编队：选人 / 放位 / 取回 / 上限');
界面.清空();
if (界面.编队.出击.length === 0) ok('清空后 0 台');
界面.选人('B1');
if (界面.编队.选中 === 'B1') ok('选中了雷萨（B1）');
界面.放位(0);
if (界面.编队.出击.length === 1 && 界面.编队.出击[0].位 === 0) ok('放进前排 1 号位');
else bad(`放位失败：${JSON.stringify(界面.编队.出击)}`);
const 放入前 = 界面.编队.出击.length;
界面.选人('B1'); 界面.放位(3);          // 同一台再放一次应该被挡住
if (界面.编队.出击.length === 放入前) ok('同一台机体不会被重复编入');
else bad('同一台机体被编入了两次');
界面.取回(0);
if (界面.编队.出击.length === 0) ok('点已放的位置可以取回');
else bad('取回失败');
界面.默认五人队();
if (界面.编队.出击.length === 5) ok(`「默认五人队」一键摆好 5 台：${界面.编队.出击.map(x => x.键 + '@' + x.位).join('、')}`);
else bad(`默认五人队给了 ${界面.编队.出击.length} 台`);
for (const 键 of ['M2', 'M3', 'M4', 'CB1', 'CB2', 'CB3', 'CB4', 'CB5']) {   // 再塞几台试上限
  if (界面.编队.出击.length >= G.slots) break;
  界面.选人(键); 界面.放位(界面.编队.出击.length === 0 ? 0 : [0, 1, 2, 3, 4, 5].find(p => !界面.编队.出击.some(x => x.位 === p)));
}
if (界面.编队.出击.length <= G.slots) ok(`出击上限生效：${界面.编队.出击.length} ≤ ${G.slots}`);
else bad(`出击超过上限：${界面.编队.出击.length}`);
界面.设等级(20);
if (界面.编队.等级 === 20 && 屏文字().includes('Lv20')) ok('可以切 Lv10 / Lv20 / Lv30（编队屏会重算速度和大招）');
else bad('等级切换没生效');
界面.设等级(10);
界面.默认五人队();

/* ============================ [3] 开战 + 战斗屏 ============================ */
console.log('\n[3] 开战：战斗屏');
界面.开战(20261010);
if (界面.屏 === '战斗') ok('开战后进了战斗屏');
else bad(`开战后停在「${界面.屏}」屏`);
const 战报 = 界面.战报;
if (战报 && 战报.我方.length === 5 && 战报.敌方.length >= 1) ok(`战报：我方 ${战报.我方.length} 台 vs 敌方 ${战报.敌方.length} 台，${战报.回合数} 回合，${战报.记录.length} 条记录`);
else bad('战报不对');
const 战斗HTML = 屏文字();
if ((战斗HTML.match(/class="uc/g) || []).length >= 8) ok(`战斗屏画出了 ${(战斗HTML.match(/class="uc/g) || []).length} 个单位卡（双方 2×3 格子）`);
else bad('战斗屏的格子太少');
for (const 关键词 of ['我方', '敌方', '战斗记录', '前排', '后排']) {
  if (战斗HTML.includes(关键词)) ok(`战斗屏有「${关键词}」`);
  else bad(`战斗屏缺少「${关键词}」`);
}
if (战斗HTML.includes('后排在上')) ok('我方后排在上、前排贴住接触线（两边前排相邻）');
if (!/undefined|NaN/.test(战斗HTML)) ok('战斗屏的 HTML 里没有 undefined / NaN（模板没有漏字段）');
else bad('战斗屏的 HTML 里出现了 undefined / NaN');
if (!/undefined|NaN/.test(编队HTML)) ok('编队屏的 HTML 里没有 undefined / NaN');
else bad('编队屏的 HTML 里出现了 undefined / NaN');

/* ============================ [4] 播放：一步步 vs 跳过，结果必须一样 ============================ */
console.log('\n[4] 播放方式不影响结果（方案 8.1：二倍速 / 跳过动画只影响播放）');
const 记录甲 = JSON.stringify(战报.记录);
const 结果甲 = 战报.结果 + '/' + 战报.回合数;

/* 4a. 手动一步步播（模拟二倍速下的播放：同样是逐条应用，只是间隔不同） */
播放.手动 = true;
播放.设倍速(2);
界面.开打();
let 步 = 0;
while (播放.在放() && 步++ < 100000) 播放.tick();
if (!播放.在放()) ok(`手动播完 ${步} 条记录（二倍速，逐条 tick）`);
else bad('手动播放没走完');
if (界面.屏 === '结算') ok('播放结束自动进结算屏');
else bad(`播放结束停在「${界面.屏}」屏`);
if (日志文字().includes('伤害') || 日志文字().includes('跳过')) ok('战斗记录面板里真的有内容（界面把记录一条条追进去了）');

/* 4b. 同一编队、同一种子，改成「跳过动画」再打一遍 */
界面.动作('去编队');
界面.默认五人队();
界面.开战(20261010);
界面.设跳过动画(true);              // 按「跳过动画」：本场直接到结尾，之后每场也直接到结尾
if (界面.屏 === '结算') ok('「跳过动画」直接到结算');
else bad(`「跳过动画」之后停在「${界面.屏}」`);
const 战报乙 = 界面.战报;
if (战报乙.结果 + '/' + 战报乙.回合数 === 结果甲 && JSON.stringify(战报乙.记录) === 记录甲) ok(`同种子两种播法结果完全一样：${结果甲}，${战报乙.记录.length} 条记录逐字相同`);
else bad(`播放方式改变了结果：${结果甲} vs ${战报乙.结果 + '/' + 战报乙.回合数}`);

/* 4c. 换种子应该（通常）不一样 —— 只做提示，不做断言 */
界面.设跳过动画(false);             // 关掉「总是跳过」，回到逐条播放
界面.开战(99999);
界面.开打();
let 步2 = 0;
while (播放.在放() && 步2++ < 100000) 播放.tick();
info(`换个种子：${界面.战报.结果} · ${界面.战报.回合数} 回合（原种子 ${结果甲}）`);

/* ============================ [5] 结算屏 ============================ */
console.log('\n[5] 结算屏');
const 结算HTML = 屏文字();
if (结算HTML.includes('回合数') && 结算HTML.includes('我方存活') && 结算HTML.includes('种子')) ok('结算屏有回合数 / 存活 / 种子');
else bad('结算屏信息不全');
if (结算HTML.includes('战斗胜利') || 结算HTML.includes('战斗失败')) ok('结算屏写明了胜负');
else bad('结算屏没有胜负');

/* ============================ [6] 界面动作的其它路径 ============================ */
console.log('\n[6] 其它按钮路径');
界面.动作('回菜单');
if (界面.屏 === '菜单') ok('「回菜单」可用');
界面.动作('去编队'); 界面.默认五人队();
const 编成数 = G.编成表.length;
界面.设编成(编成数 - 1);
if (界面.编队.编成序号 === 编成数 - 1) ok(`可以换敌方编成（共 ${编成数} 条，方案第 10 节第 4 条说这几条是初稿）`);
界面.设编成(999);
if (界面.编队.编成序号 === 编成数 - 1) ok('编成序号越界会被夹住，不会崩');
界面.开战();
界面.设跳过动画(true);
界面.动作('再来一场');   // 换种子再来一场（偏好还开着，所以这场也直接到结尾）
if (界面.战报 && 界面.屏 === '结算') ok(`「再来一场」能再打一场（结果 ${界面.战报.结果} · 种子 ${界面.战报.种子}）`);
else bad(`「再来一场」之后停在「${界面.屏}」，播放位置 ${播放.位置}/${播放.事件().length}`);
界面.动作('回菜单');

/* ============================ 结果 ============================ */
console.log(`\nERRS [${errs.join(' | ')}]`);
console.log(fails ? `共 ${fails} 项失败` : '界面测试全部通过');
process.exit(fails ? 1 : 0);
