#!/usr/bin/env node
/* ============================================================================
 * 机甲指挥 · 界面测试（方案第 9 节 M2 / M3 的验收）
 * ----------------------------------------------------------------------------
 * M2：作者能从菜单进一场固定的测试战斗并打完；播放 / 暂停 / 二倍速 / 跳过动画只影响播放。
 * M3：指令阶段能下指令（进攻 / 集火 / 守护 / 防御 / 换位 + 大招开关）、能看到敌人意图、
 *     能一回合一个回合地打（指令留着，不想改就直接开打）。
 *
 * 不依赖 Playwright：用 tests/lib/dom-stub.mjs 把 index.html 的内联脚本跑起来。
 * 页面里的动画（setTimeout）在替身里不会自己跑，所以用 `界面.手动播放 = true` + `播放.tick()`
 * 一步步推进——这正是「播放只是播放」的证据：推进方式不影响结果。
 *
 * 用法：node tests/battle_ui.js
 * ========================================================================== */
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';
import { loadPage } from './lib/dom-stub.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '..');

let fails = 0;
const errs = [];
const ok = m => console.log('  ✓ ' + m);
const bad = m => { fails++; errs.push(m); console.log('  ✗ ' + m); };
const info = m => console.log('    · ' + m);

const page = loadPage(join(ROOT, 'index.html'), { quiet: true });
if (page.errors.length) {
  page.errors.forEach(e => bad('内联脚本执行报错：' + e));
  console.log(`\nERRS [${errs.join(' | ')}]`);
  process.exit(1);
}
const G = page.sandbox.__game;
const 界面 = G.界面, 播放 = G.播放;
界面.手动播放 = true;          // 替身里没有真计时器：播放靠测试自己 tick（见文件头说明）
const 屏文字 = () => String(page.byId.get('screen') && page.byId.get('screen').innerHTML || '');
const 日志文字 = () => String(page.byId.get('log') && page.byId.get('log').innerHTML || '');
const 播完 = () => { let n = 0; while (播放.在放() && n++ < 100000) 播放.tick(); return n; };
console.log(`界面测试：机甲指挥 ${G.version} · ${G.milestone}\n`);

/* ============================ [1] 菜单 → 编队 ============================ */
console.log('[1] 菜单 → 编队');
if (界面.屏 === '菜单') ok('打开页面先到菜单屏');
else bad(`打开页面停在「${界面.屏}」屏`);
if (屏文字().includes('新的一局') && 屏文字().includes('练习')) ok('菜单屏有「新的一局（肉鸽）」和「练习」入口');
else bad('菜单屏没有入口按钮');
界面.动作('去编队');
if (界面.屏 === '编队') ok('进了编队屏');
else bad(`没进编队屏（当前 ${界面.屏}）`);
const 编队HTML = 屏文字();
for (const 关键词 of ['机师', '出击编队', '敌方编成', '空位']) {
  if (编队HTML.includes(关键词)) ok(`编队屏有「${关键词}」`);
  else bad(`编队屏缺少「${关键词}」`);
}
if (编队HTML.includes('速 ')) ok('机师列表里显示了速度和大招（方案 8.1）');
else bad('机师列表里没有速度');

/* ============================ [2] 编队操作 ============================ */
console.log('\n[2] 编队：选人 / 放位 / 取回 / 上限');
界面.清空();
if (界面.编队.出击.length === 0) ok('清空后 0 台');
界面.选人('B1');
if (界面.编队.选中 === 'B1') ok('选中了雷萨（B1）');
界面.放位(0);
if (界面.编队.出击.length === 1 && 界面.编队.出击[0].位 === 0) ok('放进前排 1 号位');
else bad(`放位失败：${JSON.stringify(界面.编队.出击)}`);
const 放入前 = 界面.编队.出击.length;
界面.选人('B1'); 界面.放位(3);          // 同一台再放一次应该被挡住
if (界面.编队.出击.length === 放入前) ok('同一台机体不会被重复编入');
else bad('同一台机体被编入了两次');
界面.取回(0);
if (界面.编队.出击.length === 0) ok('点已放的位置可以取回');
else bad('取回失败');
界面.默认五人队();
/* 作者 2026-10-10：出击上限是函数（Lv10 → 3 台、Lv20 → 5、Lv30 → 6），所以 Lv10 一键只摆 3 台 */
if (界面.编队.出击.length === G.出击上限(10)) ok(`「摆上前 N 台」按出击上限摆好 ${界面.编队.出击.length} 台（Lv10 上限 ${G.出击上限(10)}）：${界面.编队.出击.map(x => x.键 + '@' + x.位).join('、')}`);
else bad(`默认摆位给了 ${界面.编队.出击.length} 台（Lv10 上限应该是 ${G.出击上限(10)}）`);
界面.设等级(20);
if (界面.编队.等级 === 20 && 屏文字().includes('Lv20')) ok('可以切 Lv10 / Lv20 / Lv30');
else bad('等级切换没生效');
界面.设等级(10);
界面.默认五人队();

/* ============================ [2b] 拖动（作者 2026-10-10） ============================ */
console.log('\n[2b] 拖动：候选 → 格子 / 格子 → 格子 / 拖回候选');
界面.清空();
界面.拖动开始('候选', 'B1'); 界面.拖动放下(3);
if (界面.编队.出击.some(x => x.键 === 'B1' && x.位 === 3)) ok('把机师从列表拖进格子（位 3 = 前 4）');
else bad(`拖动入位失败：${JSON.stringify(界面.编队.出击)}`);
界面.拖动开始('候选', 'B2'); 界面.拖动放下(3);
if (界面.编队.出击.some(x => x.键 === 'B2' && x.位 === 3) && !界面.编队.出击.some(x => x.键 === 'B1')) ok('拖到已占的格子：原来的人被挤回候选列表');
else bad('拖到已占格子时没有挤回原来的人');
界面.拖动开始('候选', 'B1'); 界面.拖动放下(4);        // B1 放后 1
界面.拖动开始('位', 4); 界面.拖动放下(0);             // 格子 → 空格
if (界面.编队.出击.find(x => x.键 === 'B1').位 === 0) ok('格子之间拖：移到空格（后 1 → 前 1）');
else bad('格子之间拖动（移动）没生效');
界面.拖动开始('位', 0); 界面.拖动放下(3);             // B2 在位 3 → 互换
if (界面.编队.出击.find(x => x.键 === 'B1').位 === 3 && 界面.编队.出击.find(x => x.键 === 'B2').位 === 0) ok('格子之间拖：目标有人就互换');
else bad(`互换没生效：${JSON.stringify(界面.编队.出击)}`);
界面.拖动开始('位', 3); 界面.拖动放下('候选');
if (!界面.编队.出击.some(x => x.键 === 'B1')) ok('把格子里的机师拖回候选列表 = 取回');
else bad('拖回候选列表没有取回');
界面.默认五人队();
if (界面.编队.出击.length === G.出击上限(10) && 界面.编队.出击.every(x => x.位 >= 0 && x.位 < G.slots)) {
  ok(`摆位摆在 9 格阵型里的合法格子上（${界面.编队.出击.length} 台 / 出击上限 ${G.出击上限(10)}）`);
} else bad(`摆位不对：${界面.编队.出击.length} 台 / 上限 ${G.出击上限(10)}`);

/* ============================ [3] 开战 → 指令阶段 ============================ */
console.log('\n[3] 开战：指令阶段（M3）');
界面.开战(20261010);
if (界面.屏 === '战斗' && 界面.阶段 === '指令') ok('开战后进战斗屏，停在指令阶段');
else bad(`开战后是「${界面.屏} / ${界面.阶段}」`);
const ctx = 界面.ctx;
if (ctx && ctx.allies.length === G.出击上限(10) && ctx.enemies.length >= 1) ok(`引擎状态：我方 ${ctx.allies.length} 台（Lv10 出击上限 ${G.出击上限(10)}）vs 敌方 ${ctx.enemies.length} 台，第 ${ctx.turn} 回合`);
else bad('引擎状态不对');
const 战斗HTML = 屏文字();
if ((战斗HTML.match(/class="uc/g) || []).length === 2 * G.slots) ok(`战斗屏画出了 ${(战斗HTML.match(/class="uc/g) || []).length} 个单位卡（双方各 ${G.slots} 格：前 4 后 5）`);
else bad('战斗屏的格子太少');
if (战斗HTML.includes('cmdpanel')) ok('战斗屏有指令面板');
else bad('战斗屏没有指令面板');
if (!/undefined|NaN/.test(战斗HTML)) ok('战斗屏的 HTML 里没有 undefined / NaN');
else bad('战斗屏的 HTML 里出现了 undefined / NaN');
const 意图 = G.算意图(ctx);
if (意图.length === ctx.enemies.length) ok(`意图算出来了 ${意图.length} 条（方案 5.3）`);
else bad('意图条数不对');
if (意图.every(i => i.武器 && i.目标位 != null)) ok(`每个敌人都给出了「打谁 + 用什么 + 预计伤害」：${意图.map(i => `${i.名称}→${i.目标名} ${i.武器} 约${i.期望}`).join('；')}`);
else bad(`有敌人的意图不完整：${JSON.stringify(意图)}`);
if ((战斗HTML.match(/class="intent"/g) || []).length === 意图.filter(i => i.武器).length) ok('意图画到了敌人的卡片上');
else bad('卡片上的意图数不对');

/* ============================ [4] 指令阶段的操作 ============================ */
console.log('\n[4] 指令：下指令 / 大招开关');
界面.选单位(0);
if (界面.选中位 === 0) ok('点我方卡片可以选中（位 0）');
if (屏文字().includes('指令 · ')) ok('指令面板显示选中的机体');
界面.下指令('防御');
if (界面.当前指令(0).类型 === '防御') ok('能下「防御」指令');
界面.选单位(1);
界面.下指令('集火');
if (界面.选目标 === '集火') ok('点了「集火」以后进入选目标状态');
界面.点敌人(0);
if (界面.当前指令(1).类型 === '集火' && 界面.当前指令(1).目标位 === 0) ok('点一个敌人就当成了集火目标（位 0）');
else bad(`集火目标没设上：${JSON.stringify(界面.当前指令(1))}`);
界面.选单位(2);
界面.下指令('守护');
界面.点队友(0);
if (界面.当前指令(2).类型 === '守护' && 界面.当前指令(2).目标位 === 0) ok('点一个队友就当成了守护对象（位 0）');
else bad('守护对象没设上');
界面.选单位(3);
界面.下指令('守护');
界面.点队友(0);
if (界面.当前指令(3).类型 !== '守护' || 界面.当前指令(3).目标位 !== 0) ok('一名队友同时只能被一人守护（第二个守护被挡住了）');
else bad('同一名队友被两个人守护了');
const 大招前 = 界面.当前指令(4).保留大招;
界面.切大招(4);
if (界面.当前指令(4).保留大招 === !大招前) ok('大招开关能切（自动 ⇄ 保留）');
else bad('大招开关没生效');
界面.切大招(4);
if (界面.当前指令(4).保留大招 === 大招前) ok('大招开关能切回来');
if (界面.指令[1] && 界面.指令[2] && 界面.指令[3]) ok(`指令会留着（现在记着 ${Object.keys(界面.指令).length} 台的指令）`);

/* ============================ [5] 播放方式不影响结果 ============================ */
console.log('\n[5] 播放方式不影响结果（方案 8.1：二倍速 / 跳过动画只影响播放）');
界面.设跳过动画(false);
播放.设倍速(2);
界面.开打();                       // 第 1 回合
if (界面.阶段 === '播放') ok('「开打」进入播放阶段（打一回合，不是一次算完整场）');
else bad(`「开打」之后阶段是「${界面.阶段}」`);
const 本回合记录 = JSON.stringify(播放.战报.记录);
const 回合数 = ctx.turn;
const 战后血量 = JSON.stringify(ctx.allies.concat(ctx.enemies).map(u => [u.side, u.slot, u.hp]));
const 条数 = 播完();
if (!播放.在放()) ok(`手动播完这一回合的 ${条数} 条记录（二倍速，逐条 tick）`);
else bad('手动播放没走完');
if (界面.阶段 === '指令' || 界面.阶段 === '结算') ok(`回合播完回到「${界面.阶段}」（方案 3.2：指令留着，不想改就直接开打）`);
else bad(`回合播完停在「${界面.阶段}」`);
if (日志文字().includes('回合')) ok('战斗记录面板里真的有内容');

/* 同一编队、同一种子、同一套指令，改成「跳过动画」再打第 1 回合 → 逐字相同 */
const 存指令 = JSON.parse(JSON.stringify(界面.指令));   // 开战会把指令清空，这里存一份用来还原来
界面.设跳过动画(false);
界面.开战(20261010);
界面.指令 = JSON.parse(JSON.stringify(存指令));
界面.设跳过动画(true);
界面.开打();
const 记录乙 = JSON.stringify(播放.战报.记录);
if (记录乙 === 本回合记录) ok(`同种子同指令、两种播法：第 1 回合逐字相同（${JSON.parse(本回合记录).length} 条）`);
else bad('播放方式改变了这一回合的结果');
if (界面.ctx.turn === 回合数 && JSON.stringify(界面.ctx.allies.concat(界面.ctx.enemies).map(u => [u.side, u.slot, u.hp])) === 战后血量) ok('两种播法打完之后的血量状态也完全一样');
else bad('两种播法之后的血量状态不一样');
info(`第 1 回合 ${JSON.parse(本回合记录).length} 条记录、之后回到第 ${界面.ctx.turn} 回合`);

/* ============================ [6] 一路打到结算 ============================ */
console.log('\n[6] 一回合一个回合打到结算');
界面.设跳过动画(true);             // 每回合直接到结尾，方便快速打完
let 回合护栏 = 0;
while (界面.阶段 !== '结算' && 回合护栏++ < 20) 界面.开打();
if (界面.阶段 === '结算' && 界面.屏 === '结算') ok(`打完了：${回合护栏} 个回合，到结算屏`);
else bad(`没能打到结算（阶段 ${界面.阶段} / 屏 ${界面.屏}）`);
const 结算HTML = 屏文字();
if (结算HTML.includes('回合数') && 结算HTML.includes('我方存活') && 结算HTML.includes('种子')) ok('结算屏有回合数 / 存活 / 种子');
else bad('结算屏信息不全');
if (结算HTML.includes('战斗胜利') || 结算HTML.includes('战斗失败')) ok(`结算屏写明了胜负（${界面.战报.结果} · ${界面.战报.原因}）`);
else bad('结算屏没有胜负');

/* ============================ [7] 其它按钮路径 ============================ */
console.log('\n[7] 其它按钮路径');
界面.动作('回菜单');
if (界面.屏 === '菜单') ok('「回菜单」可用');
界面.动作('去编队'); 界面.默认五人队();
const 编成数 = G.编成表.length;
界面.设编成(编成数 - 1);
if (界面.编队.编成序号 === 编成数 - 1) ok(`可以换敌方编成（共 ${编成数} 条，方案第 10 节第 4 条说这几条是初稿）`);
界面.设编成(999);
if (界面.编队.编成序号 === 编成数 - 1) ok('编成序号越界会被夹住，不会崩');
界面.开战();
界面.设跳过动画(true);
界面.动作('再来一场');
if (界面.ctx && 界面.阶段 === '指令') ok(`「再来一场」能再开一场（种子 ${界面.ctx.种子}）`);
else bad(`「再来一场」之后是「${界面.阶段}」`);
界面.动作('回菜单');

/* ============================ 结果 ============================ */
console.log(`\nERRS [${errs.join(' | ')}]`);
console.log(fails ? `共 ${fails} 项失败` : '界面测试全部通过');
process.exit(fails ? 1 : 0);
