      const 条文 = 条9 ? 条9[1].replace(/<[^>]*>/g, '').replace(/\s+/g, ' ').trim() : '';
      if (/胜利/.test(条文) && /希望 \+\d+/.test(条文)) ok(`战斗结束的结果条：「${条文}」`);
      else bad(`战斗结束的结果条不对：${条文}`);
      /* ② 五样摆齐：直接设一次返回值，走到出口尽头 → 本局结算屏上要看到清单 */
