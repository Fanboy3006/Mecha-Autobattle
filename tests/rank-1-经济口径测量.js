function 拨经济档(档) { for (const k of Object.keys(经济旋钮)) 经济旋钮[k](档[k]); }
/** 把经济拨成「旧档 + 只把 `步名们` 换成新版」。`步名们` 为空 = 全旧档；`'全部'` = 全新档。 */
function 拨经济(步名们) {
  const 旧 = 经济旧档(), 新 = 经济新档();
  const 全 = 步名们 === '全部' || (Array.isArray(步名们) && 步名们.includes('全部'));
  const 取 = {};
  for (const k of Object.keys(经济旋钮)) 取[k] = 全 ? 新[k] : 旧[k];
  if (!全) for (const 名 of (步名们 || [])) for (const k of (经济步[名] || [])) 取[k] = 新[k];
  拨经济档(取);
  return 取;
}
/** 中位（偶数个取中间两个的平均，和常见口径一致）。 */
const 中位 = a => {
  const s = a.slice().sort((x, y) => x - y);
  if (!s.length) return 0;
  const m = s.length >> 1;
  return s.length % 2 ? s[m] : (s[m - 1] + s[m]) / 2;
};
const 区间 = a => `${Math.min(...a)}–${Math.max(...a)}`;
/** 数一局**整局真实场次**（普通 / 精英 / 守军 / 追击 / 侵蚀源 / Boss 全算，胜败都算）。
 *  做法 = 把 `肉鸽.战斗结束()` 包一层计数：**不改引擎、也不依赖 `RUN.场次`**（那个字段是
 *  「这一层」的，进层会归零 —— 就是任务书 §(c) 那个 bug；这里独立数，好和它对照）。 */
function 数场次(跑) {
  const 原 = 肉鸽.战斗结束;
  const 明细 = {};
  let 总 = 0;
  肉鸽.战斗结束 = function (...a) { 总++; const t = a[1] || '?'; 明细[t] = (明细[t] || 0) + 1; return 原.apply(this, a); };
  try { return { r: 跑(), 总, 明细 }; } finally { 肉鸽.战斗结束 = 原; }
}
/** 把一局里的每一场战斗都**按打赢结算**（口径 `'实战优'` 用：走法 / 推进剂 / 节点全是真的，
 *  只是把胜负这一层按住 —— 好和作者日志里那一局（几乎全胜）比）。
 *  ★ 只包 `肉鸽.战斗结束` 这一层，**不改引擎、不改地图、不改推进剂**；跑完原样还原。 */
function 强制赢(跑) {
  const 原 = 肉鸽.战斗结束;
  肉鸽.战斗结束 = function (结果, 格类型, 战报) { return 原.call(this, '胜', 格类型, 战报 || { 敌方: [], 我方: [] }); };
  try { return 跑(); } finally { 肉鸽.战斗结束 = 原; }
}
/** 24 局固定种子跑一遍，返回逐局 + 汇总（中位 / 区间 / 平均）。
 *  `口径`：
 *   · `'实战优'`（**主口径**）= `走一局()` + 每场都赢（`强制赢`）：**推进剂 / 地图 / 节点 / 追击全是真的**
 *     （每层只给该图该有的推进剂，不像 `量一局` 那样补到 31）→ 一局打几场、走到第几层、剩多少余量
 *     都和作者那份日志同一类；
 *   · `'清图'` = `量一局(…, {先打:true})`：每层把作战 / 精英 / 侵蚀源 / 守军都打掉再奔出口、
 *     每层推进剂补到 31 → **收入上限口径**（作者那份日志的「打满」形态）；
 *   · `'收支'` = `量一局()`（第 [8] 段那一套：出口优先，实际只打了守军）；
 *   · `'实战'` = `走一局()`（真的打、会输 —— 顺带量出「打输的那条路」有多少收入）。 */
function 量经济(标签, 口径 = '实战优') {
  const 名单 = [];
  for (let i = 0; i < 经济局数; i++) {
    const 种子 = 经济种子(i);
    const 跑 = 口径 === '实战' ? (() => 走一局(种子))
      : (口径 === '实战优' ? (() => 强制赢(() => 走一局(种子)))
        : (口径 === '收支' ? (() => 量一局(种子)) : (() => 量一局(种子, '改后', '尽头', { 先打: true }))));
    const r0 = 数场次(跑);
    const r = r0.r;
    名单.push({
      种子, 希望: r.希望, 源碳: r.源碳, 券: (r.券 == null ? 0 : r.券), 场次: r0.总, 明细: r0.明细,
      层: r.层, 结局: r.结局, 来源: r.来源,
    });
  }
  const 取 = f => 名单.map(f);
  const 来源项 = ['初始', '战斗', '节点', '升级', '藏品', '藏品省', '支出'];
  const 来源 = {};
  for (const k of 来源项) 来源[k] = 中位(取(r => r.来源[k] || 0));
  const 明细 = {};
  for (const r of 名单) for (const [k, v] of Object.entries(r.明细)) 明细[k] = (明细[k] || 0) + v;
  return {
    标签, 名单, 明细,
    中位: {
      希望: 中位(取(r => r.希望)), 源碳: 中位(取(r => r.源碳)), 券: 中位(取(r => r.券)),
      场次: 中位(取(r => r.场次)), 层: 中位(取(r => r.层)),
    },
    区间: {
      希望: 区间(取(r => r.希望)), 源碳: 区间(取(r => r.源碳)), 券: 区间(取(r => r.券)),
      场次: 区间(取(r => r.场次)), 层: 区间(取(r => r.层)),
    },
    平均: {
      希望: 平(取(r => r.希望)), 源碳: 平(取(r => r.源碳)), 券: 平(取(r => r.券)),
      场次: 平(取(r => r.场次)), 层: 平(取(r => r.层)),
    },
    来源,
    结局: 名单.reduce((a, r) => (a[r.结局] = (a[r.结局] || 0) + 1, a), {}),
  };
}
/** 打印一遍经济结果（人话 2 行 + 一行机器可读 JSON，探针脚本吃那一行）。 */
