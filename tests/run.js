/** 站到某一格上并结算它（战斗类会先进编队屏）。
 *  `秒杀` = true 时把敌人 HP 临时压到 1 **并把增援波次清空** —— 这一段测的是
 *  「节点能结算、能换层、能通关」，2–3 台打精英 / 终点 Boss 的胜负属于数值平衡
 *  （M6 平衡工具），不在这份测试里下结论。
 *  ★ 2026-10-11 第二轮：编成台数上调（守军 5 → 7）＋ 增援改成**第 2 回合起 4 波**之后，
 *    只把「开局在场那几台」压到 1 点血**已经不够**了：第 2 回合补进来的那几波是满血的，
 *    3 台我方清不掉 → 这一场必输、后面的「走到出口 / 通关」全断。所以这里**连波次一起清掉**。 */
function 走并结算(k, 秒杀 = false) {
  const R = 肉鸽.RUN;
  肉鸽.跳格(k);
  /* 先在起点 / 别处时 `界面.去节点(k)` 会「走一步 + 开这一格的屏」；已经站在这格上时它返回 null
     （BFS 距离 0，走不动），那就自己调一次 `准备肉鸽编队()` —— 等价于界面上点这一格的「出战」按钮。 */
  let 类型 = 界面.去节点(k);
  if (类型 == null) 类型 = (R.地图.格[k] || {}).类型;
  if (['作战', '精英', '侵蚀源', '出口守军'].includes(类型) && 界面.屏 !== '编队') 界面.准备肉鸽编队();
  if (['作战', '精英', '侵蚀源', '出口守军'].includes(类型)) {
    界面.编队.出击 = R.队伍.slice(0, 3).map((m, i) => ({ 键: m.键, 位: i }));
    界面.动作('开战');
    if (秒杀 && 界面.ctx) {
      界面.ctx.enemies.forEach(e => { e.maxHp = 1; e.hp = 1; });
      界面.ctx.allies.forEach(u => { u.maxHp = 10000000; u.hp = 10000000; });   // 我方调成不死，只验流程
      界面.ctx.波次 = [];
    }
    打完这一场();
  } else if (类型 === '招募站') {
    /* ★ 2026-10-12 修真 bug：招募**必须持券** —— 改前这里直接 `界面.招募(某人)`（不选券）就能招，
       现在那条路已经被 `肉鸽.招募()` 拒掉。这一段的目的是「把招募站这个节点结算一遍」，
       而**券在进站那一下已经发过了**（`界面.去节点` → `肉鸽.招募站领券()`），所以这里：
       有对得上某位候选的券就**按玩家的路**用券招一个（顺便证明招募站拿到的券能继续招），
       没有就只收下券、回大地图（招募站本身已经结算完了）。 */
    const 已有 = new Set(R.队伍.map(m => m.键));
    const 人 = G.ALLY_T.map(t => t.mech).filter(k => !已有.has(k));
    const 费 = k => G.肉鸽数值.招募费[G.tierOf(k)] || 0;
    let 招了 = false;
    for (let i = 0; i < (R.券 || []).length && !招了; i++) {
      const 合 = 人.filter(k => G.券合(R.券[i], k) && R.希望 >= 费(k)).sort((a, b) => 费(a) - 费(b));
      if (!合.length) continue;
      界面.用券(i);
      const r = 肉鸽.招募(合[0], i);
      if (r && r.ok) 招了 = true;
      else 肉鸽界面.选中的券 = null;
    }
    if (!招了) { 肉鸽界面.选中的券 = null; 肉鸽.节点完成(); }   // 没招也把这一格结算掉（= 格菜单上的「不招，继续前进」）
  } else if (类型 === '黑市') {
    界面.动作('黑市离开');
  } else if (类型 === '休整') {
    界面.动作('休整:耐久');
  } else if (类型 === '事件') {
    界面.动作('奇遇:源碳');
  }
  /* 瞭望站 / 遗迹 / 隧道 在 去节点 里已经结算完（含弹窗） */
  return 类型;
}
