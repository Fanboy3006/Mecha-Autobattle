#!/usr/bin/env node
/* ============================================================================
 * 机甲指挥 · 肉鸽测试（方案第 9 节 M4 的验收）
 * ----------------------------------------------------------------------------
 * 方案 M4 的验收原话：「能从选分队一路打到第 1 层出口；关掉页面能继续」。
 * 这份测试就盯着这两条，外加：
 *   - 选分队 → 新的一局 → 大地图（层 / 节点 / 希望 / 源碳 / 作战耐久）；
 *   - 一路走节点（作战 / 精英 / 招募 / 补给 / 奇遇 / 出口），战斗走 M3 的内核（跳过动画）；
 *   - 打赢了发奖励、打输了扣作战耐久（耐久归零就本局结束）；
 *   - **存档 → 清空内存 → 读档**，层 / 经济 / 队伍 / 位置全都要对得上。
 *
 * 不依赖 Playwright：用 tests/lib/dom-stub.mjs 把 index.html 的内联脚本跑起来。
 * 用法：node tests/run.js
 * ========================================================================== */
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';
import { loadPage } from './lib/dom-stub.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '..');

let fails = 0;
const errs = [];
const ok = m => console.log('  ✓ ' + m);
const bad = m => { fails++; errs.push(m); console.log('  ✗ ' + m); };
const info = m => console.log('    · ' + m);

const page = loadPage(join(ROOT, 'index.html'), { quiet: true });
if (page.errors.length) {
  page.errors.forEach(e => bad('内联脚本执行报错：' + e));
  console.log(`\nERRS [${errs.join(' | ')}]`);
  process.exit(1);
}
const G = page.sandbox.__game;
const 界面 = G.界面, 播放 = G.播放, 肉鸽 = G.肉鸽;
界面.手动播放 = true;
界面.设跳过动画(true);          // 手机/自动测试里都直接跳到结尾
console.log(`肉鸽测试：机甲指挥 ${G.version} · ${G.milestone}\n`);

/* ============================ [1] 编成表覆盖每层每种 ============================ */
console.log('[1] 编成表：每层每种 3 条（方案第 7 节）');
for (const 层 of [1, 2, 3]) {
  for (const 类型 of ['普通', '精英', 'Boss']) {
    const n = G.选编成(层, 类型).length;
    if (n === 3) ok(`第 ${层} 层 ${类型}：3 条`);
    else bad(`第 ${层} 层 ${类型} 只有 ${n} 条（方案要求每层每种 3 条）`);
  }
}
{
  const 超 = G.编成表.filter(e => (e.前 || []).length > G.行列数(G.ROW_FRONT) || (e.后 || []).length > G.行列数(G.ROW_BACK));
  if (!超.length) ok(`所有编成的站位都放得下（前 ${G.行列数(G.ROW_FRONT)} + 后 ${G.行列数(G.ROW_BACK)}）`);
  else bad(`有 ${超.length} 条编成的人比格子多：${超.map(e => `${e.层}-${e.类型}`).join('、')}`);
}

/* ============================ [2] 选分队 → 新的一局 ============================ */
console.log('\n[2] 选分队 → 新的一局');
界面.动作('回菜单');
界面.动作('去分队');
if (界面.屏 === '分队') ok('菜单能进「选分队」');
else bad(`进不了分队屏（当前 ${界面.屏}）`);
if (屏文字().includes('出发')) ok('分队屏有出发按钮');
界面.动作('选分队', '近卫');
if (屏文字().includes('近卫')) ok('能选分队（近卫）');
else bad('选了分队但界面上没标出来');
界面.动作('开新局');
const R = 肉鸽.RUN;
if (界面.屏 === '大地图' && R) ok(`开局成功：第 ${R.层} 层，队伍 ${R.队伍.length} 台，种子 ${R.种子}`);
else bad(`开局失败（屏 ${界面.屏}）`);
if (R && R.地图 && R.地图.节点.length >= 8) ok(`生成了 ${R.地图.节点.length} 个节点（起点 + 3 + 3 + 出口）`);
else bad('节点地图不对');
if (R && R.希望 === G.肉鸽数值.起始希望 && R.源碳 === G.肉鸽数值.起始源碳 && R.耐久 === G.肉鸽数值.起始耐久) ok(`初始经济：希望 ${R.希望} / 源碳 ${R.源碳} / 作战耐久 ${R.耐久}`);
else bad(`初始经济不对：${JSON.stringify({ 希望: R && R.希望, 源碳: R && R.源碳, 耐久: R && R.耐久 })}`);
if (肉鸽.能去的().length > 0) ok(`当前节点（起点）能去 ${肉鸽.能去的().length} 个节点`);
else bad('起点出不去');
{
  const 不可达 = R.地图.节点.filter(n => n.id !== R.地图.起点 && !R.地图.节点.some(m => m.通.includes(n.id)));
  if (!不可达.length) ok('每个节点都至少有一条入边（不会有走不到的节点）');
  else bad(`有 ${不可达.length} 个节点走不到：${不可达.map(n => n.id).join('、')}`);
  const 出口 = R.地图.节点.find(n => n.id === R.地图.出口);
  if (出口 && R.地图.节点.filter(n => n.列 === G.肉鸽数值.每层列数 - 1).every(n => n.通.includes(出口.id))) ok('最后一列的每个节点都能去出口');
  else bad('出口不是从最后一列都能到');
}

/* ============================ [3] 一路走到第 1 层出口 ============================ */
console.log('\n[3] 从第 1 层走到出口（这一路上会遇到各种节点）');
const 走过 = [];
let 护栏 = 0;
while (R.层 === 1 && 护栏++ < 60) {
  const 可 = 肉鸽.能去的();
  if (!可.length) break;
  const 目标 = 可.find(n => ['战斗', '精英', 'Boss'].includes(n.类型)) || 可[0];   // 优先走战斗节点，路上才有奖励
  界面.去节点(目标.id);
  const cur = 肉鸽.当前节点();
  走过.push(cur.类型);
  if (['战斗', '精英', 'Boss'].includes(cur.类型)) {
    界面.打这一场();
    界面.开打();                       // 跳过动画开着 → 直接到结算，再回大地图
    let n = 0;
    while (界面.阶段 === '播放' && n++ < 100000) 播放.tick();   // 兜底
  } else if (cur.类型 === '招募') {
    const 招 = G.ALLY_T.map(t => t.mech).find(k => !R.队伍.some(m => m.键 === k));
    界面.招募(招);
  } else if (cur.类型 === '补给') {
    界面.领补给();
  } else if (cur.类型 === '奇遇') {
    界面.选奇遇('源碳');
  }
}
if (R.层 >= 2) ok(`走到第 1 层出口，进了第 ${R.层} 层（路上经过：${[...new Set(走过)].join('、')}）`);
else bad(`没能走到出口（走到 ${走过.length} 个节点：${走过.join('→')}）`);
if (R.源碳 >= G.肉鸽数值.起始源碳 && R.希望 >= G.肉鸽数值.起始希望) ok(`经济在涨：希望 ${R.希望} / 源碳 ${R.源碳} / 耐久 ${R.耐久}`);
else bad(`经济没变化：希望 ${R.希望} 源碳 ${R.源碳}`);
if (R.队伍.length >= 5) ok(`队伍：${R.队伍.length} 台（上限 ${G.肉鸽数值.队伍上限}）`);
if (R.队伍.length > G.肉鸽数值.队伍上限) bad('队伍超过上限了');

/* ============================ [4] 关掉页面能继续（存档） ============================ */
console.log('\n[4] 存档：关掉页面能继续');
{
  const 快照 = { 层: R.层, 希望: R.希望, 源碳: R.源碳, 耐久: R.耐久, 队伍: R.队伍.length, 当前: R.当前, 种子: R.种子 };
  const 存 = 肉鸽.存档();
  if (存) ok('写存档成功（localStorage）');
  else bad('写存档失败');
  /* 模拟「关掉页面」：把内存里的 RUN 扔掉，再读档 */
  肉鸽.RUN = null;
  肉鸽.进行中 = false;
  const 读 = 肉鸽.读存档();
  if (读 && 读.层 === 快照.层 && 读.希望 === 快照.希望 && 读.源碳 === 快照.源碳 && 读.耐久 === 快照.耐久
      && 读.队伍.length === 快照.队伍 && 读.当前 === 快照.当前 && 读.种子 === 快照.种子) {
    ok(`读档一致：第 ${读.层} 层 / 希望 ${读.希望} / 源碳 ${读.源碳} / 耐久 ${读.耐久} / 队伍 ${读.队伍.length} / 位置 ${读.当前}`);
  } else bad(`读档对不上：${JSON.stringify(读 && { 层: 读.层, 希望: 读.希望, 源碳: 读.源碳, 耐久: 读.耐久, 队伍: 读.队伍 && 读.队伍.length, 当前: 读.当前 })} 期望 ${JSON.stringify(快照)}`);
  /* 界面上也能「继续上一局」 */
  界面.动作('回菜单');
  if (屏文字().includes('继续上一局')) ok('菜单上有「继续上一局」');
  else bad('菜单上没有读档入口');
  界面.动作('继续上一局');
  if (界面.屏 === '大地图' && 肉鸽.RUN) ok('「继续上一局」回到了大地图');
  else bad('「继续上一局」没回到大地图');
}

/* ============================ [5] 战斗失败会扣作战耐久 ============================ */
console.log('\n[5] 战斗失败扣作战耐久 / 耐久归零就结束');
{
  const 前 = 肉鸽.RUN.耐久;
  const r = 肉鸽.战斗结束('败', '战斗', { 敌方: [{ hp: 5 }, { hp: 0 }] });   // 还剩 1 台敌人
  if (肉鸽.RUN.耐久 === 前 - 1) ok(`失败扣耐久（战棋的规则：按剩下的敌人数）：${前} → ${肉鸽.RUN.耐久}`);
  else bad(`失败没扣耐久：${前} → ${肉鸽.RUN.耐久}`);
  肉鸽.RUN.耐久 = 1;
  const r2 = 肉鸽.战斗结束('败', '战斗', { 敌方: [{ hp: 5 }] });
  if (r2 && r2.结束 && !肉鸽.进行中) ok('耐久归零 → 本局结束（作战失败）');
  else bad('耐久归零没有结束本局');
  界面.开屏('肉鸽结算');
  if (屏文字().includes('走到第')) ok('能显示本局结算屏');
  else bad('本局结算屏不对');
}

/* ============================ 结果 ============================ */
console.log(`\nERRS [${errs.join(' | ')}]`);
console.log(fails ? `共 ${fails} 项失败` : '肉鸽测试全部通过');
process.exit(fails ? 1 : 0);

function 屏文字() { return String(page.byId.get('screen') && page.byId.get('screen').innerHTML || ''); }
