  const 可 = 肉鸽.能去的();
  if (可.length) 界面.去节点(可[0].k);
  if (界面.屏 !== '大地图') 界面.开屏('大地图');
  肉鸽.RUN.藏品 = ['g2', 'e2'];            // 藏品也跟着存档（发藏品那条路在 tests/relic.js 单测）
  肉鸽.存档();
  const 快照 = {
    层: R.层, 希望: R.希望, 源碳: R.源碳, 耐久: R.耐久, 队伍: R.队伍.length,
    当前: R.当前, 种子: R.种子, 推进剂: R.推进剂,
    地图: JSON.stringify(R.地图), 已走过: JSON.stringify(R.已走过), 藏品: JSON.stringify(R.藏品),
  };
  const 存 = 肉鸽.存档();
  if (存) ok(`写存档成功（localStorage 键 ${G.存档键}）：第 ${快照.层} 层、位置 ${坐标(快照.当前)}、推进剂 ${快照.推进剂}`);
  else bad('写存档失败');
  /* 模拟「关掉页面」：把内存里的 RUN 扔掉，再读档 */
  肉鸽.RUN = null;
  肉鸽.进行中 = false;
  const 读 = 肉鸽.读存档();
  if (读 && 读.层 === 快照.层 && 读.希望 === 快照.希望 && 读.源碳 === 快照.源碳 && 读.耐久 === 快照.耐久
      && 读.队伍.length === 快照.队伍 && 读.当前 === 快照.当前 && 读.种子 === 快照.种子 && 读.推进剂 === 快照.推进剂) {
    ok(`读档一致：第 ${读.层} 层 / 希望 ${读.希望} / 源碳 ${读.源碳} / 耐久 ${读.耐久} / 队伍 ${读.队伍.length} / 位置 ${坐标(读.当前)} / 推进剂 ${读.推进剂}`);
  } else bad(`读档对不上：${JSON.stringify(读 && { 层: 读.层, 希望: 读.希望, 源碳: 读.源碳, 耐久: 读.耐久, 队伍: 读.队伍 && 读.队伍.length, 当前: 读.当前, 推进剂: 读.推进剂 })} 期望 ${JSON.stringify(快照)}`);
  if (读 && JSON.stringify(读.地图) === 快照.地图) ok(`地图逐格一致（${Object.keys(读.地图.格).length} 格，含每格的类型 / 关卡编号 / 已过）`);
  else bad('地图没存全（读回来的地图和存之前不一样）');
  if (读 && JSON.stringify(读.已走过) === 快照.已走过) ok(`走过哪些格也存了：${读.已走过.length} 格`);
  else bad('已走过的格没存全');
  if (读 && JSON.stringify(读.藏品) === 快照.藏品) ok(`藏品（${读.藏品.length} 件）也跟着存档（M5 的 93-藏品.js）`);
  else bad('藏品没存全');
