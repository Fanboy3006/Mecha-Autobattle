/* ============================================================================
 * 「读源码」——给测试读 `src/js/<片段>` 用（★ 2026-10-13 P1 源码机械拆分后新增）。
 * ----------------------------------------------------------------------------
 * **为什么有它**：P1 把几个大片段按职责切成了多个编号片段
 * （`90-肉鸽.js` → `90-肉鸽-1-数据与规则.js` + `90-肉鸽-2-招募券与晋升.js` + …），
 * 而测试里有几处是「把源码读出来、断言里面（没有）某一句 / 某一段」——路径写死成原文件名，
 * 拆分后就 ENOENT 了。**断言本身一句都没改**（那是红线），改的只是**读文件这一个动作**。
 *
 * **语义**：先按**原路径**找；找到就原样返回（没被拆的文件走的就是老路，一个字节都不变）；
 * 找不到就把「同名前缀 + `-`」的片段**按文件名顺序拼起来**返回。
 * 拼接产物与拆分前的原文件**逐字节相同**（P1 的搬家自检 + `tools/build-src.mjs --check` 双重保证，
 * 证据在 `docs/实现/结构表.md`）——所以调用处的语义**没有变**：
 *   · `源码('src\\js\\72-势力.js')` → 拆分前那份 `72-势力.js` 的全文；
 *   · `源码('src\\js\\71-改动.js').split('const 势力特色 = {')[1]` → 同一段文本，照样切得出来。
 * ★ 片段序号是**单个数字**（`-1-`…`-9-`），所以默认字符串排序 == 拼接顺序。
 * ========================================================================== */
import { readFileSync, existsSync, readdirSync } from 'fs';
import { join, dirname, basename } from 'path';

/** 读一个源码 / 文档片段：原路径优先，其次是「同名前缀的编号片段」按序拼接。 */
export function 读源码(ROOT, ...段) {
  const 全 = join(ROOT, ...段);
  if (existsSync(全)) return readFileSync(全, 'utf8');
  const 目录 = dirname(全);
  const 主名 = basename(全).replace(/\.js$/, '');
  const 片段们 = existsSync(目录)
    ? readdirSync(目录).filter(f => f.startsWith(主名 + '-') && f.endsWith('.js')).sort()
    : [];
  if (!片段们.length) throw new Error(`找不到源码 ${全}（也没有它的编号片段）`);
  return 片段们.map(f => readFileSync(join(目录, f), 'utf8')).join('');
}
