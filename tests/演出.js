#!/usr/bin/env node
/* ============================================================================
 * 机甲指挥 · 演出线自检（阶段 1：拆 demo → 播放器 + 模块库 + 每招一份数据脚本）
 * ----------------------------------------------------------------------------
 * 权威文档：`协作/演出/演出协作.md` 第 5 节阶段 1；规则见 `协作/演出/演出语法.md`。
 * 这份测的是**演出线自己的件** `协作/演出/演出原型.html`（不是游戏里的 86-演出.js，
 * 那个要等作者拍板 + DSH 接，见演出协作第 5 节阶段 3）。
 *
 * 盯着七件事（全部真的跑，数字都是打印出来的）：
 *   [1] 三招都在、三个模板名互不相同 —— 「同一套模块做第二、三招」的第一条证据；
 *   [2] 三招都能从 0 跑到结束（逐帧走一遍不报错），每招的 T0 列表与总时长都打印出来；
 *   [3] 语-9 / 语-1：短版真的砍掉「起」段、把「发」段压到 60%，正式演出为 0；
 *   [4] 语-9 / 语-11：命中停顿插在 T0 上，T0 之后的拍在显示时间上整体顺延，停顿内停在 T0；
 *   [5] 语-10：多段攻击的段间隔与「全部段铺开 ≤ 700ms」；
 *   [6] 语-20 / 已定规则第 2 条：脚本里只有数据、**没有伤害数字与 HP**，输入全部来自第 4.2 节；
 *   [7] 语-13：同一脚本同一档跑两遍，逐帧摘要逐字一样；击破 / 未击破会真的改变画面。
 *   另外查一遍：演出层不调 `ctx.rng`，也只有合成音效允许 `Math.random`（语-13 第 3 条）。
 *
 * 不依赖任何 npm 包：用 tests/lib/dom-stub.mjs 在 Node 的 vm 里把页面内联脚本跑起来。
 * 用法：node tests/演出.js
 *
 * 注：本文件是**演出线自己的自检**，暂时**没有**登记进 `tools/verify-all.mjs` 的套件清单
 * （那要改统筹线的文件，演出协作第 7 节要求「每做完一件开新会话」，这条留给统筹收口）。
 * ========================================================================== */
import { readFileSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';
import { makeSandbox, inlineScripts, runScripts } from './lib/dom-stub.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '..');
const 页 = join(ROOT, '协作', '演出', '演出原型.html');

let fails = 0;
const errs = [];
const ok = m => console.log('  ✓ ' + m);
const bad = m => { fails++; errs.push(m); console.log('  ✗ ' + m); };
const info = m => console.log('    · ' + m);
const 断言 = (cond, m) => cond ? ok(m) : bad(m);

/* ============================ 载入（三份都跑一遍） ============================ */
const 源码 = readFileSync(页, 'utf8').replace(/\r\n/g, '\n');
const 跑一次 = () => {
  const { sandbox } = makeSandbox();
  const errors = runScripts(sandbox, inlineScripts(源码), { quiet: true });
  return { sandbox, errors };
};

console.log('\n=== 演出线自检 · 阶段 1（三招一播放器） ===');
console.log(`页面：${页}\n`);

const { sandbox, errors } = 跑一次();
if (errors.length) {
  errors.forEach(e => bad('内联脚本执行报错：' + e));
  console.log(`\nERRS [${errs.join(' | ')}]`);
  process.exit(1);
}
const Y = sandbox.window.__演出;
断言(!!Y, '页面载入后 window.__演出 在（三招都能从外部驱动）');

/* ============================ [1] 三招与三个模板 ============================ */
console.log('\n[1] 三招都在、三个模板名互不相同');
{
  const 脚本 = Y.脚本们();
  info('脚本：' + 脚本.map(s => `${s.键} → ${s.模板}（${s.档次}）`).join('　|　'));
  断言(脚本.length === 3, `脚本表里正好 3 招（实测 ${脚本.length}）`);
  断言(new Set(脚本.map(s => s.模板)).size === 3, '三个模板名互不相同（不是一招换皮）');
  断言(脚本.every(s => ['summon_drop', 'shoot_beam', 'melee_multi'].includes(s.模板)), '模板名对得上语-23 的清单');
  断言(脚本.every(s => s.键.includes('/')), '脚本键都是「机体键/武器名」（语-22）');
}

/* ============================ [2] 三招真的能跑 ============================ */
console.log('\n[2] 三招从 0 跑到结束（逐帧走一遍）');
{
  let 结果 = null;
  try { 结果 = Y.全部跑一遍(); } catch (e) { bad('跑帧抛异常：' + (e && e.stack ? e.stack.split('\n')[0] : e)); }
  if (结果) {
    for (const r of 结果) {
      info(`${r.键} → 模板 ${r.模板}　总时长 ${r.总长}ms　T0 = [${r.命中.join(', ')}]`);
      断言(r.总长 > 2000, `${r.键}：总时长是正的合理值（${r.总长}ms）`);
      断言(r.命中.length >= 1, `${r.键}：至少有 1 个命中时刻`);
      断言(r.命中.every((h, i, a) => i === 0 || h > a[i - 1]), `${r.键}：命中时刻严格递增`);
    }
    const 斩 = 结果.find(r => r.模板 === 'melee_multi');
    断言(斩 && 斩.命中.length === 5, `melee_multi 是四段连斩 + 大斩 = 5 个命中时刻（实测 ${斩 ? 斩.命中.length : '—'}）`);
    if (斩) {
      const 跨度 = 斩.命中[斩.命中.length - 1] - 斩.命中[0];
      断言(跨度 <= 700, `语-10：全部段铺开 ${跨度}ms ≤ 700ms`);
      const 隔 = 斩.命中.slice(1, 4).map((h, i) => h - 斩.命中[i]);
      断言(隔.every(d => d === 120), `语-10：连斩段间隔 = 120ms（实测 ${隔.join(' / ')}）`);
    }
  }
}

/* ============================ [3] 语-1 / 语-9：短版 ============================ */
console.log('\n[3] 语-1 / 语-9：短版砍掉「起」段、把「发」段压到 60%');
for (const [招, 名, 键] of [['A', '大招·陨石', 'M1/残月的余响'], ['B', '光束直射', 'A1/光束步枪'], ['C', '近战乱舞', 'B1/影界·万刃归一']]) {
  Y.设击破(true);
  const 全 = Y.设档('完整', 招);
  const 短 = Y.设档('短版', 招);
  const 名全 = Object.keys(全.拍).sort((a, b) => 全.拍[a][0] - 全.拍[b][0]);
  const 发首 = 全.四.发[0], 发末 = 全.四.发[全.四.发.length - 1];
  const 发长全 = 全.拍[发末][1] - 全.拍[发首][0];
  const 发长短 = 短.拍[发末][1] - 短.拍[发首][0];
  info(`${名}：完整 ${全.总长}ms（起段 ${全.拍[名全[0]][0]}–${全.拍[名全[0]][1]}）→ 短版 ${短.总长}ms`);
  断言(全.拍[名全[0]][0] === 0, `${名}：完整版「起」段从 0 开始（${全.拍[名全[0]][0]}）`);
  const 起段们 = 全.四.起.filter(k => k !== 发首);
  断言(起段们.every(k => 短.拍[k][0] === 短.拍[k][1]), `${名}：短版把「起」段（${起段们.join('/')}）真的砍掉了`);
  断言(Math.abs(发长短 - 发长全 * .6) < 1e-6, `${名}：短版「发」段压到 60%（${发长全} → ${发长短}）`);
  const 命中全 = 全.命中们[0].时刻, 命中短 = 短.命中们[0].时刻;
  断言(命中短 < 命中全, `${名}：短版的 T0 提前了（${命中全} → ${命中短}ms）`);
  断言(短.命中们.length === 全.命中们.length, `${名}：短版不改命中时刻的个数（段数一样）`);
  断言(短.收段结束 > 短.命中们[短.命中们.length - 1].时刻, `${名}：收段仍在最后一个 T0 之后`);
}
Y.设档('完整', 'A');

/* ============================ [4] 语-9 / 语-11：停顿插在 T0 上 ============================ */
console.log('\n[4] 语-9 / 语-11：命中停顿插在 T0 上，T0 之后的拍整体顺延');
for (const [名, 键] of [['大招·陨石', 'M1/残月的余响'], ['光束直射', 'A1/光束步枪'], ['近战乱舞', 'B1/影界·万刃归一']]) {
  Y.换招(名 === '大招·陨石' ? 'A' : 名 === '光束直射' ? 'B' : 'C');
  const R = Y.装了();
  const T0 = R.命中们[0].时刻;
  const 停顿和 = R.停顿.reduce((s, x) => s + x.d, 0);
  const 顺延 = Y.显示(R.收段结束) - R.收段结束;
  info(`${名}：T0=${T0}ms　停顿 ${R.停顿.map(x => x.d).join('+')} = ${停顿和}ms　总长 ${Y.总长()}ms`);
  断言(顺延 === 停顿和, `${名}：T0 之后的拍整体顺延了全部停顿（${顺延} = ${停顿和}）`);
  断言(Y.反显(Y.显示(T0) + 1) === T0, `${名}：停顿期间冻在 T0 上（反显(显示(T0)+1) === T0）`);
  断言(Y.停顿中吗(Y.显示(T0) + 1), `${名}：显示时间落在停顿窗口里 → 停顿中`);
  断言(!Y.停顿中吗(Y.显示(T0) - 1), `${名}：T0 之前不在停顿里`);
  断言(Math.abs(Y.显示(T0) - (T0 + R.停顿.filter(x => x.at < T0).reduce((s, x) => s + x.d, 0))) < 1e-6,
    `${名}：显示(T0) = T0 + 它之前所有停顿的和`);
  /* 反显单调不减 */
  let 单 = true, 前 = -1;
  for (let t = 0; t <= Y.总长(); t += 7) { const b = Y.反显(t); if (b < 前 - 1e-6) { 单 = false; break; } 前 = b; }
  断言(单, `${名}：反显在整条时间轴上单调不减`);
}

/* ============================ [5] 停顿档与倍速口径 ============================ */
console.log('\n[5] 语-11 的标准值表：60 / 100 / 140 / 180，多段「微停」30');
{
  Y.换招('A'); const A = Y.装了();
  断言(A.命中们[0].停顿毫秒 === 140, `大招·陨石 的停顿档是「大」= 140ms（实测 ${A.命中们[0].停顿毫秒}）`);
  Y.换招('B'); const B = Y.装了();
  断言(B.命中们[0].停顿毫秒 === 100, `光束直射 的停顿档是「中」= 100ms（实测 ${B.命中们[0].停顿毫秒}）`);
  Y.换招('C'); const C = Y.装了();
  断言(C.命中们.slice(0, 4).every(m => m.停顿毫秒 === 50), '近战连斩四段是「微停」= 半档（滑条 100 时 = 50ms，语-10）');
  断言(C.命中们[4].停顿毫秒 === 140, '大斩是「大」= 140ms（语-10 最后一段再吃一次完整停顿）');
  /* 停顿滑条（S.stop）就是「一档」的基准：微 = 半档、小/中/大 = 0.6 / 1 / 1.4 档 */
  Y.设档('完整', 'C');
  Y.设停顿(250); const 大 = Y.总长(); Y.设停顿(0); const 小 = Y.总长(); Y.设停顿(100);
  const 系数和 = C.命中们.reduce((s, m) => s + (m.停顿 === '微' ? .5 : m.停顿 === '大' ? 1.4 : 1), 0);
  info(`停顿滑条：0ms → 总长 ${小}ms；250ms → 总长 ${大}ms（差 ${大 - 小}ms = 250 × ${系数和}）`);
  断言(大 - 小 === 250 * 系数和, `停顿滑条对每一段按档生效（差 = 250 × 系数和 ${系数和}）`);
}

/* ============================ [6] 脚本是纯数据 ============================ */
console.log('\n[6] 语-20 / 已定规则第 2 条：脚本里没有伤害数字与 HP');
{
  /* 把脚本表整段抠出来，扫里面有没有数字字面量（除威力与节拍这类「展示用」字段） */
  const 段 = 源码.match(/const 演出脚本 = \{[\s\S]*?\n\};/);
  断言(!!段, '找得到 `const 演出脚本 = {…}` 这一段');
  if (段) {
    const 允许 = ['威力', '段数'];
    const 可疑 = [];
    for (const 行 of 段[0].split('\n')) {
      if (!/[:：]/.test(行)) continue;
      const 键 = (行.match(/^\s*['"]?([^\s:'"]+)['"]?\s*:/) || [])[1];
      /* 先把字符串字面量（含颜色 / 台词 / 招式名）整段抠掉，再看还剩不剩数字；
         「威力 / 段数」是给 HUD 与连斩分段提示用的展示字段，允许有数（已定规则第 2 条只看「不重算战斗数值」）。 */
      const 去字符串 = 行.replace(/'[^']*'/g, "''").replace(/"[^"]*"/g, '""');
      const 只剩展示字段 = 行.split(',').filter(片 => /\d/.test(片.replace(/'[^']*'/g, "''")) && !/^\s*(威力|段数)\s*:/.test(片));
      if (/\d/.test(去字符串) && 只剩展示字段.length === 0) continue;
      if (/\d/.test(去字符串) && !允许.includes(键)) 可疑.push(行.trim());    }
    断言(可疑.length === 0, `脚本里除「威力 / 段数」外没有数字字面量（可疑 ${可疑.length} 行）`);
    可疑.forEach(x => info('可疑：' + x));
    for (const 词 of ['HP前', 'HP后', '伤害:', '暴击']) 断言(!段[0].includes(词), `脚本里没有「${词}」`);
  }
  const 输入 = Y.输入();
  info(`输入来自第 4.2 节：攻击者 ${输入.攻击者.名}　武器 ${输入.武器.名}　伤害 [${输入.伤害.join(', ')}]　主目标 ${输入.主目标}`);
  断言(输入.目标们.every(t => 'HP前' in t && 'HP后' in t && '最大HP' in t), '输入里带 HP前 / HP后 / 最大HP（演出只读）');
  断言(typeof 输入.伤害[0] === 'number' && 输入.伤害[0] > 0, '伤害数字从输入来，不是脚本写死的');
}

/* ============================ [7] 语-13：确定性与随机 ============================ */
console.log('\n[7] 语-13：同种子逐帧一样；演出层不碰 ctx.rng');
{
  const 跑 = () => { const r = 跑一次(); return r.sandbox.window.__演出.跑几帧(50, 24); };
  const a = 跑(), b = 跑();
  断言(JSON.stringify(a) === JSON.stringify(b), '同一脚本跑两遍：24 帧摘要逐字一样');
  info('摘要样本：' + a.slice(0, 3).join('  /  '));
  /* 击破 / 未击破真的改变时间线 */
  Y.设击破(true); const 总击破 = Y.总长();
  Y.设击破(false); const 总未击破 = Y.总长();
  断言(总击破 !== 总未击破, `击破 / 未击破改变时间线（${总击破}ms vs ${总未击破}ms）`);
  Y.设击破(true);
  /* 源码扫描：演出层不许出现 ctx.rng / Math.random（合成音效那一节除外，语-13 第 3 条） */
  const 音效起 = 源码.indexOf('十五、音效');
  const 音效止 = 源码.indexOf('十六、播放控制');
  const 画面段 = 源码.slice(0, 音效起) + 源码.slice(音效止);
  info(`合成音效用 Math.random() 的处数：${(源码.slice(音效起, 音效止).match(/Math\.random\s*\(/g) || []).length}（都在「十五、音效」里，语-13 允许）`);
  断言(!/Math\.random\s*\(/.test(画面段), '画面 / 时间 / 模板 / 播放这些段里没有一处真的调用 Math.random()');
  断言(!/ctx\.rng\s*\(/.test(画面段), '整个原型里没有 ctx.rng 的调用（演出不消耗战斗随机数）');
  info(`四、世界 那一节：${/Math\.random\s*\(/.test(源码.slice(源码.indexOf('四、世界'), 源码.indexOf('五、文字'))) ? '有 Math.random（不该）' : '只用确定性 rng(seed)'}`);
  断言(/function rng\(seed\)/.test(源码), '演出用的是自己的伪随机（function rng(seed)，语-13）');
  /* 点击跳过：直接落到最终值 */
  Y.跳到(0); Y.跳过();
  断言(Y.装了().总长 > 0, '跳过之后总长不变（跳过关的是播放，不是数据）');
}

/* ============================ [8] 模块复用的证据 ============================ */
console.log('\n[8] 模块复用：三招共用的模块数');
{
  const M = Y.模块们();
  info('全部模块：' + M.全部.join('　'));
  info('当前这一招：' + M.当前.join('　'));
  断言(M.全部.length >= 5, `三招合起来用到的模块 ≥ 5 个（实测 ${M.全部.length}）`);
  断言(M.当前.length < M.全部.length, '当前这一招只用到其中一部分（不是每招都新增一套）');
  const 镜头们 = M.全部.filter(x => x.startsWith('镜头:'));
  断言(镜头们.length >= 2, `镜头模块被两招以上共用（${镜头们.join(' / ')}）`);
  Y.换招('A'); const A = new Set(Y.模块们().当前);
  Y.换招('C'); const C = new Set(Y.模块们().当前);
  const 交 = [...A].filter(x => C.has(x));
  info(`大招用到 ${A.size} 个：${[...A].join(' / ')}`);
  info(`近战用到 ${C.size} 个：${[...C].join(' / ')}`);
  断言(交.length >= 2, `大招与近战乱舞共用 ${交.length} 个模块：${交.join(' / ')}`);
  Y.换招('B'); const B = new Set(Y.模块们().当前);
  断言([...B].some(x => A.has(x)) && [...B].some(x => C.has(x)), '光束直射同时挂上了大招与近战的模块（同一个播放器下三种演法拼装）');
  Y.换招('A');
}

/* ============================ 总结 ============================ */
console.log('\n================ 演出线自检 ================');
console.log(`红：${fails}`);
if (fails) { console.log('ERRS [' + errs.join(' | ') + ']'); process.exit(1); }
console.log('结论：全绿');
