  /* ---- ① 没打过战斗：入口在、进得去、两个导出按钮都不崩 ---- */
  清干净();
  if (屏文字().includes('去战斗记录') && /战斗记录（最近 0 场）/.test(屏文字())) ok('开场菜单有入口「战斗记录（最近 0 场）」（N = 现在存了几场）');
  else bad(`菜单上没有作战记录入口：${屏文字().slice(0, 200)}`);
  界面.动作('去战斗记录');
  if (界面.屏 === '战斗记录' && /data-record-empty="1"/.test(屏文字()) && /还没有作战记录/.test(屏文字())) {
    ok('0 场时进得去，屏上写「还没有作战记录」（不画空框、不崩、也写了「胜 / 败都存」）');
  } else bad(`0 场时的记录屏不对：${屏文字().slice(0, 240)}`);
  const 复制空 = 界面.动作('复制记录');
  const 下载空 = 界面.动作('下载记录');
  if (复制空 && 复制空.ok === false && /还没有可以复制/.test(复制空.提示)) ok(`没打过战斗时「复制为文本」不崩，给一句可见提示：「${复制空.提示}」`);
  else bad(`没打过战斗时复制按钮不对：${JSON.stringify(复制空)}`);
  if (下载空 && 下载空.ok === false && /还没有可以下载/.test(下载空.提示)) ok(`没打过战斗时「下载 .txt」同样不崩：「${下载空.提示}」`);
  else bad(`没打过战斗时下载按钮不对：${JSON.stringify(下载空)}`);
  if (/data-export-feedback="1"/.test(屏文字())) ok('失败的反馈真的画在屏上（`data-export-feedback`）');
  else bad('失败的反馈没画出来');

  /* ---- ② 打完一场 → 记录进 localStorage（键名对、字段够复现） ---- */
  LS.removeItem(G.存档键);                    // 先把肉鸽存档清掉：这一场是练习模式，它不该碰那个键
  const 战报 = 打一场(20261010, '集中攻击');
  const 原文 = LS.getItem(键);
  if (原文 && 原文.length) ok(`打完一场 → **独立键** \`${键}\` 里有数据（${原文.length} 字符）`);
  else bad(`打完一场没存进 \`${键}\``);
  if (键 !== G.存档键 && !LS.getItem(G.存档键)) {
    ok(`这个键和肉鸽存档 \`${G.存档键}\` 是**两个键**：练习模式那一场只写了 \`${键}\`，肉鸽存档一个字节没动`);
  } else bad(`两个键的关系不对：记录键 ${键} / 存档键 ${G.存档键}（存档现在 ${JSON.stringify(LS.getItem(G.存档键))}）`);
  const 表 = G.战斗记录.读();
  const 场 = 表[0];
  if (表.length === 1 && 场) ok(`读回来 ${表.length} 场（\`战斗记录.读()\`）`);
  else bad(`读回来的场数不对：${表.length}`);
  const 要的 = ['时间', '时间戳', '来源', '种子', '层', '节点类型', '编成ID', '编成', '结果', '原因', '回合数', '我方', '敌方', '方针表', '单位开关', '波次', '记录'];
  const 缺的 = 要的.filter(k => !(k in 场));
  if (!缺的.length) {
    ok(`字段齐：${要的.join('/')} —— 种子 ${场.种子}、层 ${场.层}、节点类型 ${场.节点类型}、编成 ${场.编成ID}、结果 ${场.结果}、回合数 ${场.回合数}`);
  } else bad(`记录缺字段：${缺的.join('、')}（有：${Object.keys(场).join('/')}）`);
  if (场.种子 === 20261010 && 场.我方.length === 界面.编队.出击.length && 场.敌方.length
    && Object.keys(场.方针表).length >= 1 && 场.单位开关 && typeof 场.单位开关 === 'object' && 场.记录.length === 战报.记录.length) {
    ok(`够复现这一场：种子 ${场.种子} + 编成 ${场.编成ID} + 我方 ${场.我方.length} 台（${场.我方.map(x => `${x.键}@${x.位}Lv${x.等级}`).join('、')}）` +
      ` + 敌方 ${场.敌方.length} 台 + 方针 ${G.战斗记录.方针行(场.方针表)} + 单位开关 ${JSON.stringify(场.单位开关)} + 记录 ${场.记录.length} 条`);
  } else bad(`够复现那几个字段不对：${JSON.stringify({ 种子: 场.种子, 编成: 场.编成ID, 我方: 场.我方, 敌方: 场.敌方.length, 方针表: 场.方针表, 记录: 场.记录.length })}`);
  if (JSON.stringify(场.记录) === JSON.stringify(战报.记录)) ok(`★ 读回来的逐条记录与这一场的 \`ctx.log\` **逐字相同**（${场.记录.length} 条，一个字都没改写）`);
