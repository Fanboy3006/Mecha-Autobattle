  page.sandbox.navigator.clipboard = { writeText: async t => { page.sandbox.__剪贴板 = t; } };
  const 复2 = 界面.动作('复制记录');
  if (复2 && 复2.ok === true && 复2.方式 === '剪贴板' && page.sandbox.__剪贴板 === G.战斗记录.场文本(界面.本场记录)) {
    ok(`有剪贴板时：剪贴板里拿到的**就是导出文本**（${复2.字数} 字）—— 屏上写「${复2.提示}」`);
  } else bad(`复制成功那条路不对：${JSON.stringify(复2)}`);
  delete page.sandbox.navigator.clipboard;

  /* ---- ⑥ 下载 .txt：文件名带种子与时间；失败兜底 / 成功两条路 ---- */
  const 名 = G.战斗记录.文件名(场);
  if (名.includes(`种子${场.种子}`) && /\d{8}-\d{6}\.txt$/.test(名) && !/[\\/:*?"<>|]/.test(名)) ok(`下载文件名带种子与时间、且没有非法字符：\`${名}\``);
  else bad(`文件名不对：${名}`);
  const 下1 = 界面.动作('下载记录');
  if (下1 && 下1.ok === false && /不支持下载/.test(下1.提示)) ok(`替身里没有 Blob / URL：「下载 .txt」给可见提示：「${下1.提示}」`);
  else bad(`下载兜底不对：${JSON.stringify(下1)}`);
  {
    /* 造一个假浏览器：Blob + URL.createObjectURL；`document.createElement('a')` 是替身元素（挂在 body 上，能回读） */
    page.sandbox.Blob = class { constructor(parts, opt) { this.parts = parts; this.type = opt && opt.type; } };
    page.sandbox.URL = { createObjectURL: b => 'blob:fake/' + String(((b && b.parts && b.parts[0]) || '')).length, revokeObjectURL() {} };
    const 前 = page.sandbox.document.body.children.length;
    const 下2 = 界面.动作('下载记录');
    const 挂的 = page.sandbox.document.body.children[前];
    if (下2 && 下2.ok === true && 挂的 && 挂的.download === 名 && /^blob:fake\//.test(String(挂的.href))) {
      ok(`有 Blob / URL 时：建了 \`a[download="${挂的.download}"]\`（href ${挂的.href}）—— 屏上写「${下2.提示}」`);
    } else bad(`下载成功那条路不对：${JSON.stringify({ 下2, 挂的: 挂的 && { download: 挂的.download, href: 挂的.href } })}`);
    delete page.sandbox.Blob; delete page.sandbox.URL;
  }

  /* ---- ⑦ 最近 5 场 FIFO：连存 6 场，最老的被丢 ---- */
  清干净();
  const 造一场 = i => G.战斗记录.做一场({
    战报: { 结果: i % 2 ? '胜' : '败', 回合数: i, 记录: [{ 回合: 1, 文本: `第 ${i} 场` }] },
    种子: i, 现在: 1700000000000 + i * 1000,
  });
  for (let i = 1; i <= 6; i++) G.战斗记录.存(造一场(i));
  const 六 = G.战斗记录.读();
  if (六.length === G.战斗记录场数上限 && 六.map(x => x.种子).join(',') === '2,3,4,5,6') {
    ok(`★ FIFO：连存 6 场 → 只剩最近 ${六.length} 场（种子 ${六.map(x => x.种子).join('、')}），最老的「第 1 场」被丢掉`);
  } else bad(`FIFO 不对：${JSON.stringify(六.map(x => x.种子))}（期望 2,3,4,5,6）`);

