  if (战报.记录.every(x => x.文本 == null || 结算屏.includes(x.文本))) ok('屏幕上画的每一条都是**原文**（记录文本逐字出现在屏上，没有加料 / 改写）');
  else bad('屏幕上某条记录被改写了');

