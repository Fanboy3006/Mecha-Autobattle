  const 体积 = G.战斗记录.体积(场);
  info(`真实体积：一场（${场.结果} · ${场.回合数} 回合 · ${场.记录.length} 条）= ${体积} 字符 ≈ ${(体积 / 1024).toFixed(1)} KB；` +
    `5 场 ≈ ${(体积 * 5 / 1024).toFixed(1)} KB（上限 = ${G.战斗记录容量上限} 字符 = ${G.战斗记录容量上限 / 1024} KB）`);

  /* ---- ③ 结算屏那一块「本场记录」+ 保存反馈（三层反馈的「保存」层） ---- */
