  const 缺文 = 抽.filter(i => !文.includes(战报.记录[i].文本));
  if (!缺文.length) ok(`导出文本含**逐条原文**（抽第 ${抽.map(i => i + 1).join(' / ')} 条，一个字都没改写）`);
  else bad(`导出文本里那几条被改写了：${JSON.stringify(缺文)}`);
  const 摘要关键词 = [`种子：${场.种子}`, `层：第 ${场.层} 层`, `节点类型：${场.节点类型}`, `编成：${场.编成ID}`,
    `结果：${场.结果}`, '我方：', '敌方：', '方针：', `回合数：${场.回合数}`];
  const 缺摘要 = 摘要关键词.filter(k => !文.includes(k));
  if (!缺摘要.length) ok('导出文本开头有摘要（种子 / 层 / 节点类型 / 编成 / 我方阵容与等级 / 敌方阵容 / 方针表 / 结果 / 回合数）');
  else bad(`导出文本的摘要缺这些：${缺摘要.join('、')}`);
  const 尾 = 文.trimEnd().split('\n').slice(-战报.记录.length);
  if (尾.length === 战报.记录.length && 尾.every((行, i) => 行 === `${i + 1}. [第 ${战报.记录[i].回合} 回合] ${战报.记录[i].文本}`)) {
    ok(`末尾那一段 = 「行号. [第 N 回合] 原文」，一行一条（${尾.length} 条；行号与回合号是加的前缀，记录文本一个字没动）`);
  } else bad(`逐条记录那一段的格式不对：${JSON.stringify(尾.slice(0, 2))}`);

  /* ---- ⑤ 复制为文本：失败兜底（全选文本）+ 成功两条路 ---- */
  if (场.来源 === '练习' && 场.层 === 1 && 场.节点类型 === '普通') ok(`练习模式那一场也记了层 / 节点类型（从编成表读：第 ${场.层} 层 ${场.节点类型}，来源「${场.来源}」）`);
  else bad(`练习模式的层 / 节点类型不对：${JSON.stringify({ 来源: 场.来源, 层: 场.层, 节点类型: 场.节点类型 })}`);
  const 复1 = 界面.动作('复制记录');
  if (复1 && 复1.ok === false && 复1.方式 === '全选文本') ok(`替身里没有剪贴板：「复制为文本」给可见提示 + 退化成「全选文本」：「${复1.提示}」`);
  else bad(`复制失败兜底不对：${JSON.stringify(复1)}`);
  const 屏1 = 屏文字();
