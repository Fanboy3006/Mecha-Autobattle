const 造按钮 = 值 => {
  const m = new RegExp('<button[^>]*data-act="(' + 值 + ')"[^>]*>').exec(屏文字());
  if (!m) return null;
  return 补元素({ tagName: 'BUTTON', getAttribute: k => (k === 'data-act' ? m[1] : null), addEventListener() {}, removeEventListener() {} });
};

