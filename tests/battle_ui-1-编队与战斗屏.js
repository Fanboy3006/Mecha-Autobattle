/* ============================================================================
 * ★ 2026-10-13 第 [12] / [13] 两段共用的「真派发点击」小工具 —— 照 `tests/map.js` 第 [26] 段的写法。
 * 为什么要这一套：`tests/lib/dom-stub.mjs` 的 `addEventListener` 是**空实现**（开机那次挂的监听抓不到），
 * 所以这里**不改替身**，只在测试这一段里给 `#screen` / `#ctrl` 补一个能记住监听器的 `addEventListener`，
 * 再自己调一次 `界面.接线()` 把（浏览器里开机挂的那一条）委托挂进来 —— 之后「点按钮」走的就是
 * **`#screen` 上那一条 `[data-act]` 委托**，与浏览器里完全同一条路（**不直调** `界面.动作()` / `音乐.切开关()`）。
 * ★ `监听` / `补元素` 必须是**模块级**（两段共用一份）：替身元素是同一个对象，
 *   每段各起一个 WeakMap 会读不到上一段挂进去的监听器。
 * ========================================================================== */
const 监听 = new WeakMap();
const 补元素 = el => {
  if (!el || el.__可点) return el;
  el.__可点 = true;
  el.closest = sel => {
    let n = el;
    while (n) {
      if (n.getAttribute) {
        if (sel === '[data-act]' && n.getAttribute('data-act') != null) return n;
        if (sel === 'select[data-act]' && n.tagName === 'SELECT' && n.getAttribute('data-act') != null) return n;
      }
      n = n.parentNode || null;
    }
    return null;
  };
  const 原挂 = (typeof el.addEventListener === 'function' ? el.addEventListener : () => {}).bind(el);
  el.addEventListener = (事件, fn) => { if (!监听.has(el)) 监听.set(el, {}); 监听.get(el)[事件] = fn; 原挂(事件, fn); };
  return el;
};
/** 把 `#screen` / `#ctrl` 上的委托挂成**测试能抓到的那一条**（两段各调一次；返回 `#screen` 的 click 监听器）。
 *  ① `监听.delete` 摘掉上一段留下的那一条：不摘的话上一段挂的**旧委托**会跟着一起收到测试派发的事件，
 *     同一颗按钮被派发两次（第 [13] 段实测：`调参室:层:2` 被旧委托又派发成 `调参室:层`，把模型打回层 1）；
 *  ② `delete __可点` 让 `补元素` 重包一次 `addEventListener`（替身元素的 `addEventListener` 是空实现，
 *     只有包过的才记得住）；③ 清 `_接了…` 标记再 `接线()` —— 挂上的是**补过之后**的那一条；
 *  ④ 最后把标记补回 `true`（替身里没有真实监听，标记是 `接线()` 唯一的幂等依据，
 *     不补回的话下一次 `刷()` 会再挂一条 —— 真实浏览器/替身两边都会变成两条委托）。 */
const 接上真监听 = () => {
  const 屏 = page.byId.get('screen'), 控 = page.byId.get('ctrl');
  监听.delete(屏); 监听.delete(控);
  delete 屏.__可点; delete 控.__可点;
  补元素(屏); 补元素(控);
  屏['_接了click'] = false; 控['_接了click'] = false;
  屏['_接了change'] = false; 控['_接了change'] = false;
  界面.接线();
  屏['_接了click'] = true; 控['_接了click'] = true;
  屏['_接了change'] = true; 控['_接了change'] = true;
  return (监听.get(屏) || {}).click;
};
