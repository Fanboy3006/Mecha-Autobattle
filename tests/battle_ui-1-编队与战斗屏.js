/* ============================ [8] 结果条与记录屏的结构（2026-10-11 界面体验修复） ============================ */
/* 作者试玩后提的两条：「现在很多事情结束以后，结果没有提示」+「记录也需要显示」。
   这一段只管**界面结构**（类型 / 清空时机 / 记录屏的形状 / 没有 RUN 时不受影响）；
   真实的逐动作结算文本与条数上限在 `tests/map.js` 第 [19][20] 段（那边有 RUN，能真结算）。
   练习模式（没有 RUN）这条路**一条断言都不许变红**：所以这里同时盯着「没有 RUN 时不崩」。 */
console.log('\n[8] 结果条（成功 / 警告 / 失败 / 信息）与记录屏的界面结构');
{
  const 肉鸽 = G.肉鸽, 肉鸽界面 = G.肉鸽界面;
  const 条出 = () => {
    const m = /<p class="resbar ([a-z]+)" data-resbar="1"(?: data-res-type="([^"]*)")?>([\s\S]*?)<\/p>/.exec(屏文字());
    return m ? { 类: m[1], 类型: m[2] || null, 文本: m[3].replace(/<[^>]*>/g, '').slice(0, 40) } : null;
  };
  /* ① 四个类型各有自己的 CSS 类（成功 / 警告 / 失败 / 信息） */
  const 类型表 = G.结果类型表;
  if (JSON.stringify(类型表) === JSON.stringify({ 成功: 'ok', 警告: 'warn', 失败: 'bad', 信息: 'info' })) {
    ok(`结果条四种类型各自一个配色类：${Object.keys(类型表).map(k => `${k}→${类型表[k]}`).join('、')}`);
  } else bad(`结果类型表不对：${JSON.stringify(类型表)}`);
  /* ② 练习模式（没有 RUN）也能设结果条，但**不许往日志里写**（没有 RUN 就没有日志） */
  肉鸽界面.设结果('成功', '练习模式：这一条只上结果条，不写日志');
  const p = 肉鸽界面.提示结果();
  if (p && p.类型 === '成功' && p.文本.includes('练习模式')) ok('没有 RUN 时也能设结果条（练习模式 / 平衡工具那条路不受影响）');
  else bad(`没有 RUN 时设结果条失败：${JSON.stringify(p)}`);
  if (肉鸽.RUN === null) ok('练习模式确实没有 RUN（`设结果()` 直接跳过写日志那一步）');
  else bad(`练习模式下居然有 RUN：${JSON.stringify(肉鸽.RUN && 肉鸽.RUN.层)}`);
  /* ③ 清空时机：`清结果()` 清掉；字符串写法照样认（老调用点兼容） */
  肉鸽界面.清结果();
  if (肉鸽界面.提示结果() === null) ok('清结果() 之后结果条为空（换层 / 开新局 / 读档时清的就是它）');
  else bad('清结果() 没清掉');
  肉鸽界面.提示 = '老的字符串写法';
  const 老 = 肉鸽界面.提示结果();
  if (老 && 老.类型 === '信息' && 老.文本 === '老的字符串写法') ok('老调用点 `提示 = "一句文本"` 照样能用（按「信息」类显示）');
  else bad(`老的字符串写法认不出来：${JSON.stringify(老)}`);
  肉鸽界面.清结果();
  /* ④ 没有 RUN 时，记录屏给一句话、不抛异常；战斗奖励清单在没有数据时是空串 */
  const 记 = 界面.记录屏();
  if (typeof 记 === 'string' && 记.includes('还没有进行中的局')) ok('没有 RUN 时记录屏给「还没有进行中的局」，不抛异常');
  else bad('没有 RUN 时记录屏不对');
  if (G.战斗奖励清单Html(null) === '' && G.战斗奖励清单文字(null).includes('没有奖励数据')) ok('战斗奖励清单：没有返回值时给空串 / 一句「没有奖励数据」（不自己编数字）');
  else bad('战斗奖励清单在没有数据时不对');
  /* ⑤ 奖励清单的字段顺序与口径（只读 `肉鸽.战斗结束()` 的返回值） */
  const 样例 = { 胜: true, 希望: 6, 源碳: 5, 券: { 类: '职业', 名: '近卫', 档: null }, 零件: { 名: '报废假肢' }, 藏品: { 名: '格斗教范' } };
  const 文字 = G.战斗奖励清单文字(样例);
  if (/希望 \+6/.test(文字) && /源碳 \+5/.test(文字) && /券【近卫招募券】/.test(文字) && /零件【报废假肢】/.test(文字) && /藏品【格斗教范】/.test(文字)) {
    ok(`奖励清单一行字：${文字}`);
  } else bad(`奖励清单一行字不对：${文字}`);
  const 块 = G.战斗奖励清单Html(样例);
  if (/data-battle-res="1"/.test(块) && /这一场拿到了/.test(块)) ok('奖励清单块（结算屏上那一行）有了：data-battle-res + 「这一场拿到了」');
  else bad('奖励清单块不对');
  const 败块 = G.战斗奖励清单Html({ 胜: false, 扣: 5 });
  if (/battle-res lose/.test(败块) && /作战耐久 <b>−5<\/b>/.test(败块)) ok('失败那一场换成「这一场的账：作战耐久 −N」（红边）');
  else bad(`失败那一场清单不对：${败块}`);
  /* ⑥ 记录屏的结构（有 RUN 时）：入口 / 滚动框 / 最新在前 / 空日志 */
  {
    const 种子 = 20261076;
    界面.动作('回菜单'); 界面.动作('去分队'); 界面.动作('选分队', '无');
    界面.动作('开新局:' + 种子);
    const R = 肉鸽.RUN;
    if (R && 界面.屏 === '招募') ok(`开了一局（第 ${R.层} 层、日志 ${R.日志.length} 条、券 ${R.券.length} 张）`);
    else bad(`开新局没成功：屏 ${界面.屏}`);
    界面.开屏('大地图');
    if (条出() && /记录（\d+ 条）/.test(屏文字())) ok(`大地图顶部有结果条、按钮上有「记录（${R.日志.length} 条）」`);
    else bad('大地图上没有结果条或记录入口');
    界面.动作('去记录');
    const 行 = [...屏文字().matchAll(/data-log-line="1"/g)].length;
    if (界面.屏 === '记录' && 行 === R.日志.length && 行 > 0) ok(`记录屏打开、列出 ${行} 条（= RUN.日志 的条数）、可滚动（.logbox）`);
    else bad(`记录屏不对：屏 ${界面.屏}、${行} 行 / 日志 ${R.日志.length} 条`);
    if (/<span class="tag">第 \d+ 层 · .+<\/span>/.test(屏文字())) ok('每条带「第 N 层 · 类型」前缀');
    else bad('记录行没有「层 · 类型」前缀');
    /* 同一个种子再走一遍 → 记录逐字相同（方案 6.1 的硬规矩：结果只看种子） */
    const 一遍 = () => {
      界面.动作('回菜单'); 界面.动作('去分队'); 界面.动作('选分队', '无');
      界面.动作('开新局:' + 种子);
      界面.开屏('大地图'); 界面.动作('去记录');
      return JSON.stringify(肉鸽.RUN.日志.map(x => [x.层, x.文本]));
    };
    const a = 一遍(), b = 一遍();
    if (a === b) ok(`同种子两次开局：记录逐字相同（${JSON.parse(a).length} 条，时间戳不进比对）`);
    else bad('同种子两次的记录不一样');
  }
  界面.动作('回菜单');
}

