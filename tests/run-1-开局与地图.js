/** ★ 2026-10-11 券系统：**肉鸽开局名册是空的**（分队不带机体，改前是默认五人队）——
 *  所以后面那些「拖进格子 / 编队开战 / 名册上记 hp 比」的段落要先**真的招几个人**。
 *  这个助手走**玩家那条路**（开招募屏 → 选中一张对得上的券 → 招募），
 *  不是往 `RUN.队伍` 里硬塞（硬塞会绕开券系统，那段测试就没意义了）。
 *  ★ 2026-10-12 修真 bug：**没券就不能招** → 这里没有「不用券」那一步了；一张能用的券都没有时
 *  才补一张同类券（见函数里那句注释）。 */
function 招几个(n = 3, 预算 = 60) {
  const R = 肉鸽.RUN;
  if (!R) return 0;
  R.希望 += 预算;                              // 测试给足希望：要测的是「有没有人可用」，不是经济
  界面.开屏('招募');
  const 费 = k => G.肉鸽数值.招募费[G.tierOf(k)] || 0;
  let 招到 = 0;
  for (let 轮 = 0; R.队伍.length < n && 轮 < 16; 轮++) {
    const 已有 = new Set(R.队伍.map(m => m.键));
    const 人 = G.ALLY_T.map(t => t.mech).filter(k => !已有.has(k));
    /* 走玩家那条路：先选中一张对得上的券（`界面.用券(i)`），再 `肉鸽.招募(键, i)`。
       ★ 2026-10-12 修真 bug：**没券就不能招**（`90-肉鸽.js` 的 `招募()` 直接拒绝），
       所以这里**删掉了原来「不用券也能招」那一步的兜底**（旧语义只在 `tests/rank.js` 第 [9] 段留一条对照）。 */
    let 成了 = false;
    for (let i = 0; i < (R.券 || []).length && !成了; i++) {
      const 合 = 人.filter(k => G.券合(R.券[i], k)).sort((a, b) => 费(a) - 费(b));
      for (const k of 合) {
        if (R.希望 < 费(k)) continue;
        界面.用券(i);
        const r = 肉鸽.招募(k, i);
        if (r && r.ok) { 招到++; 成了 = true; break; }
        肉鸽界面.选中的券 = null;
      }
    }
    if (成了) continue;
    /* 手上**一张对得上的券都没有**（或者都付不起）时：补一张「和某位候选同职业」的券再试一次 ——
       这是**测试的补券口子**（补出来的券和 `战后 / 招募站` 发的是同一种对象），不是绕开券系统：
       招募那一步照样走 `界面.用券` → `肉鸽.招募(键, 下标)`；券的两个真实来源在下面第 [7] 段单独测。 */
    肉鸽界面.选中的券 = null;
    const 能付 = 人.filter(k => R.希望 >= 费(k)).sort((a, b) => 费(a) - 费(b))[0];
    if (能付 == null) break;
    R.券.push({ 类: '职业', 名: G.tplOf(能付).tags.战斗分类, 档: null, 来源: '测试' });
    const 补 = R.券.length - 1;
    界面.用券(补);
    const r2 = 肉鸽.招募(能付, 补);
    if (r2 && r2.ok) { 招到++; continue; }
    肉鸽界面.选中的券 = null;
    break;
  }
  if (界面.屏 !== '大地图') 界面.开屏('大地图');
  return 招到;
}

