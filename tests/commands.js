/** 开局 → 设单位开关 → 设方针 → 打 N 回合 */
function 打(我方, 敌方, 方针, 种子, 回合数 = 1, 开关表 = null, 选项 = null) {
  const ctx = G.开局(我方, 敌方, 种子, 开关表, 选项);
  if (方针) G.设方针(ctx, 方针);
  for (let i = 0; i < 回合数 && !ctx.result; i++) G.打一回合(ctx);
  return ctx;
}
const 攻击录 = (ctx, 位, 方 = 'ally') => ctx.log.filter(x => x.类型 === '攻击' && x.单位方 === 方 && x.单位位 === 位);
const 我方攻击 = ctx => ctx.log.filter(x => x.类型 === '攻击' && x.单位方 === 'ally');
