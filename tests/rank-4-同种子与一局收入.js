/* ============================================================================
 * ★ 2026-10-11 节点改造：**改前 vs 改后的一局资源收支**（真实数字，作者点名要）
 * ----------------------------------------------------------------------------
 * 口径（写清，免得下次换个人看不懂）：
 *   · 一局 = 第 1 → 第 4 层通关，**每层给的推进剂预算 = 31**（= 推进剂上限 7 + 一个小径 +1 +
 *     瞭望站/休整能给到的最大 8，取一个「足够走满一层」的数）；
 *   · 走法 = 「按 BFS 最短路直奔出口尽头」，顺路把**战斗节点**打完（战斗统一按打赢结算：
 *     这一段的主题是资源收支，不是胜负）、**节点按最优档选**（瞭望站登高 / 遗迹藤蔓 /
 *     休整推进剂 / 侵蚀源净化 / 隧道传送 / 事件第一个选项）；
 *   · 三组数字：① **改前口径**（出口不换希望、瞭望站希望 +3、遗迹免费给源碳 +2）、
 *     ② **改后口径**（出口尽头 1:1 换希望、瞭望站不给希望、遗迹要付代价）、
 *     ③ **改后 + 走小径**（余量不换希望、下一层推进剂上限 +1）。
 *   · 走法不碰「剩多少推进剂」以外的随机量，所以 10 个种子之间的差异来自地图形状。
 * ========================================================================== */
/** 走完一局并记下逐层账（第 [8] / [12] 段用）。
 *  `口径`：'改前' | '改后'；`出口`：'尽头' | '小径'（走哪个出口）；
 *  `选项.先打`（第 [12] 段的经济口径用）：`true` = **先把能打到的战斗打完再奔出口**
 *  （作者日志里那一局就是这种走法：一层里把作战 / 精英 / 侵蚀源都打掉）。
 *  不传 = 老行为（出口优先），第 [8] 段的数字**一个字节都不变**。 */
function 量一局(种子, 口径 = '改后', 出口 = '尽头', 选项 = null) {
  const R = 开一局(种子);
  const 原始 = {
    换希望: G.肉鸽数值.出口换希望, 瞭望站希望: G.肉鸽数值.瞭望站希望,
    遗迹源碳: G.肉鸽数值.遗迹源碳, 遗迹耐久价: G.肉鸽数值.遗迹耐久价,
    遗迹源碳价: G.肉鸽数值.遗迹源碳价, 持钩: 界面.对话框钩子,
  };
  if (口径 === '改前') {
    /* 改前：出口不换希望（推进剂直接作废）、瞭望站希望 +3、遗迹「不付代价就拿源碳 +2」（旧的免费抽奖） */
    G.肉鸽数值.出口换希望 = 0;
    G.肉鸽数值.瞭望站希望 = 3;
    G.肉鸽数值.遗迹耐久价 = 0;
    G.肉鸽数值.遗迹源碳价 = 0;
  }
  /* 战斗统一按**打赢**结算（主题是资源收支，不是胜负；也不走播放层） */
  const 打赢 = () => {
    const 格 = 肉鸽.当前格();
    const 类型 = 界面.肉鸽战斗类型 || (格 ? 格.类型 : '作战');
    界面.肉鸽战斗类型 = '作战';
    if (!肉鸽.进行中) return;
    界面.屏 = '大地图';
    肉鸽.战斗结束('胜', 类型, { 敌方: [], 我方: [] });
    if (界面.屏 === '大地图') 界面.刷();
  };
  界面.对话框钩子 = (标题) => {
    if (/瞭望站/.test(标题)) return '登高';
    if (/遗迹/.test(标题)) return R.耐久 > G.肉鸽数值.遗迹耐久价 ? '藤蔓' : '离开';
    if (/休整/.test(标题)) return '推进剂';
    if (/隧道/.test(标题)) return 'go';
    if (/侵蚀源/.test(标题)) return R.源碳 >= G.肉鸽数值.侵蚀源净化价 ? '净化' : '硬闯';
    return 'go';
  };
  const 层账 = [];
  let 步 = 0;
  while (肉鸽.进行中 && R.层 <= 4 && 步++ < 400) {
    if (界面.屏 === '肉鸽结算') break;
    /* 每层开头给推进剂预算（改后：走小径的话这一层上限已经 +1） */
    if (步 === 1 || R.推进剂 <= 0) R.推进剂 = 31 + (口径 === '改后' && 出口 === '小径' && R.层 > 1 ? G.小径上限加成(R) : 0);
    if (界面.屏 === '黑市') { 界面.动作('黑市离开'); continue; }
    if (界面.屏 === '招募') { 界面.动作('回大地图'); continue; }
    if (界面.屏 === '奇遇') { 界面.动作('奇遇:0'); continue; }
    const 菜单 = 肉鸽.格菜单();
    if (菜单.length) {
      const 动 = 菜单[0].动;
      const 层前 = R.层;
      if (动 === '打这一场') {
        打赢();
      } else if (动.startsWith('前进')) {
        层账.push({
          层: R.层, 出层推进剂: R.推进剂, 希望: R.希望, 源碳: R.源碳, 场次: R.场次,
          零件: (R.零件 || []).length, 藏品: R.藏品.length, 耐久: R.耐久,
        });
        肉鸽.选出口(出口);
        界面.动作(出口 === '小径' ? '前进:小径' : '前进:尽头');
      } else if (动 === '去黑市') 界面.动作('去黑市');
      else if (动 === '去招募') 界面.动作('去招募');
      else if (动 === '去奇遇') 界面.动作('去奇遇');
      else if (动 === '瞭望') 界面.动作('瞭望');
      else if (动 === '穿隧道') 界面.动作('穿隧道');
      else if (动 === '探查遗迹') 界面.动作('探查遗迹');
      else if (动.startsWith('休整:')) 界面.动作('休整', '推进剂');
      else if (动 === '跳过') 界面.动作('跳过节点');
      else if (动.startsWith('去节点:')) 界面.去节点(Number(动.slice(4)));
      if (R.层 !== 层前 || !肉鸽.进行中) continue;
      continue;
    }
    const 能去 = 肉鸽.能去的();
    if (!能去.length) break;
    /* 走法：能打到的战斗先打（拿资源），再奔出口 —— 出口被守军挡着时出口那格进不去，
       所以守军在能去的里面时它自然会被排在前面。
       ★ `选项.先打`：**战斗节点优先于出口**（一层里把能打的都打掉 —— 作者日志那一局的走法）。
       ★★ 2026-10-13（出口线**口径 A**：作者拍板「允许有一个出口不需要打守军」）：两个出口**不再等价** ——
       **小径免打守军**（走到就换层），尽头照旧要打赢守军。这一段量的是**经济**，而希望 / 源碳 / 券那三个
       目标区间是按「**打完关口**」那一支定的（守军的关口奖励只在打赢时发）→ 走法加一条：
       **守军没清且走得到 → 先去打守军**（就是「实战优」这个口径名要说的事）。
       ⚠ 不加这一条、机器人一头扎进小径的实测：24 局全部通关、场次 1/局、希望中位 21（量到的不是经济）。 */
    const 出口格 = 能去.find(n => G.是出口类型(n.类型));
    const 战斗格 = 能去.find(n => ['出口守军', '精英', '侵蚀源', '作战'].includes(n.类型));
    const 守军格 = 能去.find(n => n.类型 === '出口守军');
    /* ★ 口径 A 只动**没有「先打」那一条**（它原来就是「先奔出口」）：守军没清且走得到 → 先去打守军。
       ★ `先打` 那一条**与改前逐字相同**：`战斗格` 本来就把 `出口守军` 算在里面（守军是能打到的战斗格之一），
         而 `量一局` 的推进剂在每层开头会被补到 31（够走遍小图）→ 守军一定排在出口之前，
         所以「先打」这条口径下**一个数字都不该变**（第 [12] 段的 24 局中位数就是它量的）。 */
    const 目标 = (选项 && 选项.先打)
      ? (战斗格 || 出口格 || 能去[0])
      : ((守军格 && !肉鸽.守军已清()) ? 守军格 : (出口格 || 战斗格 || 能去[0]));
    const 走前 = R.当前;
    界面.去节点(目标.k);
    if (R.当前 === 走前) break;
  }
  /* 还原被这一段改过的数值（同一个测试进程里后面还要用真口径） */
  界面.对话框钩子 = 原始.持钩;
  G.肉鸽数值.出口换希望 = 原始.换希望;
  G.肉鸽数值.瞭望站希望 = 原始.瞭望站希望;
  G.肉鸽数值.遗迹源碳 = 原始.遗迹源碳;
  G.肉鸽数值.遗迹耐久价 = 原始.遗迹耐久价;
  G.肉鸽数值.遗迹源碳价 = 原始.遗迹源碳价;
  return {
    种子, 层: R.层, 希望: R.希望, 源碳: R.源碳, 耐久: R.耐久, 场次: R.场次,
    券: (R.券 || []).length,                                    // ★ 经济收紧要量的四项之一（第 [12] 段）
    零件: (R.零件 || []).length, 藏品: R.藏品.length, 等级: R.等级,
    结局: R.结局 || (R.层 >= 4 ? '未结算' : '未结束'), 层账,
    来源: Object.assign(G.希望来源空(), R.希望来源 || {}),
  };
}

