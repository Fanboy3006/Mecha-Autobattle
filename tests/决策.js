function 测屏(记录) {
  const 屏 = 界面.屏;
  if (记录.some(x => x.屏 === 屏)) return;
  const R = 肉鸽.RUN;
  const 前 = R ? JSON.stringify(R) : '无局';
  /* ★ 「不消耗随机数」的正面证据：战斗内把 `ctx.rng` 包一层数调用次数（引擎的随机数唯一入口） */
  const 计数 = { n: 0 };
  let 原rng = null;
  if (屏 === '战斗' && 界面.ctx && typeof 界面.ctx.rng === 'function') {
    原rng = 界面.ctx.rng;
    界面.ctx.rng = function () { 计数.n++; return 原rng.apply(null, arguments); };
  }
  let 甲 = [], 乙 = [], 崩 = null;
  try { 甲 = 选项.枚举(界面); 乙 = 选项.枚举(界面); } catch (e) { 崩 = e && e.message; }
  if (原rng) 界面.ctx.rng = 原rng;
  const 后 = R ? JSON.stringify(R) : '无局';
  记录.push({
    屏, 条数: 甲.length, 例: 甲.slice(0, 3), 崩,
    不改状态: 前 === 后, 两遍一致: JSON.stringify(甲) === JSON.stringify(乙), 随机数: 计数.n,
  });
}

function 战斗(记录) {
  let 轮 = 0;
  while (界面.屏 === '战斗' && 轮++ < 14) {
    测屏(记录);
    const ctx = 界面.ctx;
    const 活敌 = (ctx.enemies || []).filter(u => u.hp > 0);
    const 活我 = (ctx.allies || []).filter(u => u.hp > 0);
    if (ctx.turn === 1 && 活敌.length) { 界面.动作('方针:集中攻击'); 界面.动作('点敌人:' + 活敌[0].slot); }
    for (const u of 活我.slice(0, 2)) 界面.动作('大招:' + u.slot);
    界面.动作('开打');
    let n = 0;
    while (界面.阶段 === '播放' && n++ < 200000) G.播放.tick();
  }
}

