  const 录前 = 前有人.log.filter(x => x.类型 === '攻击' && x.单位位 === 0);
  if (录前.length && 录前.every(x => x.目标位 !== 5)) ok(`同路前排还有人时近战打不到后排：B1 打了位 ${录前.map(x => x.目标位).join('、')}（不是位 5）`);
  else bad(`近战越过了前排：${JSON.stringify(录前.map(x => x.目标位))}`);

  /* 该路前排空了（破阵暴露）→ 近战能打该路后排 */
  const 前没人 = G.开局([{ 键: 'B1', 位: 0, 等级: 30 }], [{ 键: 'hound', 位: 5, 等级: 1 }], 3142);
