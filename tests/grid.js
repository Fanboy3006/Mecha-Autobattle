/* ============================ [1] 8 格与阻挡关系表 ============================ */
console.log('[1] 8 格 = 前排 4 + 后排 4（正交 4×2），阻挡关系逐条对');
{
  if (G.slots === 8 && G.rows === 2 && G.行列数(0) === 4 && G.行列数(1) === 4) {
    ok(`阵型 ${G.slots} 格 = 前排 ${G.行列数(0)} + 后排 ${G.行列数(1)}（正交双排 4×2，前排靠敌人，排号 0 / 1）`);
  } else bad(`格数不对：slots ${G.slots} / 行列数 ${G.行列数(0)},${G.行列数(1)}`);

  const 名 = [0, 1, 2, 3, 4, 5, 6, 7].map(G.位名).join('/');
  if (名 === '前1/前2/前3/前4/后1/后2/后3/后4') ok(`位名（0–7）：${名}`);
  else bad(`位名不对：${名}`);

  /* 1 对 1 正交：F0→B0 / F1→B1 / F2→B2 / F3→B3（**4 条**关系，一个后排位只被同路那一个前排位挡） */
  const 要 = [[0, 4], [1, 5], [2, 6], [3, 7]];
  const 实 = G.阻挡关系;
  if (实.length === 4 && 要.every(([f, b], i) => 实[i][0] === f && 实[i][1] === b)) {
    ok(`阻挡关系 4 条逐条对得上（1 对 1 同路）：${实.map(([f, b]) => `${G.位名(f)}→${G.位名(b)}`).join('  ')}`);
  } else bad(`阻挡关系不对：${JSON.stringify(实)}`);

  /* 每个前排位的「阻挡位」就是同路那一个后排位；后排位反过来（恰好 1 个） */
  const 前 = [0, 1, 2, 3].map(s => G.阻挡位(s).map(G.位名).join('+')).join(' / ');
  if (前 === '后1 / 后2 / 后3 / 后4') ok(`每个前排位的阻挡位：${前}（1 对 1，不再有「一格被两个前排挡」）`);
  else bad(`阻挡位不对：${前}`);
  const 遮挡数 = [4, 5, 6, 7].map(s => G.遮挡位(s).length);
  if (遮挡数.join(',') === '1,1,1,1') ok(`每个后排位被几个前排位挡：后1=1、后2=1、后3=1、后4=1（正交 1 对 1）`);
  else bad(`遮挡位数不对：${遮挡数.join(',')}`);
  if (G.遮挡位(5).map(G.位名).join('+') === '前2' && G.遮挡位(7).map(G.位名).join('+') === '前4') {
    ok(`对位关系逐条对：后2 只被 前2 挡、后4 只被 前4 挡（F0↔B0…F3↔B3）`);
  } else bad(`对位不对：后2←${位名们(G.遮挡位(5))}、后4←${位名们(G.遮挡位(7))}`);
  if (G.阻挡位(4).length === 0 && G.遮挡位(0).length === 0) ok('阻挡位() 只对前排有意义、遮挡位() 只对后排有意义（另一排返回空数组）');
  else bad('阻挡位 / 遮挡位的方向搞反了');
  if (typeof G.被挡吗 === 'function' && G.被挡吗(5, [1]) === true && G.被挡吗(5, [0]) === false && G.被挡吗(5, []) === false) {
    ok('被挡吗(后2, 活着的位)：同路 前2 活着 → true；只有别的路（前1）活着 → false；全灭 → false');
  } else bad('被挡吗 不对');
}

/* ============================ [2] 直射按位阻挡 ============================ */
console.log('\n[2] 直射按位阻挡：阻挡位活着 → 命中 −20（真的打得到）；阻挡位全灭 → 无惩罚');
{
  /* 一台 B2（尖兵，只有直射 / 曲射），只留**直射**武器，专门验直射的按位阻挡。
     ★ 2026-10-13 正交 4×2：后2(5) 只被**同路**的 前2(1) 挡 → 挡它的那台摆在 slot 1；
       而且挡它的那台**不能是重装**（重装会被 `兰斯战线.同路重装必护卫` 100% 勾走，
       记录里的 `目标位` 就不是 5 了）—— `grunt` 是杂兵，安全。 */
  const 挡位 = 1;
  const 建 = (前排活着) => {
    const 敌 = [{ 键: 'grunt', 位: 0, 等级: 1 }, { 键: 'grunt', 位: 挡位, 等级: 1 }, { 键: 'hound', 位: 5, 等级: 1 }];
    const ctx = G.开局([{ 键: 'B2', 位: 0, 等级: 30 }], 敌, 20261010);
    if (!前排活着) ctx.enemies.find(u => u.slot === 挡位).hp = 0;
    const 攻 = ctx.allies[0];
    const e = 攻.weapons.find(x => x.t.fire === 'direct');
    攻.weapons = [e];
    return { ctx, 攻, e, 目标: ctx.enemies.find(u => u.slot === 5) };
  };

  const A = 建(true);
  const h0 = G.hitRate(A.攻, A.e.t, A.目标, { blockPenalty: 0, turn: 1 });
  const h1 = G.hitRate(A.攻, A.e.t, A.目标, { blockPenalty: -20, turn: 1 });
  const 不挡 = h0.hit, 被挡 = h1.hit;
  G.resolveAction(A.攻, { kind: 'attack', weapon: A.e.t, target: A.目标, entry: A.攻.weapons[0] }, A.ctx);
  const 录 = A.ctx.log.filter(x => x.类型 === '攻击' && x.目标位 === 5);
  info(`被挡前后的命中率：不被挡 ${不挡}%（原始 ${h0.raw}%）→ 被挡 ${被挡}%（原始 ${h1.raw}%）`);
  if (录.length === 1) ok(`直射**真的打到**了被挡的后排位（位 5 = 后2）：记录「${录[0].文本}」`);
  else bad(`直射打不到被挡的后排位（记录 ${录.length} 条）—— 规则是命中 −20，不是打不到`);
  if (录.length && String(录[0].详情).includes(`${被挡}%`)) {
    ok(`引擎自动按位算出了 −20：那一下的判定用的是 ${被挡}%（= 不被挡的 ${不挡}% − 20，且 > 0）`);
  } else bad(`引擎没有按位扣 −20：详情「${录[0] && 录[0].详情}」，期望 ${被挡}%`);
  /* 命中公式上限 100，所以要看**没被夹住**的原始值才看得出「就是差 20」 */
  if (h0.raw - h1.raw === 20) ok(`被挡就是命中 −20（原始 ${h0.raw}% → ${h1.raw}%，不是打不到）`);
  else bad(`被挡的差值不是 20：${h0.raw} - ${h1.raw} = ${h0.raw - h1.raw}`);
  if (被挡 > 0) ok(`被挡之后命中率仍然 > 0（${被挡}%）—— 打得到，只是难打`);
  else bad('被挡之后命中率变成 0 了（变成了「打不到」）');
  const 期望被挡 = G.expectedDamage(A.攻, A.目标, A.e.t, { blockPenalty: -20 });
  if (期望被挡 > 0) ok(`被挡时**期望伤害 > 0**（${Math.round(期望被挡)}）—— 打得到，只是难打`);
  else bad('被挡时期望伤害变成 0 了（变成了「打不到」）');

  /* 把挡着它的前排位（同路 前2）打死 → 无惩罚 */
  const B = 建(false);
  const 不挡2 = G.hitRate(B.攻, B.e.t, B.目标, { blockPenalty: 0, turn: 1 }).hit;
  G.resolveAction(B.攻, { kind: 'attack', weapon: B.e.t, target: B.目标, entry: B.攻.weapons[0] }, B.ctx);
  const 录2 = B.ctx.log.filter(x => x.类型 === '攻击' && x.目标位 === 5);
  if (G.被挡吗(5, B.ctx.enemies.filter(u => u.hp > 0).map(u => u.slot)) === false) ok('前2（后2 的同路阻挡位）被击坠 → 被挡吗(后2) = false');
  else bad('阻挡位全灭后还被判成「被挡」');
  if (录2.length && String(录2[0].详情).includes(`${不挡2}%`)) ok(`阻挡位全灭 → 无惩罚（那一下用 ${不挡2}%，与不被挡一致）`);
  else bad(`阻挡位全灭后还有惩罚：详情「${录2[0] && 录2[0].详情}」，期望 ${不挡2}%`);

  /* 曲射 / 范围无视阻挡 */
  const 曲射 = G.rowBlockPenalty('曲射', 5, [1], null);
  const 范围 = G.rowBlockPenalty('范围', 5, [1], null);
  const 前排 = G.rowBlockPenalty('直射', 0, [0], null);
  if (曲射 === 0 && 范围 === 0) ok('曲射 / 范围无视阻挡（被挡惩罚恒为 0）');
  else bad(`曲射 / 范围不该有惩罚：曲射 ${曲射}、范围 ${范围}`);
  if (前排 === 0) ok('直射打前排永远不被挡（阻挡只发生在后排位上）');
  else bad('打前排也被挡了');
  /* 狙击的职业特色：我方狙击打后排没有这个惩罚 */
  const 狙 = G.makeUnit('CB2', 'ally', 0, 10);
  if (G.rowBlockPenalty('直射', 5, [1], 狙) === 0) ok('我方狙击打后排没有 −20（方案 6.3 的职业特色）');
  else bad('狙击的被挡豁免没了');
}

/* ============================ [3] 近战只能打前排 ============================ */
