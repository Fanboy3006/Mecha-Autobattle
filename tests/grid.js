/** ★ 2026-10-11 券系统：**肉鸽开局名册是空的**（分队不带机体；改前白送默认五人队）。
 *  「出击名单」这一段的断言需要名册里真的有人 —— 走玩家那条路招（开招募屏 → 选中一张对得上的券 → 招募），
 *  不往 `RUN.队伍` 里硬塞。希望不够时再补预算重来（测试给足希望：测的是流程，不是经济）。
 *  ★ 2026-10-12 修真 bug：**没券就不能招** → 这里没有「不用券」那一步了（见函数里那句注释）。 */
function 招几个(n = 3, 预算 = 60) {
  const R = 肉鸽.RUN;
  if (!R) return 0;
  const 一起 = () => {
    界面.开屏('招募');
    const 费 = k => G.肉鸽数值.招募费[G.tierOf(k)] || 0;
    let 招到 = 0;
    for (let 轮 = 0; R.队伍.length < n && 轮 < 20; 轮++) {
      const 已有 = new Set(R.队伍.map(m => m.键));
      const 人 = G.ALLY_T.map(t => t.mech).filter(k => !已有.has(k));
      let 成了 = false;
      for (let i = 0; i < (R.券 || []).length && !成了; i++) {
        const 合 = 人.filter(k => G.券合(R.券[i], k)).sort((a, b) => 费(a) - 费(b));
        for (const k of 合) {
          if (R.希望 < 费(k)) continue;
          界面.用券(i);
          const r = 肉鸽.招募(k, i);
          if (r && r.ok) { 招到++; 成了 = true; break; }
          肉鸽界面.选中的券 = null;
        }
      }
      if (成了) continue;
      /* ★ 2026-10-12 修真 bug：**没券就不能招**（`90-肉鸽.js` 的 `招募()` 没券直接拒绝），
         所以这里**没有「不用券」那一步了**；一张能用的券都没有时补一张同类券再试
         （测试的补券口子；招募那一步照旧走 `界面.用券` → `肉鸽.招募(键, 下标)`）。 */
      肉鸽界面.选中的券 = null;
      const 能付 = 人.filter(k => R.希望 >= 费(k)).sort((a, b) => 费(a) - 费(b))[0];
      if (能付 == null) break;
      R.券.push({ 类: '职业', 名: G.tplOf(能付).tags.战斗分类, 档: null, 来源: '测试' });
      const 补 = R.券.length - 1;
      界面.用券(补);
      const r2 = 肉鸽.招募(能付, 补);
      if (r2 && r2.ok) { 招到++; continue; }
      肉鸽界面.选中的券 = null;
      break;
    }
    if (界面.屏 !== '大地图') 界面.开屏('大地图');
    return 招到;
  };
  const 招到 = 一起();
  if (R.队伍.length < n) { R.希望 += 预算; return 一起(); }
  return 招到;
}

