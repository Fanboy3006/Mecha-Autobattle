        if (要画在屏上 && !在屏 && !在控) return { 画了: false };
        const 监听器 = 事件监听器(在控 && !在屏 ? 'ctrl' : 'screen');
        if (!监听器) return { 画了: 在屏 || 在控, 挂了: false };
