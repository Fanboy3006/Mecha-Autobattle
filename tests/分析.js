/** 真跑一场并按导出格式生成文本（**和作者点「复制为文本」拿到的是同一段**）。 */
function 造一场(层, 类型, 种子, 方针 = { 1: '全军突击' }, 我方形 = null) {
  const 条目 = G.编成表.find(x => x.层 === 层 && x.类型 === 类型);
  if (!条目) throw new Error(`编成表里没有 ${层}-${类型}`);
  const 我 = (我方形 || G.默认五人队).map(u => Object.assign({}, u));
  const 敌 = G.编成到单位(条目);
  /* ★ 我方等级要一起带进 `做一场({我方})`，不然摘要里写的等级和真打的不一致
     （真游戏那条路 `界面.准备记录()` 传的就是这一份规格）。 */
  const 报 = G.simulate(我, 敌, 方针, 种子, { 波次: G.编成波次到单位(条目) });
  const 场 = G.战斗记录.做一场({
    战报: 报, 我方: 我, 敌方: G.敌方规格组(敌), 条目, 方针表: 方针,
    波次: G.编成波次(条目),           // ★ 真游戏那条路会传它（「敌方增援」那一行要靠它）
    现在: new Date('2026-10-12T15:04:05'),
  });
  return { 条目, 报, 场, 文: G.战斗记录.场文本(场) };
}
