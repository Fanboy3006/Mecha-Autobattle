/* ============================ [14] --out 写文件 ============================ */
console.log('\n[14] `--out` 写文件：UTF-8 无 BOM，内容与 stdout 一致');
{
  /* ★ 不用系统临时目录：沙箱给受限进程的临时目录不允许建子目录（`tests/balance.js` 踩过），
     所以放仓库内被 `.gitignore` 挡住的 `.tmp-*`。 */
  const 目录 = join(ROOT, '.tmp-分析-测试');
  const 甲文件 = join(目录, '甲.txt');
  const 出 = join(目录, '报告.md');
  try {
    rmSync(目录, { recursive: true, force: true });
    mkdirSync(目录, { recursive: true });
    writeFileSync(甲文件, 甲.文, 'utf8');
    const r = await 分析.main([甲文件, `--out=${出}`]);
    const 写到 = readFileSync(出, 'utf8');
    const 源 = readFileSync(出);   // 原始字节（查 BOM）
    if (写到 === r.文本) ok(`写出去的文件与 stdout 的报告**逐字相同**（${写到.length} 字符）`);
    else bad(`写出去的和 stdout 不一致（${写到.length} vs ${r.文本.length}）`);
    if (!(源[0] === 0xEF && 源[1] === 0xBB && 源[2] === 0xBF)) ok('文件**没有 BOM**（前 3 字节不是 EF BB BF）');
    else bad('文件带 BOM 了');
    if (r.码 === 0 && r.各场.length === 1) ok(`\`main()\` 返回 {码: 0, 各场: 1}（**不自己 exit**，测试能直接调）`);
    else bad(`main 的返回值不对：${JSON.stringify({ 码: r.码, 场: r.各场.length })}`);
    /* 读不到的文件：跳过 + 在报告里说一句，不崩 */
    const r2 = await 分析.main([join(目录, '根本没有这个文件.txt'), 甲文件]);
    if (r2.码 === 0 && /读不到这几个文件/.test(r2.文本) && r2.各场.length === 1) ok('文件读不到：跳过它、在报告里写明，其它文件照常分析（不崩、不静默）');
    else bad(`读不到文件那一路不对：码 ${r2.码} / 场 ${r2.各场.length}`);
  } catch (e) { bad('--out 写文件那一路崩了：' + e.message); }
  finally { try { rmSync(目录, { recursive: true, force: true }); } catch (e) { /* 不崩 */ } }
}

