/* ============================================================================
 * 机甲指挥 · 战报分析测试（`tools/战报分析.mjs` 的验收）
 * ----------------------------------------------------------------------------
 * 作者 2026-10-12：「另外我认为需要一个对话在理解规则的情况下检视我的游戏记录，然后尝试理解我的游戏思路」
 *   → 交付 = ① `tools/战报分析.mjs`（解析 + 算术，**绝不猜**）② `协作/战报分析-口径.md`（分析会话的规矩）。
 *
 * 这一段测的是**工具本身**（事实层）：它必须和引擎自己的账**对得上** —— 这是这个工具唯一的价值。
 *   [1] 从仓库里的记录真跑一场（`simulate` → `战斗记录.做一场` → `场文本`）当 fixture
 *   [2] 摘要字段与源战斗**逐项一致**（种子 / 层 / 节点类型 / 编成 / 结果 / 原因 / 回合数 / 条数 / 双方阵容）
 *   [3] 逐条数一致 + 每条的回合号一致 + 事件分类与引擎的 `类型` 对得上
 *   [4] ★ 硬指标与**引擎自己的** `战报统计()` 对账（我方 / 敌方 / 每回合输出 / 大招 / 镜甲）
 *   [5] ★ HP 重放**逐步**对账（我算的 HP == 引擎每条的 `目标剩余HP`）—— 重放是阵亡 / 异常①的根
 *   [6] 异常①：**人为构造**「攻击一个当时已经 0 HP 的目标」→ 必须抓到
 *   [7] 异常②：人为构造「连续打空同一台 / 每段命中率都很低还在打」→ 必须抓到
 *   [8] 异常③：机械化迹象（整场只下过一条方针 + 大招开关没动）→ 必须抓到
 *   [9] 异常④：Boss 蓄力声明的释放回合 vs 实际 → 不符必须抓到；对上了必须报 ✅
 *   [10] 缺字段 / 空文件 / 坏文件**不崩**，且照实写「记录里没有这一项」；`--no-game` 那条路
 *   [11] 多份文件 → 跨场对比表**行数对**（每份一行）
 *   [12] 同输入两遍 → 输出**逐字相同**
 *   [13] 「本局日志」宽松口径不崩（★ 那个导出格式还没定稿，另一条线在做）
 *   [14] `--out` 写文件：UTF-8 **无 BOM**，内容与 stdout 一致
 *   [15] 命令行：`--help` / 没给文件 / 文件读不到
 *
 * 用法：node tests/分析.js
 * ★ 本机沙箱不给子进程开管道（`spawnSync` 默认 `'pipe'` 会 EPERM，见 CLAUDE.md 第 4 节）：
 *   所以这里 **import 工具、直接调 `main()` / `分析文本()`**，不走子进程（和 `tests/balance.js` 一个做法）。
 * ========================================================================== */
