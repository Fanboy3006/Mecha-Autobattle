  if (穷.ok === false && /源碳不够/.test(穷.why)) ok(`源碳不够时刷不了：${穷.why}`);
  else bad(`源碳不够却刷了：${JSON.stringify(穷)}`);
  /* --- 卖零件：自然物按估价、其他一律 2 源碳（战棋 30:101,119） --- */
  const R2 = 开一局(20261081);
  R2.源碳 = 20;
  R2.零件 = [];
  G.拿零件('wheel', '测试');          // 加工品 → 2 源碳
  G.拿零件('bloodcap', '测试');       // 自然物 → 按估价
  const 碳0 = R2.源碳;
  const 估价血蕈 = (R2.零件.find(p => p.k === 'bloodcap') || {}).value;
  const 卖掉0 = 肉鸽.黑市卖零件(0);
  const 卖掉1 = 肉鸽.黑市卖零件(0);   // 卖掉第一件之后 bloodcap 变成 0 号
