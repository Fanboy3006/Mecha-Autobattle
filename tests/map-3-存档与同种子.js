  if (/data-act="黑市刷新"/.test(文) && /data-act="黑市卖:0"/.test(文)) {
    ok('黑市屏上「刷新库存」与「卖零件」两个动作都接上了（`data-act="黑市刷新"` / `data-act="黑市卖:<下标>"`）');
  } else bad('黑市屏上没有刷新 / 卖零件的按钮');
  /* 刷新次数是**存档字段**（`RUN.黑市刷新次数`）：这一段手上是 R2（刚卖过零件、还一次没刷），
     所以现场刷一次，再验它真的记在 RUN 上（值 = 1）。 */
  R2.源碳 = 50;
  const 刷一次 = 肉鸽.黑市刷新();
  if ('黑市刷新次数' in R2 && R2.黑市刷新次数 === 1 && 刷一次.ok) {
    ok(`刷新次数是存档字段：\`RUN.黑市刷新次数\` = ${R2.黑市刷新次数}（现场刷一次 → 1，价格 ${刷一次.价}）`);
  } else bad(`黑市刷新次数没进 RUN / 不对：${JSON.stringify({ v: R2.黑市刷新次数, 刷一次 })}`);
