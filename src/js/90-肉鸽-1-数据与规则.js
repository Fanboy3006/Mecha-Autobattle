  return `希望从哪来：起始 ${s.初始} ＋ 战斗 ${s.战斗} ＋ 节点 ${s.节点} ＋ ` +
    `升级 ${s.升级}（作者 2026-10-11 拍板：按原作分级表 +4…+8 逐级给，见参数表 \`每级希望表\`）` +
    ` ＋ 藏品 ${s.藏品} ＋ 藏品省下 ${s.藏品省} － 花掉 ${s.支出} ＝ 手上 ${R ? R.希望 : 0}`;
