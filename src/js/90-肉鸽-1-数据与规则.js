/** 加经验 + 升级（**逐字照抄**战棋 `27-开局.js:104-111` 的 `gainExp(x, src)`）：
 *  `RUN.经验 += x` → 经验够了就 `RUN.等级++` 并且 `RUN.希望 += HOPE_PER_LV`（**可能连升好几级**）。
 *  `来源` 只进日志（战棋也是 `runLog(`${src}：经验 +${x}`)`）。返回 `{等级, 升了}` 或 `null`。 */
function 加经验(R, x, 来源) {
  if (!R) return null;
  /* 兜底：老存档 / 测试里手搭的 RUN 可能没有这两个字段（或值是坏值）—— 补成战棋的初值，
     不然下面的 while 会在 NaN 上打转。 */
  if (!Number.isFinite(Number(R.等级)) || Number(R.等级) < 1) R.等级 = 1;
  if (!Number.isFinite(Number(R.经验)) || Number(R.经验) < 0) R.经验 = 0;
  R.经验 = (R.经验 || 0) + x;
  肉鸽.记(`${来源 || '作战'}：经验 +${x}（部队 Lv${R.等级} ${R.经验} / ${升级门槛(R.等级) ?? '—'}）`);
  let 升了 = 0;
  while (升级门槛(R.等级) != null && R.经验 >= 升级门槛(R.等级)) {
    R.等级 += 1;
    /* ★ 作者 2026-10-11 拍板「C：照原作 4–8」→ **按升到的那一级查表**给希望（连升就逐级给）。 */
    const 这一点 = 升到这一级给多少希望(R.等级);
    R.希望 = (Number(R.希望) || 0) + 这一点;
    记希望来源(R, '升级', 这一点);                  // 只记账，不加数值
    升了++;
    肉鸽.记(`部队升到 Lv${R.等级}：希望 +${这一点}`);
  }
  return 升了 ? { 等级: R.等级, 升了 } : null;
}

