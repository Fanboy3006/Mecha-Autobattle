const 希望来源空 = () => ({ 初始: 0, 战斗: 0, 节点: 0, 升级: 0, 藏品: 0, 藏品省: 0, 支出: 0 });

/** 记一笔希望账（来源：'初始' / '战斗' / '节点' / '升级' / '藏品' / '藏品省' / '支出'）。 */
function 记希望来源(R, 来源, 数) {
  if (!R || !数) return;
  R.希望来源 = R.希望来源 || 希望来源空();
  R.希望来源[来源] = (Number(R.希望来源[来源]) || 0) + 数;
}

