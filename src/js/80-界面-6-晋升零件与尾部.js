/** 解析「键或单位」入参 → `{ 方, 键, 单位, 模板 }`；认不出来返回 `null`（**绝不抛**）。
 *  认这几种写法：`'B1'` / `'CB1'`（我方键）、`'grunt'`（敌方键，`ENEMY_T` 里的都行）、
 *  `'ally_0'` / `'enemy_2'`（战斗内的目标，位号 = `u.slot`）、单位对象 `u`、
 *  编队条目 `{键:'B1'}` / `{mech:'B1'}`。 */
function 机体详情解析(参, ctx) {
  try {
    const 是我方 = k => (typeof tplOf === 'function') && !!tplOf(k);
    const 是敌方 = k => (typeof ENEMY_T !== 'undefined') && !!ENEMY_T[k];
    if (参 && typeof 参 === 'object') {
      const 键 = 参.key || 参.键 || 参.mech;
      if (!键) return null;
      const 方 = 参.side || (是我方(键) ? 'ally' : 'enemy');
      return { 方, 键, 单位: (参.maxHp != null || 参.hp != null || 参.weapons) ? 参 : null,
        模板: 方 === 'ally' ? tplOf(键) : ENEMY_T[键] };
    }
    const s = String(参 == null ? '' : 参).trim();
    if (!s) return null;
    const m = /^(ally|enemy)_(\d+)$/.exec(s);
    if (m) {
      const 方 = m[1], 位 = Number(m[2]);
      const 列 = ctx ? (方 === 'ally' ? ctx.allies : ctx.enemies) : null;
      const u = (列 || []).find(x => x && Number(x.slot) === 位) || null;
      if (!u || !u.key) return null;
      const 方2 = u.side || 方;
      return { 方: 方2, 键: u.key, 单位: u, 模板: 方2 === 'ally' ? tplOf(u.key) : ENEMY_T[u.key] };
    }
    if (是我方(s)) return { 方: 'ally', 键: s, 单位: null, 模板: tplOf(s) };
    if (是敌方(s)) return { 方: 'enemy', 键: s, 单位: null, 模板: ENEMY_T[s] };
    return null;
  } catch (e) { return null; }
}

/** 一台机体的 8 个数字（HP / 装甲 / 防御 / 机动 / 精准 / 速度 / 格斗 / 射击）。
 *  走 `makeUnit()`（**和战斗里同一套规则**），所以晋升 / 等级成长一个都不会算错。 */
function 机体数字(键, 方, lv) {
  try {
    const u = makeUnit(键, 方, 0, lv);
    return { HP: u.maxHp, 装甲: u.armor, 防御: u.defense, 机动: u.mov, 精准: u.aim, 速度: speedOf(u), 格斗: u.melee, 射击: u.shoot };
  } catch (e) { return null; }
}

