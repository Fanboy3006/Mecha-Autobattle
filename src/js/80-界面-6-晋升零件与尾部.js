/** ④ 完整武器与大招表：名称 / 射程类型 / 威力（当前 + Lv10/20/30 成长）/ 命中 / 暴击修正 /
 *  段数 / 冷却 / **解锁等级（含当前是否已解锁）** / 特殊词条 / 说明。 */
function 武器详情行(w, 当前等级) {
  if (!w) return '';
  const 取 = (lv, k) => { try { return wv({ lv }, w, k); } catch (e) { return w[k]; } };
  const 类 = rangeKindOf(w) || (w.fire === 'passive' ? '被动' : (w.fire === 'device' ? '装置' : '—'));
  const 射程 = r => (Array.isArray(r) ? (r[0] === r[1] ? `${r[0]}` : `${r[0]}–${r[1] === Infinity ? '∞' : r[1]}`) : (r == null ? '—' : `${r}`));
  const 解锁 = Number(w.unlock || 1);
  const 已解锁 = Number(当前等级) >= 解锁;
  const 成长列 = [10, 20, 30].map(lv => 取(lv, 'power'));
  const 当前威力 = 取(当前等级, 'power');
  const 有成长 = new Set(成长列.map(v => String(v))).size > 1;
  const 威力 = `${当前威力 == null ? '—' : 当前威力}` +
    (有成长 || String(当前威力) !== String(成长列[0]) ? `（Lv10 ${成长列[0]} / Lv20 ${成长列[1]} / Lv30 ${成长列[2]}）` : '');
  const 命中 = 取(当前等级, 'hit');
  const 暴击 = 取(当前等级, 'critMod');
  const 段 = Number(取(当前等级, 'hits') || w.hits || 1);
  const cd = Number(w.cd || 0), 开场Cd = (typeof startCdOf === 'function') ? Number(startCdOf(w) || 0) : 0;
  const 词条 = [];
  if (段 > 1) 词条.push(`连射 ${段} 段${w.step != null ? `（步进 ${w.step}）` : ''}`);
  if (w.ignoreDef) 词条.push('无视装甲 / 防御（一切减免）');
  if (w.noCounter) 词条.push('目标不能反击');
  if (w.noEvade) 词条.push('必中');
  if (w.afterMove === false) 词条.push('移动后不能使用');
  if (w.dmgType) 词条.push(`伤害类型 ${详情转义(w.dmgType)}`);
  if (w.special) 词条.push(`词条 ${详情转义(w.special)}`);
  if (w.bounce) 词条.push(`弹跳 ${w.bounce} 次`);
  if (w.summonN) 词条.push(`召唤 ${w.summonN} 个（持续 ${w.summonLife || '—'} 回合）`);
  if (w.buff) 词条.push('增益：' + Object.entries(w.buff).map(([k, v]) => 藏品值文字(k === 'def' ? '防御' : k === 'critX' ? '暴击倍率' : k, v)).join('、'));
  if (w.grant) 词条.push(`再动：${详情转义(w.grant)}`);
  if (w.shape) 词条.push(`范围形状 ${详情转义(w.shape)}`);
  if (w.healPct) 词条.push(`回复上限 ${w.healPct}%`);
  if (w.uses != null) 词条.push(`整场 ${w.uses} 次`);
  const 升 = (w.upgrades || []).map(up => `Lv${up.lv}${up.note ? `：${详情转义(up.note)}` : '（数值升级档）'}`).join('　·　');
  return `<div class="rv-row mech-weapon" data-武器="${详情转义(w.name)}">
    <span class="nm"><b>${详情转义(w.name)}</b>
      <small> · ${详情转义(类)} · 射程 ${射程(取(当前等级, 'range'))}${w.stat ? ` · 按 ${详情转义(w.stat)}` : ''}</small>
      <br><small style="margin-left:0">威力 <b>${威力}</b>　命中 <b>${命中 == null ? '—' : 命中}</b>
        　暴击修正 <b>${暴击 == null ? '0' : (Number(暴击) > 0 ? '+' : '') + 暴击}</b>　段数 <b>${段}</b>
        　冷却 <b>${cd}</b>${开场Cd ? `（开场冷却 ${开场Cd} 回合）` : ''}</small>
      <br><small style="margin-left:0"><b class="${已解锁 ? 'mech-ok' : 'mech-lock'}">解锁等级 ${解锁 > 1 ? `Lv${解锁}${解锁 >= 20 ? '（大招 / 强武器）' : ''}：${已解锁 ? '✓ 已解锁' : '✗ 还没解锁'}` : 'Lv1：一开始就能用（不用解锁）'}</b>${词条.length ? `　·　${词条.join('　·　')}` : ''}</small>
      ${w.desc ? `<br><small style="margin-left:0">${详情转义(w.desc)}</small>` : ''}
      ${升 ? `<br><small style="margin-left:0">升级档：${升}</small>` : ''}</span></div>`;
}
