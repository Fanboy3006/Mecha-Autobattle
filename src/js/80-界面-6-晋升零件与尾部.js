/** 这一件藏品的数值文字（**当前叠加**：`stack` / `foeStack` 按出击职业人数现算层数）。
 *  `出击职业` 不给 → 用本局出击名单（`RUN.出击阵` → `RUN.出击` → 名册）里的职业；再没有就空数组（层数 0）。 */
function 藏品数值文字(id, 出击职业) {
  const 件 = (typeof 藏品表 !== 'undefined' && 藏品表[id]) || null;
  if (!件) return '（数据里没有这一件）';
  const e = 件.数值 || {};
  const 段 = [];
  if (e.mods) for (const [k, v] of Object.entries(e.mods)) 段.push(藏品值文字(k, v));
  if (e.stat) for (const [k, v] of Object.entries(e.stat)) 段.push(藏品值文字(k, v));
  const 层 = (typeof 藏品层数 === 'function') ? 藏品层数(件, 出击职业 || []) : 0;
  if (e.stack) 段.push(`按出击职业叠层：现在 ×${层}` +
    `（每层 ${Object.entries(e.stack.per).map(([k, v]) => 藏品值文字(k, v)).join('、')}，最多 ${e.stack.max} 层）`);
  if (e.foeStack) 段.push(`敌方按出击职业叠层：现在 ×${层}` +
    `（每层 ${Object.entries(e.foeStack.per).map(([k, v]) => 藏品值文字(k, v)).join('、')}，最多 ${e.foeStack.max} 层）`);
  if (e.foe) for (const [k, v] of Object.entries(e.foe)) 段.push(`敌方 ${藏品值文字(k, v)}`);
  if (e.出击上限) 段.push(`出击上限 ${Number(e.出击上限) > 0 ? '+' : ''}${e.出击上限} 台`);
  if (e.每层希望) 段.push(`每进一层希望 +${e.每层希望}`);
  if (e.希望) 段.push(`希望 +${e.希望}`);
  if (e.晋升职业) 段.push(`免费晋升：${[].concat(e.晋升职业).join(' / ')}`);
  if (e.特殊) 段.push(`特殊：${e.特殊}`);
  return 段.length ? 段.join('　·　') : '（这一件是纯编制 / 规则类，没有数值）';
}

