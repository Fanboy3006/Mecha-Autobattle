/** ★ **机体详情** 的正文（模块 5）：四大板块一次看全。
 *  `参` = 机体键 / 战斗内目标（`ally_0` / `enemy_2`）/ 单位对象；`选项.ctx` = 战斗局面（找目标用），
 *  `选项.等级` = 强制指定当前等级。**纯读**：只调 `makeUnit()` 现算数字，不碰任何状态。 */
function 机体详情Html(参, 选项) {
  选项 = 选项 || {};
  const 解析 = 机体详情解析(参, 选项.ctx);
  if (!解析) {
    return `<div class="mech-detail" data-mech-detail="1"><p class="small" data-mech-unknown="1">
      认不出这个机体：<b>${详情转义(参)}</b>。<br>可以传机体键（<code>B1</code> / <code>CB1</code> / 敌方键如 <code>grunt</code>）、
      战斗内目标（<code>ally_0</code> / <code>enemy_2</code>，数字 = 位号），或者直接传单位对象。</p></div>`;
  }
  const 键 = 解析.键;
  /* 当前等级：显式指定 > 传进来的单位 > 本局名册里那一台 > 我方招募等级 / 敌方默认等级 */
  let 当前等级 = Number(选项.等级) || (解析.单位 && Number(解析.单位.lv)) || 0;
  if (!当前等级) {
    try {
      const R = (typeof 肉鸽 !== 'undefined' && 肉鸽 && 肉鸽.RUN) || null;
      const m = R && (R.队伍 || []).find(x => x && x.键 === 键);
      if (m && m.等级) 当前等级 = Number(m.等级);
    } catch (e) {}
  }
  if (!当前等级) {
    当前等级 = 解析.方 === 'ally'
      ? ((typeof 肉鸽数值 !== 'undefined' && 肉鸽数值.招募等级) || 10)
      : ((typeof 默认等级 === 'function' ? (默认等级(键, 'enemy') || 10) : 10));
  }
  return `<div class="mech-detail" data-mech-detail="1" data-mech-key="${详情转义(键)}" data-mech-side="${解析.方}">
    ${机体六维Html(解析, 当前等级)}
    ${机体特技Html(解析)}
    ${机体双态Html(解析)}
    ${机体武器Html(解析, 当前等级)}
  </div>`;
}

