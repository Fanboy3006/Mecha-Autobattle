/** 天人的参数（`71-改动.js` 的 `势力特色.天人`）。 */
const 天人参数 = () => 势力参数('天人');
/** 这台机体的模板上有没有这个特技（战棋 `abilOn(u,'transAm')`，`03:140`）——**不手写名单**：
 *  刹那 CB1 / 洛克昂 CB2 / 阿雷路亚 CB3 / 提耶利亚 CB4 有，**拉塞 CB5 没有**（照战棋 C8）。 */
const 有TRANSAM = (u, p) => !!(u && Array.isArray(u.abilities) && u.abilities.includes(((p || 天人参数()).特技) || 'transAm'));
/** 现在正处在 TRANS-AM 中吗（读缓存；战棋 `taActive(u)`，`17b:128`）。 */
const 天人激活 = u => !!(u && u.势力状态 && u.势力状态.天人 && u.势力状态.天人.激活);
/** 现在在冷却里吗（读缓存；战棋 `taOn(u) && turn < taReadyTurn(u)` 那一段，`17b:143`）。 */
const 天人冷却中 = u => !!(u && u.势力状态 && u.势力状态.天人 && u.势力状态.天人.冷却中);
/** 这台机体的开关是「手动」吗（★ 作者 2026-10-11 拍板：**单位级开关**）。
 *  值来自**单位开关表**（`设单位开关()` 读进 `u.TRANSAM手动`）；**没写 / 读不到 = 自动**（与改之前逐字一致）。 */
const 天人手动 = u => !!(u && u.TRANSAM手动);
/** 状态机现在记到第几回合（`已推进回合`；界面在指令阶段读它来算「CD 到没到」）。 */
const 天人现在回合 = u => {
  const 状 = (u && u.势力状态 && u.势力状态.天人) || null;
  return (状 && 状.已推进回合 != null) ? 状.已推进回合 : 1;
};

/** **这台机体现在能不能「手动点开」TRANS-AM**（指令面板那个按钮的 `disabled` 与「为什么」都读它）。
 *  返回 `{ 可以, 原因, 现在 }`：`可以: false` 时 `原因` 就是写在按钮上 / 卡片上的那句话。 */
function 天人手动可开(u, p) {
  const 参 = p || 天人参数();
  if (!有TRANSAM(u, 参)) return { 可以: false, 原因: '这台没有 TRANS-AM（照战棋：拉塞不能开）' };
  if (u.lv < (参.解锁等级 || 0)) return { 可以: false, 原因: `Lv${参.解锁等级} 才解锁，现在 Lv${u.lv}` };
  const 状 = 势力状态(u, '天人');
  const 现在 = 天人现在回合(u);
  if (状.激活) return { 可以: false, 原因: `TRANS-AM 进行中，还剩 ${状.剩余回合} 回合`, 现在 };
  if (现在 < (状.冷却到回合 || 0)) {
    return { 可以: false, 原因: `冷却中：第 ${状.冷却到回合} 回合才可以再开，现在是第 ${现在} 回合`, 现在 };
  }
  return { 可以: true, 原因: `第 ${现在} 回合可以开`, 现在 };
}

/** **真的开启一台的 TRANS-AM**（自动那一支与手动那一支**共用这一段**，所以记录 / 字段 / 冷却算法逐字相同）。
 *  `回合` = 开启的回合；`额外` = 手动点开时多带的记录字段（自动那一支传 `undefined` → 记录与改之前逐字一致）。 */
function 开启天人(ctx, u, 回合, 状, 参, 额外) {
  状.启动回合 = 回合;
  状.结束回合 = 回合 + 参.持续回合;                    // 战棋 `u.taEnd = turn + TA_LEN`（17b:134）
  状.冷却到回合 = 状.结束回合 + 参.冷却回合 - 1;         // ★ 作者 2026-10-11 拍板：开 1/5/9
  //   （战棋是 `taReadyTurn = taEnd + TA_CD`，17b:130；作者选的是「结束回合 + 冷却回合 − 1」）
  状.开启次数 = (状.开启次数 || 0) + 1;
  状.激活 = true; 状.冷却中 = false; 状.结束已记 = null;
  状.剩余回合 = Math.max(0, 状.结束回合 - 回合);
  状.冷却剩余 = 0;
  /* 文案：自动那一支**一个字都不多**（`标记` = 空串 → 与改之前逐字一致）；
     手动点开的那一条写「（手动开启）」并把 `开启方式: '手动'` 写进字段。 */
  const 标记 = 额外 && 额外.开启方式 === '手动' ? '（手动开启）' : '';
  势力记录(ctx, `天人 ${u.name} 的 TRANS-AM 启动${标记}！第 ${回合}–${状.结束回合 - 1} 回合：`
    + `所有武器威力 ×${参.威力倍率}、闪避 +${参.闪避加成}（持续 ${参.持续回合} 回合）；`
    + `之后冷却 ${参.冷却回合} 回合，第 ${状.冷却到回合} 回合可以再启动`,
    Object.assign({
      势力: '天人', 特色: 'TRANS-AM', 结果: '启动', 单位: u.key, 单位方: u.side, 单位位: u.slot,
      启动回合: 回合, 结束回合: 状.结束回合, 冷却到回合: 状.冷却到回合,
      持续回合: 参.持续回合, 冷却回合: 参.冷却回合,
      威力倍率: 参.威力倍率, 闪避加成: 参.闪避加成, 第几次: 状.开启次数,
    }, 额外 || {}));
}

/** 把 TRANS-AM 的状态机推到**第 `回合` 回合**（开局 / 回合开始 / 回合结束三处调，幂等）。
 *  ★ **只推「自动」那一档**：`手动` 的机体推到「到点」也不开（等 `手动开天人()` 那一支）。
 *  返回这一回合**自动启动了几台**（0 = 没有新的启动）。 */
function 推进天人(ctx, 回合, p) {
  if (!ctx) return 0;
  const 参 = p || 天人参数();
  let 启动数 = 0;
  for (const u of 势力在场('天人', ctx)) {
    if (!有TRANSAM(u, 参)) continue;                    // 拉塞没有这个能力 → 一次都不进状态机
    const 状 = 势力状态(u, '天人');
    if (状.已推进回合 === 回合) continue;                // 同一回合只推一次（三处调同一个函数）
    状.已推进回合 = 回合;
    if (u.lv < (参.解锁等级 || 0)) {                     // 战棋的等级门（ABIL.transAm.lv = 10，03:14 / 03:140）
      状.激活 = false; 状.冷却中 = false; 状.剩余回合 = 0; 状.冷却剩余 = 0;
      continue;
    }
    const 启动 = 状.启动回合 || 0, 结束 = 状.结束回合 || 0, 冷却到 = 状.冷却到回合 || 0;

    /* ① 刚刚结束（战棋 `taAfter`：`turn === taEnd`）→ 写一条「关」记录，每次启动只写一条。
       这一条同时把「冷却中」写清楚（作者要记录里能看出「开 / 关 / 冷却中」）。 */
    if (启动 && 回合 >= 结束 && 状.结束已记 !== 启动) {
      状.结束已记 = 启动;
      势力记录(ctx, `天人 ${u.name} 的 TRANS-AM 结束（第 ${启动}–${结束 - 1} 回合生效，持续 ${参.持续回合} 回合）`
        + `→ 冷却中：冷却 ${参.冷却回合} 回合，第 ${冷却到} 回合可以再启动`,
        {
          势力: '天人', 特色: 'TRANS-AM', 结果: '结束', 单位: u.key, 单位方: u.side, 单位位: u.slot,
          启动回合: 启动, 结束回合: 结束, 冷却到回合: 冷却到, 持续回合: 参.持续回合, 冷却回合: 参.冷却回合,
        });
    }

    if (启动 && 回合 < 结束) {
      /* ② 还在 TRANS-AM 中（战棋 `turn < taEnd`） */
      状.激活 = true; 状.冷却中 = false;
    } else if (启动 && 回合 < 冷却到) {
      /* ③ 冷却中（战棋 `taOn && turn < taReadyTurn`）—— 记录不写（每回合都写会刷屏），卡行上看得见 */
      状.激活 = false; 状.冷却中 = true;
    } else if (天人手动(u)) {
      /* ④ ★ **手动档：到点也「不自动开」**（作者 2026-10-11 拍板「单个单位开关」）——
         状态摆成「待机、CD 已到」，等玩家在指令阶段点「开 TRANS-AM」（`手动开天人()`）；
         记录不写（卡行上写着「CD 已到，点「开 TRANS-AM」在本回合开启」）。 */
      状.激活 = false; 状.冷却中 = false;
    } else {
      /* ⑤ 到点 → **自动启动**（默认档 = 改之前的行为；战棋那一步是玩家点 `taButton`，`17b:144`） */
      开启天人(ctx, u, 回合, 状, 参);
      启动数++;
    }
    状.剩余回合 = 状.激活 ? Math.max(0, 状.结束回合 - 回合) : 0;
    状.冷却剩余 = 状.冷却中 ? Math.max(0, 状.冷却到回合 - 回合) : 0;
  }
  return 启动数;
}

/** ★ **2026-10-11 新加的入口**（作者拍板「单个单位开关」）：**手动档**的机体由玩家在本回合点开的落点。
 *  触发时机：`势力开局` + `势力回合开始`（和自动那一支同一个时机）—— 这时 `设单位开关()` 已经把
 *  单位开关表里的「开关」与「本回合点没点开」读进单位（`u.TRANSAM手动` / `u.本回合开TRANSAM`）。
 *  判据（缺一不可）：① 这台是**手动**档；② 这一回合点了「开」；③ 有 `transAm` 能力、等级够；
 *  ④ **不在 TRANS-AM 中**且 **CD 已到**（`现在 >= 冷却到回合`）—— CD 没到点了也**无效**（界面那个按钮是 disabled）。
 *  **点一次只管本回合**：读掉就把 `u.本回合开TRANSAM` 清掉（界面侧开打后也会清开关表里那一位）。
 *  返回这一回合**手动开启了几台**。 */
function 手动开天人(ctx, 回合, p) {
  if (!ctx) return 0;
  const 参 = p || 天人参数();
  let 开数 = 0;
  for (const u of 势力在场('天人', ctx)) {
    if (!u.本回合开TRANSAM) continue;
    u.本回合开TRANSAM = false;                          // 点一次只管本回合
    if (!天人手动(u)) continue;                          // 没切到「手动」→ 这次点击不算数
    if (!有TRANSAM(u, 参)) continue;                     // 拉塞没有这个能力
    const 状 = 势力状态(u, '天人');
    /* ★ 这里**不动 `已推进回合`**（那是 `推进天人()` 的账）：正常流程里两者本来就同一回合
       （`势力回合开始()` 先推进、再手动开），把这个时钟往回拨反而会打乱幂等。 */
    if (u.lv < (参.解锁等级 || 0)) continue;             // 等级门（战棋 03:14 / 03:140）
    if (状.激活) continue;                                // 已经在 TRANS-AM 中
    if (回合 < (状.冷却到回合 || 0)) continue;             // ★ CD 没到 → 点不开
    开启天人(ctx, u, 回合, 状, 参, { 开启方式: '手动' });
    开数++;
  }
  return 开数;
}

