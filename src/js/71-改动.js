/** 敌方阵容 → 这一场的回合上限（杠杆 ④；见 `难度调整.回合上限` 的注释）。
 *  接受**单位数组**（`makeUnit()` 造的，认 `.key`）或**规格数组**（`{键, 位, 等级}`，认 `.键`）。 */
function 回合上限(敌方们) {
  const 表 = 难度调整.回合上限;
  const 序 = ['杂兵', '精锐', '头目', 'Boss'];
  let 最高 = 0;
  for (const u of (敌方们 || [])) {
    const 键 = u && (u.key || u.键 || u.mech);
    if (!键) continue;
    const i = 序.indexOf(tierOfEnemy(键));
    if (i > 最高) 最高 = i;
  }
  const 名 = 序[最高];
  return (表 && 表[名] != null) ? 表[名] : (表 && 表.默认) || 12;
}

/** 把一组合计值按**同类上限**夹一次（杠杆 ①；正负都往 0 的方向夹）。
 *  `上限表` = `{键: 幅度}`；没有列进去的键**原样通过**（不受影响）。 */
function 藏品合计封顶(合计, 上限表) {
  const 出 = {};
  for (const [k, v] of Object.entries(合计 || {})) {
    const 限 = 上限表 ? 上限表[k] : null;
    const 有上限 = typeof 限 === 'number' && Number.isFinite(限) && 限 > 0;
    出[k] = 有上限 ? Math.max(-限, Math.min(限, v)) : v;
  }
  return 出;
}

/** 敌方强度倍率：`层 + 梯队` → 一个 `≥ 1` 的倍率（纯函数，没有随机数）。
 *  · `倍率 = clamp(1 + (层基础强度[层] − 1) × 档位权重[梯队], 1, 上限)`；
 *  · **第 1 层 / 层基础强度 = 1 → 倍率 = 1**（`是否强化: false`，那一层完全不变）。
 *  ★ 层号从哪来：`70-编成.js` 的 `编成到单位()` / `编成波次到单位()` 都拿着编成条目的 `层`，
 *    在那里把倍率写进敌方规格（`强化` 字段），一路传到 `makeUnit()`（见 `40-单位.js`）。 */
function 敌方强度倍率(层, 梯队) {
  const c = 难度调整.敌方强度;
  const l = Number(层);
  const 层基础 = (c.层 && c.层[l] != null) ? c.层[l] : 1;
  const 权重 = (c.档位权重 && c.档位权重[梯队] != null) ? c.档位权重[梯队] : 1;
  const 倍率 = Math.min(c.上限, Math.max(1, 1 + (层基础 - 1) * 权重));
  return { 倍率, 是否强化: 倍率 > 1.0001, 层基础, 权重, 梯队: 梯队 || '杂兵', 层: Number.isFinite(l) ? l : null };
}

/** 把倍率**落到一台敌方单位身上**（`40-单位.js` 的 `makeUnit()` 在升级之后调一次）。
 *  缩放的是**这台单位自己的武器副本**（`entry.t`）与 装甲 / 防御 / 精准 / HP，
 *  **模板（`ENEMY_T`）一个字节都不动**；我方（`side !== 'enemy'`）**永远不会调到这里**。 */
function 应用敌方强化(u, 倍率, 详情) {
  const c = 难度调整.敌方强度;
  const f = c.分项 || {};
  const 系数 = k => 1 + (倍率 - 1) * (f[k] != null ? f[k] : 1);
  const 威力倍 = 系数('威力'), 精准倍 = 系数('精准');
  u.weapons = (u.weapons || []).map(e => {
    const t = Object.assign({}, e.t);
    const 这把 = (t.dmgType === '特殊' || t.ignoreDef) ? c.特殊威力系数 : 1;
    const 乘 = p => Math.max(1, Math.round(p * (1 + (威力倍 - 1) * 这把)));
    if (t.power > 0) t.power = 乘(t.power);
    if (Array.isArray(t.upgrades)) t.upgrades = t.upgrades.map(up => (up.power > 0 ? Object.assign({}, up, { power: 乘(up.power) }) : up));
    return Object.assign({}, e, { t });
  });
  u.armor = Math.round(u.armor * 系数('装甲'));
  u.defense = Math.round((u.defense || 0) * 系数('防御'));
  u.aim = Math.round((u.aim != null ? u.aim : 160) * 精准倍);
  u.maxHp = Math.max(1, Math.round(u.maxHp * 系数('HP')));
  u.hp = u.maxHp;
  u.敌方强度 = Object.assign({ 倍率: +倍率.toFixed(3) }, 详情 || {});
  return u;
}

