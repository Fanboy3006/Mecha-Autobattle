/** 晋升要花多少希望（`22-输入.js:446`；后两项在战棋里恒为 0，见文件头）。
 *  返回值最小 0（战棋的 `Math.max(0, …)` 也照抄）。 */
function 晋升要多少(键, 到, R) {
  const r = R || (肉鸽 && 肉鸽.RUN);
  const 档 = tierOf(键) || 'B';
  const 表 = 晋升价格[档] || 晋升价格.B;
  const 基 = 到 === 20 ? 表.p20 : 表.p30;
  return Math.max(0, 基 - ((r && r.下次晋升减价) ? 1 : 0));
}

/** 一台机体**晋升前后的关键数字**（界面显示 / 测试对账用）。
 *  ★ 数字全部来自 `makeUnit()`（= `levelUp()` 的真实结果），不是这里自己算的。 */
function 晋升预览(键, 等级) {
  const 前 = makeUnit(键, 'ally', 0, 等级);
  const 到 = 晋升目标(等级);
  const 后 = 到 ? makeUnit(键, 'ally', 0, 到) : 前;
  const 取 = u => ({
    lv: u.lv, maxHp: u.maxHp, armor: u.armor, defense: u.defense, eva: u.eva, aim: u.aim,
    melee: u.melee, shoot: u.shoot, awaken: u.awaken, mov: u.mov, 速度: speedOf(u),
  });
  return { 键, 前: 取(前), 后: 取(后), 到 };
}

