    R.推进剂 -= d;                                   // 30:20：消耗 = 走过的格数
    if (d > 1) this.记(`跳过中间格，直接前往（−${d} 推进剂）`);   // 30:21
    R.当前 = k;
    if (!R.已走过.includes(k)) R.已走过.push(k);
    const 格 = R.地图.格[k];
