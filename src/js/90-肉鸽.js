/** 这张券能不能用来**招募 / 晋升**这台机体 —— **逐字照战棋 `22-输入.js:436` 的 `ticketOk`**
 *  （职业券看 `tags.战斗分类`、势力券看 `tags.势力`）。
 *  `券.档` 默认 `null` → 这一项**恒真**（券不分档，§7）；留着这个口子只为了以后真要按档切时改一行。
 *  认不出来的券（`null` / 没有 `名` / 名不在 `CLASSES ∪ FACTIONS`）→ **一律 false**，不会抛。 */
function 券合(券, 键) {
  if (!券 || !键) return false;
  const t = tplOf(键);
  if (!t || !t.tags) return false;
  const 名 = 券.名;
  if (!名) return false;
  const 类 = (券.类 === '职业' || 券.类 === '势力') ? 券.类
    : (CLASSES.includes(名) ? '职业' : (FACTIONS.includes(名) ? '势力' : null));
  if (!类) return false;
  const 本类 = 类 === '职业' ? t.tags.战斗分类 === 名 : t.tags.势力 === 名;
  const 本档 = !券.档 || 券.档 === tierOf(键);          // 档 = null（我们的口径）→ 恒 true
  return 本类 && 本档;
}

