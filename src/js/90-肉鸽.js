/** **升到这一级**给几点希望（作者 2026-10-11 拍板「C：照原作 4–8」→ 按等级查表）。
 *  `肉鸽数值.每级希望表` 逐字照抄原作：Lv2 +4 / Lv3 +4 / Lv4 +5 / Lv5 +6 / Lv6 +6 / Lv7 +6 /
 *  Lv8 +7 / Lv9 +8 / Lv10 +8；**等级 > 10 沿用最后一档 +8**（口径写在参数表那段注释里）。 */
function 升到这一级给多少希望(等级) {
  const lv = Math.floor(Number(等级) || 0);
  if (lv <= 1) return 0;                                  // Lv1 不在表里（起始等级，实际到不了）
  const 表 = 肉鸽数值.每级希望表 || {};
  if (表[lv] != null) return Number(表[lv]) || 0;
  return lv > 10 ? (Number(肉鸽数值.每级希望封顶) || 0) : 0;
}

/** 从 `从` 级**连升到** `到` 级一共给几点希望（**逐级给**：对 Lv(从+1) … Lv到 逐个查表求和）。
 *  `加经验()` 的 while 循环就是这个口径；测试拿它当期望值（`tests/grid.js` / `tests/relic.js`）。 */
function 升级累计希望(从, 到) {
  const a = Math.floor(Number(从) || 0), b = Math.floor(Number(到) || 0);
  let n = 0;
  for (let lv = a + 1; lv <= b; lv++) n += 升到这一级给多少希望(lv);
  return n;
}

