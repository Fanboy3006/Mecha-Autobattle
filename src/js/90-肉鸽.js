/* ---------------------------------------------------------------------------
 * 事件选项的两个小工具（★ 2026-10-12 作者点名改「迷路的机师」时加的，就这两处）
 * ---------------------------------------------------------------------------
 * `源碳数`：把手上的源碳结晶读成一个**安全的数** —— 源碳是字符串（`'4'`）也认，
 *   `NaN` / `{}` / `null` / 负数 / 没有 RUN 一律当 0（**不崩**，判据就按 0 走）。
 * `事件选项做不了`：选项**现在能不能点** —— `null` = 能点；否则返回一句**给玩家看的理由**。
 *   选项可以写 `做不了(R)`（**可选字段**，返回理由或 `null`）；没写这个字段的选项一律能点
 *   （所以老的 7 条事件、以及「黑箱」那种「钱不够返回 `null`」的写法**一个字都不用改**）。
 *   界面（`92-肉鸽界面.js`）与引擎（`奇遇()`）都只调这一个口子 —— 两层理由永远同一句话。 */
function 源碳数(R) {
  const n = Number(R && R.源碳);
  return Number.isFinite(n) ? Math.max(0, Math.floor(n)) : 0;
}
function 事件选项做不了(o, R) {
  if (!o || typeof o.做不了 !== 'function') return null;
  const why = o.做不了(R);
  return why ? String(why) : null;
}

