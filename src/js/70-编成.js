/** 从对应层 / 类型的候选里随机抽一条；**这一档没有编成就返回 null**（兜底见 `抽编成兜底`）。 */
function 抽编成(层, 类型, rng) {
  const 候选 = 选编成(层, 类型);
  if (!候选.length) return null;
  const r = rng || Math.random;
  return 候选[Math.min(候选.length - 1, Math.floor(r() * 候选.length))];
}

/* ---------------- 兜底：抽不到编成时**绝不静默退回大地图** ----------------
 * M4 出过一次这种 bug（打完终点 Boss 不通关那阵子）：某层某类型没编成 →
 * `抽当前编成()` 返回 null → 界面把提示写一行就退回大地图，玩家看着像「点了没反应」。
 * 现在 `抽编成兜底()` 按下面的顺序退，**每退一步都调 `记(一行中文)`**（界面传 `肉鸽.记`，
 * 于是这一行进 `RUN.日志`）。正常情况（表里 13 个组合都齐）第 ① 步就命中，一行日志都不会写。
 *   ① 本层 + 本类型
 *   ② 本层「普通」（作者点名的那个例子：退回同层的普通）
 *   ③ 本层别的类型（顺序 普通 → 精英 → 守军 → 侵蚀源 → Boss）
 *   ④ 别的层的同类型（层号离得近的先试）
 *   ⑤ 全表第一条（表非空就一定抽得到）
 * 返回 `{条目, 层, 类型, 兜底}`：`兜底` = null 表示没走兜底，否则是「为什么退」的一句原因。 */
const 兜底类型顺序 = ['普通', '精英', '守军', '侵蚀源', 'Boss'];
function 抽编成兜底(层, 类型, rng, 记) {
  const r = rng || Math.random;
  const 抽一条 = (l, t) => {
    const 候选 = 选编成(l, t);
    return 候选.length ? 候选[Math.min(候选.length - 1, Math.floor(r() * 候选.length))] : null;
  };
  const 第一步 = () => {
    const 条目 = 抽一条(层, 类型);
    return 条目 ? { 条目, 层, 类型, 兜底: null } : null;
  };
  let 结果 = 第一步();
  if (结果) return 结果;
  const 退到 = (条目, 实际层, 实际类型, 原因) => {
    if (记) 记(`编成兜底：第 ${层} 层没有「${类型}」编成 → 改用第 ${实际层} 层「${实际类型}」编成（${原因}）`);
    return { 条目, 层: 实际层, 类型: 实际类型, 兜底: 原因 };
  };
  /* ② 本层的「普通」 */
  if (类型 !== '普通') {
    const 条目 = 抽一条(层, '普通');
    if (条目) return 退到(条目, 层, '普通', '这一层没有这个类型的编成，退回同层普通');
  }
  /* ③ 本层别的类型 */
  for (const t of 兜底类型顺序) {
    if (t === 类型 || t === '普通') continue;              // 本类型试过、普通试过
    const 条目 = 抽一条(层, t);
    if (条目) return 退到(条目, 层, t, '这一层连普通都没有');
  }
  /* ④ 别的层的同类型（先近后远） */
  const 层们 = [...new Set(编成表.map(e => e.层))].filter(l => l !== 层)
    .sort((a, b) => Math.abs(a - 层) - Math.abs(b - 层) || a - b);
  for (const l of 层们) {
    const 条目 = 抽一条(l, 类型);
    if (条目) return 退到(条目, l, 类型, '这一层什么编成都没有');
  }
  /* ⑤ 全表第一条 */
  const 最后的 = 编成表[0];
  return 退到(最后的, 最后的.层, 最后的.类型, '全表都没有这个类型');
}

/** 把一条编成变成"敌方单位数组"。场次 = 本层打到第几场（影响等级）。 */
function 编成到单位(条目, 场次 = 0) {
  const kind = 类型到Kind[条目.类型] || 'battle';
  const 前排 = 条目.前 || [], 后排 = 条目.后 || [];
  const 列表 = [];
  /* ★ 敌方强度（作者 2026-10-11 拍板的难度调整 · 常量与理由在 `71-改动.js` 的「难度调整」段）：
     倍率按 **编成条目的层 × 这台的梯队** 现算（`敌方强度倍率()`），写进规格的 `强化` 字段，
     由 `40-单位.js` 的 `makeUnit()` 落成 威力 / 装甲 / 防御 / HP / 精准。
     第 1 层 / 倍率 = 1 → 与改前逐字相同。 */
  const 强化 = 键 => 敌方强度倍率(条目.层, tierOfEnemy(键)).倍率;
  前排.slice(0, 行列数(ROW_FRONT)).forEach((键, i) => 列表.push({ 键, 位: slotOf(ROW_FRONT, i), 等级: runEnemyLv(kind, 条目.层, 场次) + TIER_LV[tierOfEnemy(键)], 强化: 强化(键), 层: 条目.层 }));
  后排.slice(0, 行列数(ROW_BACK)).forEach((键, i) => 列表.push({ 键, 位: slotOf(ROW_BACK, i), 等级: runEnemyLv(kind, 条目.层, 场次) + TIER_LV[tierOfEnemy(键)], 强化: 强化(键), 层: 条目.层 }));
  const 单位们 = makeUnits(列表, 'enemy');
  /* ★ 词条层（2026-10-13）：**必须在 `应用敌方强化()` 之后**（它已经跑完了，见上面那段注释）。
     ① 每台单位身上留一份 `词条原始`（= 这一台实际吃到的那几条）—— 它是**唯一的产品路径**的载体：
        `敌方规格()` 会把它带着走，`开局()` → `makeUnits()` 再落一次（见 `40-单位.js`）；
     ② 本函数自己返回的单位**也已经落好**（测试 / 工具直接用 `编成到单位()` 时行为一致）。
     ★ `词条` 不消耗随机数、`词条层.开 = false` 时两步都是空转（逐字不变）。 */
  for (const u of 单位们) u.词条原始 = 词条汇总(条目, u);
  return 词条到单位(单位们, 条目);
}

/** 敌方单位 → 「规格」（`{键, 位, 等级, 强化, 层}`）——**把敌方强度带着走**。
 *  界面 / 平衡工具 / 测试都习惯「把 `编成到单位()` 的结果摊平成规格再喂给 `开局()`」，
 *  摊平时**必须连 `强化`（+ `层`）一起带上**，否则重新造出来的敌人会退化成未强化版
 *  （工具量到的就不是玩家打到的）。
 *  ★ 2026-10-13：连 `层` 一起带上 —— 敌人强度的「伤害」那一项**按层给值**
 *    （`71-改动.js` 的 `难度调整.敌方强度.层威力系数`），层号丢了就会回落成统一值。 */
const 敌方规格 = u => ({
  键: u.key, 位: u.slot, 等级: u.lv,
  强化: u.强化 != null ? u.强化 : 1,
  层: u.层 != null ? u.层 : (u.敌方强度 && u.敌方强度.层 != null ? u.敌方强度.层 : null),
  /* ★ 2026-10-13（词条层）：把这一台吃到的 `词条` 也**带着走** —— 产品路径是
     `编成到单位()` → `敌方规格组()` → `开局()` → `makeUnits()` → `makeUnit()`，
     摊平时漏掉它，词条就会在**玩家真正打的那一场**里悄悄失效。
     没有词条的编成这里是 `null`（`makeUnits()` 那一句因此空转，与改动前逐字相同）。 */
  词条: u.词条原始 || null,
});
const 敌方规格组 = 单位们 => (单位们 || []).map(敌方规格);

/* ---------- 增援波次（作者 2026-10-10 拍板）----------
 * 编成表里的 `波次: [{回合, 来:[键…]}]` → 喂给 `开局()` 的 `选项.波次`
 * （`{回合, 来:[{键, 等级}]}`）。等级和开场那几台**同一套算法**
 * （`runEnemyLv(kind, 层, 场次) + TIER_LV[梯队]`，11-敌方梯队.js），所以增援和编成里同级。 */
const 编成波次 = 条目 => ((条目 && 条目.波次) || []);
function 编成波次到单位(条目, 场次 = 0) {
  const kind = 类型到Kind[条目.类型] || 'battle';
  const 等级 = 键 => runEnemyLv(kind, 条目.层, 场次) + TIER_LV[tierOfEnemy(键)];
  /* ★ 增援也吃同一套敌方强度（和开场那几台一样按「层 × 梯队」算），否则增援会变成「送经验」 */
  const 强化 = 键 => 敌方强度倍率(条目.层, tierOfEnemy(键)).倍率;
  /* ★ 2026-10-13（词条层）：波次里的敌人**也要吃词条**（理由和「增援也要吃强度」一样）。
     这里带的是**没按位过滤的整份词条** —— 增援补进哪个空位要等 `空位()` 才知道，
     所以过滤（`单台` 的 `位`）留给 `增援()` 里的 `词条到单位()` 现算。 */
  const 词条 = 编成词条(条目);
  return 编成波次(条目).map(w => ({ 回合: w.回合, 来: (w.来 || []).map(键 => ({ 键, 等级: 等级(键), 强化: 强化(键), 层: 条目.层, 词条 })) }));
}

