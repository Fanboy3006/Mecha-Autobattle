/** 一份编成的**全部**词条（`词条` + `挂载` 那一组；**不按位过滤** —— 过滤在 `词条汇总()` 里做）。
 *  `挂载` 指向的词条组查不到 → 只返回自己的 `词条`（不抛异常）。 */
function 编成词条(条目) {
  const 出 = [];
  for (const t of ((条目 && 条目.词条) || [])) 出.push(t);
  const 挂 = 条目 && 条目.挂载;
  if (挂 && 词条组表[挂]) for (const t of 词条组表[挂]) 出.push(Object.assign({}, t, { 来自挂载: 挂 }));
  return 出;
}

/** 这条词条作用在这台单位身上吗（`全体` 恒真；`单台` 比**位名**）。 */
function 词条作用在(词条, 单位) {
  if (!词条) return false;
  const 作用 = 词条.作用 || '全体';
  if (作用 === '全体') return true;
  if (作用 !== '单台') return false;
  return 位名(单位.slot) === String(词条.位 || '');
}

/** ★ 规格 §3.1 的 `词条汇总(条目, 单位)`：把 `词条` / `挂载` / `全体` / `单台` **四路合并**成
 *  「这台单位最终吃到的那几条」，同一个 `键` 按 `叠加` 规则收口（默认 `不叠` = 后面覆盖前面）。
 *  ★ **纯读**：不改单位、不消耗随机数。 */
function 词条汇总(条目, 单位) {
  const 命中 = 编成词条(条目).filter(t => 词条作用在(t, 单位));
  const 表 = new Map();
  for (const t of 命中) {
    const k = t && t.键;
    if (!k) continue;
    const 旧 = 表.get(k);
    if (旧 && t.叠加 === '叠' && typeof t.值 === 'number' && typeof 旧.值 === 'number') {
      表.set(k, Object.assign({}, t, { 值: 旧.值 + t.值 }));
    } else 表.set(k, Object.assign({}, t));
  }
  return [...表.values()];
}

/** 数值夹一次（`战斗结构.词条.上限` 只是防手滑的安全网）。 */
function 词条夹(键, 值) {
  const 限 = 词条上限(键);
  const v = Number(值);
  if (!Number.isFinite(v)) return 0;
  return 限 == null ? v : Math.max(-限, Math.min(限, v));
}
/** 给单位补一条常驻增益（`src:'词条'`，**同源只留一份**；`剩余` 写大数 = 整场不衰减）。 */
function 词条增益(u, 键, 值) {
  u.buffs = (u.buffs || []).filter(b => b.src !== `词条·${键}`);
  u.buffs.push({ src: `词条·${键}`, 剩余: 9999, [键]: 值 });
}
/** 给单位补一个能力键（`abilities` 是现成的开关表，`abilOn()` 读它；重复 push 不会发生）。
 *  ★ **必须先 `slice()` 复制一份**：`makeUnit()` 是浅拷贝，`u.abilities` 和模板上的
 *    `ENEMY_T[键].abilities` **是同一个数组** —— 直接 push 会把能力**永久写进模板**，
 *    于是所有关卡里同一种敌人一起变（探查脚本第一遍就撞到了这个坑：连 `grunt` 都会反弹）。
 *    复制之后污染面 = 0（词条只作用在这一场、这一台身上）。 */
function 词条加能力(u, 键) {
  u.abilities = Array.isArray(u.abilities) ? u.abilities.slice() : [];
  if (!u.abilities.includes(键)) u.abilities.push(键);
}
/** ★ `加武器`：把一把**现成的武器形状**挂到这台单位的武器表上（运行期条目，和 `makeUnit()` 同形状）。
 *  ★ 它的威力**自己乘一次「敌方强度」的威力系数**（`敌方强度.分项` / `层威力系数`）——
 *    因为 `应用敌方强化()` 在 `makeUnit()` 里**已经跑过了**，后挂的武器不乘就会在高层偏软。
 *    口径与 `应用敌方强化()` 的 `系数('威力')` **同一条公式**（`71-改动.js` 的 `难度调整.敌方强度`）。 */
function 词条加武器(u, 值, 层) {
  if (!值 || !值.name) return;
  if ((u.weapons || []).some(e => e.t && e.t.name === 值.name)) return;
  const 规 = Object.assign({}, 值);
  delete 规.随强化;
  const 倍 = 词条威力系数(层, tierOfEnemy(u.key));
  if (规.power > 0) 规.power = Math.max(1, Math.round(规.power * 倍));
  const w = wp(规);
  u.weapons = (u.weapons || []).concat([{ t: w, cd: 0, uses: w.uses, readyTurn: 1 + startCdOf(w) }]);
}
/** 「加武器」用的威力系数：与 `应用敌方强化()` 的 `系数('威力')` **同一条公式**（纯函数）。 */
function 词条威力系数(层, 梯队) {
  const c = (难度调整 && 难度调整.敌方强度) || {};
  const 倍率 = 敌方强度倍率(层, 梯队).倍率;
  const f = c.分项 || {};
  const 逐层 = (c.层威力系数 && 层 != null && c.层威力系数[层] != null) ? c.层威力系数[层] : null;
  const 基 = 逐层 != null ? 逐层 : (f.威力 != null ? f.威力 : 1);
  return 1 + (倍率 - 1) * 基;
}

