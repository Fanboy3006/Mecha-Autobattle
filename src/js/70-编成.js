/** 按层 / 类型筛出候选编成。 */
function 选编成(层, 类型) {
  return 编成表.filter(e => (层 == null || e.层 === 层) && (类型 == null || e.类型 === 类型));
}

/** 从对应层 / 类型的候选里随机抽一条；**这一档没有编成就返回 null**（兜底见 `抽编成兜底`）。 */
function 抽编成(层, 类型, rng) {
  const 候选 = 选编成(层, 类型);
  if (!候选.length) return null;
  const r = rng || Math.random;
  return 候选[Math.min(候选.length - 1, Math.floor(r() * 候选.length))];
}

/* ---------------- 兜底：抽不到编成时**绝不静默退回大地图** ----------------
 * M4 出过一次这种 bug（打完终点 Boss 不通关那阵子）：某层某类型没编成 →
 * `抽当前编成()` 返回 null → 界面把提示写一行就退回大地图，玩家看着像「点了没反应」。
 * 现在 `抽编成兜底()` 按下面的顺序退，**每退一步都调 `记(一行中文)`**（界面传 `肉鸽.记`，
 * 于是这一行进 `RUN.日志`）。正常情况（表里 13 个组合都齐）第 ① 步就命中，一行日志都不会写。
 *   ① 本层 + 本类型
 *   ② 本层「普通」（作者点名的那个例子：退回同层的普通）
 *   ③ 本层别的类型（顺序 普通 → 精英 → 守军 → 侵蚀源 → Boss）
 *   ④ 别的层的同类型（层号离得近的先试）
 *   ⑤ 全表第一条（表非空就一定抽得到）
 * 返回 `{条目, 层, 类型, 兜底}`：`兜底` = null 表示没走兜底，否则是「为什么退」的一句原因。 */
const 兜底类型顺序 = ['普通', '精英', '守军', '侵蚀源', 'Boss'];
function 抽编成兜底(层, 类型, rng, 记) {
  const r = rng || Math.random;
  const 抽一条 = (l, t) => {
    const 候选 = 选编成(l, t);
    return 候选.length ? 候选[Math.min(候选.length - 1, Math.floor(r() * 候选.length))] : null;
  };
  const 第一步 = () => {
    const 条目 = 抽一条(层, 类型);
    return 条目 ? { 条目, 层, 类型, 兜底: null } : null;
  };
  let 结果 = 第一步();
  if (结果) return 结果;
  const 退到 = (条目, 实际层, 实际类型, 原因) => {
    if (记) 记(`编成兜底：第 ${层} 层没有「${类型}」编成 → 改用第 ${实际层} 层「${实际类型}」编成（${原因}）`);
    return { 条目, 层: 实际层, 类型: 实际类型, 兜底: 原因 };
  };
  /* ② 本层的「普通」 */
  if (类型 !== '普通') {
    const 条目 = 抽一条(层, '普通');
    if (条目) return 退到(条目, 层, '普通', '这一层没有这个类型的编成，退回同层普通');
  }
  /* ③ 本层别的类型 */
  for (const t of 兜底类型顺序) {
    if (t === 类型 || t === '普通') continue;              // 本类型试过、普通试过
    const 条目 = 抽一条(层, t);
    if (条目) return 退到(条目, 层, t, '这一层连普通都没有');
  }
  /* ④ 别的层的同类型（先近后远） */
  const 层们 = [...new Set(编成表.map(e => e.层))].filter(l => l !== 层)
    .sort((a, b) => Math.abs(a - 层) - Math.abs(b - 层) || a - b);
  for (const l of 层们) {
    const 条目 = 抽一条(l, 类型);
    if (条目) return 退到(条目, l, 类型, '这一层什么编成都没有');
  }
  /* ⑤ 全表第一条 */
  const 最后的 = 编成表[0];
  return 退到(最后的, 最后的.层, 最后的.类型, '全表都没有这个类型');
}

/** 把一条编成变成"敌方单位数组"。场次 = 本层打到第几场（影响等级）。 */
function 编成到单位(条目, 场次 = 0) {
  const kind = 类型到Kind[条目.类型] || 'battle';
  const 前排 = 条目.前 || [], 后排 = 条目.后 || [];
  const 列表 = [];
  前排.slice(0, 行列数(ROW_FRONT)).forEach((键, i) => 列表.push({ 键, 位: slotOf(ROW_FRONT, i), 等级: runEnemyLv(kind, 条目.层, 场次) + TIER_LV[tierOfEnemy(键)] }));
  后排.slice(0, 行列数(ROW_BACK)).forEach((键, i) => 列表.push({ 键, 位: slotOf(ROW_BACK, i), 等级: runEnemyLv(kind, 条目.层, 场次) + TIER_LV[tierOfEnemy(键)] }));
  return makeUnits(列表, 'enemy');
}

