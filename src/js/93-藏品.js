/** 界面上显示用：这一局已经拿到的藏品（名字 + 一句效果 + 稀有度） */
const 藏品清单 = run => ((run || (肉鸽 && 肉鸽.RUN) || {}).藏品 || [])
  .map(id => Object.assign({ id }, 藏品表[id] || { 名: id, 说明: '', 稀有: '—' }));

/** 大地图上的藏品卡片（沿用现有样式，不引新框架）。
 *  ★ 2026-10-11：标题上多写一句「其中 N 件编制类（出击上限 ±N 台）」——
 *    作者要求「编队屏 / 大地图要能看出里面有 N 件编制类」。 */
function 藏品卡片Html() {
  const 们 = 藏品清单();
  const 编制 = 藏品编制件数();
  const 部署加 = 藏品部署位加成();
  const 编制句 = `其中 ${编制} 件编制类（出击上限 ${部署加 > 0 ? '+' : ''}${部署加} 台）`;
  if (!们.length) {
    return `<div class="rv-card"><h3>藏品（0）</h3><p class="small">还没有。精英战 / Boss 战胜利各发 1 件` +
      `（战棋照抄的 50 件 + 2026-10-11 新造的 8 件希望 / 编制类）。</p></div>`;
  }
  const 行 = 们.map(x => `<div class="rv-row" title="${x.说明}">
    <span class="nm"><b>${x.名}</b><small> · ${x.稀有}</small><br><small style="margin-left:0">${x.说明}</small></span></div>`).join('');
  return `<div class="rv-card"><h3>藏品（${们.length}）<span class="small">效果在开战时生效 · ${编制句}</span></h3>${行}</div>`;
}
