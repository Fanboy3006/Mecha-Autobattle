/** 叠层：按「出击队伍里这些职业有几台」算层数（战棋 23b:77,91） */
function 藏品层数(件, 出击职业) {
  const 层 = 件.数值 && (件.数值.stack || 件.数值.foeStack);
  const 按 = (层 && 层.by) || [];
  return 出击职业.filter(c => 按.includes(c)).length;
}
/** 这一件对某个职业的单体效果（mods / stat / stack） */
function 藏品单体效果(件, 职业, 出击职业) {
  const e = 件.数值 || {};
  const 我的 = !e.职业 || e.职业.includes(职业);
  const m = {};
  if (e.mods && 我的) for (const [k, v] of Object.entries(e.mods)) m[k] = (m[k] || 0) + v;
  if (e.stack && (!e.stack.to || e.stack.to.includes(职业))) {
    const 层 = Math.min(e.stack.max, 藏品层数(件, 出击职业));
    for (const [k, v] of Object.entries(e.stack.per)) m[k] = (m[k] || 0) + v * 层;
  }
  return { 我的, m, stat: 我的 ? (e.stat || null) : null };
}

/** 开战时给**我方**出击机体算藏品加成（战棋 relicApplyAllies，23b:74-95）
 *  分三层落下去：
 *    1. u.buffs 里追加两条 `src:'藏品'` 的常驻增益（mods）—— hit / eva / crit / armorPct / dmg / red
 *       都走 buffSum，公式里本来就读它，所以**没有藏品的战斗一个字节都不变**；
 *    2. stat.hpPct 直接改 maxHp / hp（照 23b:86）；
 *    3. 记录一份 `u.藏品加成` 给界面和测试看（不参与计算）。
 *  返回：受影响的单位数。 */
function 应用藏品我方(我方, 藏品们) {
  const 件们 = (藏品们 || []).map(id => 藏品表[id]).filter(Boolean);
  if (!件们.length || !我方 || !我方.length) return 0;
  const 出击职业 = 我方.map(u => 战斗分类(u));
  for (const u of 我方) {
    const 职 = 战斗分类(u);
    const 合计 = {};
    for (const 件 of 件们) {
      const { m, stat } = 藏品单体效果(件, 职, 出击职业);
      for (const [k, v] of Object.entries(m)) 合计[k] = (合计[k] || 0) + v;
      if (stat && stat.hpPct) {
        const k = 1 + stat.hpPct / 100;
        u.maxHp = Math.max(1, Math.round(u.maxHp * k));
        u.hp = Math.max(1, Math.round(u.hp * k));
      }
    }
    /* 整场加成（战棋 relicBattleStart，23b:171-181）：混编 / 孤狼。
       战棋把这两条也算进 relicMods，我们一样合进「藏品」这条 buff 里。 */
    const n = 我方.length, 职业数 = new Set(出击职业).size;
    if (件们.some(x => x.数值 && x.数值.特殊 === 'mixed')) 合计.dmg = (合计.dmg || 0) + 8 * 职业数;
    if (件们.some(x => x.数值 && x.数值.特殊 === 'lonewolf')) {
      if (n <= 2) { 合计.dmg = (合计.dmg || 0) + 50; 合计.armorPct = (合计.armorPct || 0) + 30; }
      else if (n >= 4) 合计.dmg = (合计.dmg || 0) - 15;
    }
    if (!Object.keys(合计).length) continue;
    u.buffs = (u.buffs || []).filter(b => b.src !== '藏品');
    u.buffs.push(Object.assign({ src: '藏品', 剩余: 999 }, 合计));
    u.藏品加成 = 合计;
  }
  return 我方.filter(u => u.藏品加成).length;
}

/** 开战时给**敌方**单位算藏品减益（战棋 relicApplyFoe，23b:97-107）
 *  foe 直接加；foeStack 按我方出击职业人数算层数。
 *  落在 e.buffs 的 `src:'藏品'` 上：hit 由命中公式读，armorPct 由 effArmor 读。
 *  返回：受影响的单位数。 */
function 应用藏品敌方(敌方, 我方, 藏品们) {
  const 件们 = (藏品们 || []).map(id => 藏品表[id]).filter(Boolean);
  if (!件们.length || !敌方 || !敌方.length) return 0;
  const 出击职业 = (我方 || []).map(u => 战斗分类(u));
  const 合计 = {};
  for (const 件 of 件们) {
    const e = 件.数值 || {};
    if (e.foe) for (const [k, v] of Object.entries(e.foe)) 合计[k] = (合计[k] || 0) + v;
    if (e.foeStack) {
      const 层 = Math.min(e.foeStack.max, 藏品层数(件, 出击职业));
      for (const [k, v] of Object.entries(e.foeStack.per)) 合计[k] = (合计[k] || 0) + v * 层;
    }
  }
  if (!Object.keys(合计).length) return 0;
  for (const e of 敌方) {
    e.buffs = (e.buffs || []).filter(b => b.src !== '藏品');
    e.buffs.push(Object.assign({ src: '藏品', 剩余: 999 }, 合计));
    e.藏品加成 = 合计;
  }
  return 敌方.length;
}

