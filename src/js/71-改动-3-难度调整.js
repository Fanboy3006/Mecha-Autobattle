/** 敌方阵容 → 这一场的回合上限（杠杆 ④；见 `难度调整.回合上限` 的注释）。
 *  接受**单位数组**（`makeUnit()` 造的，认 `.key`）或**规格数组**（`{键, 位, 等级}`，认 `.键`）。 */
function 回合上限(敌方们) {
  const 表 = 难度调整.回合上限;
  const 序 = ['杂兵', '精锐', '头目', 'Boss'];
  let 最高 = 0;
  for (const u of (敌方们 || [])) {
    const 键 = u && (u.key || u.键 || u.mech);
    if (!键) continue;
    const i = 序.indexOf(tierOfEnemy(键));
    if (i > 最高) 最高 = i;
  }
  const 名 = 序[最高];
  return (表 && 表[名] != null) ? 表[名] : (表 && 表.默认) || 12;
}

/** 把一组合计值按**同类上限**夹一次（杠杆 ①；正负都往 0 的方向夹）。
 *  `上限表` = `{键: 幅度}`；没有列进去的键**原样通过**（不受影响）。 */
function 藏品合计封顶(合计, 上限表) {
  const 出 = {};
  for (const [k, v] of Object.entries(合计 || {})) {
    const 限 = 上限表 ? 上限表[k] : null;
    const 有上限 = typeof 限 === 'number' && Number.isFinite(限) && 限 > 0;
    出[k] = 有上限 ? Math.max(-限, Math.min(限, v)) : v;
  }
  return 出;
}

/** ★ 2026-10-13（第 2 步「AI 目标选择」）：这台机体打**这个目标**时的「站位权重」。
 *  · 越靠前（`ROW_FRONT`）越优先；`开: false` / 两个权重都 ≤1 → 恒 1（与改动前逐字相同）。
 *  · **纯函数**：不改状态、不消耗随机数（`targetScore()` 在预告 / 结算里也会被调到）。
 *  · 只读权重表，**不碰射程 / 阻挡 / 范围落点**（那些在 `30-射程.js`，本函数一处都不改）。
 *  ★ **只对敌人生效**（`att.side === 'enemy'`）：作者那句话说的是「**让敌人**优先打能打到的最前排」——
 *    我方那五条方针（集中攻击 / 攻击后排…）的挑法因此**一个字节都没动**
 *    （我方的 `targetScore` 恒 ×1）。要给我方也加上，把 `只给敌人` 改成 false 即可。 */
function 站位权重(att, t) {
  const c = 难度调整 && 难度调整.AI站位权重;
  if (!c || c.开 === false || !t) return 1;
  if (c.只给敌人 !== false && !(att && att.side === 'enemy')) return 1;
  const w = unitRow(t) === ROW_FRONT ? (c.前排 != null ? c.前排 : 1) : (c.后排 != null ? c.后排 : 1);
  return Number.isFinite(w) && w >= 0 ? w : 1;
}

