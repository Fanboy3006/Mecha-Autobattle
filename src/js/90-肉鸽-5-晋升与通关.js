  /** 名册上每台机体的晋升情况（界面直接照着画；测试也读它）。
   *  返回 `[{键, 等级, 到, 价, 能升, 理由, 属性, 有券, 券名, 券下标}]`，顺序 = 名册顺序。
   *  ★ 2026-10-11 券系统：**晋升 = 希望 + 1 张同类券**（照战棋 `27-开局.js:84→86` 的顺序：
   *    先删券、再 `runPromote` 扣希望），所以每条多一个 `有券`（手上有没有能对上这台机体的券）
   *    与 `券名`（要哪一张的**类别**提示，照 `27:77` 的「同职业或同势力」）。
   *    **没券 → `能升 = false`、`理由` 写清「没有可用的同类券」**（界面据此 `disabled`）。 */
  晋升清单() {
    const R = this.RUN;
    if (!R) return [];
    return (R.队伍 || []).map((m, i) => {
      const 到 = 晋升目标(m.等级);
      const 价 = 到 ? 晋升要多少(m.键, 到, R) : 0;
      const 找 = 到 ? 找同类券(R, m.键) : null;
      const 有券 = !!找;
      const 能升 = !!到 && R.希望 >= 价 && 有券;
      return {
        键: m.键, 名: allyName(m.键), 等级: m.等级, 到, 价, 能升,
        /* ★ 2026-10-13 带队核心：名册**下标 0** 那一台（晋升屏 / 名册卡片上的标记读它）。
           **不改任何既有字段**，只多一个布尔。 */
        带队核心: 带队核心吗(R.队伍, i),
        档: tierOf(m.键), 档名: TIER_NAME[tierOf(m.键)] || '普通',
        有券, 券名: 有券 ? 券名(找.券) : null, 券下标: 有券 ? 找.下标 : -1,
        理由: !到 ? '已经 Lv30（到顶了）'
          : (!有券 ? `没有可用的同类券（要一张「${m.键} 的职业 / 势力」对得上的券）`
            : (能升 ? '' : `希望不够（要 ${价}，只有 ${R.希望}）`)),
        属性: 到 ? 晋升预览(m.键, m.等级) : null,
      };
    });
  },
  /** 晋升一台（照 `31-战斗.js:324-332` 的 `runPromote` + `27-开局.js:78-86` 的券门槛）：
   *  ① 等级不是 10 / 20 就拒绝（**不能跳级**：Lv10 不能直接升 30）；② **找不到同类券就拒绝**；
   *  ③ 希望不够就拒绝；④ **先删券**（`27:84` 的顺序）**再扣希望**、等级 +10、用掉「下次晋升减价」、写一行日志；
   *  ⑤ **属性真的重算**（走 `makeUnit` → `levelUp`，和招募 / 战斗里的同一套规则）、进存档。
   *  ★ 三条判据**全部先判完再动手**（照 `31:327` 的「先判再扣」）——失败时**券和希望一分都不扣**。
   *  返回 `{ok:true, 键, 从, 到, 价, 前, 后, 券, 券下标, 希望}` 或 `{ok:false, why}`。 */
  晋升(键) {
    const R = this.RUN;
    if (!R) return { ok: false, why: '没有进行中的局' };
    const m = (R.队伍 || []).find(x => x.键 === 键);
    if (!m) return { ok: false, why: '名册里没有这台机体' };
    const 到 = 晋升目标(m.等级);
    if (!到) return { ok: false, why: `${m.键} 已经 Lv${m.等级}，到顶了` };
    /* ★ 券门槛（照战棋 `27:77` 的 `ticketOk`）：没有同类券 → 直接拒绝，**希望一分不扣**。 */
    const 找 = 找同类券(R, m.键);
    if (!找) return { ok: false, why: '没有可用的同类券（要一张同职业 / 同势力的招募券）' };
    const 价 = 晋升要多少(m.键, 到, R);
    if (R.希望 < 价) return { ok: false, why: `希望不够（要 ${价}，只有 ${R.希望}）` };
    const 从 = m.等级;
    const 前 = 晋升预览(m.键, 从).前;
    /* ★ 顺序照战棋：**先删券**（`27:84` 的 `RUN.tickets.splice(i, 1)`）→ **再扣希望**（`:86` 的 `runPromote`）。 */
    R.券.splice(找.下标, 1);
    R.希望 -= 价;
    记希望来源(R, '支出', 价);
    m.等级 = 到;
    if (R.下次晋升减价) R.下次晋升减价 = false;      // 31-战斗.js:328：用掉一次就清
    const 后 = 重算名册属性(键).后;
    this.记(`${m.键} 晋升到 Lv${到}（−${价} 希望，剩 ${R.希望}；用掉一张 ${券名(找.券)}）：HP ${前.maxHp} → ${后.maxHp}、` +
      `装甲 ${前.armor} → ${后.armor}、防御 ${前.defense} → ${后.defense}、机动 ${前.mov} → ${后.mov}`);
    if (typeof 战术卡牌开 === 'function' && 战术卡牌开() && typeof 候选战术牌们 === 'function') {
      R.战术牌库 = Array.isArray(R.战术牌库) ? R.战术牌库 : [];
      R.待选战术牌 = 候选战术牌们(R, 键, 3).map(c => c.id);
    }
    this.存档();
    return { ok: true, 键, 名: allyName(键), 从, 到, 价, 前, 后, 券: 找.券, 券名: 券名(找.券), 券下标: 找.下标, 希望: R.希望 };
  },
