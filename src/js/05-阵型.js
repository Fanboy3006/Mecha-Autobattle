/* ============================================================================
 * 阵型（作者 2026-10-10 拍板：错开的 9 格 = 前排 4 + 后排 5）
 * ----------------------------------------------------------------------------
 * 这里**只改这一个地方**就能换阵型：`阵型表` 里每行写「这一排有几格」。
 * 格子编号 slot 从 0 开始，按排顺序排下来：
 *   前 4 后 5 → 前排 = 0,1,2,3（前1 前2 前3 前4）· 后排 = 4..8（后1..后5），共 9 格
 *
 * ★ 作者拍板的阻挡关系（**就按这张图**，见任务板「阵型9格」段）：
 *
 *     前排： F0   F1   F2   F3          slot 0  1  2  3
 *     后排： B0   B1   B2   B3   B4     slot 4  5  6  7  8
 *
 *     阻挡： F0→B0,B1   F1→B1,B2   F2→B2,B3   F3→B3,B4
 *     （B1/B2/B3 各被 2 个前排位挡；B0/B4 各只被 1 个挡 —— 后排比前排多一格，所以错开）
 *
 * 为什么这么排：后排 5 格比前排 4 格多一格，整体错开半格，于是每个前排位刚好挡住
 * 「自己正对的那一格 + 右边那一格」，B0 与 B4 是两端、只有 1 个阻挡位。
 *
 * 参考：舰娘的阵型（陣形）里和前后排有关的是「かばう（替旗舰挡枪）」——
 * 靠前的替靠后的挡枪；舰娘没有严格的「一列对一列」规则，所以「换位」按作者的话做成
 * **和相邻位换**：同排左右邻居 + 有阻挡关系的对位（`相邻位()`）。
 * ========================================================================== */

const 阵型表 = [
  { 名: '前排', 短名: '前', 列数: 4 },
  { 名: '后排', 短名: '后', 列数: 5 },
];

const 阵型 = (() => {
  const 行 = [];
  let 起 = 0;
  for (let i = 0; i < 阵型表.length; i++) {
    行.push({ 名: 阵型表[i].名, 行: i, 列数: 阵型表[i].列数, 起 });
    起 += 阵型表[i].列数;
  }
  return { 行, 总格数: 起 };
})();

const ROWS = 阵型.行.length;          // 有几排
const SLOTS = 阵型.总格数;            // 一共几个位置（双方各这么多）= 9
const ROW_FRONT = 0, ROW_BACK = 1;    // 排版：0 = 前排（靠敌人）、1 = 后排

const 行列数 = i => 阵型.行[i].列数;
/* 最宽的那一排有几格：界面画格子时用它，保证每张卡片一样宽 */
const 最大列数 = Math.max(...阵型.行.map(r => r.列数));
const 行首格 = i => 阵型.行[i].起;
const 行名 = i => 阵型.行[i].名;
/** 短名（前/后）：位名用短的 —— 作者说的「前1..前4 / 后1..后5」就是这套名字 */
const 行短名 = i => 阵型表[i].短名 || 行名(i);
/** slot → 第几排 */
function rowOfSlot(slot) {
  let r = 0;
  while (r < ROWS - 1 && slot >= 行首格(r + 1)) r++;
  return r;
}
/** slot → 这一排的第几列（0 起） */
const colOfSlot = slot => slot - 行首格(rowOfSlot(slot));
/** （排, 列）→ slot */
const slotOf = (row, col) => 行首格(row) + col;
/** 这一排有没有这一列（前 4 后 5 时，前排没有第 5 列） */
const 有这一列 = (row, col) => col >= 0 && col < 行列数(row);
/** 格子的人话名字：前1 / 后2（作者 2026-10-10：前1..前4、后1..后5） */
const 位名 = slot => `${行短名(rowOfSlot(slot))}${colOfSlot(slot) + 1}`;

/** 某一列上所有真实的格子（前 4 后 5 时：前列0+后列0 … 前列3+后列3、后列4 只有自己）
 *  ★ 注意：**这不是阻挡关系**（阻挡是错开的，见下面的 `阻挡表` / `对位()`）；留着给界面画列用。 */
function 列上所有格(col) {
  const out = [];
  for (let r = 0; r < ROWS; r++) if (有这一列(r, col)) out.push(slotOf(r, col));
  return out;
}

/* ============================================================================
 * 阻挡关系（作者 2026-10-10 拍板的那张图）
 * ----------------------------------------------------------------------------
 * `阻挡表[前排列]` = 这个前排位挡着的**后排列**（1–2 个）。
 *   F0(列0)→B0,B1   F1(列1)→B1,B2   F2(列2)→B2,B3   F3(列3)→B3,B4
 * ========================================================================== */
const 阻挡表 = [
  [0, 1],   // 前1 → 后1、后2
  [1, 2],   // 前2 → 后2、后3
  [2, 3],   // 前3 → 后3、后4
  [3, 4],   // 前4 → 后4、后5
];

/** 归一化「活着的位」：接受 Set / 数组 / 单位数组（取 .slot）。 */
function 活位集(x) {
  if (x instanceof Set) return x;
  const s = new Set();
  for (const v of (x || [])) s.add(v && typeof v === 'object' ? v.slot : v);
  return s;
}

/** 这个**前排位**挡着的后排位们（后排位 / 越界 → 空数组）。 */
function 阻挡位(位) {
  if (位 == null || 位 < 0 || 位 >= SLOTS) return [];
  if (rowOfSlot(位) !== ROW_FRONT) return [];
  return (阻挡表[colOfSlot(位)] || []).map(c => slotOf(ROW_BACK, c));
}

/** 挡着这个**后排位**的前排位们（前排位 → 空数组）。B1/B2/B3 各有 2 个，B0/B4 各 1 个。 */
function 遮挡位(位) {
  if (位 == null || 位 < 0 || 位 >= SLOTS) return [];
  if (rowOfSlot(位) !== ROW_BACK) return [];
  const c = colOfSlot(位);
  const out = [];
  for (let i = 0; i < 阻挡表.length; i++) if (阻挡表[i].includes(c)) out.push(slotOf(ROW_FRONT, i));
  return out;
}

/** 有阻挡关系的**对位**（对称）：前排位 → 它挡的后排位们；后排位 → 挡着它的前排位们。
 *  这就是作者说的「F0↔B0/B1、F1↔B1/B2、F2↔B2/B3、F3↔B3/B4」。 */
const 对位 = 位 => (rowOfSlot(位) === ROW_FRONT ? 阻挡位(位) : 遮挡位(位));

/** 换位用的**相邻位** = 同排左右邻居 + 有阻挡关系的对位（作者 2026-10-10 拍板）。 */
function 相邻位(位) {
  const out = [];
  const r = rowOfSlot(位), c = colOfSlot(位);
  if (有这一列(r, c - 1)) out.push(slotOf(r, c - 1));
  if (有这一列(r, c + 1)) out.push(slotOf(r, c + 1));
  for (const s of 对位(位)) if (!out.includes(s)) out.push(s);
  return out;
}

/** 这个**后排位**现在被挡着吗：它的遮挡位里还有活人 → true。
 *  `活着的位` 传 Set / 数组 / 单位数组都行（界面与 AI 两边都从这里取，规则只有一份）。 */
function 被挡吗(位, 活着的位) {
  if (位 == null || rowOfSlot(位) !== ROW_BACK) return false;
  const 活 = 活位集(活着的位);
  return 遮挡位(位).some(s => 活.has(s));
}

/** 范围武器 `area:'col'` 用的**阻挡束**：一个前排位 + 它挡的 1–2 个后排位。
 *  后排位按**同列的前排位**归束；B4（后排第 5 列）没有同列前排 → 归它唯一的遮挡位 F3。 */
function 阻挡束(位) {
  if (位 == null || 位 < 0 || 位 >= SLOTS) return [];
  let 前;
  if (rowOfSlot(位) === ROW_FRONT) 前 = 位;
  else {
    const c = colOfSlot(位);
    前 = 有这一列(ROW_FRONT, c) ? slotOf(ROW_FRONT, c) : (遮挡位(位)[0] ?? null);
  }
  if (前 == null) return [位];
  return [前].concat(阻挡位(前));
}

/** 对照表（测试与文档直接读它，避免两处各写一份）：8 条阻挡关系，逐条是 `[前排位, 后排位]`。 */
const 阻挡关系 = [];
for (let c = 0; c < 阵型表[ROW_FRONT].列数; c++) {
  for (const b of (阻挡表[c] || [])) 阻挡关系.push([slotOf(ROW_FRONT, c), slotOf(ROW_BACK, b)]);
}

/* ============================================================================
 * 出击上限（作者 2026-10-10 拍板：**我方同时最多 6 台，一开始只有 3 台**，随等级解锁）
 * ----------------------------------------------------------------------------
 * 形状照战棋 `24-Feena_指挥官.js:19` 的 `deployCap()`：
 *   `const deployCap = () => 4 + Math.floor((RUN.lvl - 1) / 3) + (skLv('编制') >= 2 ? 1 : 0) + (hasRelic('f4') ? 1 : 0);`
 * 我们抄的是**「起始值 + floor((等级 − 基准) / 每几级) + 封顶」这个形状**（战棋那两项加成
 * —— 指挥官技能 / 藏品 f4 —— 本仓库还没接，先留 0）；**具体档位是初稿，待作者调**：
 *   Lv10 → 3 台（作者：「一开始只有 3 台」）
 *   Lv15 → 4 台
 *   Lv20 → 5 台
 *   Lv25 → 6 台（到顶；Lv30 也是 6）
 * ★ 三个常量都是**初稿**，改这里就够；`82` / `93-藏品.js` 的 f4「编制扩充令」以后接这一条。
 * ========================================================================== */
const 出击上限初值 = 3;          // 【初稿】一开始只上 3 台
const 出击上限顶 = 6;            // 【初稿】我方同时最多 6 台（9 格里留 3 个空位）
const 每几级加一台 = 5;          // 【初稿】队伍等级每涨 5 级 +1 台（形状照 24-Feena_指挥官.js:19）

/** 队伍等级 → 出击上限（3 → 6，初稿档位见上）。 */
function 出击上限(等级) {
  const lv = Number(等级);
  const n = 出击上限初值 + Math.floor(((Number.isFinite(lv) ? lv : 10) - 10) / 每几级加一台);
  return Math.max(出击上限初值, Math.min(出击上限顶, n));
}

/** 名册（`RUN.队伍` = [{键, 等级}]）→ 出击上限：按**名册里最高的等级**算。 */
function 出击上限由名册(名册) {
  const 等级们 = (名册 || []).map(m => (m && (m.等级 || m.lv)) || 10);
  return 出击上限(等级们.length ? Math.max(...等级们) : 10);
}
