/* ============================================================================
 * 阵型（作者 2026-10-10 定：暂时「前 3 后 2」，之后会扩充阵型）
 * ----------------------------------------------------------------------------
 * 这里**只改这一个地方**就能换阵型：`阵型表` 里每行写「这一排有几格」。
 * 格子编号 slot 从 0 开始，按排顺序排下来：
 *   前 3 后 2 → 前排 = 0,1,2（前1 前2 前3）· 后排 = 3,4（后1 后2），共 5 格
 *   以后要改「前 4 后 2」「前 3 后 3」，把列数改掉就行，引擎 / 界面 / 测试都从下面这些函数取。
 *
 * 参考：舰娘的阵型（陣形）里和前后排有关的是「かばう（替旗舰挡枪）」和一个叫「警戒陣」的分工——
 * 5 只时是「主力艦 = 1–2 番艦（后）、警戒艦 = 3–5 番艦（前）」，靠前的替靠后的挡枪。
 * 舰娘没有严格的「一列对一列」规则，所以「换位」按作者的话做成**按列对位**：
 * 前排第 c 列 ↔ 后排第 c 列；前排多出来、后排没有对位的那一列，就在本排里换空位/换队友。
 * ========================================================================== */

const 阵型表 = [
  { 名: '前排', 列数: 3 },
  { 名: '后排', 列数: 2 },
];

const 阵型 = (() => {
  const 行 = [];
  let 起 = 0;
  for (let i = 0; i < 阵型表.length; i++) {
    行.push({ 名: 阵型表[i].名, 行: i, 列数: 阵型表[i].列数, 起 });
    起 += 阵型表[i].列数;
  }
  return { 行, 总格数: 起 };
})();

const ROWS = 阵型.行.length;          // 有几排
const SLOTS = 阵型.总格数;            // 一共几个位置（双方各这么多）
const ROW_FRONT = 0, ROW_BACK = 1;    // 排版：0 = 前排（靠敌人）、1 = 后排

const 行列数 = i => 阵型.行[i].列数;
/* 最宽的那一排有几格：界面画格子时用它，保证每张卡片一样宽 */
const 最大列数 = Math.max(...阵型.行.map(r => r.列数));
const 行首格 = i => 阵型.行[i].起;
const 行名 = i => 阵型.行[i].名;
/** slot → 第几排 */
function rowOfSlot(slot) {
  let r = 0;
  while (r < ROWS - 1 && slot >= 行首格(r + 1)) r++;
  return r;
}
/** slot → 这一排的第几列（0 起） */
const colOfSlot = slot => slot - 行首格(rowOfSlot(slot));
/** （排, 列）→ slot */
const slotOf = (row, col) => 行首格(row) + col;
/** 这一排有没有这一列（前 3 后 2 时，后排没有第 3 列） */
const 有这一列 = (row, col) => col >= 0 && col < 行列数(row);
/** 格子的人话名字：前1 / 后2 */
const 位名 = slot => `${行名(rowOfSlot(slot))}${colOfSlot(slot) + 1}`;

/** 某一列上所有真实的格子（前 3 后 2 时：前列0+后列0、前列1+后列1、前列2 只有自己） */
function 列上所有格(col) {
  const out = [];
  for (let r = 0; r < ROWS; r++) if (有这一列(r, col)) out.push(slotOf(r, col));
  return out;
}
