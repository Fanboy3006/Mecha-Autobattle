/* ---------- 回合开始（增援 + 方针落地 + 指挥 + 防御回报） ---------- */
function 回合开始(ctx) {
  /* 0. 增援（作者 2026-10-10 拍板）：波次表里写着「这一回合来一波」的，先补进空位。
     放在最前面 —— 补进来的敌人这一回合就按速度正常行动（和战棋 respawnFoes 一个时机）。 */
  const 在场的 = new Set(ctx.enemies || []);        // ★ 词条：增援之前在场的那些（到点自爆只认它们）
  增援(ctx);

  /* 0.3 ★ 词条 · `自爆回合`（到点必爆）—— 见 `词条到点自爆()` 的注释。
     ★ **这里不许 `if (ctx.result) return;`**：改前这一路没有这种早退，`方针回合()` 那些步骤
       **必须在「这一场已经分出胜负」时也照跑一次**（`tests/commands.js` 第 [3] 段就是靠这个：
       目标在第 1 回合被打死 → 第 2 回合的 `回合开始()` 仍然要把方针落回「全军突击」）。
       加了早退会让「已经打完的局」停在旧方针上（实测踩到过）。 */
  词条到点自爆(ctx, 在场的);

  /* 0.5 势力特色（作者 2026-10-10；框架在 `72-势力.js`）：「我方阶段开始」这类效果。
     排在增援之后 —— 补进来的人这一回合就在场，势力特色看到的「在场有谁」和它一致；
     排在方针落地之前 —— 势力给的增益这一回合的行动就能读到。没有势力特色时它空转。 */
  势力回合开始(ctx);

  /* 1. ★ 全队方针落地（作者 2026-10-12 拍板的第一件，§1.3 第 1、2 条）：
     ① **保持到改为止** —— `ctx.方针` 在 `设方针()` 里改，回合之间**不重置**；
     ② **集中攻击的目标被击破 → 自动回全军突击**，并写一条 `〔方针〕…` 记录
        （界面上的方针栏也跟着变，不会出现「界面写集中攻击、实际在自由攻击」）；
     ③ 敌人没有方针这一层（敌方 AI 照旧，§1.3 第 6 条）。 */
  if (气势总攻开() && ctx.turn >= 2 && ctx.自然气势已加回合 !== ctx.turn) {
    ctx.自然气势已加回合 = ctx.turn;
    加气势(ctx, Number(气势总攻参数().每回合自然加) || 10);
  }
  方针回合(ctx);
  战术回合(ctx);

  /* 1.5 ★ 月球王国「不动如山」重判（2026-10-11；**2026-10-12 改成始终生效**，见 `72-势力.js`）。
     判定写进 `u.势力状态.月球王国.不动如山`，`20-战斗计算.js` 的 `effArmor()` 通过框架钩子
     `势力装甲()` 读它（装甲 +30%）。第 1 回合在 `开局()` 里已经判过一次；这里每回合重判一次。
     ★ 没有月球王国 / 没有 `steadfast` 的机体 → 这个函数什么都不写（空循环），公式逐字不变。 */
  判定月球不动(ctx, 势力参数('月球王国'));

  /* 2. 指挥（方案 6.3）：回合开始时，同一排的队友命中 +10（本回合）
     ★ 2026-10-11 改成对称（作者：「敌人也吃职业特色」）：改前只扫我方（`livingOf('ally')`），
       现在**两边都扫** —— 敌方的指挥（`战斗结构.敌方职业` 里的 `captain`）给同排敌人 +10 命中。
       这一条**不消耗随机数**，所以没有指挥敌人的战斗与改前逐字相同。 */
  for (const 方 of ['ally', 'enemy']) {
    for (const c of livingOf(方, ctx)) {
      if (!职业是(c, '指挥')) continue;
      const 同排 = livingOf(方, ctx).filter(t => t !== c && unitRow(t) === unitRow(c));
      if (!同排.length) continue;
      for (const t of 同排) 换同源增益(t, '指挥', { hit: 10 });
      pushLog(ctx, `〔指挥〕${c.name} 让同一排的队友命中 +10（本回合）：${同排.map(t => t.name).join('、')}`,
        Object.assign({ 类型: '指挥', 单位: c.key, 目标: 同排.map(t => t.key), 目标位们: 同排.map(t => t.slot), 目标方们: 同排.map(t => t.side) }, 谁(c)));
    }
  }

  /* 2.5 ★ 2026-10-13 **标定经济 · 生产端②（指挥）**：指挥的号令 = **点名标定一台敌机**（+1 层）。
     规格书 = 作者转来的设计稿（「指挥的号令改为点名标定一台敌机」）+ 参数表
     `71-改动.js` 的 `战斗结构.标定经济`（`开: false` = 整套不生效，逐字回到改动前）。
     ★ 排在**上面那一段「指挥：同排命中 +10」之后** —— 那一条**一个字都没改**（作者 2026-10-13 要求保留）。
     ★ **对称**：敌方的指挥（`战斗结构.敌方职业` 里的 `captain`）也点名标定我方一台。
     ★ **一个随机数都不消耗**（`标定经济点名()` 里一次 `ctx.rng` 都没有）→
       「没开 / 没有指挥」的战斗与改动前**逐字相同**。 */
  标定经济点名(ctx);

  for (const u of livingUnits(ctx)) {
    if (!u.防御回复) continue;
    u.防御回复 = false;
    const amt = Math.min(Math.round(u.maxHp * 0.05), u.maxHp - u.hp);
    if (amt > 0) {
      u.hp += amt;
      pushLog(ctx, `${u.name} 防御调整完成，回复 ${amt}`, Object.assign({ 类型: '回复', 回复: amt, 目标剩余HP: u.hp }, 谁(u), 谁目标(u)));
    }
  }

  /* 4. ★ 词条层的两个「回合开始」钩子（2026-10-13）：
     ① `冷却延长`（`1-N6` / `2-EE`，★ 替代 ≠ 原案）；② `隐身刷新`（`2-E3`）。
     放在**最后**：不改上面那五步任何一条记录的顺序 —— 只有带词条的编成会多出记录，
     没有词条的编成这两句都是空转（**逐字不变**）。 */
  词条冷却延长(ctx);
  词条隐身刷新(ctx);
}

/* ---------- 增援（作者 2026-10-10 拍板：敌方被击坠后按波次补人） ----------
 * 形状照战棋 `30b-关卡目标.js:96-105` 的持续刷新：
 *   `respawn: { every: N, lv, list: t => [键…] }`，触发在回合开始时
 *   （`if (rs && c.turn > 1 && (c.turn - 1) % rs.every === 0) { respawnFoes(rs.list(c.turn), rs.lv); log('敌方增援 N 台从右侧出现') }`）。
 * 本仓库把「间隔」在编成表里**展开成波次**（`70-编成.js` 的 `波次: [{回合, 来:[键…]}]`，
 * 回合号就是 `1 + 间隔×n`），所以这里只要「回合号对上了就补」。
 * 补进**空位**（前排先、再后排 —— 被击坠的格子空出来正好顶上）；一个空位都没有就作罢，照样写日志。
 * 日志统一写 `〔增援〕…`，记录里带 `数量 / 位们 / 单位们` 给界面用。 */
function 空位(ctx, side) {
  const 占 = new Set(livingOf(side, ctx).map(u => u.slot));
  for (let r = 0; r < ROWS; r++) for (let c = 0; c < 行列数(r); c++) {
    const s = slotOf(r, c);
    if (!占.has(s)) return s;
  }
  return null;
}
function 增援(ctx) {
  for (const w of (ctx.波次 || [])) {
    if (!w || w.回合 !== ctx.turn) continue;
    const 来 = w.来 || [];
    const 位们 = [], 单位们 = [];
    let 没空位 = 0;
    for (const e of 来) {
      const s = 空位(ctx, 'enemy');
      if (s == null) { 没空位++; continue; }
      const u = makeUnit(e.键, 'enemy', s, e.等级, e.强化 != null ? e.强化 : 1, null, e.层 != null ? e.层 : null);
      /* ★ 调参室：增援进来的敌人**也要吃同一套调参**（不然「HP ×2」只对开场那几台生效）。
         `ctx.调参` 只在调参室里存在 → 正常游戏的增援一个字节都不变。 */
      if (ctx.调参) 应用调参单位([u], ctx.调参);
      /* ★ 2026-10-13（词条层）：增援**也要吃词条**（`编成波次到单位()` 把整份词条挂在规格上，
         这里按它**实际补到的位**过滤 `单台` 那几条）。规格上没有 `词条` → 空转。 */
      if (e.词条) 词条到单位([u], { 词条: e.词条, 层: e.层 != null ? e.层 : null });
      ctx.enemies.push(u);
      位们.push(s); 单位们.push(u.key);
    }
    if (位们.length) {
      pushLog(ctx, `〔增援〕第 ${ctx.turn} 回合：敌方 ${位们.length} 台赶到（${位们.map(位名).join('、')}：${单位们.join('、')}）`,
        { 类型: '增援', 数量: 位们.length, 位们, 目标方们: 位们.map(() => 'enemy'), 单位们 });
    }
    if (没空位) pushLog(ctx, `〔增援〕第 ${ctx.turn} 回合：还有 ${没空位} 台挤不进来（9 个位都占着）`, { 类型: '增援', 数量: 0, 结果: '没空位' });
  }
  /* ★ 词条层：增援里带 `全员命中`（全场浓雾）的单位到了 → 把全场效果补挂一次（幂等）。 */
  if ((ctx.enemies || []).some(u => u.词条全场)) 应用全场词条(ctx);
}

/* ---------- 一个单位这次行动做什么 ---------- */
function 单位动作(u, ctx) {
  /* 敌方走 Boss 脚本那一层（方案 5.2：每 N 回合大技能 + 半血换阶段，见 61-Boss.js）：
     没配脚本的敌人它原样转给 enemyAction，行为一个字节都不变。 */
  if (u.side === 'enemy') return bossTurn(u, ctx);
  /* ★ 2026-10-12（§1.4）：逐台指令与「守护 / 换位」两个动作整条删掉 ——
     我方**只有全队方针这一层**，具体打谁全交给 `aiAction()`（它读 `ctx.方针`）。
     「大军防御 / 前守后攻的前排」那条禁令也在 `aiAction()` 里（§1.3 第 5 条）。 */
  return aiAction(u, ctx);
}

/* ---------- 一个单位行动一次 ---------- */
function actOnce(u, ctx) {
  if (u.hp <= 0) return;
  u.actedTurn = ctx.turn;              // 「再动」要知道谁这一回合已经行动过
  const action = 单位动作(u, ctx);
  let r = null;
  if (action) r = resolveAction(u, action, ctx);
  else pushLog(ctx, `${u.name} 没有能打到人的武器，跳过`, Object.assign({ 类型: '跳过', 单位: u.key }, 谁(u)));
  runAutoCast(u, ctx);                 // 被动自动释放（2026-10-11 起空转：残月的余响改成走新钩子，见下面）

  /* 近卫（方案 6.3）：击破目标后立刻再行动一次，每回合最多 1 次 */
  if (r && r.击破 > 0 && 职业是(u, '近卫') && u.近卫再动Turn !== ctx.turn) {
    u.近卫再动Turn = ctx.turn;
    ctx.again.push(u);
    pushLog(ctx, `〔连斩〕${u.name} 击破了目标，立刻再行动一次（近卫，每回合 1 次）`, Object.assign({ 类型: '连斩' }, 谁(u)));
  }
}

/* ---------- 增益：同一个来源只留一份（避免每回合叠成天文数字） ---------- */
function 换同源增益(u, src, buff) {
  u.buffs = (u.buffs || []).filter(b => b.src !== src);
  u.buffs.push(Object.assign({ src, 剩余: 1 }, buff));
}

/* ---------- 被动自动释放（`runAutoCast`） ----------
 * 2026-10-11 起**没有任何武器走这条路径**：唯一用它的「残月的余响」按作者拍板改成了
 * 「队友攻击后追加一发」——武器上的标记从 `special:'echo'` 换成 `'echoFollow'`
 * （`71-改动.js` 的 `残月余响标记`），实现在**新钩子 `势力友军攻击后`** + `72-势力.js` 的月球王国条目。
 * 这里保留这个空转的框架，留给以后别的「行动结束后自动释放」的被动
 * （例如 Iris 的「月华再生」`special:'regen'`，第一期没做）。
 * ★ 空转 = 一条记录都不写、一个数值都不改 → 没有 `echo` 武器的战斗**逐字不变**。 */
function runAutoCast(u, ctx) {
  if (u.echoTurn === ctx.turn) return;
  const pool = u.weapons.filter(e => e.t.special === 'echo' && u.lv >= e.t.unlock && e.cd <= 0);
  if (!pool.length) return;
  pool.sort((a, b) => a.t.unlock - b.t.unlock);
  const e = pool[pool.length - 1], w = e.t;
  const foes = livingOf(otherSide(u.side), ctx);
  const targets = foes.filter(t => unitRow(t) === ROW_FRONT);
  if (!targets.length) return;
  u.echoTurn = ctx.turn;
  if (w.cd) e.cd = w.cd;
  for (const t of targets) {
    if (t.hp <= 0) continue;
    const rec = resolveAttack(u, t, w, ctx, {});
    pushLog(ctx, `〔${w.name}〕${rec.文本}`, Object.assign({ 类型: '残月余响', 单位: u.key, 目标: t.key, 武器: w.name }, 谁(u), 谁目标(t), rec.字段));
    /* 击破钩子（势力特色）：这一下打死了就通知一次（战棋 `unitDestroyed` 的等价物） */
    if (t.hp <= 0) 势力击破(ctx, u, t);
  }
}

/* ---------- 结算一个动作（攻击 / 修理 / 增益 / 再动 / 防御 / 换位） ----------
   返回 { 击破: 这一下打死了几台 }，近卫的「连斩」要用。 */
function resolveAction(actor, action, ctx) {
  const w = action.weapon;
  const 空 = { 击破: 0 };

  /* Boss 蓄力（61-Boss.js）：这一回合不出手，记录已经在 bossTurn 里写好了 */
  if (action.kind === 'none') return 空;

  /* 支援①：加增益（月光祝福） */
  if (action.kind === 'buff') {
    const buff = wv(actor, w, 'buff') || w.buff || {};
    for (const t of action.targets) 换同源增益(t, w.name, buff);
    spendWeapon(actor, action.entry);
    pushLog(ctx, `${actor.name}【${w.name}】→ ${action.targets.map(t => t.name).join('、')}：${Object.entries(buff).map(([k, v]) => `${k} ${v > 0 ? '+' : ''}${v}`).join('、')}（到本回合结束）`,
      Object.assign({ 类型: '增益', 单位: actor.key, 武器: w.name, 目标: action.targets.map(t => t.key), 目标位们: action.targets.map(t => t.slot), 目标方们: action.targets.map(t => t.side) }, 谁(actor)));
    return 空;
  }

  /* 支援②：再动 */
  if (action.kind === 'grant') {
    const t = action.target;
    t.grantedTurn = ctx.turn;
    ctx.again.push(t);
    spendWeapon(actor, action.entry);
    pushLog(ctx, `${actor.name}【${w.name}】→ ${t.name}：再行动一次`, Object.assign({ 类型: '再动', 单位: actor.key, 目标: t.key }, 谁(actor), 谁目标(t)));
    return 空;
  }

  /* 防御（方案第 4 节）：不攻击；本回合受到的伤害按防御值 +50 结算；下回合开始回复 5% 最大 HP */
  if (action.kind === 'defend') {
    actor.defending = true;
    actor.防御回复 = true;
    if (气势总攻开() && actor.side === 'ally') {
      const c = 气势总攻参数();
      const 每台 = Number(c.防御每台加) || 15;
      const 上限 = Number(c.防御每回合上限) || 45;
      const 已加 = Number(ctx.本回合防御气势) || 0;
      const 实加 = Math.max(0, Math.min(每台, 上限 - 已加));
      if (实加 > 0) {
        ctx.本回合防御气势 = 已加 + 实加;
        ctx.累计防御气势 = (Number(ctx.累计防御气势) || 0) + 实加;
        加气势(ctx, 实加);
      }
    }
    /* ★ 2026-10-12（三层反馈 · 第 2 件）：记录**文本一个字都没改**（§1.3 第 4 条那两句），
       只在不是「全军突击」时多一个 `方针` 字段 —— 战报要按方针把「进入防御」算进那一行。 */
    pushLog(ctx, `${actor.name} 进入防御（本回合伤害按防御 +50 结算，下回合开始回复 5% HP）`,
      Object.assign({ 类型: '防御' }, 谁(actor), 当前方针(ctx).类型 !== '全军突击' ? { 方针: 当前方针(ctx).类型 } : null));
    return 空;
  }

  /* ★ 2026-10-12（§1.4）：**战斗中不再有换位**（`kind:'swap'` 动作与 `〔换位〕` 记录整条删掉）。
     编队界面的摆位照旧（`05-阵型.js` 的几何 / `相邻位()` / `对位()` 一个字节没动）。 */

  if (action.kind === 'heal') {
    const amount = healAmount(actor, w);
    const before = action.target.hp;
    action.target.hp = Math.min(action.target.maxHp, action.target.hp + amount);
    spendWeapon(actor, action.entry);
    pushLog(ctx, `${actor.name} 修理 ${action.target.name}，回复 ${action.target.hp - before}`, Object.assign({
      类型: '修理', 单位: actor.key, 目标: action.target.key, 武器: w.name, 回复: action.target.hp - before, 目标剩余HP: action.target.hp,
    }, 谁(actor), 谁目标(action.target)));
    /* ★ 2026-10-11 新加的势力钩子 `势力修理(ctx, 修理者, 被修的那台, 武器, 回复)`（框架第 17 个，`72-势力.js`）：
       触发时机 = **血已经加上去、`spendWeapon()` 之后**。
       第一条用它的是**月球王国的「战地急救」**（Iris）：修完给被修的那台挂「防御 +15」
       （战棋 `17-战斗执行.js:268` 的 `if (hasTrait(u,'fieldAid')){ t.buffs.push({src:'战地急救', def:15}); … }`）。
       ★ 没有势力条目 / 条目没写这个钩子 → 空循环，**修理的数值与记录逐字不变**。 */
    势力修理(ctx, actor, action.target, w, action.target.hp - before);
    return 空;
  }

  /* 攻击（含范围）：一次打落点上的所有敌人，或打单个目标 */
  const kind = rangeKindOf(w);
  const targets = isAreaKind(kind) ? (action.hit || []) : [action.target];
  /* 站桩 Boss 脚本（61-Boss.js）：这一阶段的伤害倍率（没配脚本 = 1）。
     ★ 2026-10-12（§1.4）：原来的「守护者自己攻击 ×0.7」（`守护方`）随守护机制一起删了 ——
       这个口子上现在只剩 Boss 阶段倍率 × 势力伤害倍率，没有那条 0.7。 */
  /* ★ 势力特色 · **伤害倍率**（框架第 10 个数值钩子，`72-势力.js` 的 `势力伤害倍率()`；2026-10-11 新加）：
     和上面两个倍率**挤在同一个口子**里相乘 —— 作用在**公式算完之后**的逐段伤害上。
     ★ 2026-10-11 作者拍板「天人的 ×1.3 **挪到威力**」之后，这个口子上**已经没有势力在用了**
     （天人搬到了下面的 `威力倍率`）—— 钩子留着（后续势力随时可以用），恒 1。
     没有势力条目 / 倍率是 1 → `倍率` 与改动前**逐字相同**（`1 * 1`）。 */
  const 总攻倍 = (气势总攻开() && ctx && ctx.当前战术 === '总攻' && actor.side === 'ally')
    ? (Number(气势总攻参数().总攻伤害倍率) || 1.35) : 1;
  const 倍率 = Boss伤害倍率(actor) * 势力伤害倍率(actor, w) * (actor.调参伤害倍率 || 1) * 总攻倍;
  /* ★ 势力特色 · **武器威力倍率**（框架第 14 个数值钩子，`72-势力.js` 的 `势力威力倍率()`；
     作者 2026-10-11 拍板把天人的 ×1.3 挪到这里）—— 一路传进 `resolveAttack()`，
     **乘在 `wv(att,w,'power')`（武器威力）上、进 `dmgCore()` 之前**，
     和战棋 `15-战斗计算.js:36` 的 `wPow = round(wv(...) * taPowMul(u))` 同一个落点。
     没有势力条目 / 倍率是 1 → 传下去的是 1，威力与改动前逐字相同。 */
  const 威力倍率 = 势力威力倍率(actor, w);
  let 击破 = 0;
  /* ★ 2026-10-12（三层反馈 · 第 2 件，§2.2「即时」列）：这一发是在哪条方针下打出来的。
     ⚠ **只看我方出手**（`actor.side === 'ally'`）——三条理由：
       ① 这三条反馈讲的是**玩家的决策**，敌方那一发不是玩家下的；
       ② **格子号是分边的**（我方「位 0」和敌方「位 0」是两个格子）：要是拿 `实际.slot === 点名位`
          去认，敌方打我方位 0 的那一下会被误标成「集中」；
       ③ 默认路径（全军突击）下三个字段一个都不写 → 记录**逐字节不变**（§1.8 第 1 条继续成立）。
     点名的目标用**对象身份**比（`实际 === 点名目标`），比格子号更稳：被嘲讽勾走 / 增援换人都不误报。 */
  const 我方出手 = actor.side === 'ally';
  const 当时方针 = 我方出手 ? 当前方针(ctx).类型 : '全军突击';
  const 点名目标 = (我方出手 && 当时方针 === '集中攻击') ? 方针目标(ctx) : null;

  for (const t of targets) {
    if (t.hp <= 0) continue;
    let 实际 = t;

    if (!isAreaKind(kind)) {
      /* ★ 2026-10-12（§1.3 第 6 条）：**守护整条机制已删**（替队友挨打 + `守护方 = 0.7` + `〔守护〕` 记录）。
         这里只剩**重装嘲讽**（方案 6.3，双方都走同一条，见 `嘲讽()` 的注释）——
         它现在接手了原来「守护」的保护作用。嘲讽没勾到人时一次随机数都不消耗（顺序没变）。 */
      const 嘲 = 嘲讽(ctx, actor, t);
      if (嘲) {
        pushLog(ctx, `〔嘲讽〕${嘲.name} 把这一击勾了过去`, Object.assign({ 类型: '嘲讽', 目标: 嘲.key, 原目标: t.key }, 谁(嘲), 谁目标(嘲)));
        实际 = 嘲;
      }
    }

    const 血 = 实际.hp;
    /* 被挡（作者 2026-10-10 拍板改成**按位**）：看**实际目标这一位**的阻挡位里还有没有活人。
       近战够不够得着由 AI 那边按 `rowReachable` 过滤，这里只管直射的 −20。 */
    const 活位 = livingOf(实际.side, ctx).map(x => x.slot);
    const blockPenalty = isAreaKind(kind) ? 0 : rowBlockPenalty(kind, 实际.slot, 活位, actor, 实际);
    /* ★ 2026-10-11 新加的势力钩子 `势力攻击前(ctx, 攻击者, 目标, 武器)`（框架第 13 个，`72-势力.js`）：
       触发时机 = **这一发真的结算之前**（逐目标、`resolveAttack()` 之前、`spendWeapon()` 还没走）。
       第一条用它的是**秘银**：作战岗在这里**兑现**情报岗挂的标定（把 `debuffs` 里的 `pct` 打开）——
       破防必须先挂到目标身上，这一发自己才吃得到；写到 `势力友军攻击后` 就晚了（那是伤害算完之后）。
       ★ 没有势力条目 / 条目没写这个钩子 → 框架里是空循环，**公式与记录逐字不变**；
         实现里**不许消耗 `ctx.rng`**（在这个位置上动随机数会改整场结果）。 */
    势力攻击前(ctx, actor, 实际, w);
    const rec = resolveAttack(actor, 实际, w, ctx, { blockPenalty, 伤害倍率: 倍率, 威力倍率 });
    const 打死了 = 血 > 0 && 实际.hp <= 0;
    if (打死了) 击破++;
    /* ★ 2026-10-12：记录里**保留**四个旧字段、值恒为默认（`集火:false` / `守护挡下:false` /
       `原目标:null` / `原目标位:null`）—— 旧机制（集火指令 / 守护替人挨打）已经删了（§1.4），
       所以它们再也取不到别的值；留着是为了让记录格式**一个字节都不变**：
       §1.8 第 1 条「默认路径逐字不变」是硬验收，改前跑的那份快照里这四个字段就在每一条攻击记录上
       （全 39 场、1638 条里一个 true / 非 null 都没有，见任务板的实测数字）。
       要「打进谁」看 `目标` / `目标位`；要「为什么打它」看 `单位方` + 当时的全队方针。
       ★★ 2026-10-12（三层反馈 · 第 2 件，§2.2「即时」列）：**新加的字段同样只在「真的用得上」时才写** ——
        「全军突击」下三个字段一个都不出现（默认路径的记录因此**逐字节不变**，§1.8 第 1 条继续成立）：
          · `方针`（整个字符串）—— 这一发是在哪条方针下打出来的（回退到自由攻击时也照写当时的方针）；
          · `集中: true` —— 这一发落在「集中攻击」点名的**那一位**上（被嘲讽勾走的**不算**：
            实际打的是另一台，界面不会误报「集中」）；
          · `被挡: true` + `被挡惩罚: −20` —— 直射打被挡的后排位（§2.2 第 3 行的「被挡 −20 就沿用已有的」；
            只有在下过方针的回合里才写 —— 默认路径一个字节都不动）。
        「防御少挨了多少」不在这里：它由 `resolveAttack()` 按 §2.4 算好放进 `rec.字段`。 */
    const 反馈字段 = {};
    if (当时方针 !== '全军突击') 反馈字段.方针 = 当时方针;
    if (点名目标 && 实际 === 点名目标) 反馈字段.集中 = true;
    if (blockPenalty < 0 && 当时方针 !== '全军突击') { 反馈字段.被挡 = true; 反馈字段.被挡惩罚 = blockPenalty; }
    pushLog(ctx, rec.文本, Object.assign({ 类型: '攻击', 单位: actor.key, 目标: 实际.key, 武器: w.name, 集火: false, 守护挡下: false, 原目标: null, 原目标位: null }, 谁(actor), 谁目标(实际), rec.字段, 反馈字段));
    /* ★ 2026-10-13 **标定经济 · 即时（连锁日志）**：狙击真的兑现了标定 → 在**这一条攻击记录之后**
       紧跟一条连锁日志：`A 的标定 → B 引爆 5292!`（`!` 只在**把目标打掉**时加）+ 一张记录
       （`类型:'标定'`，带 `引爆方 / 引爆位` 与产标者，界面靠它给**两张卡**加 `标定闪框` 那个类）。
       ★ 引爆那一下的**伤害已经算进上面的攻击记录**了（`标定经济` 只改那几段的伤害，不另发一条伤害），
         所以这一条只是「说清楚刚才发生了什么」—— 战报读的也是它的 `标定伤害`（额外伤害合计）。
       ★ 没有标定 / 没有暴击 / 开关关掉 → `rec.字段.标定` 不存在 → 这一行什么都不做（记录逐字不变）。 */
    标定经济记录(ctx, actor, 实际, { 类型: '攻击', 武器: w.name }, rec.字段 && rec.字段.标定);
    /* ★ 2026-10-12（三层反馈 · 第 2 件，§2.2「即时」列）：**集中攻击的那一下把目标打死了** ——
       紧接着这条攻击记录写一条 `〔方针〕集中攻击击破 X`（玩家看得见「这个决定刚刚兑现了」）。
       判定用**对象身份**：只有真的打在点名那一台上才算（被嘲讽勾走 / 打的是别人 → 不写）。
       `类型: '方针'` 是现成的类型，界面按系统行画。
       ★ 这条**只写记录**：不改任何数值、不消耗随机数、也不影响「下一回合开始自动回全军突击」
         （那一步在 `方针回合()` 里，照旧）。 */
    if (打死了 && 点名目标 && 实际 === 点名目标) {
      pushLog(ctx, `〔方针〕集中攻击击破 ${实际.name}`, {
        类型: '方针', 事件: '集中攻击击破', 方针: '集中攻击', 原方针: null,
        单位: actor.key, 目标: 实际.key, 目标位: 实际.slot, 目标名: 实际.name, 武器: w.name, 回合: ctx.turn,
      });
    }
    /* 击破钩子（势力特色，框架在 `72-势力.js`；战棋 `unitDestroyed` 的等价物）：
       写在这一条攻击记录**之后**，记录里就能读到「谁打死了谁」。
       `势力击破()` 自己会判双方阵营（敌人击破我方时，卫星国防军 SEED 不会涨）。 */
    if (打死了) 势力击破(ctx, actor, 实际);
    /* ★ 2026-10-12（敌人卡第一批 · 钩子 `selfDestruct` = 卡 C「献祭者」）：**被击破的瞬间**对落点打一发
       （【初稿】威力 = 它主武器威力 × 1.5、落点 = `col` 阻挡束、必中、不消耗随机数）。
       放在 `势力击破()` **之后**（死亡事件的通知先走完）、`势力友军攻击后()` **之前**
       —— 死亡触发的效果归在「死亡」那一刻，而「我队友攻击后」讲的是攻击者那一方的反应。
       没有这个键的单位：`自爆()` 立刻返回 null（行为一个字节都不变）。 */
    if (打死了) 自爆(ctx, actor, 实际);
    /* ★ 2026-10-11 新加的势力钩子 `势力友军攻击后(ctx, 攻击者, 目标, 一击)`：
       触发时机 = **我方队友一次攻击真的造成伤害之后**（就在这一条攻击记录与 `势力击破()` 之后）。
       参数 `一击` = 这一下的记录字段（`伤害 > 0` 才算「造成伤害」；未命中不触发）。
       第一件用它的是**月球王国**：队友攻击后 Feena 追加一发「残月的余响」（`72-势力.js`）。
       ★ 没有势力条目 / 条目没写这个钩子 → 框架里是空循环，**公式与记录逐字不变**；
         追加的那一发在实现里自己走 `resolveAttack()`，**不会再回头触发这个钩子**（不连锁）。 */
    if (rec.字段.伤害 > 0) 势力友军攻击后(ctx, actor, 实际, rec.字段);
    /* ★ 2026-10-12（敌人卡第一批 · 钩子 `beamReflect` = 卡 B「镜甲」）：这一发**真的打出了伤害**、
       而目标带着镜甲 → **按比例反弹给攻击者**（【初稿·待作者调】受到的 30%）。
       ① **位置**：放在这一发**全部**结算完（攻击记录 / 击破记录 / 势力钩子都跑过）之后 ——
          实测里没有别的线夹在中间时，它就是紧跟着攻击记录的那一行（玩家看到「这一下疼了，我自己也疼了」）；
          放在最后还有一个好处：**反弹把攻击者打死**时，前面那些钩子看到的是「这一发打完了」的干净状态。
       ② **一个随机数都不消耗**（直接扣 HP，不走 `resolveAttack()`）→ 同一次攻击的随机数消耗顺序
          与改动前**逐字相同**（`tests/boss.js` 有 rng 调用次数对照）。
       ③ 没有镜甲敌人的战斗：`镜甲反弹()` 第一行就返回 0，**一个字段都不多**。
      ★ 2026-10-13：第 5 个参数把**这一发的武器**传下去 —— 词条键 `反弹` 的 `仅近战`（`2-EE`）要判射程。 */
    if (rec.字段.伤害 > 0) 镜甲反弹(ctx, actor, 实际, rec.字段, w);
  }
  spendWeapon(actor, action.entry);
  /* ★ 2026-10-11 新加的势力钩子 `势力武器用后(ctx, 使用者, 条目, 武器)`（框架第 12 个，`72-势力.js`）：
     触发时机 = **这一把武器真的打出去了**、普通冷却刚设上（`spendWeapon()` 之后，只有「攻击」走得到这里）。
     战棋的等价物是 `strikeResolved`（`17b-角色机制.js:87-91` 的 `evadeCdCut` 就在那个时机算，
     而且那里的 `consume(w)` 也是出手一开始就把冷却设好）→ 第一条用它的是 **ATX**（余量一次性抵冷却）。
     ★ 没有势力条目写它 → 空循环，一个字节都不变。 */
  势力武器用后(ctx, actor, action.entry, w);
  return { 击破 };
}

