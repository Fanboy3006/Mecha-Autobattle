function 连射残心(att, w, pt) {
  if (!att || att.side !== 'ally') return 0;
  const 段表 = 月球残心参数(pt);
  if (!是连射武器(w, 段表)) return 0;
  return 连射步长(att, w, 段表);
}
/** 把各种写法的「连射残心参数」归一化成那一段参数表（`71-改动.js` 里那一个对象）。 */
function 月球残心参数(pt) {
  if (!pt || typeof pt !== 'object') return 月球参数().连射残心 || {};
  if (pt.连射残心 && typeof pt.连射残心 === 'object') return pt.连射残心;   // 传了整张 势力特色.月球王国
  if (pt.残心步长 != null || pt.连射段数 != null || pt.武器特技 != null) return pt;   // 传的就是那一段
  return 月球参数().连射残心 || {};
}

