/** 月球王国的参数（`71-改动.js` 的 `势力特色.月球王国`）。 */
const 月球参数 = () => 势力参数('月球王国');
/** 光环挂出来的那条 buff 的来源名（判定成立就挂、不成立按这个来源摘掉，同源只留一份）。 */
const 月球光环来源 = '势力·月球王国';
/** 这台机体带不带「月光共鸣」（Feena 的 `trait`，按数据查，**不手写角色键**）。
 *  ★ 只认**我方**（`side === 'ally'`）：和框架「只对我方生效」那一条一致 ——
 *    把 `trait: 'autoCast'` 挂到敌人身上也不会被认成光环的施与者。 */
const 有月光共鸣 = (u, p) => !!(u && u.side === 'ally' && u.trait === ((p || 月球参数()).光环特技 || 'autoCast'));
/** 这把武器是不是「队友攻击后追加」的那一发（`71-改动.js` 换机制时打的标记）。 */
const 是残月武器 = w => !!(w && w.友军攻击后追加);

/** 光环给的那几个数：**直接读数据里那把「月光祝福」**（`wv()` 按等级取 Lv20 / Lv30 那一档）。
 *  出处 `10-数据.js:53-55` ← 战棋 `04-武器与机体.js:34-35`；读不到（数据换名字了）→ 返回空对象。 */
function 月光祝福数值(u, p) {
  const 名 = (p || 月球参数()).光环武器 || '月光祝福';
  const w = ((u && u.weapons) || []).map(e => (e && e.t) || e).find(x => x && x.name === 名);
  if (!w) return {};
  return Object.assign({}, wv(u, w, 'buff') || w.buff || {});
}
/** 这几个数的中文写法（记录 / 单位卡用；顺序固定，方便对账）。 */
const 光环属性名 = { hit: '命中', eva: '闪避', def: '防御', crit: '暴击' };
const 光环文字 = 数 => ['hit', 'eva', 'def', 'crit'].filter(k => 数 && 数[k])
  .map(k => `${光环属性名[k]} +${数[k]}`).join('、') || '（没有数值）';

/** 光环的**受益人**：Feena 的 `相邻位(位)` 上活着的**我方**单位（不含 Feena 自己）。
 *  `光环只要同势力: true` 时收窄成「只有月球王国的人」；默认 `false` = 我方任意队友
 *  （与战棋「月光祝福：友军（不含自己）」、流星小队「队友不看势力」两条先例一致）。 */
function 月球光环受益(f, ctx, p) {
  const 参 = p || 月球参数();
  const 位们 = new Set(相邻位(f.slot));
  const 候选 = livingOf('ally', ctx).filter(t => t !== f && 位们.has(t.slot));
  return 参.光环只要同势力 ? 候选.filter(t => 是我方势力(t, '月球王国')) : 候选;
}

/** 重算「月光环绕」（**开局 / 每回合开始 / 有人被击破时各调一次**，和流星小队同一个做法）。
 *  写两份：① `u.势力状态.月球王国` 的判定缓存（`光环数值` / `光环名单` / `光环位`）—— **单位卡读它**
 *            （数值钩子的签名拿不到 ctx，只能由带 ctx 的生命周期钩子算好）；
 *         ② 受益人身上那条 buff —— **数值走现成公式**（命中 / 闪避 / 暴击 / 防御）。
 *  ★ 只在判定结果**变了**的时候写一行 `〔势力〕` 记录（每回合都写会刷屏；没变就不写）。 */
function 判定月球王国光环(ctx, p) {
  if (!ctx) return;
  const 参 = p || 月球参数();
  /* 先摘掉全场我方身上的这一条 buff：受益人走了 / Feena 倒了 / 整个势力关掉，都要真的摘干净 */
  for (const u of livingOf('ally', ctx)) u.buffs = (u.buffs || []).filter(b => b.src !== 月球光环来源);
  for (const f of 势力在场('月球王国', ctx).filter(u => 有月光共鸣(u, 参))) {
    const 状 = 势力状态(f, '月球王国');
    const 数 = 月光祝福数值(f, 参);
    const 受益 = 月球光环受益(f, ctx, 参);
    状.光环数值 = 数;
    状.光环名单 = 受益.map(u => u.key);
    状.光环位 = 受益.map(u => u.slot);
    for (const t of 受益) t.buffs.push(Object.assign({ src: 月球光环来源, 剩余: 1 }, 数));
    const 签名 = JSON.stringify([f.slot, 数, 状.光环位]);
    const 变了 = 状.光环签名 !== 签名;
    状.光环签名 = 签名;
    if (!变了) continue;
    const 面 = 相邻位(f.slot).map(位名).join('、') || '（没有相邻位）';
    势力记录(ctx, 受益.length
      ? `月球王国 ${f.name} 的月光环绕：相邻位（${面}）上的队友 ${受益.map(u => `${位名(u.slot)} ${u.name}`).join('、')} 吃到 ${光环文字(数)}`
      : `月球王国 ${f.name} 的月光环绕：相邻位（${面}）上没有队友，这一条不生效`,
      {
        势力: '月球王国', 特色: '月光环绕', 结果: 受益.length ? '生效' : '失效',
        单位: f.key, 单位方: f.side, 单位位: f.slot, 相邻位: 相邻位(f.slot),
        受益: 受益.map(u => u.key), 受益位: 受益.map(u => u.slot), 数值: 数,
      });
  }
}

/** 这把残月武器**现在能不能被「追加」选中**（★ 2026-10-13 主动攻击补强的等级门）：
 *  · 「残月的余响」的属性已被 `71-改动-1-角色与Boss.js` **就地**改成 `unlock = 残月解锁等级`（初稿 10），
 *    原始门（数据里的 20）抄在 `残月原始unlock` 上；
 *  · 等级门一律问 `残月武器运行期解锁()`：
 *    `战斗结构.Feena主动攻击.开 === false` → 它返回**原始门 20**（→ Lv10 的 Feena 追不了，**与改前逐字相同**）；
 *    `开 !== false` → 返回**下放后的 10**（→ Lv10 就能追，这是这次补强的目的）。
 *  ★ 「满月·月蚀」的解锁等级是数据的 30，两种状态下都照旧。 */
function 残月可追加(f, e) {
  if (!f || !e || !e.t) return false;
  return f.lv >= 残月武器运行期解锁(e.t);
}

/** Feena 这一回合用来「追加一发」的武器：面板上带 `友军攻击后追加` 标记、等级够（`unlock`）、
 *  不在普通冷却里（`cd`）、开场冷却也过了（`readyTurn`）；有多把时取 `unlock` **最高**的那把
 *  —— 和数据原话「满月·月蚀 冷却好时代替残月的余响自动释放」一致。没有 → `null`（不追）。
 *  ★ 2026-10-13（主动攻击补强 · **协同不断档**）：Feena 自己主动出手之后，`满月·月蚀` 会进 `cd`（3 回合），
 *    这时上面那道 `e.cd <= 0` 会把它滤掉 → 池子里自然回落到 `残月的余响`（数据里 `cd: 0`，永远就绪）。
 *    这条**在改动之前也是同一句代码**（改前满月·月蚀只在 Lv30 出现、且 Feena 从不主动用武器，
 *    所以从来没走到过）—— 现在它成了「主动出手之后追加照旧不断档」的那条路，故在这里写明。 */
function 残月武器(f, ctx, p) {
  const 回 = ctx && ctx.turn != null ? ctx.turn : 0;
  const pool = ((f && f.weapons) || []).filter(e => e && e.t && 是残月武器(e.t)
    && 残月可追加(f, e) && e.cd <= 0 && (e.readyTurn == null || e.readyTurn <= 回));
  if (!pool.length) return null;
  /* 排序也走**运行期解锁**（关 = 数据里的 20/30、开 = 残月的余响 10/满月·月蚀 30）→
     「满月·月蚀 冷却好时代替残月的余响」这条规律在开关两种状态下都成立。 */
  pool.sort((a, b) => 残月武器运行期解锁(a.t) - 残月武器运行期解锁(b.t));
  return pool[pool.length - 1];
}

/** 「残月的余响」：**我方队友造成伤害之后**追加一次攻击（陨石）。返回这一发真的打了多少伤害（0 = 没触发）。
 *  触发点 = 新钩子 `势力友军攻击后`（`60-战斗.js` 的 `resolveAction()`）。
 *  顺序（决定性的，随机数只走 `ctx.rng`）：
 *    ① 只认「我方打敌方」的**队友**（`有月光共鸣` 的那台自己打的不算 —— 作者的话是「队友攻击时」）；
 *    ② `一击.伤害 > 0` 才算「造成伤害」；
 *       ★ 目标已经倒下 → **换一台活着的敌机**（作者 2026-10-11 拍板「改砸别的敌人」；挑法见下面代码：
 *         剩余 HP 比例最低的活敌，并列取位号小的）；**没有活敌 → 不追，也**不占**这一回合的次数；
 *    ③ **每回合上限**（常量，初稿 1）：写在 Feena 的 `势力状态.月球王国.追加回合 / 追加次数` 上，
 *       回合号一变就归零；到上限直接返回 0；
 *    ④ 追加的那一发走**现成公式** `resolveAttack()`（必中 / 不暴击 / 走完整减免管线，和以前一样），
 *       用掉普通冷却（`满月·月蚀` 的 cd 3）；
 *    ⑤ 写一行 `〔势力〕…追加一发…` 记录（`类型` 沿用早就有的 `'残月余响'`，**记录格式没有改**），
 *       这一发把目标打死也照常通知 `势力击破()`（和 `runAutoCast()` 一样）。 */
function 残月追加攻击(ctx, 攻击者, 目标, 一击, p) {
  const 参 = p || 月球参数();
  if (!ctx || !攻击者 || !目标) return 0;
  if (攻击者.side !== 'ally') return 0;                 // 只认我方队友（敌人打我方不触发）
  if (目标.side === 攻击者.side) return 0;              // 只认「打敌方」
  if (!(一击 && 一击.伤害 > 0)) return 0;               // 「造成伤害之后」（未命中不算）
  if (有月光共鸣(攻击者, 参)) return 0;                 // ★ 不含 Feena 自己
  /* ★ 作者 2026-10-11 拍板（看板第 5 节第 5 条「**B：改砸别的敌人**」；原文「队友打的那台倒了 →
     换一台活着的敌机」）—— 上一版是「目标已经倒下 → 不追」，现在改成**换一台活着的敌机**。
     ★ 挑法（这一版我们定的口径，写清楚）：**原目标若已倒下，就选剩余 HP 比例最低的活敌**
       （`hp / maxHp` 最小；并列时取**位号小**的 —— 决定性、同种子可复现）；
     ★ **没有活敌 → 不追、也不消耗这一回合的次数**（直接返回 0，下面的 `追加次数++` 走不到）。 */
  let 原目标 = null;
  if (目标.hp <= 0) {
    const 活敌 = livingOf('enemy', ctx).filter(u => u.hp > 0)
      .sort((a, b) => ((a.hp / Math.max(1, a.maxHp)) - (b.hp / Math.max(1, b.maxHp))) || (a.slot - b.slot));
    if (!活敌.length) return 0;                         // 没有活敌 → 不追、不占次数
    原目标 = 目标; 目标 = 活敌[0];                        // 换成剩余 HP 比例最低的那台活敌
  }
  const 菲娜 = 势力在场('月球王国', ctx).filter(u => 有月光共鸣(u, 参)).find(u => 残月武器(u, ctx, 参));
  if (!菲娜) return 0;
  const 状 = 势力状态(菲娜, '月球王国');
  if (状.追加回合 !== ctx.turn) { 状.追加回合 = ctx.turn; 状.追加次数 = 0; }
  const 上限 = Math.max(0, Number(参.残月余响每回合上限) || 0);
  if (状.追加次数 >= 上限) return 0;                    // ★ 每回合上限（初稿 1 次）
  const 挑 = 残月武器(菲娜, ctx, 参);
  if (!挑) return 0;
  状.追加次数++;
  const rec = resolveAttack(菲娜, 目标, 挑.t, ctx, {});
  if (挑.t.cd) 挑.cd = 挑.t.cd;                         // 用掉一次普通冷却（满月·月蚀 cd 3）
  势力记录(ctx, `${菲娜.name} 的残月的余响：队友【${攻击者.name}】攻击后追加一发【${挑.t.name}】→ ${目标.name}`
    + `${原目标 ? `（原目标 ${原目标.name} 已倒下 → 改砸剩余 HP 比例最低的活敌）` : ''}：`
    + `${rec.字段.伤害} 伤害（本回合第 ${状.追加次数}/${上限} 次）`,
    Object.assign({
      类型: '残月余响', 势力: '月球王国', 特色: '残月的余响', 队友: 攻击者.key,
      单位: 菲娜.key, 单位位: 菲娜.slot, 目标: 目标.key, 武器: 挑.t.name,
      本回合第几次: 状.追加次数, 每回合上限: 上限,
      原目标: 原目标 ? 原目标.key : null, 换目标: !!原目标,
    }, 谁(菲娜), 谁目标(目标), rec.字段));
  if (目标.hp <= 0) 势力击破(ctx, 菲娜, 目标);          // 这一发打死也通知一次（和 runAutoCast 一样）
  /* ★ P1.2 §1.3：**战况计数**（战术卡牌条件触发用）—— 「残月的余响」真的追加了一发 → 当场 +1。
     关牌（`ctx.战况计数` 不存在）时空转，数值与记录逐字不变。 */
  if (ctx.战况计数) ctx.战况计数.残月或月国命中++;
  return rec.字段.伤害;
}

