const 调参防御加成范围 = { 最小: 0, 最大: 500, 步: 5 };
const 调参回合上限范围 = { 最小: 0, 最大: 30, 步: 1 };      // 0 = 默认（照引擎自己那套）
const 调参场次们 = [20, 100, 200];
const 调参默认场次 = 100;
