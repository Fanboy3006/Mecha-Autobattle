/** 单位卡上的那一行字（`80-界面.js` 的单位卡读它）：一个势力一段，用 ` · ` 拼；
 *  **没有势力特色的单位 = 空串**（界面什么都不多画）。
 *  ★ 默认只问「本单位属于这个势力」的条目（前三件照旧，一个字节不变）；
 *    写了 `卡行所有人: true` 的条目**对任何我方单位**都会被问一次 —— 它自己负责在「没吃到」时返回空串
 *    （月球王国的「月光环绕」照到别势力的队友时，那个队友的卡上也要看得出吃到了）。 */
function 势力卡行(u) {
  if (!u || u.side !== 'ally') return '';
  const 段 = [];
  for (const 势力 of 启用势力们()) {
    const 条 = 势力特色表[势力];
    if (!条.卡行) continue;
    if (!是我方势力(u, 势力) && !条.卡行所有人) continue;
    const s = 条.卡行(u, 势力参数(势力));
    if (s) 段.push(s);
  }
  return 段.join(' · ');
}

