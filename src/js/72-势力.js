/* ---------- 势力判断（数据来源：10-数据.js 的 ALLY_T[].tags.势力） ---------- */
const 势力名 = u => (u && u.tags && u.tags.势力) || null;
/** 这个单位是不是「我方 + 这个势力」。★ 势力特色**只对我方生效**（敌人按梯队）。
 *  ★ 只认 `tags.势力`（任务书要求「以 10-数据.js 的 tags.势力 为准」）；战棋的 `inFaction()`
 *    还认 `tags.副势力`（拉米亚 A3 的双势力，10-数据.js:218），以后做 ATX 那条线要认副势力时，
 *    **只改这一个函数**就够（现在不动，免得别的势力被算进来）。 */
const 是我方势力 = (u, 势力) => !!u && u.side === 'ally' && 势力名(u) === 势力;

/* ---------- 注册表（一个势力一条） ---------- */
const 势力特色表 = {};

/** 注册一个势力的特色（后面 5 个势力都从这里进）。返回登记好的条目。 */
function 注册势力特色(势力, 条目) {
  势力特色表[势力] = Object.assign({ 势力, 启用: true }, 条目);
  return 势力特色表[势力];
}

/** 这个势力的参数（`71-改动.js` 的 `势力特色[势力]`）；没配 = `{}`（条目里的默认值生效）。 */
const 势力参数 = 势力 => (势力特色 && 势力特色[势力]) || {};

/** 这一套现在开着吗：参数表或条目里写 `启用: false` 就整套关掉（方便做「不带 vs 带」的对照）。 */
const 势力启用 = 势力 => {
  const 条 = 势力特色表[势力];
  return !!条 && 条.启用 !== false && 势力参数(势力).启用 !== false;
};

/** 现在真正生效的势力名（顺序 = 注册顺序，结果决定性；同种子两次一样）。 */
const 启用势力们 = () => Object.keys(势力特色表).filter(势力启用);

/** 单位上的**本场势力状态**（`u.势力状态[势力]`）：换场归零 —— 单位每场都是新造的
 *  （`makeUnit()`），本来就干净；要显式清零的势力在自己的 `开局` 钩子里清。 */
function 势力状态(u, 势力) {
  if (!u.势力状态) u.势力状态 = {};
  if (!u.势力状态[势力]) u.势力状态[势力] = {};
  return u.势力状态[势力];
}

/** 我方阵营里属于这个势力的**活着的**单位（成员按数据查，不手写名单）。 */
const 势力在场 = (势力, ctx) => livingOf('ally', ctx).filter(u => 是我方势力(u, 势力));

/* ---------- 写记录（统一 〔势力〕 前缀） ---------- */
/** 势力特色写一行记录。格式还是原来的 `pushLog(ctx, 文本, 字段)`（`类型: '势力'` 只是多一个字段），
 *  界面沿用原来的记录渲染，**记录格式没有改**。 */
function 势力记录(ctx, 文本, 字段) {
  if (!ctx) return;
  pushLog(ctx, `〔势力〕${文本}`, Object.assign({ 类型: '势力' }, 字段 || {}));
}

/* ---------- 三个生命周期钩子 ---------- */
function 势力开局(ctx) {
  for (const 势力 of 启用势力们()) {
    const 条 = 势力特色表[势力];
    if (条.开局) 条.开局(ctx, 势力参数(势力));
  }
}
function 势力回合开始(ctx) {
  for (const 势力 of 启用势力们()) {
    const 条 = 势力特色表[势力];
    if (条.回合开始) 条.回合开始(ctx, 势力参数(势力));
  }
}
function 势力回合结束(ctx) {
  for (const 势力 of 启用势力们()) {
    const 条 = 势力特色表[势力];
    if (条.回合结束) 条.回合结束(ctx, 势力参数(势力));
  }
}
/** 单位被击破时（`resolveAction` / `runAutoCast` 里刚把 HP 打到 0 的那一刻）。
 *  「谁被谁击破」都传进来，各家自己判（例如 SEED 只在**卫星国防军**击破敌机时涨）。 */
function 势力击破(ctx, 击破者, 被击破者) {
  if (!ctx || !击破者 || !被击破者) return;
  for (const 势力 of 启用势力们()) {
    const 条 = 势力特色表[势力];
    if (条.击破) 条.击破(ctx, 击破者, 被击破者, 势力参数(势力));
  }
}

/** ★ **2026-10-11 新加的钩子**（第 9 个）：**我方队友一次攻击真的造成伤害之后**。
 *  触发时机（`60-战斗.js` 的 `resolveAction()`，写死在那里）：
 *    `resolveAction()` 对**每一个目标**结算完 —— 攻击记录写过、`势力击破()` 也跑过之后；
 *    触发条件是这一下 `一击.伤害 > 0`（未命中 / 伤害 0 不算「造成伤害」）。
 *  参数（4 个）：
 *    `攻击者` —— 造成伤害的那台（**只在我方 `side === 'ally'` 时才会被调**；敌人打我方不走这里）；
 *    `目标`   —— 实际挨打的那台（**重装嘲讽**把这一击勾走时是那一台，和攻击记录里的「实际」一致）；
 *    `一击`   —— 这一下的记录字段：`{命中, 伤害, 段数, 命中段数, 暴击, 目标剩余HP, 详情}`；
 *    返回值**不参与引擎判断**（各家自己决定要不要做事；★ 2026-10-11 起本函数把各条目的返回值**加起来返回**，
 *    引擎侧不看它、只给测试 / 平衡工具读数，没有条目写这个钩子 → 恒 0）。
 *  第一条用它的是**月球王国**：队友攻击后 Feena 追加一发「残月的余响」（陨石）。
 *  ★ **没有势力条目 / 没有条目写这个钩子 → 这里什么都不做**（`启用势力们()` 是空循环）：
 *    `resolveAction()` 只多了一次空调用，**伤害公式与记录逐字不变**。
 *  ★ 用它的实现**必须自己走 `resolveAttack()`**（不要回头调 `resolveAction()`），否则会连锁触发。 */
function 势力友军攻击后(ctx, 攻击者, 目标, 一击) {
  if (!ctx || !攻击者 || 攻击者.side !== 'ally') return 0;
  /* ★ 2026-10-11：把各条目的返回值**加起来返回**（月球王国的 `残月追加攻击()` 返回这一发打了多少伤害）——
     引擎侧不看它（`resolveAction()` 那一行是语句），**只给测试 / 以后的平衡工具读数用**，
     所以对战斗结果一个字节都没影响。**没有任何条目写这个钩子 → 恒 0**（原本返回 `undefined`）。 */
  let 合计 = 0;
  for (const 势力 of 启用势力们()) {
    const 条 = 势力特色表[势力];
    if (条.友军攻击后) 合计 += Number(条.友军攻击后(ctx, 攻击者, 目标, 一击, 势力参数(势力))) || 0;
  }
  return 合计;
}

/** ★ **2026-10-11 新加的钩子**（第 11 个）：**一次攻击里「某一段没打中」的那一刻**。
 *  触发时机（写死在 `20-战斗计算.js` 的 `resolveAttack()` —— 逐段命中判定那个循环的**未命中分支**）：
 *    每一段独立判定命中之后，**这一段没中**就走这里；命中的段不走（必中武器永远不走，见下）。
 *    ★ **作者 2026-10-11 拍板「按段」**：多段武器（`w.hits > 1`）**逐段**发这个事件，
 *      **每一段未命中都算一次「打空」**（战棋是「整次攻击全空才算一次」，见 `协作/势力特色.md:53`）。
 *  参数（5 个）：
 *    `攻击者` —— 这一段是谁打的（**敌我双方都会进来**；战棋原话「敌我都算，反击也算」）；
 *    `目标`   —— 这一段打的是谁（**重装嘲讽**勾走时是那一台，和攻击记录里的「实际」一致）；
 *    `武器`   —— 这一段的武器（`w`，不是运行期条目）；
 *    `段`     —— `{ 段号, 段数, 本段命中率 }`：`段号` 从 **1** 开始（和记录里「第 N 段」一致）、
 *                `段数` = `w.hits`（多段武器才有意义，单段 = 1）、`本段命中率` = 这一段判定用的结算命中率；
 *    返回值**不参与引擎判断**（各家自己决定要不要做事）。
 *  ★ **必中武器不会进来**（`isSure`：`fire:'map'` / `passive` 的必中）——`resolveAttack()` 里它们直接算命中。
 *  ★ **没有势力条目 / 没有条目写这个钩子 → 这里什么都不做**（`启用势力们()` 是空循环）：
 *    `resolveAttack()` 只多了一次空调用，**伤害公式与记录逐字不变**（第一个用它的是 **ATX**）。
 *  ★ 用它的实现**绝不能消耗 `ctx.rng`**（这个时机在逐段判定的循环里，动随机数会改整场结果）。 */
function 势力逐段未命中(ctx, 攻击者, 目标, 武器, 段) {
  if (!ctx || !攻击者 || !武器) return;
  for (const 势力 of 启用势力们()) {
    const 条 = 势力特色表[势力];
    if (条.逐段未命中) 条.逐段未命中(ctx, 攻击者, 目标, 武器, 段, 势力参数(势力));
  }
}

/** ★ **2026-10-11 新加的钩子**（第 12 个）：**这一把武器真的打出去了**（普通冷却刚设上）。
 *  触发时机（写死在 `60-战斗.js` 的 `resolveAction()`）：攻击分支的**最后一步** ——
 *    `spendWeapon(actor, action.entry)`（把 `entry.cd` 设成 `w.cd`）**之后**、`return` 之前；
 *    只有「攻击」会走到这里（加增益 / 再动 / 防御 / 换位 / 修理都在前面 `return` 了）。
 *  参数（4 个）：
 *    `使用者` —— 出手的那台（**只在我方 `side === 'ally'` 时才会被调**）；
 *    `条目`   —— 运行期武器条目 `{t, cd, uses, readyTurn}`（要改冷却就改它）；
 *    `武器`   —— `条目.t`（静态武器数据）；
 *    返回值**不参与引擎判断**。
 *  ★ 战棋的等价物是 `strikeResolved`（`17b-角色机制.js:87-91` 的 `evadeCdCut` 就在那个时机上算，
 *    而且战棋的 `consume(w)` 也是在出手一开始就把 `cdLeft` 设好 —— 我们对齐到「设完冷却之后」）。
 *  ★ **没有条目写这个钩子 → 空循环**，`resolveAction()` 只多一次空调用，一个字节都不变。 */
function 势力武器用后(ctx, 使用者, 条目, 武器) {
  if (!ctx || !使用者 || !条目 || 使用者.side !== 'ally') return;
  for (const 势力 of 启用势力们()) {
    const 条 = 势力特色表[势力];
    if (条.武器用后) 条.武器用后(ctx, 使用者, 条目, 武器 || 条目.t, 势力参数(势力));
  }
}

