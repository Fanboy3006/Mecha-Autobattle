const 流星孤立 = u => !!(u && u.势力状态 && u.势力状态.流星小队 && u.势力状态.流星小队.孤立);

/** 这一位要检查的格子 = **相邻位** ∪ **前方格子**（就是作者说的那两个词）。
 *  `相邻位(位)` = 同排左右邻居 + 有阻挡关系的对位；`遮挡位(位)` = 挡着这个后排位的前排位。
 *  ★ 前排位（前1..前4）的 `遮挡位()` **天然是空数组**（没有「更前面的排」）→
 *    「前排单位不参与「前方」判定，只看相邻位」这条口径在代码里不用特判。
 *  ★ 后排位：`遮挡位()` 是 `相邻位()` 的**子集**（相邻位里的「对位」就是遮挡位）→
 *    两个集合一起查，等价于「`相邻位()` 里没有队友」；这一点写进了任务板，没有藏起来。 */
function 流星检查位(位) {
  const 相邻 = 相邻位(位);
  const 前方 = 遮挡位(位);
  return 相邻.concat(前方.filter(s => !相邻.includes(s)));
}

/** 这个位现在「相邻 / 前方都没有队友」吗。
 *  「队友」= **我方活着的单位**（战棋 `a.side === u.side`：**不看势力**，别的势力站在旁边也算有人），
 *  自己不算；死掉的、敌人的都不算（与 `17b:172` 的 `a.hp > 0` 一致）。 */
function 流星孤立吗(u, ctx) {
  const 检查 = new Set(流星检查位(u.slot));
  return !livingOf('ally', ctx).some(a => a !== u && 检查.has(a.slot));
}

/** 重算这一场里所有流星小队的「单独行动」状态（开局 / 回合开始 / 有人被击破时各调一次）。
 *  状态写进 `u.势力状态.流星小队`：`孤立`（判定结果）/ `检查位` / `挡路`（站在检查位上的队友）；
 *  **只在状态翻转时写一行 `〔势力〕` 记录**（每回合都写会刷屏，界面上的那一行见 `卡行`）。 */
function 判定流星小队(ctx, p) {
  if (!ctx) return;
  const 参 = p || 流星参数();
  const 队 = 势力在场('流星小队', ctx);
  if (!队.length) return;
  for (const u of 队) {
    if (!有流星单独行动(u)) continue;
    const 状 = 势力状态(u, '流星小队');
    const 检查 = 流星检查位(u.slot);
    const 挡路 = livingOf('ally', ctx)
      .filter(a => a !== u && 检查.includes(a.slot))
      .sort((a, b) => a.slot - b.slot)
      .map(a => `${位名(a.slot)} ${a.name}`);
    const 孤立 = 挡路.length === 0;
    const 变了 = 状.就绪 !== true || 状.孤立 !== 孤立;
    状.孤立 = 孤立; 状.检查位 = 检查; 状.挡路 = 挡路; 状.就绪 = true;
    /* 伤害 +N：走现成的「伤害加成」入口（`buffSum(u,'dmg')`，`20-战斗计算.js:180`）——
       判定成立就挂上、不成立就摘掉（同源只留一份，和 `换同源增益` 一个做法）。 */
    u.buffs = (u.buffs || []).filter(b => b.src !== 流星伤害来源);
    if (孤立) u.buffs.push({ src: 流星伤害来源, dmg: 参.伤害加成, 剩余: 1 });
    if (变了) {
      const 面 = 检查.map(位名).join('、');
      势力记录(ctx, 孤立
        ? `流星小队 ${u.name} 单独行动成立（${位名(u.slot)} 的相邻 / 前方 ${面} 都没有队友）→ 伤害 +${参.伤害加成}、闪避 +${参.闪避加成}`
        : `流星小队 ${u.name} 单独行动失效（${挡路.join('、')} 在 ${位名(u.slot)} 的相邻 / 前方）`,
        {
          势力: '流星小队', 特色: '单独行动', 结果: 孤立 ? '成立' : '失效',
          单位: u.key, 单位方: u.side, 单位位: u.slot, 检查位: 检查,
          伤害加成: 孤立 ? 参.伤害加成 : 0, 闪避加成: 孤立 ? 参.闪避加成 : 0,
        });
    }
  }
}

