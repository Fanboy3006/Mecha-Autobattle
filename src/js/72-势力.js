/* ---------- 势力判断（数据来源：10-数据.js 的 ALLY_T[].tags.势力） ---------- */
const 势力名 = u => (u && u.tags && u.tags.势力) || null;
/** 这个单位是不是「我方 + 这个势力」。★ 势力特色**只对我方生效**（敌人按梯队）。
 *  ★ 只认 `tags.势力`（任务书要求「以 10-数据.js 的 tags.势力 为准」）；战棋的 `inFaction()`
 *    还认 `tags.副势力`（拉米亚 A3 的双势力，10-数据.js:218），以后做 ATX 那条线要认副势力时，
 *    **只改这一个函数**就够（现在不动，免得别的势力被算进来）。 */
const 是我方势力 = (u, 势力) => !!u && u.side === 'ally' && 势力名(u) === 势力;

/* ---------- 注册表（一个势力一条） ---------- */
const 势力特色表 = {};

/** 注册一个势力的特色（后面 5 个势力都从这里进）。返回登记好的条目。 */
function 注册势力特色(势力, 条目) {
  势力特色表[势力] = Object.assign({ 势力, 启用: true }, 条目);
  return 势力特色表[势力];
}

/** 这个势力的参数（`71-改动.js` 的 `势力特色[势力]`）；没配 = `{}`（条目里的默认值生效）。 */
const 势力参数 = 势力 => (势力特色 && 势力特色[势力]) || {};

/** 这一套现在开着吗：参数表或条目里写 `启用: false` 就整套关掉（方便做「不带 vs 带」的对照）。 */
const 势力启用 = 势力 => {
  const 条 = 势力特色表[势力];
  return !!条 && 条.启用 !== false && 势力参数(势力).启用 !== false;
};

/** 现在真正生效的势力名（顺序 = 注册顺序，结果决定性；同种子两次一样）。 */
const 启用势力们 = () => Object.keys(势力特色表).filter(势力启用);

/** 单位上的**本场势力状态**（`u.势力状态[势力]`）：换场归零 —— 单位每场都是新造的
 *  （`makeUnit()`），本来就干净；要显式清零的势力在自己的 `开局` 钩子里清。 */
function 势力状态(u, 势力) {
  if (!u.势力状态) u.势力状态 = {};
  if (!u.势力状态[势力]) u.势力状态[势力] = {};
  return u.势力状态[势力];
}

/** 我方阵营里属于这个势力的**活着的**单位（成员按数据查，不手写名单）。 */
const 势力在场 = (势力, ctx) => livingOf('ally', ctx).filter(u => 是我方势力(u, 势力));

/* ---------- 写记录（统一 〔势力〕 前缀） ---------- */
/** 势力特色写一行记录。格式还是原来的 `pushLog(ctx, 文本, 字段)`（`类型: '势力'` 只是多一个字段），
 *  界面沿用原来的记录渲染，**记录格式没有改**。 */
function 势力记录(ctx, 文本, 字段) {
  if (!ctx) return;
  pushLog(ctx, `〔势力〕${文本}`, Object.assign({ 类型: '势力' }, 字段 || {}));
}

/* ---------- 三个生命周期钩子 ---------- */
function 势力开局(ctx) {
  for (const 势力 of 启用势力们()) {
    const 条 = 势力特色表[势力];
    if (条.开局) 条.开局(ctx, 势力参数(势力));
  }
}
function 势力回合开始(ctx) {
  for (const 势力 of 启用势力们()) {
    const 条 = 势力特色表[势力];
    if (条.回合开始) 条.回合开始(ctx, 势力参数(势力));
  }
}
function 势力回合结束(ctx) {
  for (const 势力 of 启用势力们()) {
    const 条 = 势力特色表[势力];
    if (条.回合结束) 条.回合结束(ctx, 势力参数(势力));
  }
}
/** 单位被击破时（`resolveAction` / `runAutoCast` 里刚把 HP 打到 0 的那一刻）。
 *  「谁被谁击破」都传进来，各家自己判（例如 SEED 只在**卫星国防军**击破敌机时涨）。 */
function 势力击破(ctx, 击破者, 被击破者) {
  if (!ctx || !击破者 || !被击破者) return;
  for (const 势力 of 启用势力们()) {
    const 条 = 势力特色表[势力];
    if (条.击破) 条.击破(ctx, 击破者, 被击破者, 势力参数(势力));
  }
}

/* ---------- 三个数值钩子（公式读它们） ---------- */
/** 势力给这个单位加的**闪避**（只对我方）。没有势力特色 / 没觉醒 → **恒 0**，
 *  所以 `hitRate()` 的公式对别的单位**逐字不变**。 */
function 势力闪避(u) {
  if (!u || u.side !== 'ally') return 0;
  let n = 0;
  for (const 势力 of 启用势力们()) {
    const 条 = 势力特色表[势力];
    if (条.闪避 && 是我方势力(u, 势力)) n += 条.闪避(u, 势力参数(势力)) || 0;
  }
  return Math.round(n);
}
/** 势力给这个单位加的**防御值**（只对我方）：`20-战斗计算.js` 的 `REDUCTIONS` stage 2 读它
 *  （战棋同款：`03-能力与减免管线.js:227-229` 的 `REDUCTIONS.seedDef`）。恒 0 → 公式逐字不变。 */
function 势力防御(u) {
  if (!u || u.side !== 'ally') return 0;
  let n = 0;
  for (const 势力 of 启用势力们()) {
    const 条 = 势力特色表[势力];
    if (条.防御 && 是我方势力(u, 势力)) n += 条.防御(u, 势力参数(势力)) || 0;
  }
  return Math.round(n);
}
/** 势力给这个单位加的**觉醒成长**（战斗内的临时成长；战棋的 `u.awG`，17b:188,197-198）。
 *  只对我方生效；没有成长 → 0。 */
function 势力觉醒成长(u) {
  if (!u || u.side !== 'ally') return 0;
  let n = 0;
  for (const 势力 of 启用势力们()) {
    const 条 = 势力特色表[势力];
    if (条.觉醒成长 && 是我方势力(u, 势力)) n += 条.觉醒成长(u, 势力参数(势力)) || 0;
  }
  return n;
}
/** 现在的**觉醒值** = 模板觉醒（`u.awaken`，随等级涨）+ 本场势力成长 —— 战棋 `awakenOf()`（17b:198）。
 *  `15-战斗计算.js:48` 的 `statVal('觉醒')` 就是读它 → 觉醒会喂进「射击 + 觉醒」那类大招。
 *  ★ 没有势力成长的单位（含全部敌人 + 没有觉醒字段的机体）**与改动前逐字相同**（`u.awaken ?? 100`）。 */
const 势力觉醒值 = u => ((u && u.awaken != null) ? u.awaken : 100) + 势力觉醒成长(u);

/** 单位卡上的那一行字（`80-界面.js` 的单位卡读它）：一个势力一段，用 ` · ` 拼；
 *  **没有势力特色的单位 = 空串**（界面什么都不多画）。 */
function 势力卡行(u) {
  if (!u || u.side !== 'ally') return '';
  const 段 = [];
  for (const 势力 of 启用势力们()) {
    const 条 = 势力特色表[势力];
    if (条.卡行 && 是我方势力(u, 势力)) {
      const s = 条.卡行(u, 势力参数(势力));
      if (s) 段.push(s);
    }
  }
  return 段.join(' · ');
}

/* ============================================================================
 * 卫星国防军 · SEED 觉醒（作者 2026-10-10：「国防军特色没问题」，照战棋原样）
 * ----------------------------------------------------------------------------
 * 逐字出处（战棋 `Claude hand off/src/js/17b-角色机制.js`，必要时 `03` / `15`）：
 *   常量        `const SEED_NEED = 50, SEED_TURN = 5, SEED_KILL = 3, SEED_EVA = .15, SEED_DEF = .25, …`  `:195`
 *   觉醒成长    `addAwaken()`：封顶到阈值、觉醒后不再涨（拉克丝除外）                                `:205-218`
 *   每回合 +5   `Hooks.on('phaseStart', …)`：「我方阶段开始（第 2 回合起）」在场每人 +5              `:220-226`
 *   击破 +3     `Hooks.on('unitDestroyed', …)`：卫星国防军击破敌机 → 在场每人 +3                     `:227-233`
 *   重装判定    `isHeavy()`                                                                    `:196`
 *   闪避 / 防御 `TRAIT_FX.seed` ← `03:100`；`REDUCTIONS.seedDef` ← `03:227-229` + `17b:200`
 *   觉醒喂攻击  `statVal('觉醒')` 读 `awakenOf` ← `15-战斗计算.js:48`
 *   无尽的 SEED `endlessSeed` ← `17b:201` + `03:34`（拉克丝：无上限、SEED 后照样成长）
 * ========================================================================== */

/** 本场累计的 SEED 成长（战棋的 `u.awG`）。 */
const SEED累计 = u => (u && u.势力状态 && u.势力状态.卫星国防军 && u.势力状态.卫星国防军.累计) || 0;
/** 已经 SEED 觉醒了吗（战棋 `seedActive()`，17b:199）。 */
const SEED已觉醒 = u => !!(u && u.势力状态 && u.势力状态.卫星国防军 && u.势力状态.卫星国防军.已觉醒);
/** 这台机体吃不吃 SEED（战棋 `abilOn(u,'seed')`）：看数据里的 `abilities`，**不手写名单**。 */
const 有SEED = u => !!(u && Array.isArray(u.abilities) && u.abilities.includes('seed'));
/** 「无尽的 SEED」（拉克丝）：觉醒无上限、SEED 后照样成长（战棋 `endless()`，17b:201）。 */
const SEED无尽 = (u, p) => !!(u && p && p.不封顶特技 && u.trait === p.不封顶特技);
/** 重装：SEED 后**不加闪避、改成防御 + 觉醒 × 0.25**（战棋 `isHeavy()`，17b:196 + 03:100）。 */
const SEED重装 = (u, p) => !!(u && u.tags && u.tags.战斗分类 === ((p && p.重装分类) || '重装'));
/** SEED 的参数（`71-改动.js` 的 `势力特色.卫星国防军`）。 */
const SEED参数 = () => 势力参数('卫星国防军');
/** 现在的觉醒值 = 模板觉醒 + 本场累计（战棋 `awakenOf()`，17b:198）。 */
const SEED觉醒值 = u => 势力觉醒值(u);

/** SEED 后的**闪避**加成 = 觉醒 × 0.15（**重装不加**；战棋 `TRAIT_FX.seed`，03:100）。 */
const SEED闪避加成 = (u, p) => {
  const 参 = p || SEED参数();
  return (!有SEED(u) || !SEED已觉醒(u) || SEED重装(u, 参)) ? 0 : Math.round(SEED觉醒值(u) * 参.闪避系数);
};
/** SEED 后的**防御**加成 = 觉醒 × 0.25（**只给重装**；战棋 `seedDefOf`，17b:200 / 03:227-229）。 */
const SEED防御加成 = (u, p) => {
  const 参 = p || SEED参数();
  return (!有SEED(u) || !SEED已觉醒(u) || !SEED重装(u, 参)) ? 0 : Math.round(SEED觉醒值(u) * 参.防御系数);
};
/** 觉醒时写在记录里的那句话（重装写防御、其他人写闪避）。 */
const SEED加成文字 = (u, p) => SEED重装(u, p)
  ? `防御 +${SEED防御加成(u, p)}（重装：SEED 后不加闪避，改成防御 + 觉醒 × ${p.防御系数}）`
  : `闪避 +${SEED闪避加成(u, p)}（= 觉醒 × ${p.闪避系数}）`;

/** 给一台机体加 SEED 成长（战棋 `addAwaken()` :205-218 **逐字**）：
 *  封顶到阈值（`Math.min(n, 阈值 − 累计)`）、**觉醒后不再成长**（拉克丝「无尽的 SEED」除外）。
 *  只对我方卫星国防军生效。返回**真的加了多少**（0 = 没加：不是这个势力 / 没有 SEED / 已经觉醒 / 已加满）。 */
function 加SEED(u, n, ctx, p) {
  const 参 = p || SEED参数();
  if (!是我方势力(u, '卫星国防军') || !有SEED(u)) return 0;      // ★ 只对我方生效
  const 状 = 势力状态(u, '卫星国防军');
  if (状.已觉醒 && !SEED无尽(u, 参)) return 0;                   // 觉醒后不再成长（17b:208）
  const 满 = 参.阈值;
  const 加 = SEED无尽(u, 参) ? n : Math.min(n, 满 - (状.累计 || 0));   // 封顶到阈值（17b:209）
  if (加 <= 0) return 0;
  状.累计 = (状.累计 || 0) + 加;
  if (!状.已觉醒 && 状.累计 >= 满) {
    状.已觉醒 = true;
    势力记录(ctx, `SEED 觉醒！${u.name} 觉醒 ${SEED觉醒值(u)}：${SEED加成文字(u, 参)}${SEED无尽(u, 参) ? '（觉醒继续成长）' : ''}`,
      { 势力: '卫星国防军', 特色: 'SEED', 结果: '觉醒', 单位: u.key, 单位方: u.side, 单位位: u.slot, 觉醒: SEED觉醒值(u) });
  }
  return 加;
}

注册势力特色('卫星国防军', {
  名: 'SEED 觉醒',
  说明: '越打越强：第 2 回合起每回合 +5、每次击破 +3；本场累计到 50 觉醒 → 闪避 + 觉醒 × 0.15'
    + '（重装改成防御 + 觉醒 × 0.25）。出处：战棋 17b-角色机制.js:187-240 / 03-能力与减免管线.js:33,100,227-229。',

  /** 本场状态清零 —— 等价于战棋 `addAwaken` 开头那行
   *  `if (u.awB !== BATTLE_ID){ u.awB = BATTLE_ID; u.awG = 0; }`（17b:206）。
   *  我们每场都是新造的单位（`makeUnit`），本来就干净；这里显式清一次，语义写明白。 */
  开局(ctx) {
    for (const u of livingOf('ally', ctx)) {
      if (!是我方势力(u, '卫星国防军')) continue;
      const 状 = 势力状态(u, '卫星国防军');
      状.累计 = 0;
      状.已觉醒 = false;
    }
  },

  /** 每回合 +SEED_TURN（战棋 17b:220-226：**我方阶段开始、第 2 回合起**、在场每人 +5）。
   *  ★ 我们挂的是**回合结束**（`endTurn`）：第 N 回合结束 = 第 N+1 回合开始，
   *    加点与次数和战棋一致（12 回合上限下都是 11 次）。 */
  回合结束(ctx, p) {
    const 队 = 势力在场('卫星国防军', ctx);
    if (!队.length) return;
    if (ctx.turn + 1 < (p.第几回合起 || 2)) return;             // 「第 N 回合起」
    const 得到 = [];
    for (const u of 队) { const 加 = 加SEED(u, p.每回合, ctx, p); if (加) 得到.push(`${u.name} +${加}`); }
    if (!得到.length) return;
    势力记录(ctx, `卫星国防军 SEED：本回合在场每人觉醒 +${p.每回合}（${得到.join('、')}）`,
      { 势力: '卫星国防军', 特色: 'SEED', 加觉醒: p.每回合, 单位们: 队.map(u => u.key), 单位方们: 队.map(() => 'ally'), 单位位们: 队.map(u => u.slot) });
  },

  /** 击破敌机 +SEED_KILL（战棋 17b:227-233）：判据逐字 —— 击破者属于卫星国防军、
   *  被击破的不是自己人（`by.side === c.unit.side` 跳过）、不是中立（`'neutral'` 跳过）。 */
  击破(ctx, 击破者, 被击破者, p) {
    if (!是我方势力(击破者, '卫星国防军')) return;
    if (!被击破者 || 被击破者.side === 击破者.side || 被击破者.side === 'neutral') return;
    const 队 = 势力在场('卫星国防军', ctx);
    if (!队.length) return;
    const 得到 = [];
    for (const u of 队) { const 加 = 加SEED(u, p.每次击破, ctx, p); if (加) 得到.push(`${u.name} +${加}`); }
    if (!得到.length) return;
    势力记录(ctx, `卫星国防军 ${击破者.name} 击破敌机：在场每人觉醒 +${p.每次击破}（${得到.join('、')}）`,
      { 势力: '卫星国防军', 特色: 'SEED', 加觉醒: p.每次击破, 击破者: 击破者.key, 被击破者: 被击破者.key,
        单位们: 队.map(u => u.key), 单位方们: 队.map(() => 'ally'), 单位位们: 队.map(u => u.slot) });
  },

  /* 数值钩子：SEED 后闪避 + 觉醒 × 0.15（其他人）/ 防御 + 觉醒 × 0.25（重装）。 */
  闪避: SEED闪避加成,
  防御: SEED防御加成,

  /* 觉醒成长喂进 `statVal('觉醒')`（战棋 15-战斗计算.js:48）——「射击 + 觉醒」那类大招越打越痛。
     参数里 `觉醒进攻击: false` 可以把这一条单独关掉（不动别的）。 */
  觉醒成长: (u, p) => (p.觉醒进攻击 === false ? 0 : SEED累计(u)),

  /* 战斗屏单位卡上的那一行（`80-界面.js`）：觉醒前写「还差多少」，觉醒后写拿到了多少。 */
  卡行: (u, p) => {
    if (!有SEED(u)) return '';
    const 阈 = p.阈值, 累 = SEED累计(u);
    if (SEED已觉醒(u)) {
      return `SEED 觉醒 · 觉醒 ${SEED觉醒值(u)} · ${SEED重装(u, p) ? `防御 +${SEED防御加成(u, p)}` : `闪避 +${SEED闪避加成(u, p)}`}${SEED无尽(u, p) ? ' · 无上限' : ''}`;
    }
    return `SEED ${累}/${阈}（还差 ${Math.max(0, 阈 - 累)}）`;
  },
});
