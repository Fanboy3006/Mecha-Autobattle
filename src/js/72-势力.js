/** 减冷却（战棋 `cutCd(u, n)`，`13-武器可用性.js:12-16` + `17b:83` 的 `cutCd(u, 1)`）：
 *  ★ **先减开场冷却，再减武器本身的冷却**（`03:17` 的原文口径；两段为什么不会同时发生见文件头「口径登记 ①」）：
 *    ① 开场冷却 = `entry.readyTurn`（下限 1：第 1 回合起，不能再早）；
 *    ② 开场冷却减完之后，多出来的额度抵 `entry.cd`（下限 0）。
 *  只对**我方 ATX + 有 `gamblerSense` + 等级够的 `evadeCd` 武器**生效；别的单位进来也恒 0。
 *  返回「真的减掉了几点冷却」（0 = 什么都没减）。 */
function ATX减冷却(u, n, p) {
  const 参 = p || ATX参数();
  if (!u || !n || n <= 0) return 0;
  const 每段 = Number(参.每段减冷却);
  const 步 = (Number.isFinite(每段) && 每段 > 0) ? 每段 : 1;     // cutCd(u, 1)：每段未命中 = 1 点（逐字）
  if (!是我方势力(u, 'ATX') || !有赌徒直觉(u, 参)) return 0;
  let 减了 = 0;
  for (const e of ATX武器们(u, 参)) {
    let 剩 = n * 步;
    const 开场 = Math.max(0, (e.readyTurn == null ? 1 : e.readyTurn) - 1);
    const 抵开场 = Math.min(剩, 开场);
    if (抵开场 > 0) { e.readyTurn -= 抵开场; 剩 -= 抵开场; 减了 += 抵开场; }
    if (剩 > 0 && e.cd > 0) { const 抵cd = Math.min(剩, e.cd); e.cd -= 抵cd; 减了 += 抵cd; }
  }
  return 减了;
}

/** 钩子①（第 11 个）：**每有一段没打中**就记一次「打空」，并按 `每段减冷却` 减一次冷却。
 *  触发点在 `20-战斗计算.js` 的 `resolveAttack()` 多段循环的未命中分支（**每一段发一次**）。
 *  判据逐字照战棋 `17b:79-86`：只在场（`势力在场` = 我方活着的）**且**有 `evadeCd` 武器且等级够的人记账；
 *  **敌我双方的未命中都算**（战棋原话「敌我都算」），但**只有我方 ATX 的响介受益**（只对我方生效）。
 *  ★ 每回合上限（`每回合上限`，初稿 0 = 不封顶）：**每台每回合**最多记几次 —— 上限到了就**不再记账也不再减冷却**。 */
function ATX逐段未命中(ctx, 攻击者, 目标, w, 段, p) {
  if (!ctx || !w) return 0;
  const 参 = p || ATX参数();
  const 队 = 势力在场('ATX', ctx).filter(u => 有赌徒直觉(u, 参) && ATX武器们(u, 参).length);
  if (!队.length) return 0;
  const 上限 = Math.max(0, Math.round(Number(参.每回合上限) || 0));   // ★ 初稿：0 = 不封顶（照战棋）
  const 段号 = (段 && 段.段号) || 1, 段数 = (段 && 段.段数) || 1;
  let 记了 = 0;
  for (const u of 队) {
    const 状 = 势力状态(u, 'ATX');
    if (状.本回合号 !== ctx.turn) { 状.本回合号 = ctx.turn; 状.本回合次数 = 0; }   // 回合号一变就归零
    if (上限 > 0 && (状.本回合次数 || 0) >= 上限) continue;                        // ★ 每回合上限
    状.打空 = (状.打空 || 0) + 1;
    状.本回合次数 = (状.本回合次数 || 0) + 1;
    记了++;
    const 减 = ATX减冷却(u, 1, 参);
    const 名单 = ATX武器们(u, 参).map(e => e.t.name);
    势力记录(ctx, `ATX ${u.name}【赌徒的直觉】${攻击者.name} 打空了（第 ${段号}/${段数} 段）：`
      + `${名单.join('、')} 冷却 −1（本场累计 ${状.打空} 段；本回合第 ${状.本回合次数}${上限 ? `/${上限}` : ''} 段）`,
      {
        势力: 'ATX', 特色: '赌徒的直觉', 结果: '打空', 单位: u.key, 单位方: u.side, 单位位: u.slot,
        攻击者: 攻击者.key, 目标: 目标 && 目标.key, 武器: w.name, 段号, 段数,
        打空累计: 状.打空, 本回合次数: 状.本回合次数, 每回合上限: 上限, 真的减了冷却: 减,
      });
  }
  return 记了;
}

/** 钩子②（第 12 个）：**这把减冷却武器被打出去的那一下** —— 把「余量」一次性抵到刚设上的普通冷却上。
 *  逐字照战棋 `17b:87-91`：`cut = evadeCdCut(u) = max(0, evN − EVADE_START)`；
 *  `cut >= w.cd` → 冷却直接归零（`03:17`「减到 0 后每次行动都能用」）；否则抵掉 `cut` 点。
 *  返回「真的抵掉了几点冷却」。 */
function ATX武器用后(ctx, 使用者, 条目, p) {
  if (!ctx || !使用者 || !条目 || !条目.t) return 0;
  const 参 = p || ATX参数();
  if (!是我方势力(使用者, 'ATX') || !有赌徒直觉(使用者, 参)) return 0;
  if (!是减冷却武器(条目.t, 参)) return 0;                      // 战棋：`if (!c.w.evadeCd) return;`
  const 余 = ATX余量(使用者, 参);
  if (余 <= 0) return 0;                                        // `else if (cut > 0)`：没有余量就什么都不做
  const 前 = 条目.cd || 0;
  if (余 >= (条目.t.cd || 0)) 条目.cd = 0;                       // `if (cut >= w.cd) w.cdLeft = 0;`
  else 条目.cd = Math.max(0, 前 - 余);                           // `w.cdLeft = Math.max(0, w.cdLeft - cut);`
  const 抵 = 前 - 条目.cd;
  if (抵 > 0) {
    势力记录(ctx, `ATX ${使用者.name}【赌徒的直觉】余量 ${余} 抵掉【${条目.t.name}】的冷却 ${抵} 点`
      + `（本场累计打空 ${ATX打空(使用者)} 段，超过起算 ${参.余量起算} 的余量）→ 现在冷却 ${条目.cd}`
      + `${条目.cd === 0 ? '（减到 0：每次行动都能用）' : ''}`,
      {
        势力: 'ATX', 特色: '赌徒的直觉', 结果: '余量抵冷却', 单位: 使用者.key, 单位方: 使用者.side,
        单位位: 使用者.slot, 武器: 条目.t.name, 余量: 余, 抵掉冷却: 抵, 现在冷却: 条目.cd,
      });
  }
  return 抵;
}

