/* ============================================================================
 * 决策日志（紧凑 · 程序可读）—— 作者 2026-10-13 提出
 * ----------------------------------------------------------------------------
 * 作者原话（2026-10-13）：
 *   「日志需要能够**记录下我当时的选项和我的实际选择**，可以是**人看不懂但是程序能看懂的简要版本**，
 *     **节省空间**。」
 *
 * 为什么要它：现有的两份记录**都只有结果、没有「当时还有别的什么选项」** ——
 *   · `89-录像.js` 记的是「种子 + 版本 + 按顺序的每一个操作」：知道**选了什么**，不知道**还能选什么**；
 *   · `tools/replay.mjs --导出决策` **能**在每个决策点枚举「可选项」，但那是**工具里的逻辑**，
 *     只有事后重放才有；**线上玩的时候没有**，玩家当时看到的那一份选项就永远丢了。
 * 这个文件把那份枚举逻辑**搬进游戏**（唯一真源），于是一边在线记、一边重放导出，用的是**同一份代码**。
 *
 * ---------------------------------------------------------------------------
 * 一、`选项.枚举()` —— **按当前屏**列出所有**合法可选项**（纯读）
 * ---------------------------------------------------------------------------
 *  · 口径照 `tools/replay.mjs` 原来的「决策表」（那一份已经搬进来，工具改成调它）：
 *    可去的格子 / 零件 / 招募候选 / 券 / 晋升 / 黑市货与刷新 / 事件选项 / 弹窗按钮 /
 *    休整三选一 / 出口两型 / 5 条方针 / 点敌人 / 大招开关 / TRANS-AM 开关 / 选分队；
 *  · 短码一律是 `动作:参数`（**原样**，不展开成人话、不带名字）——
 *    所以「选项」里的每一条都能直接喂回 `界面.动作()`（重放工具就是这么用的）；
 *  · ★ **纯读**（照 `84-反馈.js` 的规矩）：不改任何状态、不碰 `localStorage`、不刷屏。
 *    `黑市货()` 是唯一的例外说明：**货架已经摆过**（进黑市屏渲染时就摆了）→ 这一步只是读缓存；
 *    万一还没摆过，`黑市货()` 会把货架填进 `RUN.黑市货`（那是它本来就有的行为，不是枚举改的）。
 *  · 拿不到局面（没有 RUN / 没有界面）时返回**空数组**，照实报出来，**不编一个假的选项**。
 *
 * 二、`决策录` —— 把「选了什么」记成一条（`80-界面.js` 的动作派发入口那一个钩子）
 * ---------------------------------------------------------------------------
 *  · `89-录像.js` 的 `派发前()` / `派发后()` **就是**那个唯一入口（`80-界面.js` 的 `动作()` 调它），
 *    所以两条线都挂在那儿，**不改 `80-界面.js`**（2026-10-13 那个文件上躺着别人的未提交改动）；
 *  · **派发前**取一次 `选项.枚举()`（下决定的那一刻能点的那些 —— 派发之后就变了），
 *    **派发后**记一条（真选的那个）；
 *  · 存进 `89-录像.js` 那一局的 **`决策: […]`**（和 `操作` 平行的新字段；`操作` 一个字节都不动），
 *    一局的字节账见 `协作\接口约定.md`。
 *
 * 三、一条长什么样（**只记决策点**：`选了什么 / 当时还有什么`）
 * ---------------------------------------------------------------------------
 *   {"序":12,"步":37,"屏":"大地图","选":"去节点:24","选项":["去节点:21","去节点:24","使用零件:0"]}
 *   {"序":13,"步":38,"屏":"战斗","回合":2,"选":"方针:集中攻击","选项":[...]}
 *  · 键一律**单字或两字**（省空间）：`序`（这一局第几条决策，1 起、连续）/ `步`（对应的操作步序号，
 *    和 `操作[].序号` 对得上 —— 让「决策」和「操作」两份能互相找）/ `屏` / `回合`（**只在战斗内**）/
 *     `选` / `选项`；另有两个**只在出事时出现**的标记：`越界`、`截断`；
 *  · **只记决策动作**（`决策动作们` 那 19 个族 —— 和 `tools/replay.mjs` 的决策点、`tests/录像.js` 第 [6] 段
 *    的验收是同一个集合）：导航（回大地图 / 去晋升 / 开打 / 看录像…）**一条都不记**，
 *    不然一局光导航就有几百条、把空间吃光；
 *  · `选` **不在** `选项` 里 → 记 `"越界":true`（**照实记，不静默**：那说明玩家/测试点了一个
 *    当时不该能点的动作）；
 *  · `选项` 超过 `决策选项上限 = 40` → 只存前 40 并记 `"截断":true`（**但 `选` 一定留在里面**，
 *    不然「选 ∈ 选项」这条不变量自己就假了）；
 *  · 一局最多 `决策条数上限 = 300` 条，超了**从最早丢**，丢了几条记在那一局的 `决策丢: N`。
 *
 * 四、三层反馈（`CLAUDE.md` 第 7 节第 10 条）
 * ---------------------------------------------------------------------------
 *  · **预告**：`89-录像.js` 的录像屏 / 结算屏那一块写着「已记 N 步」；决策条数由 `决策录.数()` 读得到；
 *  · **即时**：每派发一个决策动作，`决策` 里当场多一条（`决策录.最近()` 能读到刚才那条）；
 *  · **结算**：一局结束封存时 `决策` 跟着这一局一起留下来；「本局日志」导出的**末尾多一节**
 *    「———— 决策记录（紧凑，程序可读，共 N 条）————」（实现在 `88-战斗记录.js`，数据由 `录像.当前决策()` 给）。
 * ========================================================================== */

