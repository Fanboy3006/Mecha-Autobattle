/** 编队屏能点的：选人 / 摆位 / 取回 / 默认五人队 / 清空 / 开战（摆位是**拖动**出来的，
 *  所以这一族只服务「当时的选项」这份账，不进 `决策动作们`）。 */
function 编队码们(界面) {
  const J = 决策界面(界面);
  const B = (J && J.编队) || {};
  const R = 试读(() => 肉鸽.RUN, null);
  const 肉鸽模式 = !!(J && J.肉鸽编队模式 && R);
  const 候选 = 肉鸽模式
    ? (R.队伍 || []).map(m => m.键)
    : 试读(() => ALLY_T.filter(t => t && t.mech && (!B.势力 || B.势力 === '全部' || inFaction(t, B.势力))).map(t => t.mech), []);
  const 出 = [];
  for (const k of 候选) 出.push(`选人:${k}`);
  const 占 = new Set((B.出击 || []).map(x => x.位));
  for (let s = 0; s < SLOTS; s++) 出.push(占.has(s) ? `取回:${s}` : `放位:${s}`);
  出.push('默认五人队');
  出.push('清空');
  出.push('开战');
  return 出;
}

