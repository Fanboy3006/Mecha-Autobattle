/** `招募:<键>` —— 招募候选（和 `92-肉鸽界面.js` 的 `招募屏()` 同一套判据：
 *  不在队里 + 对得上**当前选中的那张券**）。 */
function 招募候选码们() {
  const R = 试读(() => 肉鸽.RUN, null);
  if (!R) return [];
  const 已有 = new Set((R.队伍 || []).map(m => m.键));
  const 券们 = R.券 || [];
  const i = 试读(() => 肉鸽界面.选中的券, null);
  const 用中 = (i != null && 券们[i]) ? 券们[i] : null;
  const 出 = [];
  for (const t of 试读(() => ALLY_T || [], [])) {
    if (已有.has(t.mech)) continue;
    if (用中 && !试读(() => 券合(用中, t.mech), false)) continue;
    出.push(`招募:${t.mech}`);
  }
  return 出;
}
/** `晋升:<键>` —— 名册上每一台（口径照旧：不筛「现在能不能升」，`能升` 由 `晋升清单()` 自己写）。 */
