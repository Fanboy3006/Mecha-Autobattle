/** `奇遇:<下标>` + `奇遇:<选项文字>` —— 下标与文字两种写法都算「能点的」。 */
function 奇遇码们() {
  const 事 = 试读(() => 肉鸽.当前事件(), null);
  const 选 = (事 && (事.选 || 事.选项 || 事.选项们)) || [];
  const 出 = [];
  选.forEach((o, i) => {
    const 文 = (o && (o.选 != null ? o.选 : (o.名 != null ? o.名 : (o.动 != null ? o.动 : o.文))))
      || (typeof o === 'string' ? o : null);
    出.push(`奇遇:${i}`);
    if (文) 出.push(`奇遇:${文}`);
  });
  return 出;
}
/** `弹窗:<值>` —— 弹窗摆出来的那几个按钮。三个来源（按可靠性排）：
 *  ① 界面正摆着的真弹窗（`界面.弹窗`，浏览器里点它走动作派发入口）；
 *  ② 这一次派发从录像那一步抄下来的 `可选项`；
 *  ③ 重放时 `对话框钩子` 刚抓到的那一次弹窗的选项（`工具` 从 `89-录像.js` 的同一套里传进来）。 */
function 弹窗码们(界面, 附) {
  const 出 = [];
  const 加 = 值 => { for (const v of (值 || [])) { const t = 决策文字(v); if (t && 出.indexOf(`弹窗:${t}`) < 0) 出.push(`弹窗:${t}`); } };
  const 板 = 界面 && 界面.弹窗;
  if (板 && Array.isArray(板.选项)) 加(板.选项.map(o => (o && o.值 != null ? o.值 : o)) .filter(Boolean));
  if (附) {
    if (Array.isArray(附.可选项)) 加(附.可选项);
    if (附.步 && Array.isArray(附.步.可选项)) 加(附.步.可选项);
    if (附.上次弹窗 && Array.isArray(附.上次弹窗.选项)) 加(附.上次弹窗.选项.map(o => (o && o.值 != null ? o.值 : o)));
  }
  return 出;
}
/** 我方 / 敌方**活着的位**（`点敌人` / `大招` / `TRANSAM` / `开TRANSAM` 共用）。
 *  只在战斗屏成立（照旧）；播放阶段用 `显示单位` 那一份快照。 */
function 位码们(界面, 名, 方) {
  const J = 决策界面(界面);
  const ctx = J && J.ctx;
  if (!J || !ctx || J.屏 !== '战斗') return [];
  return 试读(() => {
    const 列 = (方 === 'ally')
      ? (J.显示单位 ? J.显示单位.我方 : ctx.allies)
      : ctx.enemies;
    return (列 || []).filter(u => u.hp == null || u.hp > 0)
      .map(u => `${名}:${u.slot}`).sort((a, b) => Number(a.split(':')[1]) - Number(b.split(':')[1]));
  }, []);
}
