/* ---------------------------------------------------------------------------
 * ③ `选项` —— 对外的那一个口子（`window.__game.选项`）
 * ------------------------------------------------------------------------- */
const 选项 = {
  动作们: 决策动作们,
  族们: Object.keys(决策族码们),
  屏族: 屏决策族,
  上限: 决策选项上限,
  条数上限: 决策条数上限,

  /** 这个动作算不算「决策点」（= `tools/replay.mjs` 的决策行、`tests/录像.js` 第 [6] 段那一串）。 */
  是决策(动) { return 决策动作们.indexOf(决策文字(动)) >= 0; },

  /** ★ 枚举**合法可选项**（短码数组，纯读、绝不抛）。两种用法：
   *   · `枚举(界面, 动作, 参, 附)` → **这个动作自己那一族的可选项**（`动作:参数` 短码数组）——
   *     **重放工具与在线记录用的都是这一份**，所以两边逐字同源；
   *   · `枚举(界面)`（不给动作）→ **当前屏**所有决策族的并集（「我当时还有哪些别的选项」的屏级视图，
   *     给测试 / 复盘 / 以后的分析用）。
   *  `参` 只影响 `弹窗` 那一族；`附`（可选）= `{可选项, 步, 上次弹窗}` 给 `弹窗:` 补选项
   *  （录像那一步抄下来的 / 重放时 `对话框钩子` 刚抓到的那一次）。 */
  枚举(界面, 动作, 参, 附) {
    const J = 决策界面(界面);
    const 名 = 决策文字(动作);
    const 出 = [];
    const 加 = 列 => {
      for (const x of (列 || [])) {
        const t = 决策文字(x);
        if (t && 出.indexOf(t) < 0) 出.push(t);
      }
    };
    const 跑 = 族 => {
      const fn = 决策族码们[族];
      if (typeof fn === 'function') 加(试读(() => fn(J, 参, 附), []));
    };
    if (!名) {
      /* ① 当前屏的决策族并集（屏自己会告诉我们要不要带「前进 / 休整」这种只在这一格成立的族） */
      const 屏族 = J && J.屏 ? 屏决策族[J.屏] : null;
      for (const 族 of 试读(() => (typeof 屏族 === 'function' ? 屏族(J) : (屏族 || [])), [])) 跑(族);
    } else {
      /* ② 这一动作自己那一族 —— **省空间的关键**：一条决策只带它自己在挑的那一份选项，
         不把同一屏上别的族抄一遍（战斗屏上照抄一遍就是 30 多条 × 每回合好几条，一局要几万字节）。
         屏级并集仍然拿得到（不给 `动作` 的那一种用法）。 */
      跑(名);
    }
    /* ③ 真弹窗正摆着的按钮（浏览器里点它走 `弹窗:<值>` 这个动作） */
    if (J && J.弹窗) 加((J.弹窗.选项 || []).map(o => `弹窗:${o && o.值 != null ? o.值 : o}`).filter(Boolean));
    return 出;
  },

  /** 当前屏的名字（没有界面 → 空串）。 */
  屏名(界面) { const J = 决策界面(界面); return (J && J.屏) ? 决策文字(J.屏) : ''; },
};

/* ---------------------------------------------------------------------------
 * ④ `决策录` —— 「取一次选项 → 派发 → 记一条」这三步（`89-录像.js` 的钩子调）
 * ------------------------------------------------------------------------- */
const 决策录 = {
  /** 开新局**之前**那几步（`选分队` 那一屏）：先排队，等这一局的录像建起来再并进 `决策`。 */
  预备: [],
  /** 这一次派发算好的那一条（`取()` 里建；`落()` 里写进录像）。 */
  本次: null,
  /** 上一条真正写下来的决策（三层反馈的「即时」层读它）。 */
  上一条: null,
  /** 这一局已经记了几条（读录像那一局的 `决策`；没有局 → 0）。 */
  数(RUN) {
    const 场 = 试读(() => 录像.当前局(RUN), null);
    return (场 && Array.isArray(场.决策)) ? 场.决策.length : 0;
  },
  最近() { return this.上一条; },

  /** ★ **派发前**算这一下的「选项」（纯读）。不是决策动作 → 返回 null（一条都不记）。 */
  取(界面, 动作, 参, 位) {
    const 名 = 决策文字(动作);
    if (!选项.是决策(名)) return null;
    const 全 = 选项.枚举(界面, 名, 参);
    const 选 = 决策文字(参) ? `${名}:${决策文字(参)}` : 名;
    const 条 = { 屏: (位 && 位.屏 != null) ? 决策文字(位.屏) : 选项.屏名(界面), 选: 选 };
    if (位 && 位.回合 != null) 条.回合 = 位.回合;
    let 选项们 = 全;
    if (选项们.length > 决策选项上限) {
      选项们 = 选项们.slice(0, 决策选项上限);
      /* 截断**只影响存下来的那一份**：「选 ∈ 选项」这条不变量不许因为截断而假掉，
         所以真选的那一条要是被切掉了，就把它补回最后一位（仍然是 40 条）。 */
      if (选 && 全.indexOf(选) >= 0 && 选项们.indexOf(选) < 0) 选项们[选项们.length - 1] = 选;
      条.截断 = true;
    }
    条.选项 = 选项们;
    /* 真选了一个**不在选项里**的动作 → 照实记，绝不静默（玩家 / 测试点了当时不该能点的那一下）。 */
    if (全.indexOf(选) < 0) 条.越界 = true;
    return 条;
  },

  /** 弹窗答案（走 `对话框钩子` 那条路时**不经过动作派发入口**）也要记一条 —— 那一屏的选项就是弹窗的按钮。 */
  取弹窗(界面, 标题, 选项们, 回, 屏, 回合) {
    const 值 = 决策文字(回);
    if (!值) return null;
    const 条 = { 屏: 决策文字(屏), 选: `弹窗:${值}` };
    if (回合 != null) 条.回合 = 回合;
    const 全 = 弹窗码们(界面, { 可选项: (选项们 || []).map(o => (o && o.值 != null ? o.值 : o)) });
    条.选项 = 全.length > 决策选项上限 ? 全.slice(0, 决策选项上限) : 全;
    if (全.length > 决策选项上限) 条.截断 = true;
    if (全.indexOf(条.选) < 0) 条.越界 = true;
    return 条;
  },

  /** **派发后**：把主步那一条 + 弹窗子步那几条写进录像（`89-录像.js` 的 `追加决策()` 负责落盘）。 */
  落(录像层, s, 本, 主编, 子编们) {
    const 加 = (条, 步) => {
      if (!条) return null;
      const 回 = 试读(() => 录像层.追加决策(s, 条, 步), null);
      if (回) this.上一条 = 回;
      return 回;
    };
    加(本 && 本.决策, 主编 && 主编.序号);
    (本 && 本.子步决策 ? 本.子步决策 : []).forEach((条, i) => 加(条, 子编们 && 子编们[i] && 子编们[i].序号));
    return true;
  },

  /** 落**一条**决策（`89-录像.js` 的 `落悬()` 用）：悬着的 `选分队` 归**当前这一局**时走它
   *  （`落()` 是「这一步刚派发完」那条路，这里补的是「悬着的那一步现在才落定」）。 */
  落单(录像层, s, 条, 步) {
    if (!条 || !录像层 || typeof 录像层.追加决策 !== 'function') return null;
    const 回 = 试读(() => 录像层.追加决策(s, 条, 步), null);
    if (回) this.上一条 = 回;
    return 回;
  },
};
