/** ★ **《兰斯10》四路战线：当前站位激活的效果**（预告层，挂在我方单位卡同一个 `.特色角标` 槽位）。
 *  逐条（与 `71-改动-5` 的判据**同一份**，这里只翻成人话）：
 *    · 前排 + 近战武器 → `[前卫近战+15%]`；
 *    · 后排 + 同路正前方有存活友军 → `[同路掩护−30%伤]`（正前方是**存活重装** → `[铁壁护卫100%]`）；
 *    · 外侧两路（`col 0` / `col 3`）+ 尖兵 / 流星小队 → `[侧翼游击]`；
 *    · 前排中枢（`slot 1` / `slot 2`）+ 重装 → `[中枢防+15]`。
 *  ★ **纯读**（`ctx.rng` 调用 0 次、不改状态、不写 `ctx.log`）；没有 `ctx` / 没有 `buffs` 数组
 *    （= 播放阶段的快照）→ 返回空数组（一个角标都不多画）。 */
function 兰斯角标们(u, ctx) {
  const out = [];
  if (!ctx || !u || !Array.isArray(u.buffs)) return out;
  if (typeof 兰斯战线开 !== 'function' || !兰斯战线开()) return out;
  if (!u.tags) return out;
  if (u.slot == null) return out;
  const 职 = u.tags.战斗分类;
  const 我的武器们 = (typeof 攻击武器们 === 'function') ? 攻击武器们(u, ctx) : [];
  const 前排 = rowOfSlot(u.slot) === ROW_FRONT;
  /* ① 前排近战增伤（判据与 `dmgCore` 里那条**同一个** `rangeKindOf(w) === 'melee'`） */
  if (前排 && 我的武器们.some(e => e && rangeKindOf(e.t) === KIND_MELEE)) out.push('[前卫近战+15%]');
  /* ② 同路掩护 / 铁壁护卫：后排 + 同路正前方有存活友军（`被挡吗` 的同一个判据） */
  if (!前排) {
    const 同阵营 = ((u.side === 'ally' ? ctx.allies : ctx.enemies) || []);
    const 活位 = new Set(同阵营.filter(x => x && x.hp > 0).map(x => x.slot));
    if (被挡吗(u.slot, 活位)) {
      const 位 = 遮挡位(u.slot)[0];
      const 正前 = 同阵营.find(x => x && x !== u && x.hp > 0 && x.slot === 位) || null;
      out.push(正前 && 职业是(正前, '重装') ? '[铁壁护卫100%]' : '[同路掩护−30%伤]');
    }
  }
  /* ③ 侧翼游击（外侧两路 + 尖兵 / 流星小队） */
  if (在外侧两路(u) && 是侧翼游击(u)) out.push('[侧翼游击]');
  /* ④ 中枢固守（前排中枢 + 重装） */
  if (职 === '重装' && 中枢重装防御加成(u) > 0) out.push('[中枢防+15]');
  return out;
}

