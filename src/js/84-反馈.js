/* ---------------- 预告①：集中攻击（§2.2 第 2 行） ----------------
 * 「全队对它的预计伤害合计 X / 它剩 Y HP」：
 *   · 逐台我方问 `chooseAttack(u, ctx)`（**纯函数**：不改状态、不消耗随机数）——
 *     它给的就是「这一台在当前方针下会打谁、期望多少」；
 *   · `预计伤害合计` = **这一回合真的会落在点名目标身上**的那几台加起来（打不到的 / 被更好的目标
 *     挤掉的照常自由攻击，§1.3 第 2 条）—— 所以它是**会发生的**，不是「大家都能打多少」；
 *   · `台数` = **打得到它**（射程 + 阻挡都过得去）的那几台；`会打` = 其中真的会打它的那几台。
 *     ⚠ 这两个数有时不等：引擎里「集中攻击」那条候选要和「自由攻击」那条一起比分数
 *       （`50-AI.js` 的 `chooseAttack()`，能击破的优先、其次比「期望 ÷ 目标 HP」），
 *       所以当目标又厚又不是最划算的那一个时，有些单位会去打别人 —— 预告照实写出来，
 *       **没有改判定**（任务书要求「不改任何战斗数值与判定」）。这一条已写进任务板待拍板。
 *   · X 是**期望值**（`expectedDamage()` = 命中率 × 伤害 ×（1 + 暴击率） × 段数），不是保证值。
 * 传进来的方针不是「集中攻击」/ 目标已倒下 → 返回 null（界面就不画这一行）。 */
function 集中攻击预告(ctx) {
  const 目标 = 方针目标(ctx);
  if (!目标) return null;
  const 详情 = [];
  let 合计 = 0, 会打 = 0, 台数 = 0;
  for (const u of livingOf('ally', ctx)) {
    const 打得到 = 打得到位(u, ctx, 目标.slot);
    if (打得到) 台数++;
    const a = chooseAttack(u, ctx);
    const 会 = !!(a && a.target && a.target.slot === 目标.slot);
    const 伤害 = 会 ? Math.round(Number(a.expected) || 0) : 0;
    if (会) { 会打++; 合计 += 伤害; }
    详情.push({ 位: u.slot, 名: u.name, 打得到, 会打: 会, 武器: 会 && a.weapon ? a.weapon.name : null, 伤害 });
  }
  return {
    目标位: 目标.slot, 目标名: 目标.name, 目标键: 目标.key,
    剩余HP: Math.max(0, 目标.hp), 上限HP: 目标.maxHp,
    预计伤害合计: 合计, 台数, 会打, 详情,
  };
}

/* ---------------- 预告②：攻击后排（§2.2 第 3 行） ----------------
 * 「打得到 / 打不到后排」= 这一台**现在手上的攻击武器**里，有没有一把按现有射程与阻挡规则
 * 能够到对面**后排**的活人：
 *   · 近战：要 `rowReachable()` 放行（对面前排全灭才够得到后排，§1.3 第 3 条）；
 *   · 直射：够得到，只是被挡时命中 −20（`rowBlockPenalty()`，那是命中修正、不是打不到）；
 *   · 曲射 / 范围：无视阻挡，但落点必须**盖住至少一个后排位**。
 * ★ 口径：这里问的是「**能力**」—— 不看大招保留 / 修理优先那类当回合取舍（那些是**意图**，不是射程），
 *   所以用的是 `usableWeapons()` 而不是 `weaponPool()`（后者会把「保留」的大招摘掉）。 */
function 攻击武器们(u, ctx) {
  return usableWeapons(u, ctx).filter(e => {
    const k = rangeKindOf(e.t);
    return k !== null && !isHealKind(k) && !isSupportKind(k);
  });
}
/** 这一台现在的攻击武器**够不够得着**那一位（射程 + 近战够前排 + 范围落点盖住它）。 */
function 打得到位(u, ctx, 位) {
  if (!u || !ctx || 位 == null) return false;
  const foes = livingOf(otherSide(u.side), ctx);
  const t = foes.find(x => x.slot === 位 && x.hp > 0);
  if (!t) return false;
  const pool = 攻击武器们(u, ctx);
  if (!pool.length) return false;
  const 局面 = 局面Of(foes);
  for (const e of pool) {
    const kind = rangeKindOf(e.t);
    if (!rowReachable(kind, unitRow(t), 局面.前排有人)) continue;
    if (isAreaKind(kind)) {
      for (let slot = 0; slot < SLOTS; slot++) {
        if (areaSlots(e.t, rowOfSlot(slot), colOfSlot(slot)).includes(t.slot)) return true;
      }
    } else if (bestWeaponOn(u, t, [e], 局面, ctx)) return true;
  }
  return false;
}
function 打得到后排(u, ctx) {
  if (!u || !ctx) return false;
  const foes = livingOf(otherSide(u.side), ctx);
  return foes.some(t => t.hp > 0 && unitRow(t) === ROW_BACK && 打得到位(u, ctx, t.slot));
}

