const 防御姿态吗 = (u, ctx) => 按防御结算(u, ctx);

/* ---------------- 预告④：大招开关（§2.2 第 5 行） ----------------
 * 「冷却剩几回合；「保留」时卡片上有标记」：
 *   · 先挑这一台**等级够、算大招、第一期武器可用**的那几把（`isUltimate()` + `weaponPlayable()`）；
 *   · 「还差几回合」= 那把武器两个计时器里更慢的那个：`readyTurn − 当前回合`（开场冷却，大招 5 回合）
 *     与 `cd`（普通冷却，大招至少 3 回合，`spendWeapon()` 设的，每回合结束 −1）；
 *   · 取**最快的那一把**（玩家关心的是「大招什么时候能放」，不是哪一把）；
 *   · 已经能放 → `可放: true`、`冷却剩: 0`。 */
function 大招状态(u, ctx) {
  const 手 = (u && u.holdUlt) ? true : false;
  const 空 = { 有大招: false, 可放: false, 冷却剩: null, 保留: 手, 名字: [] };
  if (!u || !ctx) return 空;
  const 有 = (u.weapons || []).filter(e => e && e.t && isUltimate(e.t) && u.lv >= e.t.unlock && weaponPlayable(e.t));
  if (!有.length) return 空;
  const 剩 = e => Math.max(0, Math.max((e.readyTurn || 1) - ctx.turn, e.cd || 0));
  const 冷却剩 = Math.min.apply(null, 有.map(剩));
  return { 有大招: true, 可放: 冷却剩 <= 0, 冷却剩, 保留: 手, 名字: 有.map(e => e.t.name) };
}

/* ---------------- 预告快照（界面一次性算好，卡片直接读） ----------------
 * 指令阶段每次刷屏调一次；`80-界面.js` 的 `战斗屏()` 把它传给每张卡片。
 * `回合` 一起带上：测试 / 界面要能看出「这份预告是哪一回合算的」。 */
function 预告快照(ctx) {
  if (!ctx) return null;
  const 方针 = 当前方针(ctx).类型;
  const 大招 = {};
  for (const u of (ctx.allies || [])) 大招[u.slot] = 大招状态(u, ctx);
  const 防御位 = (ctx.allies || []).filter(u => u.hp > 0 && 防御姿态吗(u, ctx)).map(u => u.slot);
  const 后排位 = 方针 === '攻击后排'
    ? (ctx.enemies || []).filter(u => u.hp > 0 && unitRow(u) === ROW_BACK).map(u => u.slot) : [];
  const 后排我能 = {};
  if (方针 === '攻击后排') for (const u of (ctx.allies || [])) 后排我能[u.slot] = 打得到后排(u, ctx);
  return {
    回合: ctx.turn, 方针,
    集中: 方针 === '集中攻击' ? 集中攻击预告(ctx) : null,
    大招, 防御位, 后排位, 后排我能,
    防御说明: '防御值 +50',
  };
}

/* ---------------- 即时：记录 → 卡片上那个小标签 ----------------
 * 「即时」那一层的**判定全在记录的字段上**（`60-战斗.js` 写 `集中` / `被挡` / `被挡惩罚`，
 * `20-战斗计算.js` 写 `防御少挨`），这里只把字段翻成人话（§2.2 的「即时」列）：
 *   · 集中攻击打在点名的那一位上 → `集中`；
 *   · 直射打被挡的后排位 → `被挡 −20`（沿用已有的说法，作者 2026-10-10 拍板）；
 *   · 挨了一下防御姿态的攻击 → `防御 少挨 N`（N 由 §2.4 的「不带防御加成再算一次」得来）。
 * 三个字段都不在 → 空串：播放层的显示与改动前**逐字相同**（默认路径一个标签都不多画）。 */
function 反馈标签(ev) {
  if (!ev) return '';
  const 们 = [];
  if (ev.集中) 们.push('集中');
  if (ev.被挡) 们.push(`被挡 −${Math.abs(Number(ev.被挡惩罚) || 20)}`);
  if (ev.防御少挨 != null) 们.push(`防御 少挨 ${ev.防御少挨}`);
  return 们.join(' · ');
}

/* ---------------- 结算：本场战报（§2.2 / §2.3 的「结算」列） ----------------
 * 数据**全部**从记录里统计（§2.4 原话）。`战斗` 可以是一次战斗的 `ctx`（有 `log` / `allies`），
 * 也可以是结算屏上的 `战报`（有 `记录` / `我方`）—— 两种形状都认，别的形状当空的（不崩）。 */
function 战报记录们(战斗) {
  if (!战斗) return [];
  const r = 战斗.记录 || 战斗.log;
  return Array.isArray(r) ? r.filter(x => x && typeof x === 'object') : [];
}
/** 那个「随伤害一起出现」的字段集：只有这两个类型会带 `伤害`（`60-战斗.js` 的攻击记录与
 *  `72-势力.js` 的残月余响）。用类型白名单是为了**不重复计账**（势力记录里也有别的数）。 */
const 战报伤害类型 = ['攻击', '残月余响'];
function 战报我方们(战斗) {
  const a = 战斗 && (战斗.我方 || 战斗.allies);
  return Array.isArray(a) ? a : [];
}
function 战报敌方们(战斗) {
  const a = 战斗 && (战斗.敌方 || 战斗.enemies);
  return Array.isArray(a) ? a : [];
}
const 战报数 = x => (Number.isFinite(Number(x)) ? Number(x) : 0);

/** 这一条记录是不是**我方放大招**打出来的？
 *  ★ 判据和 `96-音乐.js` 的 `看记录()` **完全同一条**（大招收主题曲 vs 大招伤害占比，两处不能两套话）：
 *    按记录里的 `单位方 / 单位位` 找到那台单位 → 再用记录里的 `武器` 名字找到武器条目 → 问 `isUltimate()`。
 *  ★ 所以**不需要给攻击记录加「大招」字段** —— 默认路径（全军突击）的记录因此**一个字段都不多**。 */
function 是记录大招(战斗, rec) {
  if (!rec || rec.类型 !== '攻击' || rec.单位方 !== 'ally') return false;
  const u = 战报我方们(战斗).find(x => x && x.slot === rec.单位位);
  if (!u) return false;
  const e = (u.weapons || []).find(x => x && x.t && x.t.name === rec.武器);
  return !!(e && isUltimate(e.t));
}

function 战报统计(战斗) {
  const log = 战报记录们(战斗);
  const 伤害记录 = log.filter(x => 战报伤害类型.includes(x.类型) && x.伤害 != null);
  const 我方攻击 = 伤害记录.filter(x => x.单位方 === 'ally');
  const 敌方攻击 = 伤害记录.filter(x => x.单位方 === 'enemy');
  const 我方伤害 = 我方攻击.reduce((n, x) => n + 战报数(x.伤害), 0);
  const 敌方伤害 = 敌方攻击.reduce((n, x) => n + 战报数(x.伤害), 0);
  const 总伤害 = 我方伤害 + 敌方伤害;

  /* ① 每回合输出（§2.2 第 1 行） */
  const 表 = new Map();
  for (const x of 我方攻击) 表.set(x.回合, (表.get(x.回合) || 0) + 战报数(x.伤害));
  const 每回合输出 = [...表.entries()].sort((a, b) => a[0] - b[0]).map(([回合, 伤害]) => ({ 回合, 伤害 }));

  /* ② 站位（§2.3 第 1 行）：前排承伤占「我方总共挨了多少」的比例 */
  const 挨打 = 伤害记录.filter(x => x.目标方 === 'ally' && x.目标位 != null);
  const 我方挨打 = 挨打.reduce((n, x) => n + 战报数(x.伤害), 0);
  const 前排承伤 = 挨打.filter(x => rowOfSlot(x.目标位) === ROW_FRONT).reduce((n, x) => n + 战报数(x.伤害), 0);

  /* ③ 集中攻击（§2.2 第 2 行）：击破记录 + 点名打了几次 */
  const 集中攻击 = 我方攻击.filter(x => x.集中);
  const 集中 = log.filter(x => x.类型 === '方针' && x.事件 === '集中攻击击破').map(r => ({
    目标名: r.目标名 || '目标', 目标位: r.目标位, 回合: r.回合,
    次数: 集中攻击.filter(x => x.目标位 === r.目标位).length,
  }));
  const 集中目标名 = 集中.length ? null
    : (() => {
      const 一 = 集中攻击[0];
      if (!一) return null;
      const t = 战报敌方们(战斗).find(x => x && x.slot === 一.目标位);
      return (t && t.name) || 一.目标 || `位 ${一.目标位}`;
    })();

  /* ④ 攻击后排（§2.2 第 3 行）：「击破后排 N 台」只算**下过「攻击后排」那几回合**里打后排打死的那几台 */
  const 后排攻击 = 伤害记录.filter(x => x.方针 === '攻击后排');
  const 后排击破 = 后排攻击.filter(x => x.命中 && 战报数(x.目标剩余HP) <= 0 && rowOfSlot(x.目标位) === ROW_BACK).length;
  const 被挡少中 = 后排攻击.filter(x => x.被挡 && !x.命中).length;

  /* ⑤ 防御（§2.2 第 4 行）：少挨 = 记录里 `防御少挨` 的和；回复 = 现有的「回复」记录 */
  const 少挨 = 伤害记录.reduce((n, x) => n + 战报数(x.防御少挨), 0);
  const 回复 = log.filter(x => x.类型 === '回复').reduce((n, x) => n + 战报数(x.回复), 0);
  const 防御次数 = log.filter(x => x.类型 === '防御').length;

  /* ⑥ 大招开关（§2.2 第 5 行） */
  const 大招攻击 = 我方攻击.filter(x => 是记录大招(战斗, x));
  const 大招伤害 = 大招攻击.reduce((n, x) => n + 战报数(x.伤害), 0);

  /* ⑦ 这一场玩家真的用过哪几条方针（记录里 `方针` 字段只在「不是全军突击」时写，
       所以「用过」里不会出现全军突击 —— 它是基线，每一场都显示） */
  const 用过 = [...new Set(log.map(x => x.方针).filter(Boolean))];

  return {
    结果: (战斗 && (战斗.结果 || (战斗.ctx && 战斗.ctx.result && 战斗.ctx.result.结果))) || null,
    回合数: (战斗 && 战斗.回合数) || (战斗 && 战斗.ctx && 战斗.ctx.turn) || 0,
    记录数: log.length,
    我方伤害, 敌方伤害, 总伤害, 每回合输出,
    我方挨打, 前排承伤, 后排承伤: 我方挨打 - 前排承伤,
    集中, 集中次数: 集中攻击.length, 集中目标名,
    后排击破, 被挡少中, 后排攻击次数: 后排攻击.length,
    少挨, 回复, 防御次数,
    大招伤害, 大招次数: 大招攻击.length,
    用过,
  };
}

/** 本场战报的**逐条结算句**（§2.2 + §2.3 的「结算」列，一行一条）。
 *  顺序固定：全军突击基线 → 集中攻击 → 攻击后排 → 防御 → 大招 → 站位。
 *  没有发生过的那几条（没用过的方针）**不写空话**；基线那一行与大招那一行**每场都有**。 */
function 战报行们(战斗) {
  const t = 战报统计(战斗);
  const 行 = [];
  const 占比 = (a, b) => (b > 0 ? Math.round(a / b * 100) : 0);
  /* ① 全军突击（§2.2 第 1 行）：本场伤害占比 + 每回合输出（不做任何决策时的基线，所以每场都显示） */
  const 每回合 = t.每回合输出.length
    ? t.每回合输出.map(x => `第 ${x.回合} 回合 ${x.伤害}`).join('、')
    : '（我方一次都没造成伤害）';
  行.push(`全军突击：本场我方输出 ${t.我方伤害}（占双方总伤害 ${占比(t.我方伤害, t.总伤害)}%）· 每回合输出：${每回合}`);
  /* ② 集中攻击（§2.2 第 2 行） */
  if (t.集中.length) {
    for (const x of t.集中) 行.push(`集中攻击：${x.目标名} 在第 ${x.回合} 回合被击破（共 ${x.次数} 次攻击）`);
  } else if (t.集中次数 > 0) {
    行.push(`集中攻击：点名打了 ${t.集中目标名 || '目标'} 共 ${t.集中次数} 次，本场没能击破它`);
  }
  /* ③ 攻击后排（§2.2 第 3 行） */
  if (t.用过.includes('攻击后排')) 行.push(`攻击后排：击破后排 ${t.后排击破} 台；因被挡少中 ${t.被挡少中} 次`);
  /* ④ 防御（§2.2 第 4 行：前守后攻 / 全军防御） */
  if (t.少挨 > 0 || t.回复 > 0 || t.防御次数 > 0) {
    行.push(`防御共少挨 ${t.少挨}，回复 ${t.回复}（进入防御 ${t.防御次数} 次）`);
  }
  /* ⑤ 大招开关（§2.2 第 5 行） */
  行.push(`大招造成全场 ${占比(t.大招伤害, t.总伤害)}% 的伤害（${t.大招伤害} / ${t.总伤害}，${t.大招次数} 次）`);
  /* ⑥ 站位（§2.3 第 1 行）：前排承伤比例 */
  if (t.我方挨打 > 0) 行.push(`站位：前排承伤 ${占比(t.前排承伤, t.我方挨打)}%（${t.前排承伤} / ${t.我方挨打}）`);
  return 行;
}

/** 战斗结束屏 / 大地图 / 本局结算屏上那一块「本场战报」。
 *  空数据也画一块（写一句人话），**不返回 undefined / 不抛**。 */
function 本场战报Html(行们, 副标题) {
  const 行 = Array.isArray(行们) ? 行们.filter(x => x != null) : [];
  const 体 = 行.length
    ? `<ul>${行.map(x => `<li data-report-line="1">${x}</li>`).join('')}</ul>`
    : '<p class="small" data-report-empty="1">这一场没有可结算的数据。</p>';
  return `<div class="battle-report" data-battle-report="1" data-report-n="${行.length}">
    <h3>本场战报<span class="small">${副标题 || '数据全部从这一场的战斗记录里统计（预告 / 即时 / 结算 三层里的第三层）'}</span></h3>
    ${体}</div>`;
}
