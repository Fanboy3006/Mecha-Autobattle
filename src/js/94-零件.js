/** 战棋 `newPart(k)`（`23-零件.js:20`）：`{k, uses, value}` —— 次数 / 估价没有就是 null。 */
function 新零件(k) {
  const P = 零件表[k];
  if (!P) return null;
  return { k, uses: P.次数 != null ? P.次数 : null, value: P.估价 != null ? P.估价 : null };
}

/** 拿一个零件的**参考价**（零件箱满时用来挑「最不值钱的那件」换掉）。
 *  · 有 `估价` 的（`血蕈` / `浪花` 两件自然物，黑市按估价收）→ 用它；
 *  · 没有估价的（加工品 / 概念体）→ 用表里的 `价`（战棋 `23-零件.js` 那一列参考价）。
 *  ★ 为什么不把「没有估价」当 0：那样会把**河谷祭祈**（每层推进剂上限 +1，参考价 6）这种有实际效果的
 *    先换掉、把估价 3 的血蕈留着 —— 和「换掉最不值钱的那件」的直觉相反（作者日志第 284 条那个箱子里
 *    最不值钱的是参考价 2 的重弹簧）。 */
function 零件参考价(p) {
  if (!p) return 0;
  /* ★ 注意 `Number(null) === 0`：**必须先判 null**，不然没有估价的零件会被当成 0（第一版就踩了这个坑）。 */
  if (p.value != null && Number.isFinite(Number(p.value))) return Number(p.value);
  const t = 零件表[p.k] || {};
  return Number.isFinite(Number(t.价)) ? Number(t.价) : 0;
}

/** 拿到一个零件（战棋 givePart，`30:84-95`）。
 *  战棋会弹「零件箱满了，换掉哪一件 / 放弃」；本仓库那一步的**弹窗要画按钮**（在 `92-肉鸽界面.js`，另一条线），
 *  ★ **2026-10-13（任务书 §(e)：零件箱满就白丢 —— 作者日志第 284 条）改了退化版**（统筹批准）：
 *    **满了不再直接丢**，改成「**保留新的、丢掉参考价最低的旧件**」（参考价见 `零件参考价()`），
 *    并且**日志写清**：收了哪一件、换掉的是**哪一件**、两边参考价各是多少、为什么是它（在场最低）。
 *    · **绝不静默丢** —— 原来那句「没地方放，丢下了」正是作者报的那个现象（第 284 条：遗迹给的
 *      【浪花】估价 4，箱子里还有估价 3 的血蕈 / 参考价 2 的重弹簧，却把新的丢了）。
 *    ★ 满了之后的返回值多两个字段（老调用方只读 `名` / `满了`，不受影响）：
 *      `换掉 = {k, 名, 参考价}`、`满了 = true`。
 *  以后界面空闲了，把它换成真弹窗（`界面.对话框()` 返回 Promise 那一套）只改这一处。 */
function 拿零件(k, 来源) {
  const R = 肉鸽 && 肉鸽.RUN;
  if (!R || !零件表[k]) return null;
  R.零件 = R.零件 || [];
  const 上限 = R.零件箱 || 零件箱初值;
  if (R.零件.length >= 上限) {
    let 最便宜 = 0;
    for (let i = 1; i < R.零件.length; i++) if (零件参考价(R.零件[i]) < 零件参考价(R.零件[最便宜])) 最便宜 = i;
    const 旧的 = R.零件[最便宜] || null;
    const 旧名 = 旧的 ? ((零件表[旧的.k] || {}).名 || 旧的.k) : '（空位）';
    const 旧价 = 零件参考价(旧的), 新价 = 零件参考价(新零件(k));
    R.零件.splice(最便宜, 1);
    R.零件.push(新零件(k));
    重算推进剂加成();                                 // 换掉的可能是河谷祭祈 → 推进剂上限要跟着变
    肉鸽.记(`零件箱已经满了（${上限}）：收下新的【${零件表[k].名}】，换掉参考价最低的旧件【${旧名}】`
      + `（旧件参考价 ${旧价} 是在场最低的；新件参考价 ${新价}）—— 旧的没白丢，新的收下了（${来源 || '战利品'}）`);
    肉鸽.存档();
    return {
      k, 名: 零件表[k].名, 说明: 零件表[k].说明, 来源: 来源 || '战利品',
      换掉: { k: 旧的 ? 旧的.k : null, 名: 旧名, 参考价: 旧价 }, 满了: true,
    };
  }
  R.零件.push(新零件(k));
  肉鸽.记(`获得零件【${零件表[k].名}】：${零件表[k].说明}（${来源 || '战利品'}）`);
  if (k === 'rite') 重算推进剂加成();               // 河谷祭祈：拿在手上就生效
  肉鸽.存档();
  return { k, 名: 零件表[k].名, 说明: 零件表[k].说明, 来源: 来源 || '战利品' };
}

/** 丢掉某个下标（战棋 `RUN.parts.splice`，`30:10,120`）。 */
function 丢零件(i) {
  const R = 肉鸽 && 肉鸽.RUN;
  if (!R || !R.零件) return null;
  const p = R.零件[i];
  if (!p) return null;
  R.零件.splice(i, 1);
  if (p.k === 'rite') 重算推进剂加成();
  肉鸽.存档();
  return p;
}

/** 河谷祭祈（`24-Feena_指挥官.js:18` 里 propMax() 的最后一项）：手上的零件给的推进剂上限加成。 */
function 重算推进剂加成() {
  const R = 肉鸽 && 肉鸽.RUN;
  if (!R) return 0;
  R.零件推进剂加成 = (R.零件 || []).filter(p => p.k === 'rite').length;
  return R.零件推进剂加成;
}

/** 抽一个零件（走种子）：`种子 + 层×211 + 格号×23 + 场次×29`。
 *  照战棋 `30:79,84` 的 `pick(Object.keys(PARTS))` —— 从 `零件买卖池()` 里抽
 *  （★ 2026-10-11 起含两件理财类自然物：黑市能卖它们了，所以拿到手是有意义的）。 */
function 抽零件(R, 格号值) {
  const r = R || (肉鸽 && 肉鸽.RUN);
  if (!r) return null;
  const 池 = 零件买卖池();
  if (!池.length) return null;
  const rng = mulberry32(((r.种子 || 0) + (r.层 || 1) * 211 + (格号值 || r.当前 || 0) * 23 + (r.场次 || 0) * 29) >>> 0);
  return 池[Math.min(池.length - 1, Math.floor(rng() * 池.length))];
}

/** 战利品（战后）：照战棋 `31-战斗.js:293`「精英必给，其他 35% 概率给」的**同一个公式**
 *  （原文：`if (kind === 'elite' || Math.random() < .35) await givePart(...)`）。
 *  本仓库把它落在「奖励档」上：精英 / Boss 必给（战棋的 `elite`；Boss 是终点那一场，战棋走 `final` 分支），
 *  普通 / 追击按 **35%**。界面 / `90-肉鸽.js` 在战斗胜利之后调一次，返回发出去的零件（没发就是 null）。 */
const 战利品概率 = 0.35;                  // 31-战斗.js:293
function 战斗发零件(奖励档, 来源) {
  const R = 肉鸽 && 肉鸽.RUN;
  if (!R) return null;
  const 必给 = 奖励档 === '精英' || 奖励档 === 'Boss';
  if (!必给 && !(mulberry32(((R.种子 || 0) + (R.层 || 1) * 409 + (R.场次 || 0) * 61 + 7) >>> 0)() < 战利品概率)) return null;
  const k = 抽零件(R, R.当前);
  if (!k) return null;
  return 拿零件(k, 来源 || (必给 ? '精英战战利品' : '战利品'));
}

