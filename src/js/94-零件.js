/** 拿一个零件的**参考价**（零件箱满时用来挑「最不值钱的那件」换掉）。
 *  · 有 `估价` 的（`血蕈` / `浪花` 两件自然物，黑市按估价收）→ 用它；
 *  · 没有估价的（加工品 / 概念体）→ 用表里的 `价`（战棋 `23-零件.js` 那一列参考价）。
 *  ★ 为什么不把「没有估价」当 0：那样会把**河谷祭祈**（每层推进剂上限 +1，参考价 6）这种有实际效果的
 *    先换掉、把估价 3 的血蕈留着 —— 和「换掉最不值钱的那件」的直觉相反（作者日志第 284 条那个箱子里
 *    最不值钱的是参考价 2 的重弹簧）。 */
function 零件参考价(p) {
  if (!p) return 0;
  /* ★ 注意 `Number(null) === 0`：**必须先判 null**，不然没有估价的零件会被当成 0（第一版就踩了这个坑）。 */
  if (p.value != null && Number.isFinite(Number(p.value))) return Number(p.value);
  const t = 零件表[p.k] || {};
  return Number.isFinite(Number(t.价)) ? Number(t.价) : 0;
}

/** 拿到一个零件（战棋 givePart，`30:84-95`）。
 *  战棋会弹「零件箱满了，换掉哪一件 / 放弃」；本仓库那一步的**弹窗要画按钮**（在 `92-肉鸽界面.js`，另一条线），
 *  ★ **2026-10-13（任务书 §(e)：零件箱满就白丢 —— 作者日志第 284 条）改了退化版**（统筹批准）：
 *    **满了不再直接丢**，改成「**保留新的、丢掉参考价最低的旧件**」（参考价见 `零件参考价()`），
 *    并且**日志写清**：收了哪一件、换掉的是**哪一件**、两边参考价各是多少、为什么是它（在场最低）。
 *    · **绝不静默丢** —— 原来那句「没地方放，丢下了」正是作者报的那个现象（第 284 条：遗迹给的
 *      【浪花】估价 4，箱子里还有估价 3 的血蕈 / 参考价 2 的重弹簧，却把新的丢了）。
 *    ★ 满了之后的返回值多两个字段（老调用方只读 `名` / `满了`，不受影响）：
 *      `换掉 = {k, 名, 参考价}`、`满了 = true`。
 *  以后界面空闲了，把它换成真弹窗（`界面.对话框()` 返回 Promise 那一套）只改这一处。 */
function 拿零件(k, 来源) {
  const R = 肉鸽 && 肉鸽.RUN;
  if (!R || !零件表[k]) return null;
  R.零件 = R.零件 || [];
  const 上限 = R.零件箱 || 零件箱初值;
  if (R.零件.length >= 上限) {
    let 最便宜 = 0;
    for (let i = 1; i < R.零件.length; i++) if (零件参考价(R.零件[i]) < 零件参考价(R.零件[最便宜])) 最便宜 = i;
    const 旧的 = R.零件[最便宜] || null;
    const 旧名 = 旧的 ? ((零件表[旧的.k] || {}).名 || 旧的.k) : '（空位）';
    const 旧价 = 零件参考价(旧的), 新价 = 零件参考价(新零件(k));
    R.零件.splice(最便宜, 1);
    R.零件.push(新零件(k));
    重算推进剂加成();                                 // 换掉的可能是河谷祭祈 → 推进剂上限要跟着变
    肉鸽.记(`零件箱已经满了（${上限}）：收下新的【${零件表[k].名}】，换掉参考价最低的旧件【${旧名}】`
      + `（旧件参考价 ${旧价} 是在场最低的；新件参考价 ${新价}）—— 旧的没白丢，新的收下了（${来源 || '战利品'}）`);
    肉鸽.存档();
    return {
      k, 名: 零件表[k].名, 说明: 零件表[k].说明, 来源: 来源 || '战利品',
      换掉: { k: 旧的 ? 旧的.k : null, 名: 旧名, 参考价: 旧价 }, 满了: true,
    };
  }
  R.零件.push(新零件(k));
  肉鸽.记(`获得零件【${零件表[k].名}】：${零件表[k].说明}（${来源 || '战利品'}）`);
  if (k === 'rite') 重算推进剂加成();               // 河谷祭祈：拿在手上就生效
  肉鸽.存档();
  return { k, 名: 零件表[k].名, 说明: 零件表[k].说明, 来源: 来源 || '战利品' };
}

/** ★ 2026-10-13（任务书 §1 模块 2 · ③）**血蕈估价上限**（`p.value = min(15, value + 2)`）。 */
const 血蕈估价上限 = 15;

/** ★ 2026-10-13（任务书 §1 模块 2 · ③）**血蕈（`bloodcap`）动态估价闭环** ——
 *  「每次战斗胜利后估价 +2」（上限 15，照战棋 `31-战斗.js:283` 的「血蕈每次作战估价 +2」）。
 *  纯数值维护：**不消耗 `rng`、不动任何战斗数值**，只改手上那几件的 `value`；
 *  返回涨过价的那几条文本（`90-肉鸽-4-节点结算.js` 拿去写日志 / 结果条）。 */
function 血蕈估价上涨(R, 上限) {
  const 顶 = Number.isFinite(Number(上限)) ? Number(上限) : 血蕈估价上限;
  const 涨 = [];
  for (const p of ((R && R.零件) || [])) {
    if (p.k !== 'bloodcap') continue;
    const 旧 = Number.isFinite(Number(p.value)) && Number(p.value) > 0 ? Number(p.value) : (Number(零件表.bloodcap.估价) || 3);
    const 新 = Math.min(顶, 旧 + 2);
    p.value = 新;
    涨.push(`【血蕈】${旧} → ${新} 源碳`);
  }
  return 涨;
}

/** ★ 2026-10-13（任务书 §1 模块 2 · ③）**浪花（`wave`）动态估价**：每次**移动成功后**
 *  在 2 ~ 8 源碳之间波动（任务书 §2 给的确定性公式）。
 *  ⚠ **绝不消耗 `rng`**（战斗随机数一条都不能动）：用「种子 + 层×31 + 格号×17 + 已走过格数×13」
 *    算出来的纯函数值 —— 同一局、同一步永远同一个数，所以同种子两遍逐字相同。
 *  返回变过价的那几条文本（`90-肉鸽-3-开局与移动.js` 的 `肉鸽.移动()` 拿去写日志）。 */
function 浪花估价波动(R, k) {
  const 种子 = Number(R && R.种子) || 0;
  const 层 = Number(R && R.层) || 1;
  const 格号值 = Number(k) || 0;
  const 走过 = ((R && R.已走过) || []).length;
  const v = (((种子 + 层 * 31 + 格号值 * 17 + 走过 * 13) >>> 0) % 7) + 2;
  const 变 = [];
  for (const p of ((R && R.零件) || [])) {
    if (p.k !== 'wave') continue;
    const 旧 = Number.isFinite(Number(p.value)) && Number(p.value) > 0 ? Number(p.value) : (Number(零件表.wave.估价) || 4);
    p.value = v;
    if (旧 !== v) 变.push(`【浪花】${旧} → ${v} 源碳`);
  }
  return 变;
}

