/** 一件零件**卖掉能换多少源碳**（黑市「卖零件」那一栏的真值，`卖零件()` 与 `肉鸽.零件卖价()`
 *  都从这里取，**只写一处**）。
 *  · **自然物**（血蕈 / 浪花）：按**这一件自己的动态估价** `p.value ?? 表里的估价` 卖
 *    （战棋 `30:101,119`「自然物按估价卖出」；估价由战后 +2 / 移动后波动维护）；
 *  · **其余**（加工品 / 概念体）：★ 2026-10-13（任务书 §1 模块 2 · ④）从固定 `2` 改成
 *    **按参考价折算 `Math.max(2, Math.floor(价 × 0.6))`** —— 8 源碳的喷气背包卖 4、
 *    9 源碳的小八界卖 5、3~4 源碳的零件仍然卖 2（保底 2，和旧口径的下界一致）。 */
function 零件卖出价(p) {
  if (!p) return 0;
  const P = 零件表[p.k] || {};
  if (P.类 === '自然物') {
    const v = Number(p.value);
    if (Number.isFinite(v) && v > 0) return Math.floor(v);
    const 表估价 = Number(P.估价);                  // 表里的初始估价（血蕈 3 / 浪花 4）
    return Number.isFinite(表估价) && 表估价 > 0 ? 表估价 : 0;
  }
  return Math.max(2, Math.floor((Number(P.价) || 4) * 0.6));
}

/** 卖零件（战棋 `30:117-120` 的 runSellPart 的**本仓库口径**）：
 *  自然物按当前估价、其余按参考价折算（见 `零件卖价()` 那一段）。 */
function 卖零件(i) {
  const R = 肉鸽 && 肉鸽.RUN;
  if (!R) return null;
  const p = (R.零件 || [])[i];
  if (!p) return null;
  const P = 零件表[p.k];
  const 价 = 零件卖出价(p);
  R.源碳 += 价;
  R.零件.splice(i, 1);
  if (p.k === 'rite') 重算推进剂加成();
  肉鸽.记(`卖出零件【${P.名}】+${价} 源碳结晶`);
  肉鸽.存档();
  return { ok: true, 价, 名: P.名 };
}

