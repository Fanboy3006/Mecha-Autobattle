/** 黑市零件价格（战棋 `30:96`：`Math.round(PARTS[k].price * (hasRelic('f1') ? .7 : 1))`）。
 *  ★ 本仓库的黑市**现在只卖藏品**（要不要卖零件是待拍板项）——这个函数照抄好、接口留着，
 *    界面上一行都没接（写进任务板）。 */
function 零件价(k) {
  const P = 零件表[k];
  if (!P) return 0;
  const 打折 = ((肉鸽 && 肉鸽.RUN && 肉鸽.RUN.藏品) || []).includes('f1') ? 0.7 : 1;
  return Math.round(P.价 * 打折);
}

/** 卖零件（战棋 `30:117-120` 的 runSellPart）：自然物按估价、其他一律 2 源碳。
 *  ★ 同样**没有界面入口**（黑市不卖零件、也不收零件），留着给以后拍板用。 */
function 卖零件(i) {
  const R = 肉鸽 && 肉鸽.RUN;
  if (!R) return null;
  const p = (R.零件 || [])[i];
  if (!p) return null;
  const P = 零件表[p.k];
  const 价 = P.类 === '自然物' ? p.value : 2;      // 30:101,119
  R.源碳 += 价;
  R.零件.splice(i, 1);
  if (p.k === 'rite') 重算推进剂加成();
  肉鸽.记(`卖出零件【${P.名}】+${价} 源碳结晶`);
  肉鸽.存档();
  return { ok: true, 价, 名: P.名 };
}

