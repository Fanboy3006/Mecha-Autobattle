/** 手上零件的一行字（名字 + 剩几次 / 估价 + 一句效果）。 */
function 零件行文字(p, i) {
  const P = 零件表[p.k] || { 名: p.k, 类: '—', 说明: '', 效果: '' };
  const 数 = p.uses != null ? ` · 剩 ${p.uses} 次` : (p.value != null ? ` · 估价 ${p.value}` : '');
  return `#${i} ${P.名}（${P.类}${数}）${P.用 ? '' : '【这一版用不了】'}`;
}

/** 大地图上的零件卡片：持有数 + 每件一句效果 + 可点的「使用」（带着零件去点地图）。 */
function 零件卡片Html() {
  const R = 肉鸽 && 肉鸽.RUN;
  if (!R) return '';
  const 们 = R.零件 || [];
  const 上限 = R.零件箱 || 零件箱初值;
  if (!们.length) {
    return `<div class="rv-card"><h3>零件（0 / ${上限}）</h3>
      <p class="small">还没有。战棋的零件全是大地图上用的：打赢精英战必给 1 件、普通战 35% 给 1 件、
        遗迹给 1 件。拿到之后在**这一张卡片上点「使用」**，再点地图上高亮的格子（不花推进剂）。</p></div>`;
  }
  const 行 = 们.map((p, i) => {
    const P = 零件表[p.k] || {};
    const 用中 = 肉鸽界面 && 肉鸽界面.用零件中 === i;
    return `<div class="rv-row"><span class="nm"><b>${P.名 || p.k}</b><small> · ${P.类 || '—'}` +
      `${p.uses != null ? ` · 剩 ${p.uses} 次` : (p.value != null ? ` · 估价 ${p.value}` : '')}</small>` +
      `<br><small style="margin-left:0">${P.效果 || P.说明 || ''}</small></span>` +
      `<button class="rv-btn${用中 ? ' on' : ''}" data-act="使用零件:${i}"${P.用 ? '' : ' disabled'}>` +
      `${用中 ? '正在用…' : '使用'}</button></div>`;
  }).join('');
  return `<div class="rv-card"><h3>零件（${们.length} / ${上限}）<span class="small">点「使用」→ 再点地图上高亮的格子</span></h3>${行}</div>`;
}
