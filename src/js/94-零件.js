/** 这一格「已知」吗（已走过 / 被揭开）。飞过去只看已知格，`jet` / `bagua` 例外（任意格）。 */
function 格已知(R, k) {
  return (R.已走过 || []).includes(k) || (R.已揭开 || []).includes(k);
}

/** 本层的黑市格号（坎诺特的触须用；战棋 `30:13` 的 `move:'shop'` 直接前往本层黑市）。 */
function 黑市格(R) {
  const 格 = (R && R.地图 && R.地图.格) || {};
  const k = Object.keys(格).map(Number).find(x => 格[x].类型 === '黑市');
  return k == null ? null : k;
}

/** 用某一件零件**能点哪些格**（返回数组；界面靠它高亮，测试靠它验规则）。
 *  - `line2` / `line3` / `step`：按四邻接 BFS **最短路径的格数**算（我们确实有网格，所以按格数照抄）；
 *  - `ring`：四邻接 1 格；
 *  - `ringline`：四邻接 1 格 或 2 格（`limb` + `wheel` 两条一起给）；
 *  - `any`：这一层任意存在的格（含迷雾）；**排除当前格**（原地传送没有意义）；
 *  - `fly`：已知的非战斗格（见文件头「换义」：不抄「3 格内」，不抄「+3 经验」）；
 *  - `shop`：本层的黑市格。 */
function 零件目标(p) {
  const R = 肉鸽 && 肉鸽.RUN;
  if (!R || !R.地图 || !p) return [];
  const P = 零件表[p.k];
  if (!P || !P.用) return [];
  const 距离 = 全距离(R);
  const 格们 = Object.keys(R.地图.格).map(Number);
  switch (P.移动) {
    case 'ring':   return 格们.filter(k => k !== R.当前 && 格没走过(R, k) && 距离.get(k) === 1);
    case 'ringline': return 格们.filter(k => k !== R.当前 && 格没走过(R, k) && (距离.get(k) === 1 || 距离.get(k) === 2));
    case 'line2':  return 格们.filter(k => 格没走过(R, k) && 距离.get(k) === 2);
    case 'line3':  return 格们.filter(k => 格没走过(R, k) && (距离.get(k) === 2 || 距离.get(k) === 3));
    case 'step':   return 格们.filter(k => 格没走过(R, k) && (距离.get(k) === 1 || 距离.get(k) === 2));
    case 'any':    return 格们.filter(k => k !== R.当前 && 格没走过(R, k));
    case 'fly':    return 格们.filter(k => k !== R.当前 && 格没走过(R, k) && 非战斗节点.has(R.地图.格[k].类型) && 格已知(R, k));
    case 'shop': { const s = 黑市格(R); return s != null ? [s] : []; }
    default: return [];
  }
}

/** 用掉这一件零件的**一次**（战棋 `30:6-16`：扣 uses、用光就 splice、不花推进剂）。
 *  返回 `{ok, 到, 类型, 距离, 效果}`；用不了就 `{ok:false, why}`（界面写进提示）。 */
function 用零件(i, k) {
  const R = 肉鸽 && 肉鸽.RUN;
  if (!R) return { ok: false, why: '没有进行中的局' };
  const p = (R.零件 || [])[i];
  if (!p) return { ok: false, why: '没有这件零件' };
  const P = 零件表[p.k];
  if (!P || !P.用) return { ok: false, why: `【${P ? P.名 : p.k}】这一版用不了（${(P && P.用不了) || '没有实现' }）` };
  k = Number(k);
  const 距离 = 全距离(R);
  const 目标 = 零件目标(p);
  if (!目标.includes(k)) return { ok: false, why: `【${P.名}】到不了那一格（这一格不在它的目标里）` };
  const d = 距离.get(k);
  /* 扣次数（战棋 30:10：`p.uses--; if (p.uses <= 0) RUN.parts.splice(...)`） */
  if (p.uses != null) { p.uses--; if (p.uses <= 0) R.零件.splice(i, 1); }
  const 旧 = R.当前;
  R.当前 = k;
  if (!R.已走过.includes(k)) R.已走过.push(k);
  /* `shop` / `any` 会揭开落点（战棋 30:14：`if (P.move === 'shop' || P.move === 'any') RUN.revealed.add(k)`） */
  if (P.移动 === 'shop' || P.移动 === 'any') { R.已揭开 = R.已揭开 || []; if (!R.已揭开.includes(k)) R.已揭开.push(k); }
  const 格 = R.地图.格[k];
  肉鸽.记(`使用零件【${P.名}】：(${格列(旧) + 1}, ${格行(旧) + 1}) → (${格.列 + 1}, ${格.行 + 1})` +
    `（${(节点类型表[格.类型] || {}).名 || 格.类型}${d != null ? `，${d} 步` : ''}），不消耗推进剂`);
  肉鸽.存档();
  return { ok: true, 到: k, 类型: 格.类型, 距离: d, 零件: P.名, 从: 旧 };
}

