/** 不算推进剂上限的距离表（界面用它算「走过去要几步」）。 */
function 全距离(RUN) {
  return BFS距离(RUN.当前, RUN.地图.格);      // 第二参给**普通对象**（BFS距离 的 `有(k)` 会读 格们[k]）
}
/** 推进剂够得着的距离表：BFS 深度上限 = 当前推进剂（28:25）。 */
function 移动距离(RUN) {
  const N = RUN.地图.格, 上限 = RUN.推进剂;
  const d = new Map([[RUN.当前, 0]]), q = [RUN.当前];
  while (q.length) {
    const k = q.shift();
    if (d.get(k) >= 上限) continue;                       // 28:25 超过推进剂就不往外扩
    for (const n of 邻居(k)) if (N[n] && !d.has(n)) { d.set(n, d.get(k) + 1); q.push(n); }
  }
  return d;
}
/** 能去的格（距离 ≥1）：推进剂为 0 时一个都去不了（28:29）。 */
function 能去的格(RUN) {
  if (!RUN || !RUN.地图 || RUN.推进剂 <= 0) return [];
  return [...移动距离(RUN)].filter(([, d]) => d >= 1).map(([k]) => k);
}
