/* ---------- 四邻接 / BFS（26-地图生成.js:67-68） ---------- */
function 邻居(k) {
  const c = 格列(k), r = 格行(k), o = [];
  if (c > 0) o.push(k - 1);
  if (c < 地图列数 - 1) o.push(k + 1);
  if (r > 0) o.push(k - 地图列数);
  if (r < 地图行数 - 1) o.push(k + 地图列数);
  return o;
}
/** 从 s 出发在 `格们`（Map 或 Set 或普通对象）里做四邻接 BFS：返回 Map(格号 → 步数)。 */
function BFS距离(s, 格们) {
  const 有 = k => (格们 instanceof Map || 格们 instanceof Set) ? 格们.has(k) : !!格们[k];
  const d = new Map([[s, 0]]), q = [s];
  while (q.length) {
    const k = q.shift();
    for (const n of 邻居(k)) if (有(n) && !d.has(n)) { d.set(n, d.get(k) + 1); q.push(n); }
  }
  return d;
}
/** 死胡同 = 连通份里只有一个邻居的格（26-地图生成.js:42）。 */
const 是死胡同 = (k, 有) => 邻居(k).filter(有).length === 1;

