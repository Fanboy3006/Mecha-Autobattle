/* ★ 2026-10-11 节点改造：**出口小径**的「把推进剂带到下一层」落在这一项上（【初稿】口径）。
 *   原作是「险路小径：携带剩余行动力到下一层」（见 `协作/节点设计对比-黑流树海.md` §1.5）；
 *   我们层与层之间是「每层重置 + 修正」，没法真的背一袋推进剂过去，所以换成**上限 +1**：
 *   `RUN.层出口小径` = 「哪一层的上限 +1」的层号数组（走一次小径 push 一个新的层号）。 */
function 小径上限加成(RUN) {
  const 们 = (RUN && RUN.层出口小径) || [];
  return Array.isArray(们) ? 们.filter(x => Number.isFinite(Number(x)) && Number(x) === Number(RUN.层)).length : 0;
}
/** 某一层的推进剂上限是否已经因为「小径」加过 1（防止反复点出口重复加）。 */
const 小径加过了 = (RUN, 层) => ((RUN && RUN.层出口小径) || []).some(x => Number(x) === Number(层));
function 推进剂上限(RUN) {
  return 推进剂基础 + ((RUN && RUN.层推进剂修正) || 0) + ((RUN && RUN.零件推进剂加成) || 0) + 小径上限加成(RUN);
}

