/** 不算推进剂上限的距离表（界面用它算「走过去要几步」）。 */
function 全距离(RUN) {
  return BFS距离(RUN.当前, RUN.地图.格, RUN.地图.列数);      // 第二参给**普通对象**（BFS距离 的 `有(k)` 会读 格们[k]）
}
/** 推进剂够得着的距离表：BFS 深度上限 = 当前推进剂（28:25）。 */
function 移动距离(RUN) {
  const N = RUN.地图.格, 上限 = RUN.推进剂, L = RUN.地图.列数;
  const d = new Map([[RUN.当前, 0]]), q = [RUN.当前];
  while (q.length) {
    const k = q.shift();
    if (d.get(k) >= 上限) continue;                       // 28:25 超过推进剂就不往外扩
    for (const n of 邻居(k, L)) if (N[n] && !d.has(n)) { d.set(n, d.get(k) + 1); q.push(n); }
  }
  return d;
}
/** 能去的格（距离 ≥1）：推进剂为 0 时一个都去不了（28:29）。 */
function 能去的格(RUN) {
  if (!RUN || !RUN.地图 || RUN.推进剂 <= 0) return [];
  return [...移动距离(RUN)].filter(([, d]) => d >= 1).map(([k]) => k);
}

/* ---------- ★ 2026-10-12 地图大改新增：**退路成本**（调研 §5 A4，纯读） ----------
 * 界面要告诉玩家「走进去之后要花 M 点才回得来」（三层反馈的「预告」那一层，
 * `CLAUDE.md` 第 7 节第 10 条）。
 * 口径（照调研 A4 的原话：「M = 从该格跳回干路上任一未走过格的最短距离」）：
 *   · **干路格** = 度 ≥3 或 割点 的格（与 `试放` 里挑池的判据同一个函数，不是另造一套）；
 *   · 从目标格做 BFS，找到第一个「干路格 且 不是目标格自己 且 不在已走过里」，
 *     它的 BFS 步数就是 M（走进去之后再回来要花的点数）。
 *   该格自己就在干路上 → M = 0（不需要退路）。
 *   ★ 这是**纯读**：不写 `RUN` 任何字段、不消耗随机数（`tests/map.js` 第 [23] 段钉这一条）。 */
function 退路成本(RUN, k) {
  const R = RUN;
  if (!R || !R.地图 || !R.地图.格 || R.地图.格[k] == null) return null;
  const L = R.地图.列数, 有 = x => !!R.地图.格[x];
  const 度 = x => 邻居(x, L).filter(有).length;
  const 割点集 = 割点们(new Set(Object.keys(R.地图.格).map(Number)), L);
  const 是干路 = x => 度(x) >= 3 || 割点集.has(x);
  if (是干路(k)) return 0;
  const 已走过 = new Set(R.已走过 || []);
  const d = new Map([[k, 0]]), q = [k];
  while (q.length) {
    const x = q.shift();
    for (const n of 邻居(x, L)) {
      if (!有(n) || d.has(n)) continue;
      if (是干路(n) && n !== k && !已走过.has(n)) return d.get(x) + 1;
      d.set(n, d.get(x) + 1); q.push(n);
    }
  }
  return null;                       // 找不到回得去的干路格（理论上不会：起点是干路格）
}
