/* ---------- 生成一层（照 26-地图生成.js:21-66） ----------
 *  `严` = true 时要求这一张图**能把「固定个数」表里的节点一个不少地放下**，
 *  放不下就换下一个种子重试（见 `试放` 的注释：这是本仓库为了满足任务书
 *  「每层节点固定个数」加的一句，战棋的 `put()` 池子空了会静默少放）。
 *  `诊断` 省略时正常返回地图；给了数组就把每次尝试的原因推进去（测试 / 调参用）。 */
function 生成层(层, 种子, 严 = true, 诊断 = null) {
  for (let 试 = 0; 试 < 200; 试++) {                       // 26:22 最多重试 200 次
    const r = mulberry32((种子 + 试 * 7919) >>> 0);        // 26:23
    const 有 = new Set();
    const 起点 = 格号(0, 1 + Math.floor(r() * 2));         // 26:24 第 1 列、第 2 或 3 行
    for (let 行 = 0; 行 < 地图行数; 行++) {
      for (let 列 = 0; 列 < 地图列数; 列++) if (r() < 0.78) 有.add(格号(列, 行));   // 26:25 每格 78% 存在
    }
    有.add(起点);
    /* 连通性：从起点做 BFS，只留连通分量（26:28-30） */
    const 距离 = BFS距离(起点, 有);
    const 格们 = [...距离.keys()];
    const 最右 = 格们.filter(k => 格列(k) >= 地图列数 - 2);        // 26:31 第 5、6 列
    if (格们.length < 15 || 最右.length < 2) { 说(诊断, 试, '连通格数或最右 2 列不够'); continue; }   // 26:32
    if (Math.max(...最右.map(k => 距离.get(k))) < 5) { 说(诊断, 试, '最远 BFS < 5'); continue; }     // 26:34
    /* 出口尽头 / 出口小径 / 出口守军（26:37-38 的 far[0]/far[1]）—— 见文件头「换义」那一段。
     * ★ 2026-10-11：出口从 1 个变成**两个互斥类型**（尽头 / 小径），取最右 2 列里最远的两个格；
     *   出口守军放在**任一出口**旁边（四邻接，先打赢，两个出口一起放行）。 */
    最右.sort((a, b) => 距离.get(b) - 距离.get(a));
    if (最右.length < 2) { 说(诊断, 试, '最右 2 列不够放两个出口'); continue; }
    const 出口尽头 = 最右[0], 出口小径 = 最右[1];
    if (出口尽头 === 出口小径) { 说(诊断, 试, '两个出口是同一格'); continue; }
    const 守军 = 邻居(出口尽头).concat(邻居(出口小径))
      .filter((k, i, a) => a.indexOf(k) === i && 距离.has(k) && k !== 出口尽头 && k !== 出口小径)[0];
    if (守军 == null) { 说(诊断, 试, '两个出口都没有可放守军的邻格'); continue; }
    /* 候选池（26:39-43）：剩下的格先洗一遍，put = 池子里第一个还没被占用的格 */
    const 空白 = 格们.filter(k => k !== 起点 && k !== 出口尽头 && k !== 出口小径 && k !== 守军);
    洗牌(空白, r);                                          // 26:40-41
    /* 真的放一遍（顺序照 26:45-54；「空」放到最后当填充，见 试放 的注释） */
    const T = 试放(层, 距离, 起点, 出口尽头, 出口小径, 守军, 空白, r);
    if (!T) { 说(诊断, 试, '固定节点放不下'); if (严) continue; }
    const 用的T = T || new Map([[起点, '起点'], [出口尽头, '出口尽头'], [出口小径, '出口小径'], [守军, '出口守军']]);
    for (const k of 格们) if (!用的T.has(k)) 用的T.set(k, '空');     // 26:54 其余全是空节点
    /* 组节点对象（26:55-57）：连通格一个不多一个不少 */
    const 格 = {};
    for (const k of 格们) 格[k] = { k, 列: 格列(k), 行: 格行(k), 类型: 用的T.get(k), 已过: k === 起点 };
    格[起点].类型 = '空';                                    // 26:57 起点建完后 type 改成 empty（cleared:true）
    /* 关卡编号（26:58-61）：按格号顺序轮转指派；出口守军在第 4 层用终点 Boss 关（26:59 的 bossReady 分支） */
    for (const 类 of ['作战', '精英', '出口守军', '侵蚀源']) {
      const 池 = (类 === '出口守军' && 层 === 4) ? 关卡编号池(4, '终点') : (类 === '出口守军' ? 关卡编号池(层, '守军') : 关卡编号池(层, 类));
      let i = 0;
      for (const k of 格们) if (格[k].类型 === 类 && 池.length) 格[k].关卡 = 池[i++ % 池.length];
    }
    const 隧道们 = 格们.filter(k => 用的T.get(k) === '隧道');
    return { 列数: 地图列数, 行数: 地图行数, 种子, 起点, 出口: 出口尽头, 出口尽头, 出口小径, 守军, 隧道: 隧道们, 格, 试 };
  }
  throw new Error('地图生成失败（200 次重试都没有找到合条件的 6×4 网格）');   // 26:65
}
function 说(诊断, 试, 原因) { if (诊断) 诊断.push({ 试, 原因 }); }

/** 洗牌（26:40 的 shuffle，逐字照搬：从后往前换）。 */
function 洗牌(a, r) {
  for (let i = a.length - 1; i > 0; i--) { const j = Math.floor(r() * (i + 1)); const t = a[i]; a[i] = a[j]; a[j] = t; }
  return a;
}

