  const 试 = [];
  const m = (typeof 肉鸽 !== 'undefined' && 肉鸽 && 肉鸽.RUN && 肉鸽.RUN.地图) || null;
  const 当前 = (m && Number.isFinite(m.列数)) ? m.列数 : null;
