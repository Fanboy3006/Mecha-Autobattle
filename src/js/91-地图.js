/** 试放一遍（不改任何外部状态）：能按「固定个数」放满就返回 Map(格号 → 类型)，放不下返回 null。
 *  顺序照 26:45-53：作战（优先非死胡同）→ 精英（BFS ≥3）→ 侵蚀源（BFS ≥3）→ 黑市 / 事件 / 瞭望站 →
 *  遗迹（只在死胡同）→ 休整 → 招募站 → 隧道（成对：一格列 ≤1、一格最右 2 列）→ 空（填充）。
 *
 *  ★ 怎么挑格（2026-10-11 节点改造时重写，两处和上一版不同）：
 *    ① **每个类型各有一条自己的挑法**（不是从一个大池子里按洗牌顺序 `find`），候选按格号升序；
 *    ② **放不下就换一种摆放次序再试**（`顺序` = 这次尝试的随机排列）——
 *       因为出口从 1 个变 2 个之后，第 2 / 3 层的「固定个数」表贴着容量上界，
 *       固定次序会把某一种类型逼到无格可放；换次序能救回一大半（真实重试次数见任务板）。
 *  随机数仍然只来自调用方传进来的 `rng`（`mulberry32(种子 + 试×7919)`），**没有 Math.random**。 */
function 试放(层, 距离, 起点, 出口尽头, 出口小径, 守军, 空白, rng) {
  const T = new Map([[起点, '起点'], [出口尽头, '出口尽头'], [出口小径, '出口小径'], [守军, '出口守军']]);
  const 升 = a => a.slice().sort((x, y) => x - y);
  const 死 = 升(空白.filter(k => 是死胡同(k, x => 距离.has(x))));      // 26:42
  const 非死 = 升(空白.filter(k => !死.includes(k)));
  const 远3 = 升(空白.filter(k => 距离.get(k) >= 3));
  const 空着 = () => 升(空白.filter(k => !T.has(k)));
  /* 从候选里挑「第一个还没被占的」放一种类型。
     ★ 变量名不能叫 `k`：`用.find(x => !T.has(k))` 里那个 `k` 会被 `const k` 自己遮蔽成 TDZ
       （`Cannot access 'k' before initialization`）—— 这个坑踩过一次，留注释在这里。 */
  const 挑 = (类型, 个数, 池) => {
    const 用 = 升(池 || 空白);
    for (let i = 0; i < 个数; i++) {
      const 落 = 用.find(x => !T.has(x));
      if (落 == null) return false;
      T.set(落, 类型);
    }
    return true;
  };
  /* 这一趟的摆放次序：先放「格子要求最刁」的（遗迹只在死胡同、隧道要两端的列位），
     再放没什么要求的；列位有讲究的（隧道在两端、遗迹尽量靠起点）单独挑，其余按格号升序 + 洗牌扰动。 */
  const 硬骨头 = [
    /* 26:50 遗迹只在死胡同；**一张 78% 密度的图经常一个死胡同都没有**（实测 10 张里 6 张的死胡同数 = 0），
       所以真没有就退回「离起点最近的空格」——语义仍然是「偏僻角落里的遗迹」，但不会把整张图判死。 */
    () => 挑('遗迹', 1, 死.length ? 死
      : 升(空白.filter(k => 距离.has(k))).sort((a, b) => (距离.get(a) - 距离.get(b)) || (a - b))),
    () => { if (!(层 >= 2)) return true;                                 // 26:52-53 隧道成对（★ 第 2 层起）
      const 剩 = 空着();
      const 甲 = 升(剩.filter(k => 格列(k) <= 1))[0];
      const 乙 = 升(剩.filter(k => 格列(k) >= 地图列数 - 2 && k !== 甲))[0];
      if (甲 == null || 乙 == null) return false;
      T.set(甲, '隧道'); T.set(乙, '隧道');
      return true; },
    () => 挑('作战', 计划要放(层).作战, 非死.length >= 计划要放(层).作战 ? 非死 : 空白),   // 26:45
    () => (层 >= 2 ? 挑('侵蚀源', 1, 远3) : true),                      // 26:47（BFS ≥3）
    () => 挑('精英', 1, 远3),                                          // 26:46（BFS ≥3）
    () => 挑('黑市', 1, 空着()),                                        // 26:48
    () => 挑('事件', 2, 空着()),
    () => 挑('瞭望站', 2, 空着()),
    () => (层 >= 2 ? 挑('休整', 1, 空着()) : true),                      // 26:51（★ 第 1 层不放）
    () => 挑('招募站', 1, 空着()),
  ];
  /* 次序：**先跑一遍固定的（照 26:45-53 的原顺序）**，再按 rng 给的一两个交换扰动 ——
     这样「第一次尝试」仍然是原顺序（和改前的行为一致），后面几次才换组合。 */
  const 次 = 硬骨头.map((f, i) => i);
  const 打乱 = () => { for (let i = 次.length - 1; i > 0; i--) { const j = Math.floor((rng ? rng() : 0.5) * (i + 1)); const t = 次[i]; 次[i] = 次[j]; 次[j] = t; } };
  if (rng) 打乱();
  for (const i of 次) if (!硬骨头[i]()) return null;
  if (!挑('空', 2, 空着())) { /* 「空」不够也没关系：剩下的格最后都会补成空节点（26:54） */ }
  return T;
}

