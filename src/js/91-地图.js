/* ---------- 四邻接 / BFS（26-地图生成.js:67-68；★ 改成形状感知） ---------- */
function 邻居(k, 列数) {
  const L = Number.isFinite(列数) && 列数 > 0 ? Math.floor(列数) : 几何列数(列数, k);
  const R = L;                                        // 正方形：行数 = 列数
  const c = k % L, r = (k / L) | 0, o = [];
  if (c > 0) o.push(k - 1);
  if (c < L - 1) o.push(k + 1);
  if (r > 0) o.push(k - L);
  if (r < R - 1) o.push(k + L);
  return o;
}
/** ★ 一个跨「沙箱 / Node」两界的坑（2026-10-12 踩到）：**不要用 `instanceof Map/Set` 判类型** ——
 *  页面里的脚本跑在 `vm` 沙箱里，`tests/lib/dom-stub.mjs` / 仓库外探针从外面传进来的 `Set`
 *  与沙箱里的 `Set` **不是同一个构造器**，`instanceof` 会返回 false，于是这些格被当成
 *  「普通对象」去读 `格们[k]`（`Set` 上没有这个属性 → 恒 undefined）→ BFS 只走得到起点自己。
 *  改用**鸭子类型**（看有没有 `.has`），两边都认。 */
const 是集 = x => !!x && typeof x.has === 'function' && typeof x.add === 'function';
const 是映射 = x => !!x && typeof x.has === 'function' && typeof x.get === 'function' && typeof x.add !== 'function';
/** 把「Set / Map / 普通对象（键是格号）」统一成 Set。 */
function 成集(格们) {
  if (是集(格们)) return 格们;
  if (是映射(格们)) return new Set(格们.keys());
  return new Set(Object.keys(格们 || {}).map(Number));
}
/** 从 s 出发在 `格们`（Set / Map / 普通对象）里做四邻接 BFS：返回 Map(格号 → 步数)。
 *  ★ 形状感知：`列数` 省略时按「肉鸽当前那一层」的边长算（见 `几何列数`）。 */
function BFS距离(s, 格们, 列数) {
  const L = Number.isFinite(列数) && 列数 > 0 ? Math.floor(列数) : 几何列数(列数, s);
  const 有 = k => 是集(格们) ? 格们.has(k) : (是映射(格们) ? 格们.has(k) : !!格们[k]);
  const d = new Map([[s, 0]]), q = [s];
  while (q.length) {
    const k = q.shift();
    for (const n of 邻居(k, L)) if (有(n) && !d.has(n)) { d.set(n, d.get(k) + 1); q.push(n); }
  }
  return d;
}
/** 死胡同 = 连通份里只有一个邻居的格（26-地图生成.js:42）。 */
const 是死胡同 = (k, 有, 列数) => 邻居(k, 列数).filter(有).length === 1;

/** 割点（Tarjan；无向连通图）。`有` = 这一层真的存在的格集合。返回 Set(割点格号)。
 *  ★ 2026-10-12 地图大改新增（调研 §5 A2）：出口守军要放「起点→两个出口」的必经点上。
 *  这是**纯读**（不动任何状态、不消耗随机数），界面与测试都能直接调。 */
function 割点们(有, 列数) {
  const L = Number.isFinite(列数) && 列数 > 0 ? Math.floor(列数) : 几何列数(列数);
  const 有集 = 成集(有);
  const disc = new Map(), low = new Map(), ap = new Set();
  let t = 0;
  const dfs = (u, p) => {
    disc.set(u, t); low.set(u, t); t++;
    let 子 = 0;
    for (const v of 邻居(u, L)) {
      if (!有集.has(v)) continue;
      if (!disc.has(v)) {
        子++; dfs(v, u); low.set(u, Math.min(low.get(u), low.get(v)));
        if (p != null && low.get(v) >= disc.get(u)) ap.add(u);
      } else if (v !== p) low.set(u, Math.min(low.get(u), disc.get(v)));
    }
    if (p == null && 子 > 1) ap.add(u);
  };
  for (const k of 有集) if (!disc.has(k)) dfs(k, null);
  return ap;
}
/** 从 s 到 t 的**必经点**（去掉它之后 t 就不可达；不含 s / t 自己）。
 *  ★ 2026-10-12 地图大改新增（调研 §5 A2）：`s → t` 的割集，用来挑「收费站」。
 *  口径与仓库外探针 `_probe/路线量化.mjs` 的 `必经点()` 逐字一致（去掉每个内部格再 BFS 一遍），
 *  那是 96 张图量过的口径，所以这里的数字与调研报告可以直接对账。 */
function 必经点(有, s, t, 列数) {
  const L = Number.isFinite(列数) && 列数 > 0 ? Math.floor(列数) : 几何列数(列数, s);
  const 有集 = 成集(有);
  const out = [];
  for (const v of 有集) {
    if (v === s || v === t) continue;
    const 去 = new Set(有集); 去.delete(v);
    if (!BFS距离(s, 去, L).has(t)) out.push(v);
  }
  return out;
}

