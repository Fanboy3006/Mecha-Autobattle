const 规则签名 = () => {
  const 战斗表 = (typeof 战斗结构 !== 'undefined' && 战斗结构) ? 战斗结构 : null;
  const 难度表 = (typeof 难度调整 !== 'undefined' && 难度调整) ? 难度调整 : null;
  const 势力表 = (typeof 势力特色 !== 'undefined' && 势力特色) ? 势力特色 : null;
  const 肉鸽表 = (typeof 肉鸽数值 !== 'undefined' && 肉鸽数值) ? 肉鸽数值 : null;
  const 守军表 = (typeof 守军奖励 !== 'undefined' && 守军奖励) ? 守军奖励 : null;
  return 'r1:' + 规则FNV(
    '战斗结构=' + 规则序列化(战斗表) +
    '|难度调整=' + 规则序列化(难度表) +
    '|势力特色=' + 规则序列化(势力表) +
    '|肉鸽数值=' + 规则序列化(肉鸽表) +
    '|守军奖励=' + 规则序列化(守军表));
};

