/* ============================================================================
 * ★ 2026-10-13 架构 2.0 · **规则签名（Replay Versioning 的判据）**
 * ----------------------------------------------------------------------------
 * 问题（DEBT-03）：录像只记「种子 + 游戏版本 + 操作流」——**种子只决定随机序列**，
 *   而规则一变（`战斗结构` 某个开关 / `肉鸽数值` 某个价钱），同一份录像重放出来的数值
 *   就会与录的时候不一样，可 `游戏版本` 号还可能是同一个（两条线同时改一个文件时不许撞号）。
 * 做法：对**当前运行时的规则参数**（★ 2026-10-13 修：**五张核心规则表** ——
 *   `71-改动-4-战斗结构.js` 的 `战斗结构` + `71-改动-3-难度调整.js` 的 `难度调整` +
 *   `71-改动-2-势力特色.js` 的 `势力特色` + `90-肉鸽-1-数据与规则.js` 的 `肉鸽数值` +
 *   `90-肉鸽-1-数据与规则.js` 的 `守军奖励`）做一次**决定性的稳定 JSON 序列化**，
 *   再算一个 **8 位十六进制 FNV-1a** → `'r1:' + hex8`，代表「**当前处于哪个规则宇宙**」。
 *   ⚠ 为什么是这五张：它们全是**顶层规则表**（改一个数就换一个规则宇宙）——
 *     只序列化 `战斗结构` + `肉鸽数值` 时，改 `难度调整.敌方强度` 或 `势力特色[...]` 的数值
 *     **签名竟然不变**，跨规则版本重放就抓不到了（Guardian 破坏性审查抓出的真漏洞，2026-10-13 补）。
 * 三条纪律：
 *   ① **纯函数**：只读、不写任何状态、不消耗随机数、不抛；
 *   ② **决定性**：对象键**排序**后序列化，所以同一次运行 + 同一份参数 → 逐字同一个签名；
 *   ③ **只放数据**：函数 / `undefined` / `Set` / `Map` 一律化成固定标记（不是它们的源码文本，
 *      不然改一行注释就会换签名，签名就不再是「规则宇宙」而是「源码宇宙」了）。
 * 它挂两处：`录像.规则签名()`（录像自己用）与 `window.__game.规则签名()`（门禁 / 工具用）。
 * ========================================================================== */
/** 规则参数的**稳定 JSON 序列化**（对象键排序；函数 / undefined / 异类对象 → 固定标记）。 */
const 规则序列化 = v => {
  if (v === null) return 'null';
  const t = typeof v;
  if (t === 'number') return Number.isFinite(v) ? String(v) : '"' + String(v) + '"';
  if (t === 'boolean') return v ? 'true' : 'false';
  if (t === 'string') return JSON.stringify(v);
  if (t === 'undefined') return '"__undefined__"';
  if (t === 'function') return '"__function__"';
  if (Array.isArray(v)) return '[' + v.map(规则序列化).join(',') + ']';
  if (t === 'object' && v.constructor === Object) {
    return '{' + Object.keys(v).sort().map(k => JSON.stringify(k) + ':' + 规则序列化(v[k])).join(',') + '}';
  }
  return JSON.stringify('__' + ((v && v.constructor && v.constructor.name) || t) + '__');
};
/** FNV-1a（32 位）→ 8 位小写十六进制。按 **UTF-16 码元**逐字节喂（中文键也可复现）。 */
const 规则FNV = 文 => {
  let h = 0x811c9dc5;
  for (let i = 0; i < 文.length; i++) {
    const c = 文.charCodeAt(i);
    h = Math.imul(h ^ (c & 0xff), 0x01000193) >>> 0;
    h = Math.imul(h ^ ((c >>> 8) & 0xff), 0x01000193) >>> 0;
  }
  return ('00000000' + h.toString(16)).slice(-8);
};
