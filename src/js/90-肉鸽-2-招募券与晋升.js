/** 把 `参` 解析成「手上的第几张券」的下标：可以是下标（`'1'` / `1`），也可以是券的**显示名**
 *  （`'近卫招募券'` / `'近卫'`）——认不出来返回 `-1`。 */
function 解析券下标(R, 参) {
  const 们 = (R && R.券) || [];
  if (参 == null || 参 === '') return -1;
  const s = String(参);
  const n = Number(s);
  if (Number.isFinite(n) && s.trim() !== '') return (n >= 0 && n < 们.length) ? Math.floor(n) : -1;
  for (let i = 0; i < 们.length; i++) {
    if (券名(们[i]) === s || 们[i].名 === s) return i;
  }
  return -1;
}

